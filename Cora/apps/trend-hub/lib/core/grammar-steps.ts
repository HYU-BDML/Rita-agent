/**
 * 만드는 순서 — **방식 12개마다 미리 쓴 단계.**
 *
 * 전에는 `frame` 별 템플릿으로 문장을 만들었다. 그래서 어느 방식에 붙여도 말이 되는
 * 글쓰기 조언이 나왔다 — `docs/grammars.md` 를 한 줄도 열지 않고 쓸 수 있는 문장이고,
 * 그러면 게시물 2,023건을 훑은 값이 0 이 된다.
 *
 * **판정 기준 하나.** 근거를 열지 않고도 쓸 수 있는 문장이면 버린다. 각 단계는
 * 캡션·숫자·해시태그 중 하나를 근거에서 그대로 인용한다.
 *
 * **근거를 번호가 아니라 이름으로 적는다.** 화면에 나가는 것은 번호지만(「근거 1·2·4」),
 * 번호는 그 방식 근거 목록의 순서이고 그 순서는 신선도에 따라 **데이터가 정한다**.
 * 번호를 적어 두면 다음 수집에서 순서가 바뀌는 순간 전부 틀린 곳을 가리킨다. 이름으로
 * 적고 화면이 그때의 자리를 세어 번호를 붙인다.
 *
 * `docs/grammars.md` 의 근거와 각 소재의 실제 캡션에서 나왔다. 근거가 얇아 단계 셋을
 * 못 채우는 방식은 둘까지만 쓴다 — 빈 칸을 일반론으로 메우지 않는다.
 */

export interface Step {
  /** 무엇을 하나. 한 줄. */
  do: string;
  /** 어느 근거에서 나왔나. 소재 이름이고, 화면이 번호로 바꾼다. */
  from: string[];
  /** 근거에서 그대로 따온 것. 캡션·숫자·해시태그. 지어낸 문장을 넣지 않는다. */
  cite: string;
}

export interface GrammarSteps {
  steps: Step[];
  /** 피할 것 — 이유까지 데이터로 적는다. */
  avoid: { text: string; from: string[] };
}

