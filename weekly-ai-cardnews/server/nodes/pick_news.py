# 뽑음: 주간AI소식_카드뉴스.yml 의 «소식 고르기» 단계 — 손으로 고치지 말 것 (weekly/server/extract.py 로 다시 뽑는다)
# Dify 코드 노드 「소식 고르기」   ← HTTP 「소식 긁기」(/procure/week) 뒤에 붙는다
#
# 입력 변수:
#     body   String   ← 소식 긁기 / body   (브랜드 일곱의 그 주 후보. 실측 41KB)
#
# 출력 변수:
#     news       String        대본 LLM 에 그대로 넘길 소식 목록 (한 건씩 줄바꿈)
#     picked     Array[Object] 고른 것들 — 사람이 확인할 때 쓴다
#     dropped    String        그 주 글이 없어 빠진 브랜드 (쉼표로 이음)
#     count      Number        꼭지 수 = 슬라이드에 들어갈 뉴스 장 수
#
# 하는 일은 둘뿐이다.
#   ① 브랜드마다 «그 주 좋아요+리트윗 으뜸» 을 그 브랜드의 소식으로 삼는다
#   ② 그 소식과 같은 얘기를 하는 그 주 블로그 글이 있으면 붙여 준다 (본문이 두툼해진다)
#
# **그 주 X 글이 없는 브랜드는 그냥 빠진다.** 없는 소식을 지어내지 않는다.
# 그래서 슬라이드 수가 주마다 다르다 — 8월 2주차는 Grok 이 조용해서 여섯 꼭지였다.
#
# 왜 코드 노드인가: 재는 일이라서다. «어느 글이 제일 반응이 컸나» 는 숫자로 정해진다.
# LLM 에 물으면 매번 답이 달라지고 왜 골랐는지도 설명이 안 된다.

import json
import re

# 이 계정 글 거의 전부에 들어 있어 후보를 못 가르는 말들. 짝짓기에서 뺀다.
흔한말 = {
    "the", "a", "an", "and", "or", "but", "for", "with", "from", "into", "over",
    "to", "of", "in", "on", "at", "by", "is", "are", "was", "were", "be", "been",
    "it", "its", "this", "that", "these", "those", "we", "our", "you", "your",
    "now", "new", "more", "all", "can", "will", "has", "have", "how", "what",
    "ai", "model", "models", "available", "today", "introducing", "learn",
    "https", "http", "com", "www", "t", "co",
}


def 낱말(글):
    """영문·숫자·한글 덩어리로 쪼갠다. 두 글자 미만과 흔한 말은 버린다."""
    것들 = re.findall(r"[A-Za-z][A-Za-z0-9\-\.]+|[0-9]+(?:\.[0-9]+)?|[가-힣]{2,}", 글.lower())
    return {w.strip(".-") for w in 것들 if len(w) >= 2 and w not in 흔한말}


def 반응(c):
    """고르는 기준. 좋아요와 리트윗을 더한다 — 사용자가 정한 규칙이다."""
    return (c.get("likes") or 0) + (c.get("retweets") or 0)


영상꼴 = (".mp4", ".m3u8", ".mov", ".m4v", "video-s.twimg", "video.twimg", "/amplify_video/")
"""주소만 보고 영상인지 가른다. X 영상은 `video-s.twimg.com/amplify_video/…` 로 온다."""


def 미디어갈래(주소):
    ㄱ = str(주소 or "").lower()
    return "영상" if any(k in ㄱ for k in 영상꼴) else "사진"


칸 = (1080, 796)
"""뉴스 장의 미디어 자리. 이보다 작은 원본은 늘려 넣어야 해서 흐려진다."""


def 해상도(주소):
    """X 영상 주소에는 크기가 박혀 있다 — `/vid/avc1/1920x1080/`. 없으면 (0,0).

    스레드·사진 주소에는 안 박혀 있다. 그건 여기서 못 재고, «모름» 으로 둔다 —
    **모르는 것을 «작다» 로 취급하면 멀쩡한 후보를 버린다.**
    """
    m = re.search(r"/(\d{3,4})x(\d{3,4})/", str(주소 or ""))
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def 확실히넉넉한가(주소):
    """칸을 안 늘리고 채울 수 있다고 **확인된** 것만 True. 모르면 False.

    **모르는 것을 «넉넉하다» 로 봤더니 나쁜 맞바꿈이 났다** (실측 2026-08-20):
    Claude 는 X 에 ♥11062 짜리 영상 글이 있는데 그게 1280x720 이었고, 스레드 글은
    크기를 몰라서 «넉넉» 으로 뽑혔다. 그래서 **10등짜리 글이 1등을 밀어냈다.**
    화질을 조금 얻자고 그 주의 대표 소식을 바꾼 셈이다 — 대본이 그 글로 쓰이니까.

    그래서 **모름은 밀어주지도, 깎지도 않는다.** 확인된 큰 것이 있을 때만 그쪽으로
    가고, 없으면 아래 `넉넉 or 무리` 가 예전 규칙(반응 1등)으로 되돌린다.
    """
    w, h = 해상도(주소)
    return bool(w) and w >= 칸[0] and h >= 칸[1]


def 미디어골라(후보):
    """**영상이 있는 글을 먼저 고른다.** 없으면 사진, 그것도 없으면 그냥 반응 1등.

    예전엔 «반응 1등 글 하나» 의 미디어만 봤다. 그래서 그 글에 사진·영상이 없으면
    그 브랜드 장이 통째로 죽었다 — 8장 중 3장이 그랬다(실측 2026-08-20).
    그런데 같은 브랜드의 다른 글에는 있었다: ChatGPT 는 그 주에 **4K 영상 4개**를
    올렸는데 우리는 하나도 안 쓰고 있었다.

    **왜 «다른 글의 미디어를 가져오기» 가 아니라 «미디어 있는 글을 고르기» 인가.**
    대본은 고른 글의 «내용» 으로 쓴다. 미디어만 딴 글에서 떼어 오면 글과 그림이
    따로 논다. 미디어가 붙은 글을 통째로 고르면 둘이 항상 맞는다.

    돌려주는 것: (고른 글, 미디어 주소, 갈래, 왜 골랐나)
    """
    영상것 = [c for c in 후보 if any(미디어갈래(m) == "영상" for m in (c.get("media") or []))]
    사진것 = [c for c in 후보 if (c.get("media") or []) and c not in 영상것]
    전체으뜸 = max(후보, key=반응)

    for 무리, 갈래 in ((영상것, "영상"), (사진것, "사진")):
        if not 무리:
            continue

        def 주소뽑기(c):
            것들 = c.get("media") or []
            return next((m for m in 것들 if 미디어갈래(m) == 갈래), 것들[0])

        # **칸보다 작은 원본은 늘려 넣어야 해서 흐려진다.** 1280x720 을 1080x796
        # 자리에 채우면 1.11배 늘어난다. 같은 브랜드에 1920x1080 짜리 글이 따로
        # 있으면 그쪽이 낫다 — 반응이 조금 낮더라도.
        #
        # **반응을 버리는 게 아니라 «먼저 거른 뒤 반응으로 고른다».** 넉넉한 것이
        # 하나도 없으면 예전대로 반응 1등을 쓴다. 없는 화질을 지어낼 수는 없다.
        넉넉 = [c for c in 무리 if 확실히넉넉한가(주소뽑기(c))]
        고른것 = max(넉넉 or 무리, key=반응)
        주소 = 주소뽑기(고른것)
        등수 = sorted(후보, key=반응, reverse=True).index(고른것) + 1
        w, h = 해상도(주소)
        크기말 = (" · %dx%d" % (w, h)) if w else ""
        좁음 = "" if 넉넉 else " · %dx%d 뿐이라 늘려 넣는다" % (w, h) if w else ""
        왜 = "%s 있는 글 중 반응 1등 (전체 %d등/%d)%s%s" % (
            갈래, 등수, len(후보), 크기말, 좁음)
        return 고른것, 주소, 갈래, 왜
    return 전체으뜸, "", "없음", "미디어가 하나도 없다 — 그림을 만들어야 한다"


def 짝찾기(소식, 블로그들):
    """같은 얘기를 하는 그 주 블로그 글. 겹치는 낱말이 제일 많은 것.

    **두 낱말 이상 겹쳐야 짝으로 본다.** 한 낱말만 겹치는 건 우연이 흔하다 —
    브랜드 이름 하나만 같아도 걸리기 때문이다.

    **날짜가 없는 블로그는 더 까다롭게 본다 (넉 낱말).** 앤트로픽 블로그는 글
    페이지에도 발행일이 없어서(실측 2026-08-19) 그 주 것인지 가릴 수가 없다.
    그러면 «몇 달 전 글이 낱말 두 개 겹쳐서 붙는» 사고가 난다 — 그 옛 글의 숫자가
    이번 주 대본에 실려 들어간다. 날짜로 못 거르면 내용으로 더 세게 거른다.
    Perplexity·Meta AI 는 블로그 자체가 없어 X 만으로 간다.
    """
    ㄱ = 낱말(소식.get("text") or "")
    최고, 최고점, 겹친것 = None, 0, []
    for b in 블로그들:
        겹침 = ㄱ & 낱말(b.get("text") or "")
        문턱 = 2 if (b.get("date") or "").strip() else 4
        if len(겹침) >= 문턱 and len(겹침) > 최고점:
            최고, 최고점, 겹친것 = b, len(겹침), sorted(겹침)
    if not 최고:
        return None, 0, []
    return 최고, 최고점, 겹친것[:6]


def main(body: str) -> dict:
    자료 = json.loads(body)

    # **번호표를 되물은 답이 온다.** 긁기는 30초를 넘어서 곧바로 답을 못 준다
    # (API Gateway 가 거기서 끊는다) — 번호표를 받아 되묻는 구조다.
    # 그래서 여기 오는 몸통에는 `state` 가 붙어 있다.
    상태 = 자료.get("state")
    if 상태 == "실패":
        raise RuntimeError("소식 긁기가 실패했다 — %s" % (자료.get("error") or "이유가 안 남았다"))
    if 상태 and 상태 != "됨":
        raise RuntimeError(
            "소식 긁기가 아직 «%s» 다 — 되묻기가 모자란다. 「소식 묻기」 노드를 더 늘려라"
            % 상태)

    주 = 자료.get("week") or {}
    골라둠, 빠짐, 줄들 = [], [], []

    for 칸 in 자료.get("브랜드") or []:
        브랜드 = 칸.get("brand") or ""
        # 주소가 없는 줄은 액터가 끼워 넣은 광고문이다. 서버가 이미 거르지만
        # 여기서도 한 번 더 본다 — 이게 으뜸으로 뽑히면 그게 그대로 대본이 된다.
        # **스레드 글도 같은 후보 통에 넣는다.** 모양이 X 와 같아서 그냥 합치면 된다.
        # 스레드는 «좋아요» 가 X 보다 한참 낮지만(16 vs 수천) 그래도 밀리지 않는다 —
        # 고르는 규칙이 «영상 있는 것 먼저, 그 안에서 반응 1등» 이라, X 에 사진밖에
        # 없으면 스레드 영상이 이긴다. 그러라고 넣은 것이다(실측 2026-08-20:
        # Claude·Grok 은 X 에 영상이 0개인데 스레드에 11개·4개가 있었다).
        후보 = [c for c in (칸.get("x") or []) if c.get("url")]
        for c in (칸.get("threads") or []):
            if c.get("url"):
                후보.append(dict(c, _출처="스레드"))
        if not 후보:
            빠짐.append(브랜드)
            continue

        으뜸, 미디어주소, 미디어갈래이름, 왜골랐나 = 미디어골라(후보)
        짝, 점수, 겹침 = 짝찾기(으뜸, 칸.get("blog") or [])
        # 블로그 대표 그림은 마지막 수단이다. X 에 아무것도 없을 때만 본다.
        if not 미디어주소 and 짝:
            블것 = (짝.get("media") or [])
            if 블것:
                미디어주소, 미디어갈래이름, 왜골랐나 = 블것[0], "사진", "블로그 대표 그림"

        골라둠.append({
            "brand": 브랜드,
            "x_text": 으뜸.get("text") or "",
            "x_url": 으뜸.get("url") or "",
            "date": 으뜸.get("date") or "",
            "likes": 으뜸.get("likes") or 0,
            "retweets": 으뜸.get("retweets") or 0,
            "media": [미디어주소] if 미디어주소 else [],
            "미디어갈래": 미디어갈래이름,
            "왜골랐나": 왜골랐나 + (" · 스레드" if 으뜸.get("_출처") else ""),
            "출처": 으뜸.get("_출처") or "X",
            "blog_text": (짝 or {}).get("text") or "",
            "blog_url": (짝 or {}).get("url") or "",
            "겹친낱말": 겹침,
            "후보수": len(후보),
        })

        # 대본 LLM 이 읽을 몫. 사실만 넘긴다 — 말투는 스킬 문서가 만든다.
        조각 = ["[%s] %s" % (브랜드, (으뜸.get("text") or "").replace("\n", " "))]
        if 짝:
            조각.append("  (블로그) %s" % (짝.get("text") or "").replace("\n", " "))
        줄들.append("\n".join(조각))

    # **하나도 못 골랐으면 죽는다.**
    #
    # 「그 주에 소식이 없다」와 「긁기가 실패했다」는 여기서 똑같이 보인다 —
    # 둘 다 빈 목록이다. 그런데 앞의 것은 있을 수 없다. 브랜드 일곱이 한 주 내내
    # 아무 말도 안 하는 일은 없다. **0이면 사고다.**
    #
    # 예전엔 0을 그대로 흘려보냈고, 판이 끝까지 돌아 마무리 한 장짜리 결과가
    # 「성공」으로 나왔다(실측 2026-08-20). **실패했는데 성공으로 뜨는 게 제일 나쁘다.**
    if not 골라둠:
        raise ValueError(
            "고른 소식이 0건이다 — 브랜드 일곱이 한 주 내내 조용할 리 없으니 "
            "앞에서 못 긁은 것이다. 빠진 브랜드: %s / 긁기 탈: %s"
            % (", ".join(빠짐) or "없음",
               " / ".join((주.get("탈") or [])[:3]) or "안 남았다"))

    return {
        "news": "%s\n\n%s" % (주.get("라벨") or "", "\n\n".join(줄들)),
        "picked": 골라둠,
        "dropped": ", ".join(빠짐),
        "count": len(골라둠),
    }
