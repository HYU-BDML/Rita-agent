# -*- coding: utf-8 -*-
"""지휘자 — 구간 달리기(설계 2장). 한 구간 = 새 대화 [지시문 + 도구 설명] + [작업판].

구간 안에서는 딥시크 규칙대로 생각 글을 그대로 되돌려 주며 걸음을 잇는다. 한 응답에 도구가 여럿이면 바깥 도구는
나란히(최대 4), 작업판·증거 보기·결과 내기는 그 뒤 차례로 돈다. 구간은 «결과를 냈다(냄) / 구간 걸음을 다 썼다(계속) /
람다 시간이 모자라다(시간)» 에서 끝난다. 예산이 «끝» 이면 submit_result 만 주고, 두 걸음 안에 안 내면 빈 결과로 낸다."""
from concurrent.futures import ThreadPoolExecutor

from topic import board, instructions, tools, trace, watchlist

구간걸음 = 10
지휘한도 = 20000   # 2026-10-01 시험 18걸음: 생각 최대 9,333 · 상위 5% 6,953 (계획 Task 10 머리)
최대한도 = 40000   # 넘치면 한 번만 두 배로
도구기다림초 = 390  # 나란한 도구 몫 — Apify 시작 60 + 기다림 200 + 받기 60(최종 검토) + 모을 때 사진 판정 60(계획 4 B, tools.사진마감초). 걸음 시작 전에 읽기초 + 이만큼


def 읽기초(한도: int) -> int:
    """딥시크 답을 기다리는 시간. 시험에서 초당 약 115토큰 — 느린 날을 생각해 80토큰으로 잡고 60초 더."""
    return 한도 // 80 + 60
_안쪽 = ("update_board", "get_evidence", "submit_result")
고르기만걸음 = 4  # 저장한 분야 판 — 이 걸음 뒤엔 submit_result 만, 두 걸음 더 안 내면 빈 결과(합 6걸음, 사용자 10-05)
_고르기만말 = ("이번 판은 저장한 분야 — 매주 볼 곳에서 이미 모은 증거만으로 고른다. 새로 찾지 말고 지금 증거에서 소식을 골라 "
           "submit_result 하라.")


def 딥시크적기(재료: dict, 답: dict, 열쇠: str, 시각: str) -> None:
    재료.setdefault("딥시크기록", []).append(
        {"열쇠": 열쇠, "모델": 답.get("모델"), "넘침": 답.get("넘침", False), "입력토큰": 답["입력토큰"],
         "캐시토큰": 답.get("캐시토큰", 0), "출력토큰": 답["출력토큰"], "생각토큰": 답.get("생각토큰", 0),
         "초": 답.get("초", 0), "시각": 시각, "걸음": 재료.get("지금걸음"),
         "단계": (재료.get("작업판") or {}).get("단계")})  # 걸음별 돈(cost.걸음별) — 단계는 이 걸음을 시작할 때 것


def _도구들(끝: bool, 고르기만: bool) -> list:
    if 끝:
        return [d for d in tools.도구설명 if d["function"]["name"] == "submit_result"]
    return [d for d in tools.도구설명 if d["function"]["name"] in _안쪽] if 고르기만 else tools.도구설명


def _걸음돌기(현, 호출들: list, 고르기만: bool = False) -> list[str]:
    """한 응답의 도구들 — 같은 호출이 둘이면 하나만. 바깥 도구는 나란히, 안쪽 도구는 그 뒤 차례로.
    고르기만 판이면 바깥 도구는 부르지 않는다(주지 않은 도구를 불러도)."""
    글 = [""] * len(호출들)
    본것 = {}
    바깥, 안쪽 = [], []
    for i, h in enumerate(호출들):
        열쇠 = (h["이름"], repr(sorted(h["인자"].items())) if isinstance(h["인자"], dict) else "")
        if 열쇠 in 본것:
            글[i] = f"이 걸음에 같은 호출을 두 번 했다 — {호출들[본것[열쇠]]['id']} 결과를 보라."
            continue
        본것[열쇠] = i
        if 고르기만 and h["이름"] not in _안쪽:
            글[i] = "이번 판은 새로 찾지 않는다 — 지금 증거에서 골라 submit_result 하라."
            continue
        (안쪽 if h["이름"] in _안쪽 else 바깥).append(i)
    if 바깥:
        with ThreadPoolExecutor(max_workers=4) as 풀:
            for i, 결과 in zip(바깥, 풀.map(lambda j: tools.부르기(현, 호출들[j]), 바깥)):
                글[i] = 결과
    for i in 안쪽:
        글[i] = tools.부르기(현, 호출들[i])
    return 글


def 구간(현, 대화, 남은초, 저장, 고르기만: bool = False) -> str:
    """고르기만 — 저장한 분야 판: 안쪽 도구만 주고 «고르기만걸음» 뒤엔 예산이 끝난 것처럼 내게 한다(사용자 10-05)."""
    메시지들, 자리, 끝 = [], {"적은수": 0}, "오류"
    try:
        끝 = _구간(현, 대화, 남은초, 저장, 메시지들, 자리, 고르기만)
        return 끝
    finally:
        현.재료["지금걸음"] = None  # 구간 밖(검증·정리)의 판정관 값은 «걸음 밖» 으로 센다
        현.흔적.쓰기("구간끝", {"끝": 끝, "못본것": [m for m in 메시지들[자리["적은수"]:] if m["role"] != "assistant"]})
        # ↑ 지휘자가 못 보고 끝난 도구 결과·알림 (지휘자 자신의 마지막 답은 «지휘» 사건에 이미 있다)


def _구간(현, 대화, 남은초, 저장, 메시지들: list, 자리: dict, 고르기만: bool) -> str:
    첫글 = board.지휘자글(현.판, 현.주문서, 현.창고, 현.예산.기록, 현.예산.한줄(), 현.예산.경고())
    if 현.재료.get("목록글") and not 현.재료.get("목록글보임"):  # 목록 판의 첫 구간에만 — 사용자 글 하나로(계획 4 설계 A-4)
        첫글 += "\n\n" + watchlist.결과글(현.재료["목록글"])  # 다음 구간부터는 작업판 «이미 한 일» 에 남는다
        현.재료["목록글보임"] = True
    if 고르기만:
        첫글 += "\n\n" + _고르기만말
    메시지들 += [{"role": "system", "content": instructions.지휘자}, {"role": "user", "content": 첫글}]
    한도, 안낸걸음, 안적은걸음 = 지휘한도, 0, 0
    for 걸음 in range(구간걸음):
        if 남은초() < 읽기초(한도) + 도구기다림초:
            return "시간"
        예산끝 = 현.예산.상태() == "끝"
        끝 = 예산끝 or (고르기만 and 걸음 >= 고르기만걸음)
        다씀 = "예산을 다 썼" if 예산끝 else "고를 걸음을 다 썼"
        if 끝 and 안낸걸음 == 0:
            메시지들.append({"role": "user", "content": f"{다씀}다 — 지금까지 모은 것으로 submit_result 하라. "
                                                       "못 채운 칸은 unfilled 에 찾아본 곳과 까닭을 적어라."})
        if 끝 and 안낸걸음 >= 2:
            현.재료["제출"] = {"items": [], "unfilled": [{"slot": "전부", "searched": [x["요약"] for x in 현.예산.기록][-10:],
                                                     "why": f"{다씀}는데 결과를 내지 못함", "more_cost": ""}],
                            "시각": 현.지금글(), "강제": True}
            현.흔적.쓰기("강제제출", {"걸음": 현.재료.get("걸음수"), "제출": 현.재료["제출"]})
            저장()
            return "냄"
        현.재료["걸음수"] = 현.재료.get("걸음수", 0) + 1  # 판 전체에서 이어 센다(구간·람다가 바뀌어도)
        현.재료["지금걸음"] = 현.재료["걸음수"]
        답 = 대화(메시지들, 한도, 도구들=_도구들(끝, 고르기만), 읽기=읽기초(한도))
        딥시크적기(현.재료, 답, "지휘", 현.지금글())
        현.흔적.쓰기("지휘", {"걸음": 현.재료["지금걸음"], "단계": 현.판["단계"], "한도": 한도, "이어짐": 자리["적은수"] > 0,
                           "보낸것": [m for m in 메시지들[자리["적은수"]:] if m["role"] != "assistant"],
                           **trace.답칸(답)})
        자리["적은수"] = len(메시지들)
        if 끝:
            안낸걸음 += 1
        if 답["넘침"]:
            한도 = min(한도 * 2, 최대한도)
            메시지들.append({"role": "user", "content": "생각이 한도를 넘었다 — 생각은 짧게, 확인은 도구로(원칙 8). "
                                                       "다음 걸음을 바로 정하라."})
            저장()
            continue
        메시지들.append(답["메시지"])
        if not 답["도구호출"]:
            메시지들.append({"role": "user", "content": "도구로 다음 걸음을 하라. 다 모았으면 submit_result."})
            저장()
            continue
        낼것 = [h for h in 답["도구호출"] if h["이름"] == "submit_result"]
        글들 = _걸음돌기(현, 답["도구호출"], 고르기만)
        for h, 글 in zip(답["도구호출"], 글들):
            메시지들.append({"role": "tool", "tool_call_id": h["id"], "content": 글})
        # 작업판을 잘 안 적어 단계 표시가 멈췄다(진짜 한 판 17걸음에 5번) — 세 걸음이면 재촉한다
        안적은걸음 = 0 if any(h["이름"] == "update_board" for h in 답["도구호출"]) else 안적은걸음 + 1
        if 안적은걸음 >= 3 and not 낼것:
            메시지들.append({"role": "user", "content": "세 걸음 동안 작업판을 안 적었다 — update_board 로 지금 단계와 "
                                                       "판단을 적어라(대화는 끊기고 작업판만 남는다)."})
            안적은걸음 = 0
        현.창고.쓰기()
        저장()
        if any(글.startswith("받았다") for h, 글 in zip(답["도구호출"], 글들) if h in 낼것):
            return "냄"
    return "계속"
