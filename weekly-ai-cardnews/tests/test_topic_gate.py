def 검사(현, 소식들, 마지막=False, 칸=()):
    return gate.검사(현, {"items": [dict(x) for x in 소식들], "unfilled": list(칸)}, 마지막)


def test_좋은_소식은_통과하고_공식_언론이_아니면_2차():
    판정관 = 가짜판정관()
    d = 검사(준비(판정관), [좋은, 기사, 팬])
    assert d["돌려보낼말"] == [] and [x["tags"] for x in d["통과"]] == [[], [], ["2차"]]
    assert [x[1] for x in 판정관.받은 if x[0] == "문장"] == [
        "코르티스가 9월 24일 뮤직비디오 «FaSHioN» 을 공개했다.", "코르티스가 9월 25일 음악방송에서 첫 1위를 했다.",
        "팬 사인회 후기가 올라왔다."]


def test_지어낸_증거는_되돌린다():
    d = 검사(준비(), [{**좋은, "source": "E99"}])
    assert d["통과"] == [] and d["돌려보낼말"] == ["1번 «뮤직비디오 공개»: 없는 증거 번호 E99 — 도구 결과의 번호만"]


def test_발췌_날짜_때말_숫자를_코드가_잡는다():
    현 = 준비()
    말 = 검사(현, [{**좋은, "quote": "CORTIS 'FaSHioN' 뮤직비디오 최초 공개"},
                 {**좋은, "event": "b", "source": "E2", "quote": "팬미팅 공지", "date": "2026-09-30", "media": "없음"},
                 {**기사, "event": "c", "summary": "지난주 음악방송에서 첫 1위를 했다 [E3]."},
                 {**좋은, "event": "d", "source": "E5", "quote": "FaSHioN 뮤직비디오 공개", "media": "없음",
                  "summary": "뮤직비디오가 1,000만 뷰를 넘었다 [E5]."},
                 {**기사, "event": "e", "date": "2026-09-23"}])["돌려보낼말"]
    assert "발췌가 E1 원문에 글자 그대로 없음" in 말[0]
    assert "E2 원문 날짜 2026-09-30 가 기간(2026-09-21~2026-09-27) 밖" in 말[1]
    assert "«지난주»" in 말[2] and "요약의 숫자 1000 가 발췌에 없음" in 말[3]
    assert "date 2026-09-23 가 원문 날짜 2026-09-25 와 다름" in 말[4]


def test_미디어는_그_글_것만_기사_사진은_장면만():
    말 = 검사(준비(), [{**좋은, "media": "E4"}, {**기사, "event": "x", "media": "E3#2"}, {**팬, "media": "E4"}])["돌려보낼말"]
    assert "미디어 E4 가 출처 글 E1 에 붙은 것이 아님" in 말[0] and "판정이 «로고»" in 말[1]
