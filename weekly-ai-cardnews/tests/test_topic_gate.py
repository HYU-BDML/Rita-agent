def 검사(현, 소식들, 마지막=False, 칸=()):
    return gate.검사(현, {"items": [dict(x) for x in 소식들], "unfilled": list(칸)}, 마지막)


def test_좋은_소식은_통과하고_공식_언론이_아니면_2차():
    판정관 = 가짜판정관()
    d = 검사(준비(판정관), [좋은, 기사, 팬])
    assert d["돌려보낼말"] == [] and [x["tags"] for x in d["통과"]] == [[], [], ["2차"]]
