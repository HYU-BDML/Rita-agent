def test_통과한_소식은_잠가서_다시_재지_않는다():
    # 통과한 것까지 매번 다시 재서 «받쳐줌» 이 «모자람» 으로 뒤집혔다(판 3)
    판정관 = 가짜판정관(문장={"코르티스가 9월 25일 음악방송에서 첫 1위를 했다.": "모자람"})
    현 = 준비(판정관)
    첫 = 검사(현, [좋은, 기사])
    assert 첫["통과"] == [] and len(첫["돌려보낼말"]) == 1 and 첫["돌려보낼말"][0].startswith("2번 «음악방송 첫 1위»")
    고친기사 = {**기사, "summary": "코르티스가 9월 25일 음악방송 1위를 했다 [E3]."}
    둘째 = 검사(현, [{**좋은, "summary": "코르티스가 뮤직비디오를 공개했다 [E1]."}, 고친기사])
    assert [x["summary"] for x in 둘째["통과"]] == [좋은["summary"], 고친기사["summary"]]
    assert "코르티스가 뮤직비디오를 공개했다." not in [x[1] for x in 판정관.받은 if x[0] == "문장"]


