# -*- coding: utf-8 -*-
import pytest

import cost


def test_딥시크는_한가한_시간에_절반():
    # 2026-09-30(수) 15:28 UTC 는 한가 — 입력 56,683 · 출력 32,040 토큰이면 약 $0.10 (9월 3주차 실제 판)
    x = {"입력토큰": 56683, "캐시토큰": 0, "출력토큰": 32040, "시각": "2026-09-30T15:28:12Z"}
    assert cost.딥시크값(x) == pytest.approx(56683 * 0.66e-6 + 32040 * 1.98e-6)
    바쁨 = dict(x, 시각="2026-09-30T02:00:00Z")  # 수요일 UTC 02시
    assert cost.딥시크값(바쁨) == pytest.approx(2 * cost.딥시크값(x))
    주말 = dict(x, 시각="2026-10-03T02:00:00Z")  # 토요일은 하루 종일 한가
    assert cost.딥시크값(주말) == pytest.approx(cost.딥시크값(x))


def test_딥시크_캐시로_맞힌_입력은_싸다():
    x = {"입력토큰": 10000, "캐시토큰": 8000, "출력토큰": 0, "시각": "2026-09-30T15:00:00Z"}
    assert cost.딥시크값(x) == pytest.approx(2000 * 0.66e-6 + 8000 * 0.022e-6)


def test_그림값():
    u = {"입력글토큰": 300, "입력그림토큰": 2000, "출력토큰": 1600}
    assert cost.그림값(u) == pytest.approx(300 * 5e-6 + 2000 * 8e-6 + 1600 * 30e-6)


def test_합계는_딥시크와_그림만_아피파이는_뺀다():
    재료 = {"딥시크기록": [{"입력토큰": 1_000_000, "캐시토큰": 0, "출력토큰": 0, "시각": "2026-09-30T15:00:00Z"}],
          "그림기록": [{"종류": "표지", "입력글토큰": 0, "입력그림토큰": 0, "출력토큰": 1_000_000}]}
    assert cost.합계(재료) == {"딥시크": 0.66, "그림": 30.0, "그림장수": 1, "합계": 30.66, "표지값모름": False}


def test_표지_사용량이_없으면_모른다고_적는다():
    재료 = {"그림기록": [{"종류": "표지", "모름": True}]}
    assert cost.합계(재료) == {"딥시크": 0.0, "그림": 0.0, "그림장수": 1, "합계": 0.0, "표지값모름": True}
