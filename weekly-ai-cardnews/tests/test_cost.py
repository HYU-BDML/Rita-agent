# -*- coding: utf-8 -*-
import pytest

import cost


def test_딥시크는_한가한_시간에_절반():
    # 2026-09-30(수) 15:28 UTC 는 한가 — 입력 56,683 · 출력 32,040 토큰이면 약 $0.10 (9월 3주차 실제 판)
    x = {"입력토큰": 56683, "캐시토큰": 0, "출력토큰": 32040, "시각": "2026-09-30T15:28:12Z"}
    assert cost.딥시크값(x) == pytest.approx(56683 * 0.66e-6 + 32040 * 1.98e-6)
    바쁨 = dict(x, 시각="2026-09-30T02:00:00Z")  # 수요일 UTC 02시
    assert cost.딥시크값(바쁨) == pytest.approx(2 * cost.딥시크값(x))
    주말 = dict(x, 시각="2026-10-03T02:00:00Z")  # 토요일은 하루 종일 한가
    assert cost.딥시크값(주말) == pytest.approx(cost.딥시크값(x))


def test_딥시크_캐시로_맞힌_입력은_싸다():
    x = {"입력토큰": 10000, "캐시토큰": 8000, "출력토큰": 0, "시각": "2026-09-30T15:00:00Z"}
    assert cost.딥시크값(x) == pytest.approx(2000 * 0.66e-6 + 8000 * 0.022e-6)


def test_그림값():
    u = {"입력글토큰": 300, "입력그림토큰": 2000, "출력토큰": 1600}
    assert cost.그림값(u) == pytest.approx(300 * 5e-6 + 2000 * 8e-6 + 1600 * 30e-6)


def test_합계는_딥시크와_그림만_아피파이는_뺀다():
    재료 = {"딥시크기록": [{"입력토큰": 1_000_000, "캐시토큰": 0, "출력토큰": 0, "시각": "2026-09-30T15:00:00Z"}],
          "그림기록": [{"종류": "표지", "입력글토큰": 0, "입력그림토큰": 0, "출력토큰": 1_000_000}]}
    assert cost.합계(재료) == {"딥시크": 0.66, "그림": 30.0, "그림장수": 1, "아피파이": 0.0, "합계": 30.66,
                             "표지값모름": False}


def test_표지_사용량이_없으면_모른다고_적는다():
    재료 = {"그림기록": [{"종류": "표지", "모름": True}]}
    assert cost.합계(재료) == {"딥시크": 0.0, "그림": 0.0, "그림장수": 1, "아피파이": 0.0, "합계": 0.0,
                             "표지값모름": True}


def test_flash_는_flash_단가():
    x = {"모델": "deepseek-flash", "입력토큰": 10000, "캐시토큰": 0, "출력토큰": 1000, "시각": "2026-09-30T15:00:00Z"}
    assert cost.딥시크값(x) == pytest.approx(10000 * 0.15e-6 + 1000 * 0.6e-6)


def test_주제_판은_아피파이_짐작값도_더한다():
    재료 = {"딥시크기록": [{"모델": "deepseek-v4-pro", "입력토큰": 1_000_000, "캐시토큰": 0, "출력토큰": 0,
                          "시각": "2026-09-30T15:00:00Z"}],
          "아피파이기록": [{"도구": "x_search", "건수": 40, "돈": 0.01}, {"도구": "web_search", "건수": 1, "돈": 0.0055}]}
    assert cost.합계(재료) == {"딥시크": 0.66, "그림": 0.0, "그림장수": 0, "아피파이": 0.0155, "합계": 0.6755,
                             "표지값모름": False}


def test_걸음마다_쓴_돈():
    토 = "2026-10-03T12:00:00Z"  # 토요일 — 한가 단가
    재료 = {"딥시크기록": [
        {"열쇠": "지휘", "걸음": 1, "단계": "①", "모델": "deepseek-v4-pro", "입력토큰": 10000, "캐시토큰": 0,
         "출력토큰": 1000, "생각토큰": 800, "시각": 토},
        {"열쇠": "판정", "걸음": 1, "모델": "deepseek-flash", "입력토큰": 1000, "캐시토큰": 0, "출력토큰": 10,
         "생각토큰": 0, "시각": 토},
        {"열쇠": "지휘", "걸음": 2, "단계": "③", "모델": "deepseek-v4-pro", "입력토큰": 20000, "캐시토큰": 10000,
         "출력토큰": 2000, "생각토큰": 1500, "시각": 토},
        {"열쇠": "판정", "걸음": None, "모델": "deepseek-flash", "입력토큰": 2000, "캐시토큰": 0, "출력토큰": 20,
         "생각토큰": 0, "시각": 토}],
        "아피파이기록": [{"도구": "x_search", "걸음": 1, "돈": 0.01}, {"도구": "web_search", "걸음": 2, "돈": 0.0055}],
        "호출기록": [{"도구": "x_search", "걸음": 1}, {"도구": "view_images", "걸음": 1}, {"도구": "web_search", "걸음": 2}]}
    줄들 = cost.걸음별(재료)
    assert [(x["걸음"], x["단계"], x["생각토큰"], x["도구"]) for x in 줄들] == [
        (1, "①", 800, ["x_search", "view_images"]), (2, "③", 1500, ["web_search"]), (None, "검증·정리", 0, [])]
    assert 줄들[0] == {**줄들[0], "딥시크": 0.0087, "아피파이": 0.01, "합계": 0.0187}
    assert 줄들[1]["합계"] == round(10000 * 0.66e-6 + 10000 * 0.022e-6 + 2000 * 1.98e-6 + 0.0055, 4)
    assert 줄들[2]["합계"] == round(2000 * 0.15e-6 + 20 * 0.6e-6, 4)
    assert cost.걸음별({}) == []
