def test_한_장에_사람_말부터_관문까지_차례로():
    쪽 = trace_view.화면(*견본())
    차례 = ["코르티스 소식 보고 싶어 &lt;b&gt;", "기간이 안 정해졌다", "1걸음 · ① 이해하기 · 한도 20,000", "12:00:10",
          "공식 계정부터 찾자",
          "x_search", "판정관 (1걸음)", "[그림] (그림 base64 5,023자 — 생략)", "구간 끝 — 냄", "<summary>관문</summary>", "뮤직비디오 공개"]
    자리 = [쪽.find(x) for x in 차례]
    assert all(i >= 0 for i in 자리), [x for x, i in zip(차례, 자리) if i < 0]
    assert 자리 == sorted(자리)
    assert "<b>" not in 쪽  # 사람이 친 말은 글자 그대로(태그로 안 먹힌다)
    assert "prefers-color-scheme: dark" in 쪽


def test_사건들은_쓴_차례대로_읽고_파일이름을_단다():
    s3 = 가짜S3()
    for 키, 종류 in (("2-000001-b-지휘.json", "지휘"), ("1-000000-a-다듬기.json", "다듬기"), ("3-000002-c-관문.json", "관문")):
        s3.put_object(Bucket="통", Key=f"weekly/trace/j1/{키}", Body=json.dumps({"종류": 종류}, ensure_ascii=False))
    s3.put_object(Bucket="통", Key="weekly/trace/j10/1-000000-z-지휘.json", Body="{}")  # 앞머리가 겹치는 다른 판
    xs = trace_view.사건들(s3, "j1")
    assert [(x["종류"], x["_키"]) for x in xs] == [("다듬기", "1-000000-a-다듬기.json"), ("지휘", "2-000001-b-지휘.json"),
                                                 ("관문", "3-000002-c-관문.json")]
