# -*- coding: utf-8 -*-
from datetime import date

import pytest

from topic import order

오늘 = date(2026, 10, 1)  # 목요일


def 원본(**바꿀것):
    d = {"주제": "코르티스(CORTIS)", "범위": "그룹 + 멤버 개인", "기간": {"말": "이번 주", "종류": "이번주"},
         "넣을것": ["컴백", "음악방송"], "뺄것": "팬 잡담, 루머", "목표건수": 6, "한장단위": "소식 하나",
         "분야이름": "코르티스", "등급": "b"}
    d.update(바꿀것)
    return d


@pytest.mark.parametrize("기간, 기대", [
    ({"종류": "이번주"}, ("2026-09-28", "2026-10-04")),
    ({"종류": "지난주"}, ("2026-09-21", "2026-09-27")),
    ({"종류": "최근N일", "N": 7}, ("2026-09-25", "2026-10-01")),
    ({"종류": "이번달"}, ("2026-10-01", "2026-10-31")),
    ({"종류": "지난달"}, ("2026-09-01", "2026-09-30")),
    ({"종류": "직접", "시작": "2026-09-21", "끝": "2026-09-27"}, ("2026-09-21", "2026-09-27")),
])
def test_기간_말을_날짜로(기간, 기대):
    assert order.기간계산(기간, 오늘) == 기대


def test_다듬은_주문서_모양():
    d = order.다듬기(원본(), 오늘)
    assert (d["시작"], d["끝"], d["기간말"]) == ("2026-09-28", "2026-10-04", "이번 주")
    assert d["뺄것"] == ["팬 잡담", "루머"] and d["넣을것"] == ["컴백", "음악방송"]
    assert d["등급"] == "B" and d["예산"] == {"호출": 50, "돈": 2.0, "분": 40}


@pytest.mark.parametrize("바꿀것, 말", [
    ({"기간": {"종류": "직접", "시작": "2026-10-05", "끝": "2026-10-10"}}, "아직 오지 않은"),
    ({"기간": {"종류": "직접", "시작": "2026-08-31", "끝": "2026-10-01"}}, "32일"),
    ({"기간": {"종류": "최근N일", "N": 32}}, "1~31일"),
    ({"기간": {"종류": "다음주"}}, "기간 종류"),
    ({"분야이름": "가나다라마바사아자차카타"}, "12자"),
    ({"분야이름": ""}, "분야 이름"),
    ({"주제": " "}, "주제"),
    ({"목표건수": 12}, "3~8건"),
    ({"등급": "S"}, "A·B·C"),
])
def test_미래_긴기간_긴이름은_거절(바꿀것, 말):
    with pytest.raises(order.주문서탈, match=말):
        order.다듬기(원본(**바꿀것), 오늘)
