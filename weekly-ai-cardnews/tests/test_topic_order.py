# -*- coding: utf-8 -*-
from datetime import date

import pytest

from topic import order

오늘 = date(2026, 10, 1)  # 목요일


def 원본(**바꿀것):
    d = {"주제": "코르티스(CORTIS)", "범위": "그룹 + 멤버 개인", "기간": {"말": "이번 주", "종류": "이번주"},
         "넣을것": ["컴백", "음악방송"], "뺄것": "팬 잡담, 루머", "목표건수": 6, "한장단위": "소식 하나",
         "분야이름": "코르티스", "등급": "b"}
    d.update(바꿀것)
    return d


@pytest.mark.parametrize("기간, 기대", [
    ({"종류": "이번주"}, ("2026-09-28", "2026-10-04")),
    ({"종류": "지난주"}, ("2026-09-21", "2026-09-27")),
    ({"종류": "최근N일", "N": 7}, ("2026-09-25", "2026-10-01")),
    ({"종류": "이번달"}, ("2026-10-01", "2026-10-31")),
    ({"종류": "지난달"}, ("2026-09-01", "2026-09-30")),
    ({"종류": "직접", "시작": "2026-09-21", "끝": "2026-09-27"}, ("2026-09-21", "2026-09-27")),
])
def test_기간_말을_날짜로(기간, 기대):
    assert order.기간계산(기간, 오늘) == 기대


def test_다듬은_주문서_모양():
    d = order.다듬기(원본(), 오늘)
    assert (d["시작"], d["끝"], d["기간말"]) == ("2026-09-28", "2026-10-04", "이번 주")
    assert d["뺄것"] == ["팬 잡담", "루머"] and d["넣을것"] == ["컴백", "음악방송"]
    assert d["등급"] == "B" and d["예산"] == {"호출": 50, "돈": 2.0, "분": 40}


@pytest.mark.parametrize("바꿀것, 말", [
    ({"기간": {"종류": "직접", "시작": "2026-10-05", "끝": "2026-10-10"}}, "아직 오지 않은"),
    ({"기간": {"종류": "직접", "시작": "2026-08-31", "끝": "2026-10-01"}}, "32일"),
    ({"기간": {"종류": "최근N일", "N": 32}}, "1~31일"),
    ({"기간": {"종류": "다음주"}}, "기간 종류"),
    ({"분야이름": "가나다라마바사아자차카타파하가나다라마바사"}, "21자"),
    ({"분야이름": ""}, "분야 이름"),
    ({"주제": " "}, "주제"),
    ({"목표건수": 12}, "3~8건"),
    ({"등급": "S"}, "A·B·C"),
])
def test_미래_긴기간_긴이름은_거절(바꿀것, 말):
    with pytest.raises(order.주문서탈, match=말):
        order.다듬기(원본(**바꿀것), 오늘)


def test_분야_이름은_20자까지_넉넉하게():
    # 11자(표지 2행 폭)는 아직 없는 새 분야 카드를 위해 미리 건 제한이었다 — 사용자 «넉넉하게»(2026-10-03)
    assert order.분야이름최대 == 20
    o = order.다듬기(원본(분야이름="하츠투하츠 멤버 개인 활동 소식"), 오늘)  # 17자
    assert o["분야이름"] == "하츠투하츠 멤버 개인 활동 소식"


def test_주문서는_프로필을_받지_않는다():
    # 카드뉴스는 기간 안 소식 전달용 — MBTI 같은 기본 정보는 찾지 않는다(사용자 2026-10-04)
    assert "프로필" not in order.다듬기(원본(프로필=["멤버별 MBTI"]), 오늘)


def test_주차는_이번_주부터_3주_전까지():
    # 저장한 분야의 «몇 월 몇 주차» — 사용자 «어»(2026-10-04, 최근 4주 안)
    assert [order.기간계산({"종류": "주차", "앞": 앞}, 오늘) for 앞 in range(4)] == [
        ("2026-09-28", "2026-10-04"), ("2026-09-21", "2026-09-27"), ("2026-09-14", "2026-09-20"),
        ("2026-09-07", "2026-09-13")]
    for 틀린 in (4, -1, "1", None, True, 1.0):
        with pytest.raises(order.주문서탈, match="주차는"):
            order.기간계산({"종류": "주차", "앞": 틀린}, 오늘)
