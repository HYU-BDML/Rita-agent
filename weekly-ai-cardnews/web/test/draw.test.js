test("대화·지갑·주소", () => {
  assert.equal(대화줄({ who: "사람", text: "코르티스" }), "나: 코르티스");
  assert.equal(대화줄({ who: "지휘자", text: "어느 기간?" }), "지휘자: 어느 기간?");
  const 넉넉 = { apify: { 쓸수있는합: 9, 낮음: false, 멈춤: false }, deepseek: { 남은: 56, 멈춤: false } };
  assert.equal(지갑띠글(넉넉), "");
  assert.equal(지갑띠글({ ...넉넉, apify: { 쓸수있는합: 1.5, 낮음: true, 멈춤: false } }), "이번 달 자료 모으기 분량이 얼마 안 남았어요 (약 $1.50) — 다 쓰면 새 분야는 잠시 쉬어요");
  assert.match(지갑띠글({ ...넉넉, apify: { 쓸수있는합: 0.5, 낮음: true, 멈춤: true } }), /새 분야는 잠시 쉬어요 — AI 소식은 그대로/);
  assert.equal(새분야막힘({ ...넉넉, deepseek: { 남은: 3, 멈춤: true } }), true);
  assert.equal(새분야막힘(null), false);
  assert.equal(안전주소("javascript:alert(1)"), "");
  assert.equal(안전주소("https://x.com/a"), "https://x.com/a");
});

