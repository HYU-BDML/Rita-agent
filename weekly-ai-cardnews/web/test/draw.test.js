  assert.equal(총시간줄({ ...주제판, state: "됨", updated: "2026-09-30T03:00:00Z", cost: c }),
    "총 걸린 시간: 20분 24초 · 쓴 돈 약 $0.83 (딥시크 $0.52 · 자료 수집 $0.31)");
