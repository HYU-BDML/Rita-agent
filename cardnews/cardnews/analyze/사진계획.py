def 시스템짓기(화풍지정: str = "") -> str:
    """계획 AI 에게 주는 시스템 글. 사람이 화풍을 골랐으면 목록 대신 그 이름만 준다."""
    x = 화풍.찾기(화풍지정)
    if x:
        화풍줄 = f"화풍은 사람이 정했다: «{x['이름']}». \"화풍후보\" 는 적지 않는다."
        목록 = ""
    else:
        화풍줄 = _고르라
        목록 = "\n\n화풍 목록:\n" + 화풍.목록줄()
    return _머리.replace("(화풍줄)", 화풍줄) + 목록 + "\n\n" + _표시말 + "\n\n" + _답꼴


def 자리말(자리: dict, 캔버스=캔버스기본) -> str:
    """자리 네모를 **말로** 한다 — 「큰 자리, 위쪽, 가로로 긴 꼴(1.80:1)」.

    모델에게 좌표를 주면 산수를 시키는 꼴이 된다. 크기·위치·꼴은 코드가 뽑는다.
    """
    b = 자리.get("box")
    if not (b and len(b) == 4):
        return "크기 모름"
    w, h = max(1.0, float(b[2]) - float(b[0])), max(1.0, float(b[3]) - float(b[1]))
    몫 = (w * h) / (캔버스[0] * 캔버스[1])
    크기 = "큰 자리" if 몫 >= 0.35 else "중간 자리" if 몫 >= 0.12 else "작은 자리"
    가운데 = (float(b[1]) + float(b[3])) / 2 / 캔버스[1]
    위치 = "위쪽" if 가운데 < 1 / 3 else "아래쪽" if 가운데 > 2 / 3 else "가운데"
    비 = w / h
    꼴 = ("가로로 긴 꼴" if 비 >= 1.25 else "세로로 긴 꼴" if 비 <= 0.8
         else "정사각에 가까운 꼴") + f"({비:.2f}:1)"
    쪽 = [크기, 위치, 꼴]
    if 자리.get("배경자리"):
        쪽.append("장 전체를 덮는 배경")
    if 자리.get("누끼"):
        쪽.append("배경을 뺀 피사체만")
    설명 = str(자리.get("설명") or "").strip()
    if 설명:
        쪽.append(f"틀 설명 「{설명}」")
    return ", ".join(쪽)


def _틀읽기(틀_json: str) -> dict:
    try:
        틀 = json.loads(틀_json or "{}")
    except Exception:  # noqa: BLE001 — 힌트는 없어도 된다
        return {}
    return 틀 if isinstance(틀, dict) else {}


def 틀힌트(틀_json: str) -> str:
    """틀에서 이미 재 둔 것 셋 — 강조색·첫 장 배경·글꼴. 결을 맞추는 데 쓴다."""
    틀 = _틀읽기(틀_json)
    쪽 = []
    if 틀.get("강조색"):
        쪽.append(f"강조색 {틀['강조색']}")
    장들 = 틀.get("슬라이드") or []
    첫 = 장들[0] if 장들 and isinstance(장들[0], dict) else {}
    배경 = 첫.get("배경") or {}
    if isinstance(배경, dict) and 배경.get("hex"):
        쪽.append(f"첫 장 배경 {배경['hex']}")
    슬롯 = 첫.get("글자슬롯") or []
    if 슬롯 and isinstance(슬롯[0], dict) and 슬롯[0].get("font"):
        쪽.append(f"글꼴 {슬롯[0]['font']}")
    return ", ".join(쪽)


def 강조색(틀_json: str) -> str:
    """틀의 강조색(`#RRGGBB`). 색 하나를 쓰는 화풍(497·513)이 그 색으로 그린다. 없으면 빈 글자."""
    값 = str(_틀읽기(틀_json).get("강조색") or "").strip()
    return 값 if re.fullmatch(r"#[0-9A-Fa-f]{6}", 값) else ""


def _사진자리인가(r: dict) -> bool:
    return (r or {}).get("종류") in 사진만들기.사진종류


def _찼나(r: dict) -> bool:
    return bool(str((r or {}).get("media_url") or "").strip())


def 계획자리(카드들: list) -> list:
    """계획할 자리 — 사진 자리인데 아직 사진이 없는 것. `(장, 자리)` 는 0부터.

    표지 밈 자리도 센다 — 그 자리만 있는 판이라도 화풍은 골라야 한다."""
    return [{"장": ci, "자리": ri}
            for ci, 카드 in enumerate(카드들 or [])
            for ri, r in enumerate((카드 or {}).get("장식영역") or [])
            if _사진자리인가(r) and not _찼나(r)]


def _넓이(r: dict, 캔버스=캔버스기본) -> float:
    b = r.get("box")
    if b and len(b) == 4:
        return max(0.0, float(b[2]) - float(b[0])) * max(0.0, float(b[3]) - float(b[1]))
    return float(캔버스[0] * 캔버스[1]) if r.get("배경자리") else 0.0


def 밈자리(카드들: list) -> set:
    """표지마다 **가장 큰 사진 자리** 하나 — 여기는 표지 밈으로 그린다. `(장, 자리)` 0부터.

    넓이가 같으면 앞의 것(`max` 는 처음 것을 남긴다). 네모가 없는 배경 자리는 장 전체로 친다.
    """
    난것 = set()
    for ci, 카드 in enumerate(카드들 or []):
        if not 사진만들기.표지인가(카드):
            continue
        자리들 = [(ri, r) for ri, r in enumerate((카드 or {}).get("장식영역") or [])
                if _사진자리인가(r)]
        if 자리들:
            ri, _ = max(자리들, key=lambda x: _넓이(x[1]))
            난것.add((ci, ri))
    return 난것


def 입력짓기(카드들: list, 주제: str, 원고: str = "", 힌트: str = "",
         참조들: list | None = None, 바람: str = "", 캔버스=캔버스기본) -> str:
    """모델에게 줄 사용자 글. **번호는 1부터, 자리 번호는 `장식영역` 차례 그대로.**

    도형·로고를 건너뛰어도 번호를 안 당긴다 — 돌려받은 번호로 그 자리를 바로
    찾아야 한다.
    """
    줄 = [f'카드뉴스 주제: "{주제}"']
    if 원고:
        줄.append(f"원고(앞부분): {원고[:원고상한]}")
    if 힌트:
        줄.append(f"틀의 결 힌트: {힌트}")
    if 바람:
        줄.append(f'사람의 바람: "{바람}"')
    참조들 = [x for x in (참조들 or []) if str((x or {}).get("주소") or "").strip()]
    if 참조들:
        줄.append(f"\n참조 사진 {len(참조들)}장 (번호로 부른다):")
        for i, x in enumerate(참조들, start=1):
            줄.append(f"{i}번: {str(x.get('본것') or '무엇인지 못 읽음').strip()}")
    밈 = 밈자리(카드들)
    for ci, 카드 in enumerate(카드들 or [], start=1):
        역할 = str((카드 or {}).get("역할") or "본문")
        줄.append(f'\n장 {ci} (역할 {역할}) — 글: "{사진만들기._글줄(카드)}"')
        자리있음 = False
        for ri, r in enumerate((카드 or {}).get("장식영역") or [], start=1):
            if not _사진자리인가(r):
                continue
            자리있음 = True
            if _찼나(r):
                줄.append(f"  자리 {ri}: 사람 사진이 이미 들어감 — 계획하지 않는다")
            elif (ci - 1, ri - 1) in 밈:
                줄.append(f"  자리 {ri}: 표지 밈 자리 — 한줄은 안 적는다 ({자리말(r, 캔버스)})")
            else:
                줄.append(f"  자리 {ri}: {자리말(r, 캔버스)}")
        if not 자리있음:
            줄.append("  (사진 자리 없음)")
    return "\n".join(줄)


def _JSON만(글: str) -> str:
    """앞뒤에 붙은 말이나 ```json 울타리를 걷어낸다(`사진읽기._JSON만` 과 같은 결)."""
    글 = str(글 or "").strip()
    처음, 끝 = 글.find("{"), 글.rfind("}")
    return 글[처음:끝 + 1] if 0 <= 처음 < 끝 else "{}"


def _정수(x) -> bool:
    return isinstance(x, int) and not isinstance(x, bool)


def 계획읽기(글: str, 카드들: list, 참조들: list | None = None) -> dict | None:
    """모델 답을 읽어 **쓸 수 있는 것만** 남긴다. 번호는 0부터로 바꾼다.

    모델은 없는 자리 번호·같은 자리 둘·글자 번호·빈 줄·목록 밖 화풍을 다 한다. 틀린
    줄만 버리고 나머지는 산다. 아무것도 안 남으면 `None` — «계획 없음» 이다.
    """
    try:
        난것 = json.loads(_JSON만(글))
    except Exception:  # noqa: BLE001 — 깨진 답은 계획 없음
        return None
    if not isinstance(난것, dict):
        return None
    참조주소 = [str((x or {}).get("주소") or "").strip() for x in (참조들 or [])]
    결 = str(난것.get("결") or "").strip()[:결상한]

    # AI 가 고를 수 있는 것만 후보로 남긴다 — «기본» 은 사람만 고른다(미리보기 「AI 추천」 표가 거짓이 된다).
    후보 = []
    for 값 in 난것.get("화풍후보") or []:
        아이디 = 화풍.이름으로(값)
        if 아이디 and 화풍.찾기(아이디)["AI후보"] and 아이디 not in 후보:
            후보.append(아이디)

    인물, 이름들 = [], set()
    for x in 난것.get("인물") or []:
        if not isinstance(x, dict):
            continue
        이름 = str(x.get("이름") or "").strip()[:30]
        생김새 = str(x.get("생김새") or "").strip()[:생김새상한]
        if 이름 and 생김새 and 이름 not in 이름들 and len(인물) < 인물상한:
            이름들.add(이름)
            인물.append({"이름": 이름, "생김새": 생김새})

    밈 = 밈자리(카드들)
    자리들, 본것 = [], set()
    for 장묶음 in 난것.get("장별") or []:
        if not isinstance(장묶음, dict):
            continue
        장 = 장묶음.get("장")
        if not (_정수(장) and 1 <= 장 <= len(카드들 or [])):
            continue
        영역 = ((카드들[장 - 1] or {}).get("장식영역") or [])
        for x in 장묶음.get("자리") or []:
            if not isinstance(x, dict):
                continue
            자리 = x.get("자리")
            if not (_정수(자리) and 1 <= 자리 <= len(영역)):
                continue
            # **빈 사진 자리가 아니면 버린다**(검토 2026-09-29) — 살려 두면 참조만 «쓴 것»
            # 으로 세져 사진이 화면에서 통째로 사라진다.
            if not (_사진자리인가(영역[자리 - 1]) and not _찼나(영역[자리 - 1])):
                continue
            곳 = (장 - 1, 자리 - 1)
            if 곳 in 본것:
                continue
            참조 = x.get("참조")
            주소 = 참조주소[참조 - 1] if _정수(참조) and 1 <= 참조 <= len(참조주소) else ""
            if 곳 in 밈:
                # 밈 자리는 한 줄을 안 쓴다. 참조를 줄 때만 산다.
                if not 주소:
                    continue
                한줄 = ""
            else:
                한줄 = str(x.get("한줄") or "").strip()[:한줄상한]
                if not 한줄:
                    continue
            등장 = []
            for n in x.get("등장") or []:
                n = n.strip() if isinstance(n, str) else ""
                if n in 이름들 and n not in 등장:
                    등장.append(n)
            본것.add(곳)
            자리들.append({"장": 곳[0], "자리": 곳[1], "한줄": 한줄, "참조": 주소, "등장": 등장})

    if not (자리들 or 결 or 후보 or 인물):
        return None
    return {"결": 결, "화풍후보": 후보, "인물": 인물, "자리": 자리들}


def 적용(카드들: list, 계획: dict) -> int:
    """계획을 카드에 써 넣는다. **카드는 그 자리에서 고쳐진다.** 써 넣은 자리 수.

    사진이 이미 든 자리와 사진 아닌 자리는 안 건드린다. 틀 설명은 덮는다 — 틀 파일에
    살아 있고 판마다 새로 복사되므로 잃는 것이 없다(설계 §2.5). 한 줄이 빈 줄(밈 자리)은
    설명을 안 쓴다 — 비어 있어야 표지 밈으로 그려진다.
    """
    n = 0
    for x in (계획 or {}).get("자리") or []:
        try:
            r = 카드들[x["장"]]["장식영역"][x["자리"]]
        except (IndexError, KeyError, TypeError):
            continue
        if not _사진자리인가(r) or _찼나(r):
            continue
        if x.get("한줄"):
            r["설명"] = x["한줄"]
        if x.get("참조"):
            r["참조"] = x["참조"]
        if x.get("등장"):
            r["등장"] = list(x["등장"])
        n += 1
    return n


def 짓기(카드들: list, 주제: str, 원고: str = "", 힌트: str = "",
       참조들: list | None = None, 바람: str = "", 화풍지정: str = "",
       부르기=None, 마감=None, 뽑기=random.choice) -> dict | None:
    """딥시크를 **한 번** 불러 계획을 받고 카드에 써 넣는다. 돌려주는 것은 계획이다.

    계획에 `"화풍"` 을 붙인다 — 사람이 골랐으면 그것, 아니면 AI 후보에서 코드가 뽑은 것.
    **자리가 없으면 안 부른다** — 돈도 시간도 안 쓴다. **못 짜면 `None`** — 설명이 빈
    자리는 지금 틀로 만든다. 카드는 안 죽는다.
    """
    자리들 = 계획자리(카드들)
    if not 자리들:
        return None
    부르기 = 부르기 or 대본짓기.부르기
    try:
        글 = 부르기(시스템짓기(화풍지정), 입력짓기(카드들, 주제, 원고, 힌트, 참조들, 바람),
                 최대토큰=계획토큰, 마감=마감)
        계획 = 계획읽기(글, 카드들, 참조들)
    except Exception as e:  # noqa: BLE001 — 계획 때문에 카드뉴스를 죽이지 않는다
        print(f"!! 사진 계획을 못 짰다: {type(e).__name__} — 계획 없이 간다")
        return None
    if not 계획:
        print("!! 사진 계획이 비어 왔다 — 계획 없이 간다")
        return None
    계획["화풍"] = 화풍.지정받기(화풍지정) or 화풍.고르기(계획["화풍후보"], 뽑기)
    n = 적용(카드들, 계획)
    print(f"++ 사진 계획 {n}/{len(자리들)}자리 · 화풍 {계획['화풍']} "
          f"(후보 {', '.join(계획['화풍후보']) or '없음'}) · 인물 {len(계획['인물'])}")
    return 계획
