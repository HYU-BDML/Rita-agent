        # 그림 없음」 다섯 자만 남아서, 18장 중 7장이 왜 빈손으로 왔는지 로그로
        # 영영 알 수 없었다.
        #
        # **무엇을 달라고 했는지도 같이 적는다** — 크기나 품질이 원인이면 그 줄만
        # 봐도 갈린다.
        raise 그림없음(f"fal 그림 없음 · {폭}x{높} {품질}"
                   f"{' 누끼' if 누끼 else ''} · 답={_간추리기(결과)}"
                   f" · 상태={_간추리기(s)}")
