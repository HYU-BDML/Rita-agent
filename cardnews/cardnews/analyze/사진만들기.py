        # **사진 단계 전체 시계.** 줄이 아무리 길어도 여기서는 손을 뗀다 — 람다가
        # 900초에 끊기므로, 사진 몇 장이 비는 편이 판 전체가 날아가는 것보다 낫다.
        if 마감 is not None and time.monotonic() >= 마감:
            취소(접수)
            raise RuntimeError("사진 단계 시간이 다 됐다 — 줄에서 뺐다")
        # **사람이 그만두라고 했으면 줄에서 뺀다**(2026-09-24).
        #
        # **여기가 돈을 아끼는 자리다.** fal 문서: 줄에 있을 때 취소하면 「즉시
