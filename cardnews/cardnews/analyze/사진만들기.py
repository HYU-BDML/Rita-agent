    접수["_품질"] = 품질
    접수["_크기"] = f"{폭}x{높}"
    접수["_누끼"] = bool(누끼)
    # **벽시계로 끊는다**(실물 2026-09-20). 여태는 «90번 물어보기» 로 셌는데,
    # 한 번 물어보는 데 최대 60초를 기다리므로 **실제로는 90분까지 갈 수 있었다.**
    # 실측에서 한 장이 3분 48초 걸렸다 — 나머지 여섯은 17~24초였다.
    #
    # 물어보는 시간도 15초로 줄인다. 「다 됐나」를 묻는 것뿐이라 60초를 기다릴
    # 까닭이 없고, 그 60초가 바로 벽시계를 넘기던 자리다.
    # **줄 서 있는 시간은 안 센다**(2026-09-24). fal 은 한도를 넘으면 거절하지
    # 않고 큐에 세우는데, 그 기다림까지 이 시계에 넣으면 **사람이 몰렸을 때 차례가
    # 오기도 전에 우리가 먼저 포기하고 사진을 빈칸으로 만든다.**
    #
