    if 누끼:
        # 칸(`background: transparent`)만으로는 모자란다 — 모델이 배경째 그려 놓고 그 위에
        # 투명을 씌우는 일이 있어서 말로도 같이 시킨다. 사람이 체크한 자리에만 붙는다.
        쪽.append(누끼줄)
    # **줄을 나눠 쌓는다**(사람이 정한 꼴 2026-09-20). 한 줄로 이어 붙이면 「주제」와
    # 「시킴」이 한 문장처럼 보인다 — 주제가 긴 날에는 어디까지가 주제인지 모델이 가리기 어렵다.
    return chr(10).join(쪽)


