def 채울자리(카드들: list) -> list:
    """**아직 사진이 없고 채워야 할** 자리를 `(자리, 그 장)` 짝으로 모은다.

    자리와 «그 자리가 있는 장» 을 같이 준다 — 지시문은 그 장의 글을 봐야 짓는다.

    **밖에서도 센다**(2026-09-24). 굽기가 사진을 만든 «뒤» 에 다시 불러서 몇
    자리가 빈 채로 남았는지 안다. 세는 규칙이 두 군데로 갈리면 화면에 뜨는
    숫자와 실제가 어긋나므로 여기 하나만 둔다.
    """
    return [(r, 카드) for 카드 in (카드들 or [])
            for r in (카드.get("장식영역") or [])
            if r.get("종류") in 사진종류 and not str(r.get("media_url") or "").strip()
            # **건너뛸 역할이라도 «설명» 이 적힌 자리는 만든다.** 빈 칸은 안 센다 —
            # 라벨판에서 칸만 열고 안 적은 자리가 다 뚫리면 안 된다.
            and (카드.get("역할") not in 건너뛸역할
                 or str(r.get("설명") or "").strip())]


# «첫 그림 기준» 에서 한 자리가 받는 인물 기준 그림 수의 상한. 넘으면 앞에서부터.
기준참조상한 = 4


def _등장(자리: dict) -> list:
    """그 자리에 나오는 인물 이름들. **설명이 빈 자리는 없다고 본다**(2026-09-29 검토 M-6) —
    사람이 미리보기에서 설명을 지운 것은 «기본으로 돌아가라» 라, 계획했던 인물이 계속
    나오면 안 된다."""
    if not str((자리 or {}).get("설명") or "").strip():
        return []
    return list((자리 or {}).get("등장") or [])


def 등장줄(자리: dict, 인물: dict | None) -> str:
    """그 자리에 나오는 인물의 생김새 — 「지미 = …; 판사 = …」. 없으면 빈 글자.

    인물표(`사진계획`)의 생김새를 **글자 그대로** 붙인다. 자리마다 따로 쓰게 두면 장마다
    딴 사람이 된다(설계 §10.3)."""
    인물 = 인물 or {}
    return "; ".join(f"{n} = {인물[n]}" for n in _등장(자리) if n in 인물)


def 기준자리(자리카드: list, 인물: dict | None, 이미=()) -> dict:
    """인물마다 **처음 나오는 자리** — `{id(자리): [이름, …]}`.

    «첫 그림 기준»(사람 결정 2026-09-29): 이 자리들을 먼저 굽고, 그 인물이 또 나오는 자리는
    그 그림을 IMAGE 참조로 받는다. 사람이 올린 참조가 있는 자리는 기준이 못 된다 — 그
    자리는 사람 사진을 따른다. `이미` 는 첫 그림이 벌써 박혀 있는 인물이다(`박힌기준`) —
    그 인물은 새 기준을 안 세운다."""
    인물 = 인물 or {}
    본것, 기준 = set(이미), {}
    for 자리, _ in 자리카드:
        if str(자리.get("참조") or "").strip():
            continue
        for n in _등장(자리):
            if n in 인물 and n not in 본것:
                본것.add(n)
                기준.setdefault(id(자리), []).append(n)
    return 기준


def 박힌기준(카드들: list, 인물: dict | None) -> dict:
    """이미 사진이 박힌 자리에서 인물의 첫 그림을 찾는다 — `{이름: 주소}`.

    **빈 자리만 다시 만들 때 쓴다**(2026-09-29 검토 M-2). 1차에서 지미 첫 그림이 박혔는데
    2차에서 그것을 안 보면, 다시 만든 자리의 지미는 얼굴이 달라진다. 사람이 올린 사진은
    `등장` 이 없어 안 걸린다. 사람 참조로 만든 자리는 기준으로 안 쓴다(`기준자리` 와 같은 잣대)."""
    인물 = 인물 or {}
    기준주소: dict = {}
    for 카드 in 카드들 or []:
        for r in (카드 or {}).get("장식영역") or []:
            주소 = str(r.get("media_url") or "").strip()
            if not 주소 or str(r.get("참조") or "").strip():
                continue
            for n in _등장(r):
                if n in 인물 and n not in 기준주소:
                    기준주소[n] = 주소
    return 기준주소


def 채우기(카드들: list, 주제: str, 부르기=부르기, 잔액보기=잔액, 알림=None,
        예산초: float = None, 꽂힘=None, 그만인가=None, 결: str = "",
        화풍문장: str = "", 인물: dict | None = None) -> int:
    """장식영역의 사진 자리마다 그림을 하나씩 만들어 `media_url` 에 박는다.

    돌려주는 것은 **실제로 박은 장 수** 다. 카드들은 그 자리에서 고쳐진다.

    `결` 은 판 전체의 사진 결 한 줄이다(`사진계획`). 자리마다 지시문에 실린다.

    `화풍문장` 은 판 전체의 화풍 한 덩이(`화풍.문장`), `인물` 은 인물표 `{이름: 생김새}` 다
    (사람 결정 2026-09-29). 둘 다 비면 여태와 똑같이 돈다.

    **첫 그림 기준.** 인물표가 있고 자리에 `등장` 이 있으면 두 판으로 굽는다 — 인물이 처음
    나오는 자리를 먼저, 나머지는 그 그림을 IMAGE 참조로 받아(`편집끝점`) 같은 얼굴·옷으로.
    기준 그림이 실패하면 나머지는 생김새 글로만 그린다. 값은 같고 첫 판만큼 시간이 는다.

    이미 `media_url` 이 있는 자리는 안 건드린다 — 사람이 넣은 것이나 자리표가
    가리키는 것이 더 세다.

    `예산초` 는 **이 일에 쓸 수 있는 시간**이다(2026-09-24). 안 주면 `사진전체상한`
    (600초)을 그대로 쓴다.

    **람다가 죽을 시각을 부르는 쪽이 안다.** 여태 여기는 제 시계만 보고 600초를
    셌는데, 람다는 900초에 **강제로** 끊긴다. 끊기면 그때까지 만든 사진이 메모리째
    날아간다 — 값은 이미 나갔는데 남는 것이 없다. 그래서 부르는 쪽이 「이만큼만
    쓰라」고 일러 주고, 여기는 그 앞에서 스스로 손을 뗀다. 못 만든 자리는 빈 채로
    두고 **되는 데까지 구워서** 낸다.

    `그만인가()` 가 참을 내면 **더 안 만들고 손을 뗀다**(2026-09-24). 줄에서
    기다리는 것은 fal 에서 빼므로 그만큼 값이 안 나간다. 이미 만든 것은 그대로
    두고, 부르는 쪽이 되는 데까지 굽는다.

    `꽂힘(장번호, 자리번호, 주소)` 은 **한 장이 꽂힐 때마다** 부른다(2026-09-24).
    번호는 `카드들[장번호]["장식영역"][자리번호]` 를 가리키는 0부터의 차례다.

    **화면이 기다리는 동안 채워 보여 주려고 있다.** 여태는 다 끝나야 한 번에
    나왔다 — 사진 일곱 장이면 3분을 빈 자리만 보고 기다렸다.
    """
    알림 = 알림 or (lambda *_: None)
    자리카드 = 채울자리(카드들)
    if not 자리카드:
        return 0
    if 잔액보기() <= 0:
        raise 돈없음("fal 잔액이 없습니다 — 사진을 만들 수 없어요")

    시작 = time.monotonic()
    쓸시간 = 사진전체상한 if 예산초 is None else min(사진전체상한, max(0.0, 예산초))
    if 쓸시간 < 사진전체상한:
        print(f"++ 사진에 쓸 시간은 {쓸시간:.0f}초다 (람다가 곧 끝난다)")
    마감 = 시작 + 쓸시간

    인물 = {k: v for k, v in (인물 or {}).items() if k and v}
    # 이름 → 그 인물의 첫 그림 주소. 이미 박힌 첫 그림(빈 자리만 다시 만드는 판)으로 먼저
    # 채우고, 첫 판이 다 끝난 뒤 새 첫 그림을 더한다. **판이 도는 동안에는 쓰지 않는다** —
    # 여럿이 같이 읽기만 한다.
    기준주소: dict = 박힌기준(카드들, 인물)
    기준 = 기준자리(자리카드, 인물, 이미=set(기준주소))

    def 한자리(번호, 자리, 카드):
        """한 자리를 맡는다. **제 값만 세어 돌려준다** — 여럿이 같이 도니
        바깥 셈을 직접 건드리면 어긋난다."""
        # **기본은 «안 뺌». 라벨판에서 체크한 자리만 뺀다**(사람 지시
        # 2026-09-19: 「기본으로는 안빼고 체크해야 뺌」).
        누끼 = bool(자리.get("누끼"))
        # **장마다 고른다**(`품질고르기`). 지금은 표지도 본문도 미디움이라 같은
        # 값이 나오지만, 고르는 자리는 여기 하나로 둔다.
        이품질 = 품질고르기(카드)
        # **그 자리 비율로 만든다.** 네모를 모르는 자리(라벨 전·배경자리)는
        # 크기를 안 정하고 모듈 기본값에 맡긴다.
        b = 자리.get("box")
        크기 = (그림크기(b[2] - b[0], b[3] - b[1])
              if b and len(b) == 4 else None)
        # **사람이 올린 참조가 이긴다.** 없으면 이 자리 인물들의 첫 그림을 참조로 받는다.
        사람참조 = str(자리.get("참조") or "").strip()
        # **같은 그림은 한 번만 싣고 이름을 묶는다**(검토 I-4, 2026-09-29) — 둘이 처음 같이
        # 나온 그림을 두 번 실으면 같은 그림 두 장을 서로 다른 두 사람이라고 하는 꼴이다.
        그림참조: list = []           # [(주소, [이름, …])]
        if not 사람참조:
            for n in _등장(자리):
                u = 기준주소.get(n)
                if not u:
                    continue
                같은것 = next((묶음 for 묶음 in 그림참조 if 묶음[0] == u), None)
                if 같은것:
                    같은것[1].append(n)
                else:
                    그림참조.append((u, [n]))
            그림참조 = 그림참조[:기준참조상한]
        지시문 = 지시문짓기(주제, 카드, 자리, 누끼, 결=결, 화풍문장=화풍문장,
                       등장=등장줄(자리, 인물),
                       인물참조=["·".join(이름들) for _, 이름들 in 그림참조])
        참조 = [사람참조] if 사람참조 else [u for u, _ in 그림참조]
        # **참조가 있을 때만 그 인자를 준다**(2026-09-28). 늘 주면 `참조` 를 모르는
        # 옛 손(시험의 가짜 fal)이 깨진다 — 참조 없는 자리는 옛 꼴 그대로 부른다.
        더 = {"참조": 참조} if 참조 else {}
        # **빈손으로 오면 다시 부른다**(사람 지시 2026-09-22).
        #
        # `그림없음` 만 잡는다 — 시간 초과·통신 오류는 다시 불러도 같은 값만 더
        # 든다. **크기는 그대로 둔다**: 한때 크기를 의심했지만, 빈손으로 왔던
        # 지시문을 같은 크기로 여덟 번 불러 여덟 번 다 성공하는 것을 보고 접었다.
        주소, 쓴돈, 부른수 = "", 0.0, 0
        # **아직 안 걸었으면 걸지도 않는다.** 이미 그만두라고 했는데 새로 걸면
        # 그 한 장은 온전히 값이 나간다.
        if 그만인가 is not None and 그만인가():
            return 번호, 자리, "", 0.0, 0
        for 판 in range(1, 부를횟수 + 1):
            # **부른 값은 빈손으로 와도 나간다.** 성공한 것만 세면 로그에 찍히는
            # 값이 잔액에서 빠지는 값과 갈린다(여태 그랬다).
            쓴돈 += 어림값(이품질, 참조=bool(참조))
            부른수 += 1
            try:
                주소 = 부르기(지시문, 누끼=누끼, 품질=이품질, 크기=크기, 마감=마감,
                          그만인가=그만인가, **더)
                if 판 > 1:
                    print(f"++ 사진 {번호}/{len(자리카드)} {판}번째에 됐다")
                break
            except 그만뒀음:
                # **다시 안 부른다.** 그만두라고 했는데 또 걸면 값만 더 나간다.
                print(f"!! 사진 {번호}/{len(자리카드)} 그만뒀다")
                break
            except 그림없음 as e:
                if 판 < 부를횟수 and time.monotonic() < 마감:
                    print(f"!! 사진 {번호}/{len(자리카드)} {판}번째 빈손 — 다시 부른다: {e}")
                    continue
                print(f"!! 사진 {번호}/{len(자리카드)} 못 만듦({판}번 불렀다): {e}")
                break
            except Exception as e:  # noqa: BLE001 — 한 장이 실패해도 나머지는 만든다
                print(f"!! 사진 {번호}/{len(자리카드)} 못 만듦: {e}")
                break
        return 번호, 자리, 주소, 쓴돈, 부른수

    박은수, 쓴돈, 부른수, 끝난수 = 0, 0.0, 0, 0

    # 자리 하나가 «몇 번 장의 몇 번 자리» 인지 미리 적어 둔다 — 꽂힌 것을
    # 화면에 알릴 때 그 주소가 필요하다. 여럿이 같이 돌아도 이 표는 안 바뀐다.
    자리번호 = {id(r): (ci, ri)
            for ci, 카드 in enumerate(카드들 or [])
            for ri, r in enumerate(카드.get("장식영역") or [])}

    def 담기(난것):
        nonlocal 박은수, 쓴돈, 부른수, 끝난수
        번호, 자리, 주소, 든돈, 센수 = 난것
        쓴돈 += 든돈
        부른수 += 센수
        끝난수 += 1
        # **아무 글자나 안 박는다.** 그리는 쪽이 이것을 그대로 받아 부른다.
        if 주소 and not str(주소).startswith(("http://", "https://")):
            print(f"!! 사진 {번호}/{len(자리카드)} 주소가 이상하다")
            주소 = ""
        if 주소:
            자리["media_url"] = 주소
            박은수 += 1
            # **알림보다 먼저 적는다.** 알림이 번호표를 쓰므로, 뒤에 적으면
            # 이번에 꽂힌 사진이 한 판 늦게 화면에 뜬다.
            if 꽂힘 and id(자리) in 자리번호:
                꽂힘(*자리번호[id(자리)], 주소)
        # **알림은 맨 마지막이다** — 위에서 적은 것까지 같이 실어 보낸다.
        알림(끝난수, len(자리카드))

    def 돌리기(일감):
        """한 판을 건다(사람 결정 2026-09-24 「한꺼번에」).

        여태는 한 장이 끝나야 다음 장을 시작해서, 일곱 장에 213초가 걸렸다(실측
        2026-09-22). fal 은 한도를 넘어도 거절하지 않고 줄을 세우므로 **다 걸어 두고
        되는 대로 받으면 된다.** `동시일꾼 = 1` 이면 예전처럼 한 장씩 차례로 간다.
        """
        if not 일감:
            return
        일꾼수 = 동시일꾼 if 동시일꾼 > 0 else len(일감)
        if 일꾼수 <= 1:
            for 것 in 일감:
                담기(한자리(*것))
            return
        from concurrent.futures import ThreadPoolExecutor, as_completed  # noqa: PLC0415

        with ThreadPoolExecutor(max_workers=일꾼수) as 방:
            던진것 = [방.submit(한자리, *것) for 것 in 일감]
            for 된것 in as_completed(던진것):
                담기(된것.result())

    일감 = [(n, 자리, 카드) for n, (자리, 카드) in enumerate(자리카드, start=1)]
    첫판 = [것 for 것 in 일감 if id(것[1]) in 기준]
    뒤판 = [것 for 것 in 일감 if id(것[1]) not in 기준]
    일꾼 = 동시일꾼 if 동시일꾼 > 0 else len(일감)
    print(f"++ 사진 {len(일감)}장을 한꺼번에 건다 (일꾼 {일꾼})"
          if 일꾼 > 1 else f"++ 사진 {len(일감)}장을 한 장씩 만든다")
    if 첫판:
        print(f"++ 인물 기준 그림 {len(첫판)}장을 먼저 만든다 — 나머지 {len(뒤판)}장이 그 모습을 따른다")
        돌리기(첫판)
        for _, 자리, _ in 첫판:
            주소 = str(자리.get("media_url") or "")
            if 주소:
                for n in 기준[id(자리)]:
                    기준주소[n] = 주소
