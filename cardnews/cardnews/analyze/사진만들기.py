    # 실패해도 부른 값은 나간다. 여태 주석은 이렇게 적혀 있었는데 셈은 성공한 것만
    # 셌다 — 2026-09-22 에 $0.031 로 찍힌 판은 실제로 일곱 번 불렀다.
