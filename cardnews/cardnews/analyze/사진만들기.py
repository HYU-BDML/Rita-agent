# fal 이 받는 범위(모델 문서 2026-09-20). 하나라도 어기면 400 이다.
_배수 = 16
_긴변한도 = 3840
_픽셀하한, _픽셀상한 = 655_360, 8_294_400
_비율한도 = 3.0
# **«눈에 안 보인다» 를 픽셀로 잰다**(사람 물음 2026-09-20: 「어떻게 보편적으로
