# 같은 0.1% 가 708px 자리에서는 0.7px 이고 246px 자리에서는 0.2px 이다.
# 그래서 «자리에 넣었을 때 이만큼보다 덜 어긋난다» 를 정하고, 허용 비율은
# 자리 크기에서 스스로 나오게 둔다.
_어긋남한도px = 0.5


def 그림크기(w: float, h: float) -> tuple[int, int]:
    """자리 네모(`w`×`h`)와 **같은 비율**인, fal 이 받아 주는 크기.

    16 의 배수라는 조건 때문에 아무 비율이나 딱 떨어지지는 않는다. 딱 떨어지는
    자리도 있다 — 675:320 은 5로 약분하면 135:64 라 16 을 곱해 2160×1024 고,
    이 크기를 달라고 하니 그대로 왔다(실물 확인 2026-09-20).

    **문제는 딱 떨어지는 크기가 터무니없이 클 때다.** 605×346 을 정확히 맞추는
    가장 작은 크기가 3776×2160(816만 픽셀)인데, 그 그림은 자리에 들어갈 때
    605×346 으로 줄어든다 — 키운 만큼 버려지고 값만 2.5배다.

    그래서 «자리에서 0.5px 보다 덜 어긋나는 것» 을 모두 같다고 보고, 그중
    지금 쓰던 픽셀 수(1024×1536)에 가장 가까운 것을 고른다. 실측 자리 일곱이
    모두 0.4px 안에 들고 픽셀 수는 1.56~1.72M 로 지금과 같은 수준이다.

    허용선 안에 하나도 없으면(3:1 을 넘는 띠 자리 같은 것) 가장 덜 어긋나는
    것으로 간다 — 그런 자리는 애초에 비율을 못 맞춘다.
    """
    if w <= 0 or h <= 0:
        return 그림폭, 그림높이
    비 = min(max(w / h, 1 / _비율한도), _비율한도)
    목표픽셀 = 그림폭 * 그림높이
    허용 = _어긋남한도px / min(w, h)      # 자리 크기에서 스스로 나온다
    안, 밖 = None, None
    for 높 in range(_배수, _긴변한도 + 1, _배수):
        폭 = max(_배수, round(높 * 비 / _배수) * _배수)
        if 폭 > _긴변한도 or not (_픽셀하한 <= 폭 * 높 <= _픽셀상한):
            continue
        오차 = abs(폭 / 높 - 비) / 비
        가까움 = abs(폭 * 높 - 목표픽셀)
        if 오차 <= 허용 and (안 is None or 가까움 < 안[0]):
            안 = (가까움, (폭, 높))
        # 허용선 안이 비었을 때 쓸 차선. 부동소수 찌꺼기로 «오차 0» 끼리
        # 갈리지 않게 자른 뒤 견준다.
        점수 = (round(오차, 9), 가까움)
        if 밖 is None or 점수 < 밖[0]:
            밖 = (점수, (폭, 높))
    고른것 = 안 or 밖
    return 고른것[1] if 고른것 else (그림폭, 그림높이)


