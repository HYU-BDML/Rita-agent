def 한장값(품질: str) -> float:
    """그 품질 한 장의 값(달러). 모르는 품질이면 제일 비싼 것으로 친다 —
    **모자라게 잡으면 잔액이 있는 줄 알고 시작했다가 중간에 멈춘다.**"""
    return 품질표.get(품질, max(품질표.values()))


# **실제 값은 표보다 비싸다**(잔액 대조 2026-09-29). 표는 짧은 지시문 기준인데 우리는 긴
# 화풍 문장을 싣고, 인물 기준 그림도 싣는다.
