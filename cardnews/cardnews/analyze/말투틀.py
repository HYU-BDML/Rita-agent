# -*- coding: utf-8 -*-
"""말투를 **디자인과 따로** 저장한다.

여태 말투는 디자인에 붙어 있었다. 키키를 분석하면 키키의 네모 자리와 키키의
말투가 한 덩이로 저장돼서, 「**키키 디자인**에 **다른 데 말투**」를 못 골랐다.

사람이 고르는 축은 둘이다(사람 결정 2026-08-27) — **디자인 하나, 말투 하나.**
그러려면 둘이 따로 쌓여 있어야 한다.

**새로 재는 것은 없다.** 어미·격식·인칭·재미·정중·열정·훅 수법은 이미 계량표에
장마다 들어 있다. 여기서 하는 일은 **한 게시물치를 하나로 접어** 고를 수 있는
꼴로 만드는 것뿐이다.
"""
import collections
import json
import re
from pathlib import Path

# 본보기로 실을 문장 수와 길이.
#
# **본보기가 말투의 알맹이다.** 「반말·편안·재미 중간」 같은 낱말만으로는 결이
# 안 전해진다 — 실제 문장 몇 줄이 훨씬 많은 것을 말해 준다. 다만 길면 대본
# 모델이 «내용» 까지 베낀다. 셋이면 결은 충분하고 베낄 거리는 안 된다.
본보기수 = 3
본보기길이 = 40

# **역할마다 이만큼까지 원문을 싣는다.**
#
# 「말투를 고른다」는 것은 그 템플릿의 훅·규칙·문장 결을 다 배워서 비슷하게
# 쓴다는 뜻이다(사람 결정 2026-08-29). 여태는 짧은 본보기 세 줄뿐이라 모델이
# 대부분을 스스로 지어냈고, 그래서 「너무 AI 스럽다」는 말이 나왔다.
#
# 역할별로 나눠 담는 까닭은 **훅은 훅끼리 보고 배워야** 하기 때문이다.
역할당원문 = 12
원문길이 = 120


# ── 어미를 «문장» 으로 잰다 (사람 결정 2026-09-19) ────────────────────
#
# **줄은 문장이 아니다.** 카드뉴스는 한 문장이 여러 줄에 걸쳐 잘리고, 잘린 줄의
# 끝은 대개 명사다. 그래서 줄만 세면 「명사형」이 이긴다 — 실측으로 틀 10벌 중
# **일곱 벌이 「명사형」으로 적혀 있는데 그중 넷이 실제로는 해요체**였다.
#
#     얼마전 여돌이 공개 되었는데   ← 줄 끝이 이음말이다
#     이름하여 바로 키키!
#
# 줄을 이어 붙인 뒤 문장 끝을 본다.

_어미표 = (
    ("합니다체", ("습니다", "ㅂ니다", "입니다", "합니다")),
    ("해요체", ("해요", "예요", "이에요", "세요", "네요", "어요", "아요", "죠", "대요")),
    # **「다」로 끝나면 평서형이다.** 꼴을 하나씩 세다가는 「달성했다」처럼 빠지는
    # 것이 생긴다. 합니다체(「~습니다」)는 위에서 먼저 걸러지므로 안 겹친다.
    ("평서형", ("다",)),
    # 「~할게」·「~자」는 약속·권유라 반말 쪽이다. 「공유해줄게」가 그 꼴이다.
    ("반말", ("지", "야", "어", "아", "구", "네", "거든", "게", "자", "래")),
)

# **캐릭터 말끝.** 표준 어미 뒤에 덧붙는 한 글자짜리 꼬리다 — 「달성했다몬」은
# 「달성했다(평서) + 몬(꼬리)」이다. 마스코트가 화자인 계정이 쓴다.
#
# **꼬리는 안 따라 쓴다**(사람 결정 2026-09-19). 「도리몬」은 남의 계정 마스코트라
# 내 카드뉴스에서 「~몬」이 나오면 어색하기만 한 게 아니라 베낀 티가 난다.
# 재서 적어 두기만 하고, 프롬프트는 「쓰지 마라」고 못 박는다.
_꼬리꼴 = re.compile(r"(?:다|게|라|자)([가-힣])$")
"""**문장 «끝» 에서만 본다.** 처음엔 어디서든 찾게 뒀더니 조사를 잡았다 —
「…트렌드를」의 「를」, 「…요즘」의 「즘」처럼(실측 2026-09-19: 10벌 중 아홉에
헛것이 붙었다). 앞 글자도 종결어미(다·게·라·자)로 좁혔다."""

_꼬리최소 = 3
"""이만큼은 나와야 «버릇» 으로 본다. 한두 번은 우연일 수 있다 — 키키의
「몬」은 다섯 번이다."""


_이음말 = ("는데", "은데", "ㄴ데", "인데", "지만", "면서", "니까", "어서", "아서",
         "하고", "이고", "으며", "하며", "라서", "는지", "다가", "거나", "든지")
"""**여기서 끊기면 다음 줄로 이어진다.** 카드뉴스는 한 문장이 여러 줄에 걸친다."""


def _문장들(줄들) -> list:
    """줄을 «문장» 으로 묶는다.

    **통째로 이어 붙이면 안 된다.** 마침표를 안 쓰는 계정이 많아서, 다 이으면
    열 줄이 한 문장이 되고 마지막 줄 어미 하나만 세게 된다(실측: 키키는 34줄에
    마침표 0개다).

    그래서 **줄이 이음말로 끝나면 다음 줄과 잇고, 아니면 거기서 끊는다.**
    「…공개 되었는데」 + 「이름하여 바로 키키!」 는 한 문장이고, 「…있어요」 와
    「…주세요」 는 두 문장이다.
    """
    깨끗 = [str(x or "").strip() for x in 줄들]
    깨끗 = [x for x in 깨끗 if x]
    난것, 모으는중 = [], []
    for 줄 in 깨끗:
        모으는중.append(줄)
        끝 = 줄.rstrip("!?. \"'”’)")
        if not 끝.endswith(_이음말):
            난것.append(" ".join(모으는중))
            모으는중 = []
    if 모으는중:
        난것.append(" ".join(모으는중))
    # 문장 안에 마침표가 여러 개면 그것도 가른다.
    쪼갬 = []
    for 문장 in 난것:
        쪼갬 += [s.strip() for s in re.split(r"(?<=[.!?])\s+", 문장) if s.strip()]
    return 쪼갬


def 캐릭터꼬리(줄들) -> str:
    """그 계정이 문장 끝에 덧붙이는 한 글자. 없으면 빈 글자."""
    난것 = collections.Counter()
    for 문장 in _문장들(줄들):
        끝 = 문장.rstrip("!?. \"'”’)")
        m = _꼬리꼴.search(끝)
        if m:
            난것[m.group(1)] += 1
    if not 난것:
        return ""
    꼬리, 수 = 난것.most_common(1)[0]
    return 꼬리 if 수 >= _꼬리최소 else ""


def 문장어미(줄들) -> str:
    """문장 끝으로 재는 어미. **캐릭터 꼬리는 떼고 본다.**"""
    꼬리 = 캐릭터꼬리(줄들)
    셈 = collections.Counter()
    for 문장 in _문장들(줄들):
        끝 = 문장.rstrip("!?. \"'”’)")
        if 꼬리 and 끝.endswith(꼬리):
            끝 = 끝[:-1]
        if not 끝:
            continue
        for 이름, 꼴들 in _어미표:
            if 끝.endswith(꼴들):
                셈[이름] += 1
                break
        # **조각은 안 센다**(실측 2026-09-19). 카드뉴스 줄은 대부분 문장이
        # 아니다 — 「마케팅 레퍼런스」·「SNS 담당자가 알아야 할」·「무려
        # 686만회에」처럼 제목이거나 중간이 잘린 것이다. 그것을 「명사형」으로
        # 세면 열 벌 중 아홉이 명사형이 되어 변별이 사라진다.
        #
        # 우리가 알고 싶은 것은 **「이 계정이 서술을 끝낼 때 무엇을 쓰나」** 다.
        # 진짜 어미가 하나도 없으면 「미정」이 옳다 — 지어내지 않는다.
    if not 셈:
        return "미정"
    # **동점이면 «덜 기본값인 쪽» 이 이긴다.** 「명사형」은 아무 데도 안 걸릴 때
    # 떨어지는 자리라, 진짜 어미와 같은 수면 진짜 어미를 골라야 한다.
    차례 = ["합니다체", "해요체", "평서형", "반말"]
    return max(셈.items(), key=lambda kv: (kv[1], -차례.index(kv[0])))[0]


def _모든줄(잰것: dict) -> list:
    """그 게시물이 쓴 줄 전부. 어미·마침표를 잴 때 쓴다."""
    난것 = []
    for s in 잰것.get("slides") or []:
        for r in s.get("regions") or []:
            for l in ((r.get("text") or {}).get("line_detail") or []):
                글 = str(l.get("text") or "").strip()
                if 글:
                    난것.append(글)
    return 난것


def 훅뜯기(잰것: dict) -> dict:
    """훅(첫 장)을 뜯어 «어떻게 생겼는지» 를 적는다. 없으면 빈 사전.

    **훅은 표지다** — 여덟 장 중 일곱을 잘 써도 표지가 딴사람이면 아무도 안
    본다. 그런데 여태 훅을 본문과 똑같이 «자수» 로만 봤다.

    실측(틀 10벌): 훅은 2~3줄이고 **줄마다 하는 일이 다르다** — 무엇에 대한
    글인지 / 핵심 / 구체적인 것. 그리고 **10벌 전부 끝에 부호가 없다.**
    """
    장들 = 잰것.get("slides") or []
    첫장 = None
    for s in 장들:
        if (s.get("role") or "") == "훅":
            첫장 = s
            break
    # **역할이 「훅」이라고 적힌 장만 본다.** 첫 장을 훅으로 넘겨짚지 않는다 —
    # 역할이 「미정」으로 나온 게시물이 실제로 있었고, 그때 본문을 훅으로 뜯으면
    # 엉뚱한 골격을 가르치게 된다.
    if 첫장 is None:
        return {}
    줄들 = []
    for r in 첫장.get("regions") or []:
        for l in ((r.get("text") or {}).get("line_detail") or []):
            글 = str(l.get("text") or "").strip()
            if 글:
                줄들.append(글)
    if not 줄들:
        return {}
    끝 = 줄들[-1][-1]
    return {
        "줄": 줄들,
        "줄수": len(줄들),
        "줄자수": [len(x) for x in 줄들],
        "끝부호": 끝 if not (끝.isalnum() or "가" <= 끝 <= "힣") else "",
    }


def _제일많은것(값들, 기본="미정") -> str:
    """가장 자주 나온 값. **「미정」은 세지 않는다** — 그건 못 잰 것이지 답이 아니다."""
    쓸것 = [v for v in 값들 if v and v != "미정"]
    if not 쓸것:
        return 기본
    return collections.Counter(쓸것).most_common(1)[0][0]


def _본보기뽑기(잰것: dict) -> list:
    """실제 문장 몇 줄. **짧은 조각은 거른다** — 「키키!」 한 마디로는 결을 못 본다."""
    문장들 = []
    for s in 잰것.get("slides") or []:
        for r in s.get("regions") or []:
            for l in ((r.get("text") or {}).get("line_detail") or []):
                글 = str(l.get("text") or "").strip()
                if len(글) >= 8:
                    문장들.append(글[:본보기길이])
    # 앞에서부터 고른다 — 훅과 첫 본문이 그 게시물의 결을 제일 잘 드러낸다.
    본것, 난것 = set(), []
    for 글 in 문장들:
        if 글 in 본것:
            continue
        본것.add(글)
        난것.append(글)
        if len(난것) >= 본보기수:
            break
    return 난것


def _원문뽑기(잰것: dict) -> dict:
    """역할마다 그 게시물이 **실제로 쓴 줄들.** `{역할: [줄, …]}`

    짧은 조각도 버리지 않는다 — 본보기와 다른 점이다. 「키키!」 한 마디도 그
    게시물의 결이고, 훅 자리에서는 특히 그렇다. 같은 줄만 한 번으로 줄인다.
    """
    난것 = {}
    for s in 잰것.get("slides") or []:
        역할 = s.get("role") or "미정"
        칸 = 난것.setdefault(역할, [])
        for r in s.get("regions") or []:
            for l in ((r.get("text") or {}).get("line_detail") or []):
                글 = str(l.get("text") or "").strip()
                if not 글 or 글 in 칸 or len(칸) >= 역할당원문:
                    continue
                칸.append(글[:원문길이])
    return {k: v for k, v in 난것.items() if v}


def 뽑기(잰것: dict, 이름: str = "") -> dict:
    """계량표 하나 → 말투 한 벌.

    장마다 다른 값이 나오는 것들(어미·격식·인칭·세 축)은 **제일 많이 나온 것**으로
    접는다. 평균을 내지 않는 까닭은 이 값들이 낱말이라서다 — 「합니다체와 반말의
    평균」 같은 것은 없다.
    """
    장들 = 잰것.get("slides") or []
    코드 = 잰것.get("shortcode") or ""
    축 = {}
    for 이름칸 in ("humor", "respect", "enthusiasm"):
        축[이름칸] = _제일많은것([(s.get("tone") or {}).get(이름칸) for s in 장들])
    첫장 = 장들[0] if 장들 else {}
    return {
        "코드": 코드,
        # **틀 이름과 같게 두지 않는다.** 둘 다 「키키」면 채팅에서 「키키
        # 말투로」라고 해도 틀 이름이 같이 걸려 무엇을 고른 건지 흐려진다
        # (실물 시험 2026-08-27).
        "이름": f"{이름.strip()} 말투" if (이름 or "").strip() else 코드,
        # **문장으로 이어 잰다.** 장별 `ending` 을 최빈값으로 접던 것이 틀렸다 —
        # 줄이 잘려 명사로 끝나니 「명사형」이 이겼다. 위 `문장어미` 참고.
        "어미": 문장어미(_모든줄(잰것)) if _모든줄(잰것) else
                _제일많은것([s.get("ending") for s in 장들]),
        "격식": _제일많은것([(s.get("tone") or {}).get("formality") for s in 장들]),
        "인칭": _제일많은것([s.get("person") for s in 장들]),
        # 훅이 물음표로 끝나나 — 첫 장만 본다. 뒤 장은 본문이라 뜻이 다르다.
        "물음표훅": bool(첫장.get("is_question")),
        "재미": 축["humor"], "정중": 축["respect"], "열정": 축["enthusiasm"],
        "성격": 잰것.get("post_type") or "미정",
        "훅수법": 잰것.get("hook_strategy") or "미정",
        # **캐릭터 꼬리는 적어만 둔다 — 안 따라 쓴다**(사람 결정 2026-09-19).
        # 「도리몬」은 남의 계정 마스코트라 내 카드뉴스에서 「~몬」이 나오면
        # 베낀 티가 난다. 프롬프트가 「쓰지 마라」고 못 박는다.
        **({"캐릭터꼬리": 캐릭터꼬리(_모든줄(잰것))}
           if 캐릭터꼬리(_모든줄(잰것)) else {}),
        # 마침표를 쓰는 계정과 안 쓰는 계정이 갈린다 — 키키는 34줄에 0개,
        # AI 시대 일하는 법은 22개다. 여태 아무도 안 쟀다.
        "마침표": sum(x.count(".") for x in _모든줄(잰것)),
        **({"훅": 훅뜯기(잰것)} if 훅뜯기(잰것) else {}),
        "본보기": _본보기뽑기(잰것),
        # **그 게시물이 쓴 글 전부.** 말투를 고르면 이것을 통째로 보여 준다.
        "원문": _원문뽑기(잰것),
        "장수": len(장들),
    }


def 한줄설명(말투: dict) -> str:
    """사람이 목록에서 읽을 한 줄. **낱말을 늘어놓지 않고 문장으로 만든다.**"""
    조각 = [말투.get("어미"), 말투.get("격식")]
    인칭 = 말투.get("인칭")
    if 인칭 and 인칭 not in ("생략", "미정"):
        조각.append(f"「{인칭}」 부름")
    if 말투.get("물음표훅"):
        조각.append("물음표 훅")
    쓸것 = [x for x in 조각 if x and x != "미정"]
    앞 = " · ".join(쓸것) if 쓸것 else "못 잼"
    return f"{앞} · 재미 {말투.get('재미')}·정중 {말투.get('정중')}·열정 {말투.get('열정')}"


def 쓰기(말투: dict, 경로) -> dict:
    경로 = Path(경로)
    경로.parent.mkdir(parents=True, exist_ok=True)
    경로.write_text(json.dumps(말투, ensure_ascii=False, indent=1), encoding="utf-8")
    return 말투


def 목록줄(말투: dict, 주소: str, 만든날: str) -> dict:
    """창고 목록에 실을 한 줄. **간판이고, 알맹이는 각 파일 안에 있다** —
    틀 목록과 같은 결이다."""
    return {"코드": 말투.get("코드"), "이름": 말투.get("이름"),
            "만든날": 만든날, "설명": 한줄설명(말투),
            "본보기": (말투.get("본보기") or [""])[0], "주소": 주소}


def 프롬프트글(말투: dict) -> str:
    """대본 모델에게 줄 말. **없으면 빈 글자** — 그러면 프롬프트가 안 붙는다."""
    if not 말투:
        return ""
    줄 = [f"말투: {한줄설명(말투)}"]

    # **훅을 따로 뜯어 말한다.** 훅은 표지라 여기가 딴사람이면 나머지를 잘
    # 써도 소용없다. 원문만 던져 주면 모델이 한 줄짜리 제목을 낸다 —
    # 실측: 골격을 알려 줬을 때 「탕후루로 배우는 유행의 수명」, 안 알려 줬을
    # 때 「탕후루 몰락의 비밀」. 뒤엣것은 다른 계정 글이다.
    훅 = 말투.get("훅") or {}
    if 훅.get("줄"):
        줄.append("훅(표지 첫 장)은 이렇게 생겼다 — 이 모양을 그대로 따른다:")
        for i, x in enumerate(훅["줄"], 1):
            줄.append(f"  {i}줄 ({len(x)}자): «{x}»")
        끝 = 훅.get("끝부호") or ""
        줄.append(f"  → {훅.get('줄수')}줄이고 "
                  + (f"끝을 «{끝}» 로 맺는다." if 끝 else "**끝에 부호를 안 붙인다.**"))

    # **캐릭터 꼬리는 «쓰지 마라» 고 못 박는다.** 그냥 보여 주면 따라 쓴다.
    꼬리 = 말투.get("캐릭터꼬리")
    if 꼬리:
        줄.append(f"이 계정은 문장 끝에 «{꼬리}» 를 붙인다(마스코트 말투다). "
                  f"**그건 그 계정 것이니 쓰지 마라** — 어미는 그대로 두고 "
                  f"«{꼬리}» 만 뺀 꼴로 쓴다.")

    if 말투.get("마침표") == 0:
        줄.append("이 계정은 **마침표를 안 쓴다.** 문장을 부호 없이 끝낸다.")

    원문 = 말투.get("원문") or {}
    if 원문:
        # **역할별로 편다.** 훅 문장과 요약 문장은 결이 딴판이라, 섞어 놓으면
        # 어느 것을 언제 쓸지 모른다.
        줄.append("이 사람이 실제로 쓴 글 — 자리마다 결이 다르다:")
        for 역할, 줄들 in 원문.items():
            줄.append(f"  [{역할}]")
            줄 += [f"    «{x}»" for x in 줄들]
    else:
        # 옛 말투 파일에는 «원문» 이 없다. 그때는 본보기로 물러선다.
        본보기 = 말투.get("본보기") or []
        if 본보기:
            줄.append("이 말투로 쓴 실제 문장:")
            줄 += [f"  «{x}»" for x in 본보기]
    줄.append("**주제는 새것이되, 훅 여는 법·문장 길이·끝맺음·강조하는 자리를 "
            "위 글에서 그대로 배워 써라. 내용만 베끼지 마라.**")
    return "\n".join(줄)
