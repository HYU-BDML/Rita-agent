# -*- coding: utf-8 -*-
"""배경판 — 사람이 그은 네모를 뺀 **나머지 전부**를 그림 한 장으로 뜬다.

**이게 진짜 디자인이다**(사람 결정 2026-08-27). 지금까지 배경은 「단색
`#FFFFFF`」 같은 **이름 하나**로만 나왔다. 그래서 제목 밑 가로선, 옅은 무늬,
모서리 장식 같은 것이 통째로 사라졌다 — 격자 대부분이 흰색이라 「단색」으로
판정되고 선은 어디에도 안 실린다.

남은 픽셀을 그림으로 뜨면 그런 것이 **전부 공짜로** 따라온다. 그라데이션도
그림이니 저절로 들어온다.

**뚫린 자리는 메워 채운다**(사람 결정 2026-09-17: 「층을 올리는 거지 뚫는 게
아니다」). 전에는 투명으로 비워 굽는 쪽의 배경색이 비치게 했는데, 색 있는 면
위에서는 그 자리가 네모나게 파여 보였다(실측: 파란 주머니, 노란 덩이).

**메울 때 지어내지 않는다**(사람 결정 2026-09-17). 바닥판을 깔고 그 위에 라벨
안 된 것만 얹는다 — `뜨기` 참고.

**뜰 값이 없으면 안 뜬다.** 실측(키키 일곱 장): 남은 자리의 색 흩어짐이
0.0~1.0 이다 — 순백이라 뜰 것이 없다. 그런 판을 만들면 1MB짜리 흰 그림을
장마다 창고에 쌓을 뿐이다.
"""
import io

import cv2
import numpy as np
from PIL import Image

# **남은 자리를 이만큼 안쪽으로 물린다.**
#
# 사람이 그은 네모는 글자에 바짝 붙지 않는다 — 획 끝이나 받침이 몇 픽셀 삐져
# 나온다. 그대로 두면 그 잉크가 «남은 자리» 로 잡혀 배경판에 눌어붙는다.
#
# 실측(키키 일곱 장, 으뜸색과 다른 화소의 몫):
#
# |      | 0px | 2px | **4px** |
# |---|---|---|---|
# | 5장 | 0.164% | 0.018% | **0.000%** |
# | 6장 | 0.164% | 0.032% | **0.000%** |
# | 7장 | 0.082% | 0.000% | **0.000%** |
#
# 4px 에서 일곱 장이 다 0 이 된다. 더 물려도 얻을 게 없고, 배경에 진짜로 있는
# 것을 네모 가까이에서 깎아 먹기만 한다.
물릴폭 = 4


def 물리기(남음: np.ndarray, 폭: int = 물릴폭) -> np.ndarray:
    """남은 자리를 안쪽으로 `폭` 만큼 깎는다. 삐져나온 잉크를 떼려는 것이다."""
    if 폭 <= 0:
        return 남음
    커널 = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * 폭 + 1, 2 * 폭 + 1))
    return cv2.erode(남음.astype(np.uint8), 커널).astype(bool)


# 「으뜸색과 다르다」고 볼 채널 차. 아래 `쓸모있나` 참고.
다름문턱 = 20

# 다른 화소가 이 몫을 넘으면 뜰 값이 있다고 본다.
#
# **0.0002 로 낮췄다**(2026-08-29). 옛 값 0.001 은 굵은 가로선 하나(900×4 =
# 3,600 화소, 0.25%)를 기준으로 잡은 값인데, **옅은 종이 질감이 그 아래로
# 떨어졌다.** 실측:
#
# | 게시물 | 장별 다른 화소 몫 |
# |---|---|
# | 키키(DG0AA6PJ8s4) | 일곱 장 모두 **정확히 0.0000%** — 정말 아무것도 없다 |
# | DHqCBQnRAjW | 34.85 · 0.0754 · 0 · 0.0041 · 0.0092 · 0 · 0 |
# | DYWiVHhlNwo 2·6번 | **0.0521% · 0.0898%** — 종이 질감이 있는데 떨어졌다 |
#
# 「진짜 없음」은 0.0000% 로 딱 떨어지고, 질감은 0.05% 위다. 그 사이 0.02% 에
# 그으면 잡음(0.0041·0.0092 — 수십 화소)은 걸러지고 질감은 산다.
있음문턱 = 0.0002


def 으뜸색(rgb: np.ndarray, 남음: np.ndarray):
    """남은 자리의 대표색. 없으면 `None`.

    **중앙값을 쓴다.** 평균은 선 하나에도 끌려가고, 최빈값은 그라데이션에서
    한 점으로 쏠린다.
    """
    화소 = rgb[남음]
    if not len(화소):
        return None
    return np.median(화소, axis=0)


def 다른화소(rgb: np.ndarray, 남음: np.ndarray) -> np.ndarray:
    """남은 자리 중 으뜸색과 «눈에 띄게» 다른 화소의 참거짓 판."""
    색 = 으뜸색(rgb, 남음)
    빈판 = np.zeros(남음.shape, bool)
    if 색 is None:
        return 빈판
    차 = np.abs(rgb.astype(np.int16) - 색.astype(np.int16)).max(axis=2)
    return 남음 & (차 > 다름문턱)


def 쓸모있나(rgb: np.ndarray, 남음: np.ndarray) -> bool:
    """이 장에 뜰 값이 있나 — 남은 자리가 한 색이 아니면 있다.

    **없는데 뜨면 창고에 흰 그림만 쌓인다.** 실측(키키 일곱 장): 물리고 나면
    일곱 장이 다 0.0000% 다. 그게 맞다 — 키키 배경에는 정말로 아무것도 없다.
    """
    return float(다른화소(rgb, 물리기(남음)).mean()) > 있음문턱


# **구멍을 이만큼 더 넓혀 지운다.**
#
# 글자 획 끝·받침이 사람 네모 밖으로 몇 화소 나온다. 그 검은 점이 구멍 테두리에
# 남으면 이어 그리기가 그 색을 끌어와 길게 번진다(실물 2026-09-17, 예시 ③
# 「Monthly」의 h·l 꼭대기가 아래로 검은 막대 둘이 됐다).
넓힐폭 = 14

def 넓히기(뚫림: np.ndarray, 폭: int = 넓힐폭) -> np.ndarray:
    """구멍을 `폭` 만큼 부풀린다."""
    커널 = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * 폭 + 1, 2 * 폭 + 1))
    return cv2.dilate(뚫림.astype(np.uint8), 커널).astype(bool)


def 뜨기(rgb: np.ndarray, 남음: np.ndarray, 바닥: np.ndarray | None = None) -> bytes | None:
    """배경판 PNG — **바닥판을 깔고 라벨 안 된 것만 그 위에 얹는다.**

    사람 결정 2026-09-17: 「그걸 기본으로 다 깔면 빈칸이 없을 거 아니야? 거기서
    각 슬라이드마다 라벨링 안 되었던 부분들만 추가를 하는 거지」.

    **바닥판은 게시물에 하나고 장마다 안 달라진다**(`바닥고르기`). 장마다 따로
    뜨면 그 장에 깨끗한 자리가 얼마나 있느냐에 따라 질감이 미세하게 갈린다.

    «라벨 안 된 것» 은 남은 자리 안의 **덩어리**다(`_덩어리`) — 구분선·동그라미
    처럼 으뜸색과 세게 다른 화소가 뭉친 것. 종이 질감의 점은 한두 화소라 덩어리가
    안 되고, 그건 바닥판이 이미 담고 있다.

    `바닥` 을 안 주면 이 장에서 떠서 쓴다 — 시험과 홑장 쓰임새를 위한 길이다.
    """
    if not 쓸모있나(rgb, 남음):
        return None
    if 바닥 is None:
        깔것 = 바닥뜨기(rgb, 남음)
        if 깔것 is None:
            return None
        바닥 = np.asarray(Image.open(io.BytesIO(깔것)).convert("RGB"))
    if 바닥.shape[:2] != rgb.shape[:2]:
        바닥 = cv2.resize(바닥, (rgb.shape[1], rgb.shape[0]), interpolation=cv2.INTER_LINEAR)

    물린것 = 물리기(남음)
    얹을것 = _덩어리(rgb, 물린것) & 물린것
    if 얹을것.any():
        # 덩어리 둘레의 흐릿한 테두리까지 같이 얹는다 — 안 얹으면 선 가장자리에
        # 바닥색이 비쳐 톱니처럼 보인다.
        얹을것 = cv2.dilate(얹을것.astype(np.uint8), np.ones((5, 5), np.uint8)).astype(bool)
    판 = np.where(얹을것[..., None], rgb, 바닥).astype(np.uint8)
    통 = io.BytesIO()
    Image.fromarray(판, "RGB").save(통, format="PNG", optimize=True)
    return 통.getvalue()


# ---------------------------------------------------------------- 바닥판
#
# **바닥은 «그냥 배경» 뿐이다**(사람 결정 2026-09-15). 종이 질감이면 종이 질감,
# 그라데이션이면 그라데이션. 선·동그라미·로고는 배경이 아니라 그 위에 쌓는
# 조각이다. 배경판(`뜨기`)은 사람이 그은 네모만 뺀 «나머지 전부» 라 그런 조각이
# 같이 들어 있다 — 그걸 사진 장에 깔았더니 2번 장의 세로 선과 동그라미가 표지에
# 딸려 나왔다(실물 2026-09-15, DSW-6lrk5rs).
#
# 그래서 남은 자리 안에서 **구조 없는 조각** 을 찾아 장 크기로 이어 붙인다.
# 「구조」는 으뜸색과 세게 다른 화소가 뭉친 덩어리다 — 종이 질감의 점은 한두
# 화소짜리라 덩어리가 안 되고, 선·동그라미는 수백 화소가 붙어 있다.

강한문턱 = 48     # 이보다 채널 차가 크면 «세게 다르다». 잉크는 다 넘는다
덩어리문턱 = 24   # 세게 다른 화소가 이만큼 붙어 있으면 조각이다. 질감 점은 한 자리 수
# 잘라 붙일 조각의 한 변. 큰 것부터 시도한다 — 실물 DSW-6lrk5rs 2번 장은 글자
# 네모가 커서 180px 짜리 빈 창이 없고 120px 부터 있다. 80px 아래는 질감이라기
# 보다 얼룩 하나라 안 내려간다.
조각크기들 = (180, 120, 80)


def _덩어리(rgb: np.ndarray, 남음: np.ndarray) -> np.ndarray:
    """세게 다른 화소 중 «덩어리» 에 속한 것의 참거짓 판."""
    색 = 으뜸색(rgb, 남음)
    if 색 is None:
        return np.zeros(남음.shape, bool)
    차 = np.abs(rgb.astype(np.int16) - 색.astype(np.int16)).max(axis=2)
    n, 라벨, 통계, _ = cv2.connectedComponentsWithStats((차 > 강한문턱).astype(np.uint8))
    큰것 = np.zeros(n, bool)
    큰것[1:] = 통계[1:, cv2.CC_STAT_AREA] > 덩어리문턱
    return 큰것[라벨]


def _깨끗한조각(rgb: np.ndarray, 남음: np.ndarray, 크기: int):
    """구멍도 덩어리도 없는 크기×크기 조각. 없으면 `None`.

    창을 반 칸씩 옮기며 처음 깨끗한 것을 집는다. 못 쓰는 화소의 누적합으로
    창마다 한 번에 센다 — 1080×1350 에 창이 백 개 남짓이라 금방이다.
    """
    못씀 = (~남음) | _덩어리(rgb, 남음)
    h, w = 남음.shape
    걸음 = max(1, 크기 // 2)
    누적 = np.pad(못씀.astype(np.int32).cumsum(0).cumsum(1), ((1, 0), (1, 0)))
    for y in range(0, h - 크기 + 1, 걸음):
        for x in range(0, w - 크기 + 1, 걸음):
            합 = (누적[y + 크기, x + 크기] - 누적[y, x + 크기]
                 - 누적[y + 크기, x] + 누적[y, x])
            if 합 == 0:
                return rgb[y:y + 크기, x:x + 크기]
    return None


# 조각 한 변과 겹칠 폭. 80 은 실물 한지 점(평균 3.6화소)보다 충분히 크고,
# 깨끗한 자리가 드문 장에서도 후보가 남는 크기다(실측 DSW-6lrk5rs: 여섯 장에서
# 후보 4,282개). 겹침 20 은 이음매를 가릴 만큼이면서 조각을 다 덮지 않는 폭이다.
조각한변 = 80
조각겹침 = 20

# 큰 것부터 내려가며 시도한다. 깨끗한 자리가 좁은 장(글자·도형이 빽빽한 장)과
# 작은 그림에서는 80 짜리 창이 하나도 안 잡힌다.
베낄크기들 = (80, 56, 32, 20)

# 후보를 견줄 때 몇 개까지 재나. 실물에서 후보가 4만 개 넘게 나와 전부 재면
# 2분을 넘겼다 — 고루 뽑아 이만큼만 잰다.
잴후보수 = 400

# 가운데값에서 이만큼 벗어난 후보는 뺀다.
#
# **후보가 많은 쪽이 이기면 안 된다.** 실물 DSW-6lrk5rs 는 10번 장만 질감 없는
# 순백(거칠기 0.00 · 점 0개)인데 그 장 후보가 3,173개로 나머지 여섯 장(4,282개)의
# 74% 였다. 그냥 무작위로 뽑으면 열에 넷이 밋밋한 조각이라 바닥판이 맨들맨들해진다.
거칠기창 = (0.45, 2.2)   # 가운데값 대비
밝기벗어남 = 6           # 가운데값에서 이만큼 밝거나 어두우면 뺀다(그림자·번짐)

# 잔 결을 지울 때 쓰는 뭉갬 — 이보다 큰 것은 «무늬» 다.
무늬뭉갬 = 4

# 큰 무늬가 가운데값 대비 이 창을 벗어나면 뺀다.
#
# **실측(2026-09-17)**: DSW 한지처럼 잔 질감뿐인 배경은 조각마다 0.83~1.14 로
# 고른데, 옅은 구름 무늬가 있는 DYWiVHhlNwo 는 0.37~3.35 로 벌어진다. 무늬가
# 든 조각을 떠다 흩뿌리면 같은 모양이 여러 군데 되풀이된다.
무늬창 = (0.5, 1.8)


def _깨끗한자리들(깨끗: np.ndarray, 한변: int) -> np.ndarray:
    """한변×한변 창이 통째로 깨끗한 왼쪽 위 좌표들. (N, 2) 배열."""
    if min(깨끗.shape) < 한변:
        return np.empty((0, 2), np.int64)
    누적 = np.pad((~깨끗).astype(np.int32).cumsum(0).cumsum(1), ((1, 0), (1, 0)))
    합 = (누적[한변:, 한변:] - 누적[:-한변, 한변:]
          - 누적[한변:, :-한변] + 누적[:-한변, :-한변])
    ys, xs = np.nonzero(합 == 0)
    return np.stack([ys, xs], axis=1)


def _조각값(조각: np.ndarray) -> tuple[float, float, float]:
    """조각의 (평균밝기, 거칠기, 큰무늬).

    - **거칠기** — 잔 결의 세기. 질감이 없으면 0 이다.
    - **큰무늬** — 잔 결을 지우고 남는 큰 변화. 옅은 워터마크·구름 무늬가 여기
      걸린다. 이건 «베낄 질감» 이 아니다 — 조각을 떠다 흩뿌리면 같은 모양이
      여러 군데 되풀이된다(실물 2026-09-17 DYWiVHhlNwo 구름·따옴표 무늬).
    """
    g = 조각.mean(axis=2).astype(np.float32)
    큰것 = cv2.GaussianBlur(g, (0, 0), 무늬뭉갬)
    return float(g.mean()), float(g.std()), float(큰것.std())


def _고른자리들(rgb: np.ndarray, 자리: np.ndarray, 한변: int) -> np.ndarray:
    """후보끼리 견줘 «가운데」에서 벗어난 것을 뺀다 — 위 `거칠기창` 참고."""
    if len(자리) <= 2:
        return 자리
    걸음 = max(1, len(자리) // 잴후보수)
    본것 = 자리[::걸음]
    값 = np.array([_조각값(rgb[y:y + 한변, x:x + 한변]) for y, x in 본것])
    밝기중앙, 거칠기중앙 = float(np.median(값[:, 0])), float(np.median(값[:, 1]))
    무늬중앙 = float(np.median(값[:, 2]))
    if 거칠기중앙 <= 0:
        return 자리          # 이 장에는 질감 자체가 없다 — 고를 것이 없다
    좋음 = ((np.abs(값[:, 0] - 밝기중앙) <= 밝기벗어남)
            & (값[:, 1] >= 거칠기창[0] * 거칠기중앙)
            & (값[:, 1] <= 거칠기창[1] * 거칠기중앙))
    if 무늬중앙 > 0:
        좋음 &= ((값[:, 2] >= 무늬창[0] * 무늬중앙)
                 & (값[:, 2] <= 무늬창[1] * 무늬중앙))
    남은것 = 본것[좋음]
    return 남은것 if len(남은것) else 본것


# 큰 흐름을 얼마나 뭉갤까 — 이보다 잔 것은 «질감», 이보다 큰 것은 «흐름» 이다.
# 한지 점은 평균 3.6화소라 흐름에 안 섞이고, 200화소짜리 줄무늬는 흐름에 남는다.
흐름뭉갬 = 24


def _흐름(rgb: np.ndarray, 깨끗: np.ndarray) -> np.ndarray:
    """배경의 «큰 흐름» — 색이 화면에서 어떻게 변하는지. 구멍은 이어서 메운다.

    그라데이션·큰 무늬가 여기 담긴다. 층층이 줄였다 늘리며 아는 곳을 번지게 해
    구멍까지 채운 뒤 뭉갠다 — 아는 값에서만 나오니 지어내는 것이 아니다.
    """
    앎 = 깨끗.astype(np.float32)
    값 = rgb.astype(np.float32) * 앎[..., None]
    층값, 층앎 = [값], [앎]
    while min(층값[-1].shape[:2]) > 4:
        층값.append(cv2.pyrDown(층값[-1]))
        층앎.append(cv2.pyrDown(층앎[-1]))
    찬것 = 층값[-1] / np.maximum(층앎[-1], 1e-6)[..., None]
    for i in range(len(층값) - 2, -1, -1):
        h, w = 층값[i].shape[:2]
        위 = cv2.resize(찬것, (w, h), interpolation=cv2.INTER_LINEAR)
        아래 = 층값[i] / np.maximum(층앎[i], 1e-6)[..., None]
        믿음 = np.clip(층앎[i], 0, 1)[..., None]
        찬것 = 아래 * 믿음 + 위 * (1 - 믿음)
    return cv2.GaussianBlur(찬것, (0, 0), 흐름뭉갬)


def 베껴채우기(rgb: np.ndarray, 깨끗: np.ndarray, 높이: int, 폭: int,
             한변: int = 조각한변, 겹침: int = 조각겹침, 씨: int = 0,
             자름: bool = True):
    """**지어내지 않고 베낀다** — 깨끗한 자리에서 조각을 무작위로 떠다 이어 붙인다.

    **거울로 뒤집지 않는다.** 옛 방식은 조각 하나를 거울처럼 이어 붙여서 조각 안의
    옅은 기울기가 마름모 격자로 되풀이됐다(실물 2026-09-17 예시 ③·④). 자리를 매번
    새로 뽑으면 되풀이가 안 생긴다(실측: 조각 간격에서 닮은 정도 +0.002, 옛 방식은
    +0.018·+0.021).

    **판을 한 변씩 넉넉히 만들고 가운데만 잘라 쓴다.** 이음매를 가리는 사다리꼴
    무게가 가장자리에서 0 이라, 딱 맞게 만들면 테두리 한 줄이 까맣게 난다.
    """
    자리 = _고른자리들(rgb, _깨끗한자리들(깨끗, 한변), 한변)
    if not len(자리):
        return None
    난수 = np.random.RandomState(씨)
    걸음 = 한변 - 겹침
    H, W = 높이 + 2 * 한변, 폭 + 2 * 한변
    판 = np.zeros((H + 한변, W + 한변, 3), np.float32)
    무게 = np.zeros((H + 한변, W + 한변, 1), np.float32)
    비 = np.ones(한변, np.float32)
    비[:겹침] = np.linspace(0, 1, 겹침)
    비[-겹침:] = np.linspace(1, 0, 겹침)
    창무게 = (비[:, None] * 비[None, :])[..., None]
    for y in range(0, H, 걸음):
        for x in range(0, W, 걸음):
            sy, sx = 자리[난수.randint(len(자리))]
            판[y:y + 한변, x:x + 한변] += rgb[sy:sy + 한변, sx:sx + 한변] * 창무게
            무게[y:y + 한변, x:x + 한변] += 창무게
    속 = slice(한변, 한변 + 높이), slice(한변, 한변 + 폭)
    난것 = 판[속] / np.maximum(무게[속], 1e-6)
    # `자름=False` 는 «잔결»(0 언저리에서 오르내리는 값)을 뜰 때 쓴다 — 0~255 로
    # 자르면 음수가 전부 0 이 되어 질감의 절반이 사라진다.
    return np.clip(난것, 0, 255).astype(np.uint8) if 자름 else 난것


def 바닥뜨기(rgb: np.ndarray, 남음: np.ndarray, 크기들: tuple = 조각크기들) -> bytes | None:
    """«그냥 배경» PNG — 장 크기의 RGB. 뜰 값이 없거나 깨끗한 자리가 없으면 `None`.

    **두 겹으로 나눠 담는다. 둘 다 원본에서 가져오니 지어내는 것이 없다**
    (사람 결정 2026-09-17: 「그냥 네가 만들지 말고 그것을 그대로 캡쳐하든지 해서
    전체 슬라이드 꽉 차게 채우면 되는 거 아님?」·「그라데이션이면 그라데이션,
    디자인이 한지면 한지, 등등 다 흡수할 수 있어야 한다」).

    - **큰 흐름**(`_흐름`) — 색이 화면에서 어떻게 변하는지. 그라데이션·큰 무늬.
    - **질감**(`베껴채우기`) — 한지 점·종이 올. 진짜 화소를 떠다 잇는다.

    옛 방식은 조각의 평균색 위에 잔점을 새로 뿌렸는데, 배경이 거의 흰색(253)이라
    255 를 넘는 밝은 잔점이 전부 잘려 나갔다 — 실물 DSW-6lrk5rs 2번 장 실측으로
    한지 점 무리가 135개에서 **0개**, 거칠기 σ 6.62 → 2.53 이 됐다.
    """
    if not 쓸모있나(rgb, 남음):
        return None
    물린것 = 물리기(남음)
    깨끗 = 물린것 & ~_덩어리(rgb, 물린것)
    if not 깨끗.any():
        return None
    흐름 = _흐름(rgb, 깨끗)
    잔결 = rgb.astype(np.float32) - 흐름
    h, w = 남음.shape
    베낀질감 = None
    for 한변 in 베낄크기들:
        베낀질감 = 베껴채우기(잔결, 깨끗, h, w, 한변=한변,
                          겹침=min(조각겹침, max(2, 한변 // 4)), 자름=False)
        if 베낀질감 is not None:
            break
    if 베낀질감 is None:
        return None
    깐것 = np.clip(흐름 + 베낀질감, 0, 255).astype(np.uint8)
    통 = io.BytesIO()
    Image.fromarray(깐것, "RGB").save(통, format="PNG", optimize=True)
    return 통.getvalue()


# 바닥판 감으로 얼마나 많은 후보를 봐야 하나. 조각이 적으면 되풀이가 보인다.
자리넉넉 = 200


def _장의질감(rgb: np.ndarray, 남음: np.ndarray) -> tuple[int, float] | None:
    """이 장이 바닥판 감으로 얼마나 좋은가 — `(뜰 수 있는 자리 수, 거칠기)`.

    못 쓸 장이면 `None`. 거칠기가 0 이면 질감이 없는 장이다.

    **`베낄크기들` 을 그대로 내려간다 — 뜨는 쪽과 같은 잣대라야 한다.** 80 짜리
    창만 찾으면, 80 이 안 들어가는 게시물이 「바닥판 못 뜸」이 되고 장마다 제
    바닥을 따로 떠서 질감이 갈린다(실물 2026-09-17 DYWiVHhlNwo: 장마다 한지 점
    367~410개가 제각각).
    """
    물린것 = 물리기(남음)
    깨끗 = 물린것 & ~_덩어리(rgb, 물린것)
    for 한변 in 베낄크기들:
        자리 = _깨끗한자리들(깨끗, 한변)
        if len(자리):
            break
    else:
        return None
    걸음 = max(1, len(자리) // 잴후보수)
    거칠 = [_조각값(rgb[y:y + 한변, x:x + 한변])[1] for y, x in 자리[::걸음]]  # noqa: E501
    return len(자리), float(np.median(거칠))


# 두 장의 바탕색이 이만큼 안에 들면 «같은 색» 으로 본다.
같은색폭 = 24


def _바탕색(rgb: np.ndarray, 남음: np.ndarray) -> np.ndarray:
    """이 장 배경의 대표색 — 라벨을 뺀 자리의 중앙값."""
    자리 = 물리기(남음)
    if not 자리.any():
        return np.array([0, 0, 0], np.int16)
    return np.median(rgb[자리], axis=0)


def _많은색만(잰것: list) -> list:
    """**바탕색이 가장 많은 무리만 남긴다**(사람 결정 2026-09-18: 「가장 많은 것을
    바닥판으로」).

    질감만 보고 고르면 «깨끗한 자리가 넓은» 장이 이긴다. 실물 DNUFIa4NIkK 는
    일곱 장 가운데 넷이 회색(#F2F2F2)인데, 질감이 아예 없는 디자인이라 잣대가
    전부 동점이 됐고 목록에서 첫째인 파란 장(#007AFF)이 그냥 이겼다 — 그 파란
    바닥판이 일곱 장에 다 깔려 회색 장들이 파랗게 덮였다.

    색이 다른 장 하나는 포기한다(사람 결정). 많은 쪽을 맞히는 것이 낫다.
    """
    무리 = []
    for v in 잰것:
        for 것 in 무리:
            if np.abs(것[0][5].astype(int) - v[5].astype(int)).max() <= 같은색폭:
                것.append(v)
                break
        else:
            무리.append([v])
    # 장 수가 가장 많은 무리. 같으면 깨끗한 자리가 넓은 쪽.
    return max(무리, key=lambda 것: (len(것), max(v[0] for v in 것)))


def 바닥고르기(후보: list):
    """단색 장들 가운데 **가장 잘 나온 하나**를 고른다. `(hex, rgb, 남음)` 또는 `None`.

    **네모가 적은 장부터 처음 되는 것을 쓰면 안 된다**(사람 결정 2026-09-17).
    실물 DSW-6lrk5rs 는 네모가 가장 적은 장이 10번인데 그 장만 질감 없는
    순백(거칠기 0.00 · 한지 점 0개)이라, 그 규칙이 밋밋한 바닥판을 골랐다.

    고르는 잣대 셋:

    1. **질감이 있을 것** — 거칠기 0 인 장은 뺀다.
    2. **여러 장이 동의하는 질감일 것** — 장마다 대푯값을 내고 그 가운데값에서
       크게 벗어난 장을 뺀다. **장 단위로 견준다** — 후보 조각 수로 견주면
       밋밋한 쪽이 되레 이긴다(실물: 10번 장 후보 3,173개 대 여섯 장 합 4,282개).
    3. **깨끗한 자리가 넓을 것** — 뜰 조각이 많을수록 되풀이가 안 생긴다.
    """
    잰것 = []
    for 몫 in 후보:
        hex글, rgb, 남음 = 몫[1], 몫[2], 몫[3]
        값 = _장의질감(rgb, 남음)
        if 값:
            잰것.append((값[0], 값[1], hex글, rgb, 남음, _바탕색(rgb, 남음)))
    if not 잰것:
        return None
    잰것 = _많은색만(잰것)
    # **질감이 있는 장이 하나라도 있으면 그쪽에서 고른다.** 없으면 밋밋한 것
    # 가운데 하나를 쓴다 — 통째로 버리면 바닥판이 없어지고, 그러면 장마다 제
    # 바닥을 따로 떠서 「고정하라」는 뜻과 정반대가 된다(실물 DbkuOn_mgi3:
    # 단색 장이 4개 있는데도 「못 뜸」이 되어 네 장이 각자 떴다).
    질감있음 = [v for v in 잰것 if v[1] > 0]
    잰것 = 질감있음 or 잰것
    가운데 = float(np.median([v[1] for v in 잰것])) or 1.0
    고른것 = [v for v in 잰것
            if 거칠기창[0] * 가운데 <= v[1] <= 거칠기창[1] * 가운데] or 잰것
    # 자리가 넉넉한 것들 가운데 질감이 가운데값에 가장 가까운 장
    넉넉 = [v for v in 고른것 if v[0] >= 자리넉넉] or 고른것
    골라진 = min(넉넉, key=lambda v: abs(v[1] - 가운데))
    return 골라진[2], 골라진[3], 골라진[4]
