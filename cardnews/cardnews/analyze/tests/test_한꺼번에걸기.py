def test_끝난_수로_알린다():
    """**한꺼번에 걸면 «몇 번째를 시작했나» 는 뜻이 없다.** 끝난 수로 센다."""
    본것 = []
    _채우기([카드("사진") for _ in range(4)], 가짜fal(),
          알림=lambda 끝난, 전체: 본것.append((끝난, 전체)))
    assert 본것 == [(1, 4), (2, 4), (3, 4), (4, 4)]
