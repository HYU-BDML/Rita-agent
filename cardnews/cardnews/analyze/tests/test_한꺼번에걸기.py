"""**사진을 한꺼번에 건다**(사람 결정 2026-09-24).

여태는 한 장이 끝나야 다음 장을 시작했다 — 실측 2026-09-22 에 일곱 장에 **213초**,
굽기 전체 235초 중 90%였다.

fal 은 우리 계정의 동시 처리 한도를 넘어도 **거절하지 않고 줄을 세운다**(fal 문서:
「한도 때문에 거절되는 일은 없다」). 그러니 다 걸어 두고 되는 대로 받으면 된다 —
한도가 2면 2개씩, 40이면 40개가 한꺼번에 돈다. **코드는 같고 알아서 빨라진다.**

`test_사진만들기.py` 는 «부른 차례» 를 보느라 한 장씩 돌린다. 한꺼번에 거는 길은
차례가 매번 달라지므로 **여기서 따로** 본다 — 차례가 아니라 «다 불렀나» 를 본다.

**망을 안 탄다.** 가짜 fal 을 끼운다.
"""
