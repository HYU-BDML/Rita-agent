# ── 시간이 다 되면 ──────────────────────────────────────────────────

def test_시간이_다_되면_다시_안_건다(monkeypatch):
    """람다 900초를 넘겨 판 전체를 날리는 것보다 사진 몇 장이 비는 편이 낫다."""
    monkeypatch.setattr(사진만들기, "사진전체상한", 0)
    카드들 = [카드("사진") for _ in range(3)]
    손 = 가짜fal(탈={1: 사진만들기.그림없음("빈손"),
                  2: 사진만들기.그림없음("빈손"),
                  3: 사진만들기.그림없음("빈손")})
    assert _채우기(카드들, 손) == 0
    assert len(손.부른것) == 3, "시간이 다 됐는데 다시 걸었다"


def test_마감을_부르는_쪽에_넘긴다():
    """`부르기` 가 줄에 서 있는 동안에도 이 마감을 보고 손을 뗀다."""
    본것 = {}

    def 손(지시문, 누끼=False, 품질=None, 크기=None, 마감=None, 그만인가=None):
        본것["마감"] = 마감
        return "https://x/1.png"

    _채우기([카드("사진")], 손)
    assert isinstance(본것.get("마감"), float), "마감을 안 넘겼다"
    assert 본것["마감"] > time.monotonic(), "이미 지난 마감을 넘겼다"


