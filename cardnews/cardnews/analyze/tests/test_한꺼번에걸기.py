def test_여럿이_같이_돌아도_셈이_안_어긋난다(capsys):
    """**여럿이 같이 도는 자리라 셈이 제일 틀리기 쉽다.** 바깥 셈을 직접
    건드리지 않고 제 값만 돌려주게 해 두었다."""
    카드들 = [카드("사진") for _ in range(7)]
    손 = 가짜fal()
    _채우기(카드들, 손)
    찍힌것 = capsys.readouterr().out
    assert "사진 7/7장" in 찍힌것
    assert "7번 불렀다" in 찍힌것
    # 로그는 표 값이 아니라 실측 어림값으로 센다(2026-09-29).
    일곱값 = 사진만들기.어림값(사진만들기.본문품질) * 7
    assert f"${일곱값:.3f}" in 찍힌것


