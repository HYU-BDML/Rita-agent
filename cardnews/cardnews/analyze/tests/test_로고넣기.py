# -*- coding: utf-8 -*-
"""로고 자리를 채우거나 없애는 규칙.

제일 중요한 것: **안 넣기로 했으면 자리가 남아 있으면 안 된다.** 남으면 완성
카드에 점선 네모와 물음표가 박혀 나간다.
"""
import 로고넣기

주소 = "https://cardnews-render-554608989606.s3.ap-northeast-2.amazonaws.com/photos/ab12.png"


def 카드셋():
    """로고 둘·사진 하나·도형 하나. 장마다 칸이 섞여 있는 실제 모양이다."""
    return [
        {"장식영역": [{"종류": "로고", "box": [0, 0, 10, 10]},
                   {"종류": "사진", "box": [0, 0, 20, 20]}]},
        {"장식영역": [{"종류": "도형", "box": [0, 0, 5, 5]}]},
        {"장식영역": [{"종류": "로고", "box": [1, 1, 9, 9]}]},
    ]


def test_자리수는_로고만_센다():
    assert 로고넣기.자리수(카드셋()) == 2


def test_주소를_주면_로고_자리마다_박는다():
    카드 = 카드셋()
    assert 로고넣기.채우기(카드, 주소) == 2
    로고들 = [r for 장 in 카드 for r in 장["장식영역"] if r["종류"] == "로고"]
    assert len(로고들) == 2, "자리가 사라졌다 — 넣기로 했는데"
    assert all(r["media_url"] == 주소 for r in 로고들)


def test_주소가_없으면_자리를_통째로_뺀다():
    """**이 시험이 이번 일의 알맹이다.** 자리가 남으면 물음표가 찍힌다."""
    카드 = 카드셋()
    assert 로고넣기.채우기(카드, "") == 2
    남은것 = [r["종류"] for 장 in 카드 for r in 장["장식영역"]]
    assert "로고" not in 남은것, f"로고 자리가 남았다 — {남은것}"


def test_로고를_빼도_다른_칸은_그대로다():
    """사진·도형까지 같이 지우면 카드가 텅 빈다."""
    카드 = 카드셋()
    로고넣기.채우기(카드, "")
    assert [r["종류"] for 장 in 카드 for r in 장["장식영역"]] == ["사진", "도형"]


def test_빈칸_None_이상한것에_안_죽는다():
    """틀은 사람이 그린 것에서 나온다 — 빈 장도 오고 장식영역이 없는 장도 온다."""
    for 카드 in ([], None, [{}], [{"장식영역": None}], [{"장식영역": [None, "글자"]}]):
        assert 로고넣기.자리수(카드) == 0
        assert 로고넣기.채우기(카드, 주소) == 0
        assert 로고넣기.채우기(카드, "") == 0


def test_앞뒤_빈칸만_있는_주소는_안_넣은_것으로_친다():
    카드 = 카드셋()
    assert 로고넣기.채우기(카드, "   ") == 2
    assert not [r for 장 in 카드 for r in 장["장식영역"] if r["종류"] == "로고"]


def test_같은_장에_로고가_둘이어도_둘_다_없앤다():
    카드 = [{"장식영역": [{"종류": "로고"}, {"종류": "로고"}, {"종류": "사진"}]}]
    assert 로고넣기.채우기(카드, "") == 2
    assert [r["종류"] for r in 카드[0]["장식영역"]] == ["사진"]


def test_로고종류는_그리는_쪽과_같은_낱말이다():
    """갈리면 「2자리 있어요」라고 해 놓고 한 자리도 안 채운다."""
    assert 로고넣기.로고종류 == "로고"
