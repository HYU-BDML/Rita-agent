"""사람이 고른 «언어» 가 화면에서 대본 지시문까지 **끊기지 않고** 닿나.

사람 결정 2026-09-18: 「영어만 하면 돼」·「가 덩어리부터 해」 — 영어 카드가
실제로 나오는 데까지.

**이 사슬은 마디가 많다** — 봉투 → 짓기 → 검증사슬 → 프롬프트. 한 마디만
빠뜨려도 프롬프트는 영어를 알지만 아무도 안 넘겨서 **영어가 한 장도 안
나온다.** 그런데 그건 조용하다 — 카드는 나오고, 한국어일 뿐이다. 그래서
마디마다 따로 못을 박는다.
"""
import os
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(여기))
os.environ.setdefault("CARDNEWS_DATA", str(여기 / "data"))

import lambda_분석 as 분석  # noqa: E402
import 카드뉴스만들기 as 만들기  # noqa: E402


def _짓기잡기(monkeypatch):
    """`짓기` 에 실제로 넘어온 것을 잡아 둔다. LLM 도 그물도 안 쓴다."""
    받은것 = {}

    # `람다마감` 은 람다가 끊기는 시각이다(2026-09-24) — 진짜와 모양이
    # 갈리면 문이 던지는 값을 못 받아 통째로 실패한다.
    def 가짜짓기(주제, 원고="", 틀이름="기본", 알림=None,
              예산초=600, 언어=만들기.프롬프트.한국어, 사진="", 로고="",
              사진들=None, 람다마감=0, 사진꽂힘=None, 그만인가=None):
        받은것.update(주제=주제, 틀이름=틀이름, 언어=언어,
                  사진=사진, 로고=로고, 사진들=list(사진들 or []))
        return {"장수": 1, "작업대": "https://x/판.html", "구운것": [], "표지": "",
                "주제": 주제, "틀": 틀이름, "말투": "짝", "점수표": ""}

    # `카드뉴스한판` 안에서 `import 카드뉴스만들기` 를 그때 한다(무거워서).
    # 그래도 sys.modules 에 있는 **같은 모듈 객체**를 받으므로 여기서 갈아
    # 끼우면 그대로 걸린다.
    monkeypatch.setattr(만들기, "짓기", 가짜짓기)
    monkeypatch.setattr(분석, "_일적기", lambda *a, **k: None)
    monkeypatch.setattr(분석, "_덜잡힘한줄", lambda 틀: "")
    return 받은것


def test_봉투에_실은_언어가_짓기까지_간다(monkeypatch):
    받은것 = _짓기잡기(monkeypatch)
    분석.카드뉴스한판({"번호": "1", "주제": "강남 카페", "언어": "영어"})
    assert 받은것["언어"] == "영어"


def test_봉투에_언어가_없으면_한국어다(monkeypatch):
    """옛 요청이 그대로 돌아야 한다 — 칸이 늘었다고 깨지면 안 된다."""
    받은것 = _짓기잡기(monkeypatch)
    분석.카드뉴스한판({"번호": "1", "주제": "강남 카페"})
    assert 받은것["언어"] == 만들기.프롬프트.한국어


def test_모르는_언어는_한국어로_떨어진다(monkeypatch):
    """«en»·«English»·오타가 와도 죽지 않는다.

    **조용히 한국어로 떨어지는 쪽을 고른다** — 카드가 안 나오는 것보다 낫다.
    영어로 가는 길은 「영어」 한 낱말뿐이고, 그건 화면이 보낸다.
    """
    받은것 = _짓기잡기(monkeypatch)
    분석.카드뉴스한판({"번호": "1", "주제": "강남 카페", "언어": "English"})
    assert 받은것["언어"] ==만들기.프롬프트.한국어


