# ── 답 읽기 ─────────────────────────────────────────────────────────

def _답(결="따뜻한 색", 장별=None, 인물=None, 후보=None):
    return json.dumps({"화풍후보": 후보 if 후보 is not None else [], "인물": 인물 or [],
                       "결": 결, "장별": 장별 if 장별 is not None else []}, ensure_ascii=False)


def _장(장, *자리):
    return {"장": 장, "생각": "…", "자리": list(자리)}


def test_계획읽기가_번호를_0부터로_바꾼다():
    카드들 = [카드(사진, 도형, 작은사진)]
    계획 = 사진계획.계획읽기(_답(장별=[_장(1, {"자리": 3, "한줄": "과자통 뚜껑을 닫는 손"})]), 카드들)
    assert 계획["결"] == "따뜻한 색"
    assert 계획["자리"] == [{"장": 0, "자리": 2, "한줄": "과자통 뚜껑을 닫는 손",
                          "참조": "", "등장": []}]


def test_계획읽기가_틀린_줄만_버린다():
    """없는 장·없는 자리·글자 번호·빈 한줄·같은 자리 둘 — 모델은 다 한다."""
    카드들 = [카드(사진, 작은사진)]
    글 = _답(장별=[_장(1, {"자리": 1, "한줄": "산다"},
                         {"자리": 1, "한줄": "같은 자리 — 버린다"},
                         {"자리": 5, "한줄": "없는 자리"},
                         {"자리": "2", "한줄": "글자 번호"},
                         {"자리": 2, "한줄": "   "},
                         "이건 사전이 아니다"),
                   _장(9, {"자리": 1, "한줄": "없는 장"}),
                   _장("1", {"자리": 2, "한줄": "글자 장 번호"}),
                   "이것도 사전이 아니다"])
    계획 = 사진계획.계획읽기(글, 카드들)
    assert [x["한줄"] for x in 계획["자리"]] == ["산다"]


def test_계획읽기가_참조_번호를_주소로_바꾼다():
    참조들 = [{"주소": "https://x/a.png", "본것": "캔"}, {"주소": "https://x/b.png", "본것": "컵"}]
    글 = _답(장별=[_장(1, {"자리": 1, "한줄": "참조 사진의 캔이 탁자 위", "참조": 2},
                          {"자리": 2, "한줄": "범위 밖", "참조": 7})])
    계획 = 사진계획.계획읽기(글, [카드(사진, 작은사진)], 참조들)
    assert 계획["자리"][0]["참조"] == "https://x/b.png"
    assert 계획["자리"][1]["참조"] == "", "범위 밖 번호는 참조 없음으로 산다"


def test_계획읽기가_화풍후보를_번호로_바꾸고_목록_밖은_버린다():
    글 = _답(후보=["겹종이 입체", "없는 화풍", "533", "겹종이 입체"])
    assert 사진계획.계획읽기(글, [카드(사진)])["화풍후보"] == ["435", "533"]


def test_기본은_AI_후보가_못_된다():
    """«기본» 은 사람만 고른다 — 후보에 남으면 미리보기에 「기본 · AI 추천」 이 뜬다."""
    글 = _답(후보=["기본", "기본 화풍", "겹종이 입체"])
    assert 사진계획.계획읽기(글, [카드(사진)])["화풍후보"] == ["435"]


def test_계획읽기가_인물표를_읽고_등장은_인물표에_있는_이름만_남긴다():
    글 = _답(인물=[{"이름": "지미", "생김새": "검은 후드티, 둥근 안경"},
                 {"이름": "지미", "생김새": "겹친 이름 — 버린다"},
                 {"이름": "", "생김새": "이름 없음"}, {"이름": "판사"}, "글자"],
             장별=[_장(1, {"자리": 1, "한줄": "책상 앞 지미", "등장": ["지미", "유령", "지미", 3]})])
    계획 = 사진계획.계획읽기(글, [카드(사진)])
    assert 계획["인물"] == [{"이름": "지미", "생김새": "검은 후드티, 둥근 안경"}]
    assert 계획["자리"][0]["등장"] == ["지미"]


def test_밈_자리는_한줄을_버리고_참조만_산다():
    카드들 = [카드(사진, 작은사진, 역할="훅", index=1)]
    참조들 = [{"주소": "https://x/a.png", "본것": "캔"}]
    글 = _답(장별=[_장(1, {"자리": 1, "한줄": "밈 자리에 적은 줄 — 버린다", "참조": 1},
                          {"자리": 2, "한줄": "작은 자리"})])
    계획 = 사진계획.계획읽기(글, 카드들, 참조들)
    assert 계획["자리"][0] == {"장": 0, "자리": 0, "한줄": "", "참조": "https://x/a.png", "등장": []}
    assert 계획["자리"][1]["한줄"] == "작은 자리"
    글2 = _답(장별=[_장(1, {"자리": 1, "한줄": "참조 없는 밈 줄 — 통째로 버린다"})])
    assert 사진계획.계획읽기(글2, 카드들)["자리"] == []


def test_계획읽기가_울타리와_앞뒤_말을_걷어낸다():
    글 = "알겠습니다.\n```json\n" + _답(장별=[_장(1, {"자리": 1, "한줄": "손"})]) + "\n```"
    assert 사진계획.계획읽기(글, [카드(사진)])["자리"][0]["한줄"] == "손"


def test_계획읽기가_깨진_글이나_빈_계획이면_None():
    assert 사진계획.계획읽기("{이건 깨졌다", [카드(사진)]) is None
    assert 사진계획.계획읽기(_답(결=""), [카드(사진)]) is None
    assert 사진계획.계획읽기("[]", [카드(사진)]) is None


def test_계획읽기가_긴_줄을_자른다():
    글 = _답(결="가" * 1000, 장별=[_장(1, {"자리": 1, "한줄": "나" * 1000})],
             인물=[{"이름": "다" * 100, "생김새": "라" * 1000}])
    계획 = 사진계획.계획읽기(글, [카드(사진)])
    assert len(계획["결"]) == 사진계획.결상한
    assert len(계획["자리"][0]["한줄"]) == 사진계획.한줄상한
    assert len(계획["인물"][0]["생김새"]) == 사진계획.생김새상한


def test_계획읽기가_사진_아닌_자리와_찬_자리를_버린다():
    """모델이 번호를 다시 매겨 참조를 도형 자리에 붙이면(검토 I2) — 그 줄을 버려야
    참조가 «안 쓴 사진» 에 남는다."""
    카드들 = [카드(사진, 도형, dict(사진, media_url="https://x/1.png"))]
    글 = _답(장별=[_장(1, {"자리": 2, "한줄": "도형 자리 — 버린다", "참조": 1},
                          {"자리": 3, "한줄": "찬 자리 — 버린다"},
                          {"자리": 1, "한줄": "산다"})])
    계획 = 사진계획.계획읽기(글, 카드들, [{"주소": "https://x/a.png", "본것": "캔"}])
    assert [x["한줄"] for x in 계획["자리"]] == ["산다"]
    assert not any(x["참조"] for x in 계획["자리"]), "버린 줄의 참조가 살아남았다"


