def test_시스템_글은_사람이_정한_것만_말한다():
    글 = 사진계획.시스템짓기()
    for 있어야 in ("한 장에 한 장면", "네 컷", "그림 속에 글자를 넣지 않는다", "상표 로고",
                "셋을 고른다", "필름 스냅 실사", "생김새", "표지 밈 자리", "사람 사진이 이미 들어감"):
        assert 있어야 in 글, 있어야
    for 없어야 in ("피사체 하나", "다른 컷", "얼굴을 안 그린다", "비율에 맞는", "실존인물"):
        assert 없어야 not in 글, f"걷어낸 규칙 «{없어야}» 가 남았다"
    assert 화풍.목록줄() in 글
    for 칸 in ('"장별"', '"화풍후보"', '"인물"', '"등장"', '"참조"', '"결"'):
        assert 칸 in 글, f"답 모양에 {칸} 이 없다"


