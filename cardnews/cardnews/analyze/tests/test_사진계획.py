def 카드(*영역, 글=("첫 줄", "둘째 줄"), 역할="사례", index=None):
    난것 = {"역할": 역할,
            "장식영역": [dict(r) for r in 영역],
            "글자영역": [{"lines": [{"글": g} for g in 글]}]}
    if index is not None:
        난것["index"] = index
    return 난것


사진 = {"종류": "사진", "box": [0, 0, 1080, 600]}          # 큰 · 위 · 가로 1.80:1
작은사진 = {"종류": "사진", "box": [740, 1090, 1000, 1330]}  # 작은 · 아래 · 1.08:1
도형 = {"종류": "도형", "box": [0, 0, 100, 100]}


# ── 자리 말 ─────────────────────────────────────────────────────────

def test_자리말이_크기_위치_꼴을_말로_한다():
    말 = 사진계획.자리말({"box": [0, 0, 1080, 600]})
    assert "큰 자리" in 말 and "위쪽" in 말 and "가로로 긴 꼴" in 말


def test_자리말이_작은_아래_정사각을_가린다():
    말 = 사진계획.자리말({"box": [740, 1090, 1000, 1330]})
    assert "작은 자리" in 말 and "아래쪽" in 말 and "정사각에 가까운 꼴" in 말


def test_자리말에_배경_누끼_틀설명이_붙는다():
    말 = 사진계획.자리말({"box": [0, 0, 1080, 1350], "배경자리": True,
                     "누끼": True, "설명": "제품 사진"})
    assert "장 전체를 덮는 배경" in 말
    assert "배경을 뺀 피사체만" in 말
    assert "틀 설명 「제품 사진」" in 말


def test_네모를_모르면_모른다고_한다():
    assert 사진계획.자리말({}) == "크기 모름"


# ── 틀 힌트 ─────────────────────────────────────────────────────────

def test_틀힌트가_강조색_배경_글꼴을_뽑는다():
    틀 = {"강조색": "#A9ED66",
          "슬라이드": [{"배경": {"종류": "단색", "hex": "#FFFFFF"},
                     "글자슬롯": [{"font": "프리텐다드"}]}]}
    assert 사진계획.틀힌트(json.dumps(틀)) == "강조색 #A9ED66, 첫 장 배경 #FFFFFF, 글꼴 프리텐다드"


def test_틀힌트는_깨진_글이나_빈_틀이면_빈_글자다():
    assert 사진계획.틀힌트("이건 JSON 이 아니다") == ""
    assert 사진계획.틀힌트("{}") == ""


# ── 계획할 자리 ─────────────────────────────────────────────────────

def test_계획자리는_사진이_없는_사진_자리만_센다():
    카드들 = [카드(사진, 도형, dict(사진, media_url="https://x/1.png")),
           카드(작은사진, 역할="CTA")]
    assert 사진계획.계획자리(카드들) == [{"장": 0, "자리": 0}, {"장": 1, "자리": 0}]


# ── 입력 ────────────────────────────────────────────────────────────

def test_입력에_주제_장_자리가_번호와_말로_들어간다():
    글 = 사진계획.입력짓기([카드(사진, 도형, 작은사진, 글=("과자통 보관",), 역할="사례")],
                       "과자통 비트코인")
    assert '카드뉴스 주제: "과자통 비트코인"' in 글
    assert '장 1 (역할 사례) — 글: "과자통 보관"' in 글
    assert "  자리 1: 큰 자리" in 글
    assert "  자리 3: 작은 자리" in 글, "번호는 장식영역 차례다 — 도형을 건너뛰어도 3이다"
    assert "자리 2" not in 글, "도형은 사진 자리가 아니다"


def test_입력에_원고_힌트_바람_참조가_붙는다():
    글 = 사진계획.입력짓기([카드(사진)], "주제", 원고="원고 첫 줄", 힌트="강조색 #A9ED66",
                       참조들=[{"주소": "https://x/a.png", "본것": "빨간 캔 음료"}],
                       바람="카페 테이블 위에")
    assert "원고(앞부분): 원고 첫 줄" in 글
    assert "틀의 결 힌트: 강조색 #A9ED66" in 글
    assert '사람의 바람: "카페 테이블 위에"' in 글
    assert "참조 사진 1장" in 글 and "1번: 빨간 캔 음료" in 글


def test_원고는_앞부분만_싣는다():
    # 「가」를 세면 안 된다 — 자리 말의 「가로로 긴 꼴」에도 「가」가 있다.
    글 = 사진계획.입력짓기([카드(사진)], "주제", 원고="나" * 5000)
    assert "나" * 사진계획.원고상한 in 글
    assert "나" * (사진계획.원고상한 + 1) not in 글


