def test_본것만은_한_줄씩_돌려주고_자리에_안_꽂는다():
    카드들 = [카드("사례", 자리수=2)]
    사진들 = ["https://x/a.png", "https://x/b.png"]
    보내기 = _답([{"번호": 1, "본것": "빨간 캔 음료", "자리": 1},
                {"번호": 2, "본것": "흰 머그컵", "자리": None}])
    assert 사진읽기.본것만(카드들, 사진들, "주제", 보내기) == {
        "https://x/a.png": "빨간 캔 음료", "https://x/b.png": "흰 머그컵"}
    assert all("media_url" not in r for r in 카드들[0]["장식영역"]), "참조는 꽂지 않는다"


def test_본것만은_사진이나_자리가_없으면_안_부른다():
    보내기 = _답([])
    assert 사진읽기.본것만([카드("사례")], [], "주제", 보내기) == {}
    assert 사진읽기.본것만([카드("사례", 자리수=0)], ["https://x/a.png"], "주제", 보내기) == {}
    assert not hasattr(보내기, "받은몸"), "부를 까닭이 없는데 불렀다"


def test_본것만은_틀린_번호를_버린다():
    보내기 = _답([{"번호": 9, "본것": "없는 사진"}, {"번호": "1", "본것": "글자 번호"},
                {"번호": 1, "본것": "캔"}])
