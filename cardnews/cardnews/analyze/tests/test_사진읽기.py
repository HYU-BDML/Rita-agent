"""사람이 올린 사진을 «보고» 자리에 꽂는다.

사람 결정 2026-09-19: 「대본이 받은 사진을 보게 해야지 딥시크 비전 있잖아」.
사람 결정 2026-09-20: 「1번으로 ㄱ」 — 표지에는 자동으로 안 꽂는다.

**여기서 못 박는 것 셋**

1. **표지는 후보에 아예 안 든다.** 표지는 좋은 품질로 밈을 만드는 자리라,
   사람 사진이 자동으로 꽂히면 그걸 통째로 버린다.
2. **못 읽어도 카드뉴스는 나온다.** 사진을 못 보는 것과 카드가 안 나오는 것은
   다른 일이다 — 빈 자리는 역할 틀이 그린다.
3. **모델이 규칙을 어겨도 안 깨진다.** 같은 사진을 두 자리에, 없는 자리 번호로,
   글자를 번호 자리에 — 모델은 셋 다 한다.
"""
import json
import os
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(여기))
os.environ.setdefault("CARDNEWS_DATA", str(여기 / "data"))
os.environ.setdefault("DEEPSEEK_API_KEY", "시험열쇠")

import 사진읽기  # noqa: E402


def 카드(역할, 자리수=1, index=None, 설명=None):
    영역 = [{"종류": "사진", "box": [0, 0, 100, 100]} for _ in range(자리수)]
    if 설명 is not None:
        영역[0]["설명"] = 설명
    난것 = {"역할": 역할, "장식영역": 영역, "글자영역": []}
    if index is not None:
        난것["index"] = index
    return 난것


def _답(짝들):
    """딥시크가 낸 것처럼 꾸민 답. 망을 안 쓴다."""
    def 보내기(몸, 상한):
        보내기.받은몸 = 몸
        return {"choices": [{"message": {
            "content": json.dumps({"사진": 짝들}, ensure_ascii=False)}}]}
    return 보내기


# ── 꽂는다 ─────────────────────────────────────────────────────────

def test_짝지은_대로_꽂는다():
    카드들 = [카드("훅", index=1), 카드("사례", index=2), 카드("데이터", index=3)]
    사진들 = ["https://x/a.png", "https://x/b.png"]
    # 빈 자리는 표지를 뺀 둘 — 1번 사례, 2번 데이터.
    난것 = 사진읽기.꽂기(카드들, 사진들, "연말정산",
                   보내기=_답([{"번호": 1, "본것": "사람", "자리": 1},
                            {"번호": 2, "본것": "도표", "자리": 2}]))
    assert 난것["꽂은수"] == 2
    assert 카드들[1]["장식영역"][0]["media_url"] == "https://x/a.png"
    assert 카드들[2]["장식영역"][0]["media_url"] == "https://x/b.png"
    assert 난것["안쓴사진"] == []
    assert 난것["본것"]["https://x/a.png"] == "사람"


def test_표지에는_자동으로_안_꽂는다():
    """**사람 결정 2026-09-20.** 표지는 밈을 만드는 자리다 — 사람 사진이 자동으로
    꽂히면 좋은 품질도 밈도 한국어 문구도 다 버린다."""
    카드들 = [카드("훅", index=1), 카드("사례", index=2)]
    보내기 = _답([{"번호": 1, "본것": "사람", "자리": 1}])
    사진읽기.꽂기(카드들, ["https://x/a.png"], "연말정산", 보내기=보내기)
    assert "media_url" not in 카드들[0]["장식영역"][0], "표지에 꽂았다"
    assert 카드들[1]["장식영역"][0]["media_url"] == "https://x/a.png"
    # 모델에게 보여 준 자리 목록에도 표지가 없어야 한다.
    보인것 = 보내기.받은몸["messages"][1]["content"][0]["text"]
    assert "훅" not in 보인것, "표지를 후보로 보여 줬다"
    assert "사례" in 보인것


