def test_바닥판이_원본_무늬를_그대로_옮기고_거울로_뒤집지_않는다():
    """조각을 거울처럼 이어 붙이니 원본에 없던 줄무늬·격자가 생겼다
    (실물 2026-09-17: 예시 ③ 연노란 마름모 격자, ④ 세로 줄무늬).

    **잣대를 바꿨다**(사람 결정 2026-09-17: 「그라데이션이면 그라데이션, 디자인이
    한지면 한지, 등등 다 흡수할 수 있어야 한다」). 옛 시험은 바닥판이 «평평해질
    것»을 요구했는데, 그러면 줄무늬 배경을 만난 순간 그 디자인을 통째로 잃는다.
    지금 잣대는 «원본 무늬를 그대로 옮기되 없던 무늬를 만들지 말 것» 이다.

    거울 이어붙이기는 이 잣대에 걸린다 — 톱니를 반씩 뒤집어 붙이므로 가로
    무늬가 원본과 안 닮는다(실측: 닮은 정도 0.10. 지금 방식은 0.84).
    """
    h, w = 600, 1080
    rgb = np.zeros((h, w, 3), np.uint8)
    for x in range(w):
        rgb[:, x] = 200 + int(48 * (x % 200) / 200)      # 200화소마다 되풀이되는 톱니
    rgb = np.clip(rgb.astype(np.int16)
                  + np.random.RandomState(1).randint(-3, 4, (h, w, 3)), 0, 255).astype(np.uint8)
    png = B.바닥뜨기(rgb, np.ones((h, w), bool))
    assert png is not None
    깐것 = _풀기(png)
    원 = rgb.mean(axis=(0, 2))
    난 = 깐것.mean(axis=(0, 2))
    닮음 = float(np.corrcoef(원, 난)[0, 1])
    assert 닮음 >= 0.6, f"가로 무늬가 원본과 안 닮는다: {닮음:.2f}"
    # 거울로 붙였다면 이 잣대에 걸려야 한다 — 시험이 무엇이든 통과시키지 않는지 본다
    거울 = np.concatenate([원[:200], 원[:200][::-1]] * 3)[:w]
    assert float(np.corrcoef(원, 거울)[0, 1]) < 0.6


def test_바닥판이_잔점을_남긴다():
    """단색으로만 깔면 종이 질감이 통째로 사라진다.

    노이즈 ±6 은 `쓸모있나` 문턱을 못 넘어 `바닥뜨기` 가 `None` 을 낸다
    (위 시험과 같은 까닭). ±25 로 올려 관문을 통과시켰다."""
    h, w = 400, 600
    rgb = np.clip(np.full((h, w, 3), 240, np.int16)
                  + np.random.RandomState(2).randint(-25, 26, (h, w, 3)), 0, 255).astype(np.uint8)
    png = B.바닥뜨기(rgb, np.ones((h, w), bool))
    assert png is not None
    깐것 = _풀기(png).astype(np.float32)
    assert 깐것.std() > 1.0, "잔점이 없다"


# ---------------------------------------------------------------- 질감 되살리기
#
# **바닥판은 지어내지 않고 베낀다**(사람 결정 2026-09-17: 「그냥 네가 만들지 말고
# 그것을 그대로 캡쳐하든지 해서 전체 슬라이드 꽉 차게 채우면 되는 거 아님?」).
#
# 옛 방식(평균색 + 새로 뿌린 잔점)은 질감을 통째로 잃었다. 실물 DSW-6lrk5rs 2번
# 장 실측: 원본 배경은 어두운 점 무리가 80×160 칸에 135개(평균 3.6화소)인데 만든
# 바닥판은 **0개**였다. 거칠기도 σ 6.62 → 2.53. 배경이 거의 흰색(253)이라 255 를
# 넘는 밝은 잔점이 전부 잘려 나간 탓이다.

def _점무리(rgb, 기준칸=80 * 160):
    """어두운 점 무리의 «수·평균 크기» — 한지 질감의 잣대. 기준칸 넓이로 맞춰 센다."""
    g = rgb.mean(axis=2).astype(float)
    어두운 = (g < g.mean() - 12).astype(np.uint8)
    n, _, stats, _ = cv2.connectedComponentsWithStats(어두운)
    크기 = stats[1:, cv2.CC_STAT_AREA] if n > 1 else np.array([0])
    return (n - 1) / (g.size / 기준칸), float(크기.mean())


def test_바닥판이_원본_질감을_그대로_옮긴다():
    """점 무리의 수와 크기가 원본과 같아야 한다 — 지어내면 이 둘이 안 맞는다."""
    rgb = _장식얹기(_종이())
    남음 = _남음(rgb)
    깐것 = _풀기(B.바닥뜨기(rgb, 남음))
    원수, 원크기 = _점무리(rgb[100:400, 300:900])      # 라벨·장식 없는 자리
    난수, 난크기 = _점무리(깐것)
    assert 0.6 * 원수 <= 난수 <= 1.6 * 원수, f"점 무리 {난수:.0f}개 — 원본 {원수:.0f}개"
    assert 0.6 * 원크기 <= 난크기 <= 1.6 * 원크기, f"점 크기 {난크기:.1f} — 원본 {원크기:.1f}"


def test_바닥판_거칠기가_원본과_같다():
    """σ 가 원본의 3분의 1로 주저앉던 것(실측 6.62 → 2.53)을 막는다."""
    rgb = _장식얹기(_종이())
    깐것 = _풀기(B.바닥뜨기(rgb, _남음(rgb)))
    원 = rgb[100:400, 300:900].mean(axis=2).std()
    난 = 깐것.mean(axis=2).std()
    assert 0.7 * 원 <= 난 <= 1.4 * 원, f"거칠기 σ {난:.2f} — 원본 {원:.2f}"


def test_밋밋한_자리가_섞여도_질감을_잃지_않는다():
    """**후보가 많은 쪽이 이기면 안 된다.**

    실물 DSW-6lrk5rs: 10번 장만 질감 없는 순백(σ 0.00·점 0개)인데 그 장 후보가
    3,173개로 나머지 여섯 장(4,282개)의 74% 였다. 무작위로 뽑으면 열에 넷이
    밋밋한 조각이라 바닥판이 다시 맨들맨들해진다.
    """
    rgb = _장식얹기(_종이())
    rgb[100:1300, 600:1060] = 255            # 질감 없는 순백 — 넓이로는 이쪽이 크다
    남음 = _남음(rgb)
    깐것 = _풀기(B.바닥뜨기(rgb, 남음))
    원수, _ = _점무리(rgb[100:400, 80:560])   # 질감이 살아 있는 쪽
    난수, _ = _점무리(깐것)
    assert 난수 >= 0.6 * 원수, f"점 무리 {난수:.0f}개 — 밋밋한 쪽에 끌려갔다(원본 {원수:.0f}개)"


# ---------------------------------------------------------------- 하나를 골라 다 깐다
#
# **바닥판은 게시물에 하나고, 장마다 달라지면 안 된다**(사람 결정 2026-09-17:
# 「그냥 바닥판은 고정하라니까? 왜 바닥판이 슬라이드마다 달라지냐고」).
#
# 장마다 따로 뜨면 그 장에 깨끗한 자리가 얼마나 있느냐에 따라 질감이 미세하게
# 갈린다. 잘 나온 것 하나를 골라 **모든 장에 깔고**, 장마다는 라벨 안 된 것만
# 그 위에 얹는다.

def test_바닥판은_가장_잘_나온_장에서_고른다():
    """깨끗한 자리가 넓고, 여러 장이 동의하는 질감을 고른다.

    실물 DSW-6lrk5rs 는 네모가 가장 적은 장이 10번(질감 없는 순백)이라
    「네모 적은 장부터 처음 되는 것」 규칙이 밋밋한 바닥판을 골랐다.
    """
    좋은장 = _종이(seed=5)
    민민한장 = np.full((1350, 1080, 3), 255, np.uint8)
    후보 = [(3, "#FFFFFF", 민민한장, np.ones((1350, 1080), bool)),   # 네모가 가장 적다
            (9, "#FEFEFE", 좋은장, np.ones((1350, 1080), bool))]
    고른것 = B.바닥고르기(후보)
    assert 고른것 is not None, "하나도 못 골랐다"
    _, rgb, _ = 고른것
    assert rgb.mean(axis=2).std() > 3, "질감 없는 장을 골랐다"


def test_배경판은_바닥판을_깔고_라벨_안_된_것만_얹는다():
    """**빈칸이 없어야 한다**(사람 결정 2026-09-17: 「그걸 기본으로 다 깔면
    빈칸이 없을 거 아니야? 거기서 각 슬라이드마다 라벨링 안 되었던 부분들만
    추가를 하는 거지」)."""
    rgb = _장식얹기(_종이())
    바닥 = _풀기(B.바닥뜨기(rgb, _남음(rgb)))
    남음 = _남음(rgb)
    png = B.뜨기(rgb, 남음, 바닥=바닥)
    assert png is not None
    판 = _풀기(png)
    assert 판.shape == rgb.shape
    # 라벨 안 된 세로 검은 선은 살아 있어야 한다
    assert 판[600, 52].mean() < 100, "라벨 안 된 선이 사라졌다"
    # 라벨한 자리(구멍)에는 바닥판 질감이 깔려 있어야 한다 — 빈칸이 없다
    구멍속 = 판[920:980, 150:900]
    assert 구멍속.mean(axis=2).std() > 2, "구멍이 맨들맨들하다 — 바닥판이 안 깔렸다"
    assert 구멍속.mean() > 200, "구멍에 엉뚱한 것이 칠해졌다"


def test_모든_장이_같은_바닥판을_쓴다():
    """장마다 다른 질감이 나오면 안 된다."""
    가 = _장식얹기(_종이(seed=1))
    나 = _장식얹기(_종이(seed=2))
    바닥 = _풀기(B.바닥뜨기(가, _남음(가)))
    판가 = _풀기(B.뜨기(가, _남음(가), 바닥=바닥))
    판나 = _풀기(B.뜨기(나, _남음(나), 바닥=바닥))
    잰곳 = (slice(920, 980), slice(150, 900))     # 두 장 모두 구멍인 자리
    assert np.array_equal(판가[잰곳], 판나[잰곳]), "같은 바닥판인데 구멍 속이 다르다"


def test_자리가_좁은_장도_바닥판_후보가_된다():
    """**고르는 잣대가 뜨는 잣대보다 빡빡하면 안 된다.**

    `바닥고르기` 는 80화소 창만 찾는데 `바닥뜨기` 는 56·32·20 까지 내려간다.
    그래서 80 짜리 자리가 없는 게시물은 「바닥판 못 뜸」이 되고, 장마다 제
    바닥을 따로 떠서 질감이 갈렸다 — 실물 2026-09-17 DYWiVHhlNwo: 장마다
    한지 점 367~410개가 제각각 나왔다.
    """
    rgb = _종이(h=400, w=400, seed=7)
    남음 = np.zeros((400, 400), bool)
    남음[10:70, 10:390] = True         # 80 짜리 창이 안 들어가는 좁은 띠
    남음[330:390, 10:390] = True
    assert B._깨끗한자리들(남음, 80).size == 0, "시험 재료가 뜻과 다르다"
