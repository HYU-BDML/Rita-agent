"""바닥판 — 게시물의 «그냥 배경» 한 장.

**바닥은 종이 질감(또는 그라데이션) 뿐이다**(사람 결정 2026-09-15). 선·동그라미·
로고는 배경이 아니라 그 위에 쌓는 조각이다. 배경판(`배경판.뜨기`)은 사람이 그은
네모만 뺀 «나머지 전부» 라 그런 조각이 같이 들어 있고, 그걸 사진 장에 깔았더니
2번 장의 세로 선과 동그라미가 표지에 딸려 나왔다(실물 2026-09-15, DSW-6lrk5rs).

그래서 남은 자리 안에서 **구조가 없는 조각**(구멍 없고 큰 덩어리 없음)을 찾아
장 크기로 이어 붙인다. 못 찾으면 안 뜬다.
"""
import io
