def _종이(h=1350, w=1080, seed=0):
    """흰 종이에 잔 점이 흩어진 질감."""
    rng = np.random.default_rng(seed)
    rgb = np.full((h, w, 3), 254, np.uint8)
    점 = rng.random((h, w)) < 0.02
    rgb[점] = (200, 200, 200)
    return rgb


def _장식얹기(rgb):
    rgb = rgb.copy()
    rgb[300:900, 50:56] = (20, 20, 20)                       # 세로 검은 선
    cv2.circle(rgb, (540, 30), 40, (92, 142, 245), -1)        # 파란 동그라미
    return rgb


def _남음(rgb, 구멍=((900, 1000, 100, 980),)):
    남음 = np.ones(rgb.shape[:2], bool)
    for y0, y1, x0, x1 in 구멍:
        남음[y0:y1, x0:x1] = False
    return 남음


def _큰덩어리수(rgb, 문턱=24):
    """으뜸색과 눈에 띄게 다른 화소 중 `문턱` 화소보다 큰 덩어리의 수."""
    색 = np.median(rgb.reshape(-1, 3), axis=0)
    차 = np.abs(rgb.astype(np.int16) - 색.astype(np.int16)).max(axis=2)
    n, _, stats, _ = cv2.connectedComponentsWithStats((차 > B.강한문턱).astype(np.uint8))
    return int((stats[1:, cv2.CC_STAT_AREA] > 문턱).sum())


def _풀기(png: bytes) -> np.ndarray:
    return np.asarray(Image.open(io.BytesIO(png)).convert("RGB"))


def test_선과_동그라미는_빠지고_질감은_남는다():
    rgb = _장식얹기(_종이())
    png = B.바닥뜨기(rgb, _남음(rgb))
    assert png is not None
    난것 = _풀기(png)
    assert 난것.shape == rgb.shape
    assert _큰덩어리수(난것) == 0, "선이나 동그라미가 바닥에 남았다"
    다른 = B.다른화소(난것, np.ones(난것.shape[:2], bool))
    assert 다른.mean() > 0.005, "종이 질감이 사라졌다"


def test_구멍은_안_남는다():
    """뚫린 자리(사람이 그은 네모)가 조각에 들면 그 자리가 평평해진다."""
    rgb = _종이()
    png = B.바닥뜨기(rgb, _남음(rgb))
    난것 = _풀기(png)
    # 구멍 자리에도 질감이 있어야 한다
    다른 = B.다른화소(난것, np.ones(난것.shape[:2], bool))
    assert 다른[900:1000, 100:980].mean() > 0.005


def test_구멍이_촘촘해도_작은_조각으로_뜬다():
    """실물 DSW-6lrk5rs 2번 장: 글자 네모가 커서 180px 창은 없고 120px 부터 있다."""
    rgb = _종이()
    남음 = np.ones(rgb.shape[:2], bool)
    for y in range(0, 1350, 130):
        남음[y:y + 30, :] = False           # 가로 띠 구멍
    for x in range(0, 1080, 130):
        남음[:, x:x + 30] = False           # 세로 띠 구멍 → 빈 칸이 100px
    assert B.바닥뜨기(rgb, 남음) is not None


