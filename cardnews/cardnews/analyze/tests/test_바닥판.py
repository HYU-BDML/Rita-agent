def test_바닥판은_질감이_가장_좋은_장에서_뜬다(monkeypatch, tmp_path):
    """**네모가 적은 장부터 처음 되는 것을 쓰지 않는다**(사람 결정 2026-09-17).

    실물 DSW-6lrk5rs 는 네모가 가장 적은 장이 10번인데 그 장만 질감 없는
    순백(거칠기 0.00 · 한지 점 0개)이라, 옛 규칙이 밋밋한 바닥판을 골랐다.
    """
    monkeypatch.setattr(config, "DATA", tmp_path)
    종이 = _장식얹기(_종이())
    민민 = np.full((1350, 1080, 3), 255, np.uint8)
    후보 = [(3, "#FFFFFF", 민민, np.ones((1350, 1080), bool)),     # 네모가 적지만 질감이 없다
          (9, "#FEFEFE", 종이, _남음(종이))]
    난것, 깐것 = merge_labeled.바닥판("PID", 후보)
    assert 난것 == {"hex": "#FEFEFE", "판": "PID/base.png"}
    assert (tmp_path / "배경판" / "PID" / "base.png").exists()
    assert 깐것 is not None and 깐것.mean(axis=2).std() > 3, "질감 없는 바닥판을 떴다"


