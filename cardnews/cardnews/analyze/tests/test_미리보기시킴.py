# ── 번호표에 «어디까지 왔는지» 를 적는다 (사람 지시 2026-09-20) ────
#
# 「기다리는 표시 예를들어 얼마나 되고있는지 퍼센트를 나타내주는거」
#
# **여태 단계 이름이 로그에만 찍히고 번호표에는 안 실렸다.** 화면이 5초마다
# 번호표를 보는데 거기 `progress` 숫자만 있으니, 사람은 3분 24초 동안 아무
# 변화도 못 봤다. 「1~2분」이라 적힌 말만 보고 「멈췄나?」 하게 된다.

def test_번호표에_퍼센트와_단계_이름이_같이_적힌다(그물, monkeypatch):
    def 알림쓰는대본(주제, 원고="", 틀이름="기본", 알림=None,
                 예산초=600, 언어=만들기.프롬프트.한국어, 사진들=None):
        알림(30, "대본을 쓴다")
        return {"카드": _카드(), "주제": 주제, "틀": 틀이름, "말투": "짝",
                "장수": 1, "점수표": ""}

    monkeypatch.setattr(만들기, "대본까지", 알림쓰는대본)
    분석.미리보기한판({"번호": "1", "주제": "강남 카페"})
    도는중 = [것 for 것 in 그물["적힌것"] if 것.get("status") == "running"]
    assert 도는중, "도는 동안 번호표에 아무것도 안 적었다"
    적힌것 = 도는중[-1]
    assert 적힌것["progress"] == 30
    assert 적힌것.get("말") == "대본을 쓴다", (
        f"단계 이름이 번호표에 없다 — 화면이 보여 줄 것이 없다: {적힌것}")


# ── 미리보기: 돈이 안 나간다 ──────────────────────────────────────

def test_미리보기는_굽지_않는다(그물):
    분석.미리보기한판({"번호": "1", "주제": "강남 카페"})
    assert "굽기" not in 그물["부른것"], "미리보기가 구웠다 — 돈이 나갔다"
    assert 그물["부른것"] == ["대본까지"]


def test_미리보기는_사진_고른것을_받아도_안_만든다(그물):
    """「만듦」을 골라 둔 채로 와도 여기서는 안 만든다 — 구울 때 만든다."""
    분석.미리보기한판({"번호": "1", "주제": "강남 카페", "사진": "만듦"})
    assert 그물["부른것"] == ["대본까지"]


def test_미리보기_답에_밑그림이_통째로_실린다(그물):
    """화면이 장마다 그려야 하고, 구울 때 그대로 돌려보내야 한다."""
    분석.미리보기한판({"번호": "1", "주제": "강남 카페"})
    끝 = _끝난것(그물)
    assert 끝["status"] == "succeeded"
    밑그림 = 끝["result"]["밑그림"]
    assert 밑그림["카드"] == _카드()
    assert 밑그림["장수"] == 1


def test_미리보기도_언어와_틀을_그대로_넘긴다(그물):
    """봉투 읽는 자리를 만들기와 나눠 쓴다 — 한쪽만 새 칸을 받으면 안 된다."""
    분석.미리보기한판({"번호": "1", "주제": "강남 카페", "언어": "영어",
                 "틀": "키키"})
    받은것 = 그물["대본까지받은것"]
