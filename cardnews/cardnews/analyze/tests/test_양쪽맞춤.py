# -*- coding: utf-8 -*-
"""양쪽 맞춤 — 왼쪽 끝도 오른쪽 끝도 일자인 글은 «가운데» 가 아니다.

실물 2026-09-16, DSW-6lrk5rs 7번 장 본문: 신문 조판처럼 양쪽 끝을 다 맞춘 글이라
왼쪽·가운데·오른쪽 흩어짐이 셋 다 0 에 가까웠고, 몇 픽셀 차이로 «가운데» 가 뽑혔다.
새 글은 줄 길이가 제각각이라 가운데로 몰면 삐뚤빼뚤해진다.

우리는 양쪽 맞춤을 못 그린다 — 그러니 **왼쪽** 으로 적는다.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))

from ruler import text as rtext  # noqa: E402


def _줄(x0, x1, y=0):
    return {"box": [x0, y, x1, y + 40]}


def test_양쪽_다_맞으면_왼쪽이다():
    줄들 = [_줄(143, 1031), _줄(144, 1030), _줄(143, 1032), _줄(142, 1031), _줄(143, 1030)]
    assert rtext._align(줄들) == "왼쪽"


def test_마지막_줄만_짧아도_양쪽_맞춤이다():
    줄들 = [_줄(143, 1031), _줄(144, 1030), _줄(143, 1032), _줄(142, 1031), _줄(143, 700)]
    assert rtext._align(줄들) == "왼쪽"


def test_진짜_가운데는_가운데다():
    줄들 = [_줄(300, 780), _줄(400, 680), _줄(200, 880)]
    assert rtext._align(줄들) == "가운데"


def test_왼쪽_정렬은_그대로_왼쪽이다():
    줄들 = [_줄(143, 900), _줄(143, 600), _줄(143, 1000)]
    assert rtext._align(줄들) == "왼쪽"


def test_오른쪽_정렬은_그대로_오른쪽이다():
    줄들 = [_줄(300, 1000), _줄(600, 1000), _줄(100, 1000)]
    assert rtext._align(줄들) == "오른쪽"
