def test_뜬_판도_물린_자리를_쓴다():
    """판정만 물리고 그림은 안 물리면 삐져나온 잉크가 그대로 실린다.

    뜻이 뒤집혔다(사람 결정 2026-09-17): 이제 뚫린 자리는 투명이 아니라
    면잇기가 메운다. 삐져나온 잉크 자리도 뚫림에 들어가 이어 그린 색으로
    바뀌므로, 「실렸는지」는 원래 검은 잉크(0,0,0)가 그대로 남았는지로 잰다."""
    rgb = np.full((300, 300, 3), 255, np.uint8)
    rgb[10:20, :] = (20, 20, 20)     # 진짜 무늬 — 넉넉히 크다
    rgb[147:150, 100:200] = 0        # 네모에서 삐져나온 잉크
    남음 = np.ones((300, 300), bool)
    남음[150:200, 100:200] = False
    a = np.asarray(Image.open(io.BytesIO(B.뜨기(rgb, 남음))))
    assert tuple(a[15, 150]) == (20, 20, 20), "진짜 무늬가 빠졌다"
    assert tuple(a[148, 150]) != (0, 0, 0), "삐져나온 잉크가 그대로 실렸다"


def _끊은그림():
    """노란 원·파란 네모·그라데이션 띠를 글자 네모가 가로막은 그림.
    `(원본, 가려진 그림, 뚫림)` 을 돌려준다."""
    import cv2
    민것 = np.full((700, 1080, 3), (250, 250, 248), np.uint8)
    cv2.circle(민것, (220, 220), 160, (250, 226, 120), -1)
    cv2.rectangle(민것, (440, 90), (1020, 330), (150, 185, 235), -1)
    for x in range(440, 1020):
        민것[380:430, x] = (255 - int((x - 440) * 0.18), 240, 200)
    가림 = 민것.copy()
    네모들 = [(110, 175, 470, 285), (470, 165, 1040, 275), (330, 400, 700, 500)]
    뚫림 = np.zeros((700, 1080), bool)
    for x0, y0, x1, y1 in 네모들:
        가림[y0:y1, x0:x1] = (20, 20, 20)
        뚫림[y0:y1, x0:x1] = True
    return 민것, 가림, 뚫림


# **「끊긴 도형을 이어 되살린다」 시험을 걷어냈다**(2026-09-17).
#
# 그 장치(색을 열 갈래로 나누고 면마다 반지름 닫기로 구멍을 건너기)는 실물에서
# **한 번도 안 돌았다** — 닫기 반지름이 열 장 모두 상한값 480 으로 나와 아무것도
# 제한하지 못했고, 결국 「제일 가까운 갈래가 먹는다」로 주저앉았다. 그 대가로
# 흰 배경이 255·254·246·235 로 갈려 구멍 안에 곧은 회색 줄이 생겼고(세로줄
# 흔들림 원본 1.08 대 3.36), 사진 장은 화면의 27% 가 색 서너 개로 칠해졌다.
#
# 사람 결정 2026-09-17: 「그냥 나머지는 유추하지 말고 우리의 바닥판 그걸 하면
# 되잖니」. 도형이 잘려 보이면 그 도형을 라벨한다 — 지어내서 메우지 않는다.


def test_배경판에는_투명한_화소가_없다():
    """사람 결정 2026-09-17: 배경판은 「구멍 뚫린 그림」이 아니라 「꽉 찬 배경」이다."""
    _, 가림, 뚫림 = _끊은그림()
    png = B.뜨기(가림, ~뚫림)
    assert png is not None
    그림 = Image.open(io.BytesIO(png))
    assert 그림.mode == "RGB", f"투명 칸이 남았다: {그림.mode}"
    assert (np.asarray(그림) == 0).all(axis=2).mean() < 0.01


def test_네모_밖으로_삐져나온_획을_구멍을_넓혀_지운다():
    """글자 획 끝·받침이 사람 네모 밖으로 몇 화소 나온다.

    **한동안 「획만 지우기」로 갈아탔다가 되돌렸다**(사람 결정 2026-09-18).
    통째로 지우는 지금은 다시 구멍을 `넓힐폭` 만큼 부풀려 그 삐져나온 잉크를
    먹는다 — 안 먹으면 그 검은 점이 배경판에 눌어붙는다.
    """
    뚫림 = np.zeros((100, 100), bool)
    뚫림[40:60, 40:60] = True
    넓힌 = B.넓히기(뚫림)
    assert 넓힌[40 - B.넓힐폭, 50]
    assert not 넓힌[40 - B.넓힐폭 - 3, 50]


def test_글자_네모는_통째로_지운다():
    """**획만 지우지 않는다**(사람 결정 2026-09-18: 「야 획 말고 그냥 내가 글자
    라벨링 칠한 그 공간 있잖아, 그걸 지워」).

    획만 지우기는 «지워진 자리를 지어내야 하니 되도록 적게 버리자» 는 셈이었다.
    바닥판이 제대로 생긴 뒤로는 지어낼 일이 없다 — 통째로 지워도 그 자리에
    바닥판이 깔린다. 그래서 얻는 것 없이 탈만 남았다: 칸 안에 형광펜·사진이
    깔리면 바탕색이 뒤집혔고(실물 키키 1번 장), 부드러운 경계가 문턱을 못 넘어
    얼룩이 남았다.
    """
    rgb = np.full((300, 400, 3), 252, np.uint8)
    rgb[120:200, 60:340] = (220, 229, 102)        # 칸 안 형광펜 덩어리
    rgb[140:180, 80:320] = (230, 60, 60)          # 그 위 글씨
    regs = [{"kind": "글자", "box": [40, 60, 360, 240]}]
    남음 = merge_labeled.residual(rgb, regs, rgb=rgb)   # `_build` 가 부르는 그대로
    assert not 남음[60:240, 40:360].any(), "글자 네모 안이 남았다"
    assert 남음[10, 10], "칸 밖까지 지웠다"
