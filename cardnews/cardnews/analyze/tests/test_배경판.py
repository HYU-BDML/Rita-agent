"""배경판 — 남은 픽셀을 그림으로 뜬다.

**뜰 값이 없으면 안 뜬다**가 이 파일이 지키는 첫 성질이다. 없는데 뜨면 창고에
흰 그림만 장마다 쌓인다.
"""
import io
