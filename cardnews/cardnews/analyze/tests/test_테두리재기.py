# ── 라벨 모양이 선에서 몇 px 어긋나도 찾는다 (실측 2026-09-28) ────────────
#
# 옛 코드는 «모양 가장자리 0번 겹이 곧 선» 이라고 믿었다. 사람이 그은 모양이 선보다
# 2~4px 안쪽이거나(그로스플래닛 Point! 상자), 기계가 흘려채우기로 딴 모양이 번짐까지
# 포함해 1~2px 바깥이면(스나이퍼팩토리 꿀팁 상자) 0번 겹은 배경·번짐색이라 「선 없음」
# 이었다. 8칸 중 7칸을 그렇게 놓쳤다. 선은 모양 가장자리 «둘레 몇 px 안» 에서 찾는다.

def _상자와선(굵기=2, 선색=(0, 0, 0), 속색=(255, 255, 255), 밖색=(242, 242, 242),
           크기=300, 안=(60, 60, 240, 240), 번짐=False):
    """종이 위 상자. 상자 가장자리 «안쪽» 으로 `굵기` px 선이 둘러 있다.
    `번짐` 이면 선 안팎 1px 을 중간색으로 흐린다(사진 압축·안티에일리어싱 자리)."""
    img = np.full((크기, 크기, 3), 밖색, np.uint8)
    x0, y0, x1, y1 = 안
    img[y0:y1, x0:x1] = 속색
    g = 굵기
    img[y0:y0 + g, x0:x1] = 선색; img[y1 - g:y1, x0:x1] = 선색
    img[y0:y1, x0:x0 + g] = 선색; img[y0:y1, x1 - g:x1] = 선색
    if 번짐:
        밖섞 = tuple((a + b) // 2 for a, b in zip(선색, 밖색))
        속섞 = tuple((a + b) // 2 for a, b in zip(선색, 속색))
        img[y0 - 1, x0 - 1:x1 + 1] = 밖섞; img[y1, x0 - 1:x1 + 1] = 밖섞
        img[y0 - 1:y1 + 1, x0 - 1] = 밖섞; img[y0 - 1:y1 + 1, x1] = 밖섞
        img[y0 + g, x0 + g:x1 - g] = 속섞; img[y1 - g - 1, x0 + g:x1 - g] = 속섞
        img[y0 + g:y1 - g, x0 + g] = 속섞; img[y0 + g:y1 - g, x1 - g - 1] = 속섞
    return img


def _네모마스크(크기, x0, y0, x1, y1):
    m = np.zeros((크기, 크기), bool); m[y0:y1, x0:x1] = True; return m


