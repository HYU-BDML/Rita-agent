def _네모(크기=260, 여백=30):
    """그림 안에 «떠 있는» 네모. 그림을 꽉 채우면 `_선넣기` 쪽 거리 재기도
    같이 막혀서 시험이 시험을 못 한다."""
    m = np.zeros((크기, 크기), bool)
    m[여백:-여백, 여백:-여백] = True
    return m


