# -*- coding: utf-8 -*-
"""말투를 디자인과 따로 뽑아 두는 자리.

사람이 고르는 축은 둘이다 — **디자인 하나, 말투 하나**. 그러려면 둘이 따로
쌓여 있어야 한다. 여태는 한 덩이라 「키키 디자인 + 다른 데 말투」를 못 골랐다.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import 말투틀  # noqa: E402


def _장(어미="반말", 격식="편안", 인칭="생략", 물음=False,
       재미="중간", 정중="중간", 열정="높음", 글들=(), 역할=None):
    return {"ending": 어미, "person": 인칭, "is_question": 물음,
            **({"role": 역할} if 역할 else {}),
            "tone": {"formality": 격식, "humor": 재미,
                     "respect": 정중, "enthusiasm": 열정},
            "regions": [{"text": {"line_detail": [{"text": g} for g in 글들]}}]}


def _잰것(장들, **더):
    return {"shortcode": "AAA", "post_type": "정보", "hook_strategy": "궁금증유발",
            "slides": 장들, **더}


def test_제일_많이_나온_것으로_접는다():
    """「합니다체와 반말의 평균」 같은 것은 없다 — 낱말이라서다."""
    난것 = 말투틀.뽑기(_잰것([_장(어미="반말"), _장(어미="반말"), _장(어미="해요체")]))
    assert 난것["어미"] == "반말"


def test_미정은_안_센다():
    """못 잰 것이지 답이 아니다."""
    난것 = 말투틀.뽑기(_잰것([_장(어미="미정"), _장(어미="미정"), _장(어미="해요체")]))
    assert 난것["어미"] == "해요체"


def test_다_미정이면_미정이다():
    assert 말투틀.뽑기(_잰것([_장(어미="미정")]))["어미"] == "미정"


def test_물음표_훅은_첫_장만_본다():
    """뒤 장은 본문이라 물음표의 뜻이 다르다."""
    assert 말투틀.뽑기(_잰것([_장(물음=True), _장()]))["물음표훅"] is True
    assert 말투틀.뽑기(_잰것([_장(), _장(물음=True)]))["물음표훅"] is False


def test_본보기는_실제_문장에서_온다():
    난것 = 말투틀.뽑기(_잰것([_장(글들=["요즘 강남 카페가 완전히 달라졌어"])]))
    assert 난것["본보기"] == ["요즘 강남 카페가 완전히 달라졌어"]


def test_짧은_조각은_본보기가_아니다():
    """「키키!」 한 마디로는 결을 못 본다."""
    assert 말투틀.뽑기(_잰것([_장(글들=["키키!", "짧다"])]))["본보기"] == []


def test_본보기는_셋까지다():
    글들 = [f"여덟 자가 넘는 문장 번호 {i}" for i in range(9)]
    assert len(말투틀.뽑기(_잰것([_장(글들=글들)]))["본보기"]) == 3


def test_같은_문장은_한_번만():
    난것 = 말투틀.뽑기(_잰것([_장(글들=["똑같은 문장이 두 번 나온다", "똑같은 문장이 두 번 나온다"])]))
    assert len(난것["본보기"]) == 1


def test_이름을_안_주면_코드가_이름이다():
    assert 말투틀.뽑기(_잰것([_장()]))["이름"] == "AAA"


def test_이름_뒤에_말투를_붙인다():
    """틀 이름과 같으면 채팅에서 「키키 말투로」라고 해도 틀이 같이 걸린다."""
    assert 말투틀.뽑기(_잰것([_장()]), "키키")["이름"] == "키키 말투"


def test_한줄설명이_문장이_된다():
    말투 = 말투틀.뽑기(_잰것([_장(어미="반말", 격식="편안", 인칭="여러분", 물음=True)]))
    글 = 말투틀.한줄설명(말투)
    assert "반말" in 글 and "편안" in 글 and "「여러분」" in 글 and "물음표 훅" in 글


def test_생략_인칭은_설명에_안_적는다():
    """부르는 말이 없다는 것은 특징이 아니라 «없음» 이다."""
    말투 = 말투틀.뽑기(_잰것([_장(인칭="생략")]))
    assert "생략" not in 말투틀.한줄설명(말투)


def test_프롬프트글이_원문을_보여_주고_내용은_베끼지_말라고_적는다():
    """**말이 바뀌었다**(사람 결정 2026-08-29). 「말투·문장 결·끝맺음만 따라
    써라」에서 「훅 여는 법·문장 길이·끝맺음·강조하는 자리를 그대로 배워 써라」로.

    말투를 고르는 것은 그 템플릿의 글을 **다 배워 따라 쓰라**는 뜻이지, 결만
    슬쩍 흉내 내라는 뜻이 아니다. 여태 배울 글이 세 줄뿐이라 모델이 대부분을
    스스로 지어냈고 그래서 「AI 스럽다」가 됐다.
    """
    말투 = 말투틀.뽑기(_잰것([_장(글들=["요즘 강남 카페가 완전히 달라졌어"])]))
    글 = 말투틀.프롬프트글(말투)
    assert "«요즘 강남 카페가 완전히 달라졌어»" in 글
    assert "배워 써라" in 글, 글
    assert "내용만 베끼지 마라" in 글, 글


def test_말투가_없으면_프롬프트글도_없다():
    """빈 글자면 프롬프트에 아무것도 안 붙는다."""
    assert 말투틀.프롬프트글({}) == "" and 말투틀.프롬프트글(None) == ""


def test_목록줄은_간판만_담는다():
    말투 = 말투틀.뽑기(_잰것([_장(글들=["요즘 강남 카페가 완전히 달라졌어"])]), "키키")
    줄 = 말투틀.목록줄(말투, "https://x/a.json", "2026-08-27")
    assert set(줄) == {"코드", "이름", "만든날", "설명", "본보기", "주소"}
    assert 줄["이름"] == "키키 말투"


# ── 문장으로 이어 재기 · 캐릭터 꼬리 · 훅 뜯기 (사람 결정 2026-09-19) ──
#
# 어미를 **줄 단위**로 재던 것이 틀렸다. 카드뉴스는 한 문장이 여러 줄에 걸쳐
# 잘리고, 잘린 줄의 끝은 대개 명사다. 그래서 줄만 세면 「명사형」이 이긴다 —
# 실측으로 10벌 중 **일곱 벌이 「명사형」으로 적혀 있는데 그중 넷이 해요체**다.


def test_줄이_잘려도_문장으로_이어_어미를_잰다():
    # 「…되었는데 / 이름하여 바로 키키!」 — 첫 줄 끝은 명사가 아니라 이음말이다.
    글 = ["얼마전 여돌이 공개 되었는데", "이름하여 바로 키키!",
         "많은 관심을 받고 있어요", "앞으로도 지켜봐 주세요"]
    assert 말투틀.문장어미(글) == "해요체"


def test_캐릭터_꼬리는_떼고_잰다():
    """「~다몬」은 «평서형 + 몬» 이다. 어미는 평서형이고 몬은 꼬리다."""
    # 꼬리는 세 번 넘게 나와야 «버릇» 으로 본다.
    글 = ["인급동 1위까지 달성했다몬", "바로 공유해줄게몬",
         "댓글로 남겨달라몬", "많은 관심을 끌었다몬"]
    assert 말투틀.문장어미(글) == "평서형"


def test_캐릭터_꼬리를_따로_적어_둔다():
    """**꼬리는 안 따라 쓴다**(사람 결정 2026-09-19). 「도리몬」은 남의 계정
    마스코트라, 내 카드뉴스에서 「~몬」이 나오면 베낀 티가 난다. 적어만 둔다."""
    # 세 번은 나와야 «버릇» 으로 본다 — 한두 번은 우연일 수 있다.
    난것 = 말투틀.뽑기(_잰것([
        _장(글들=["인급동 1위까지 달성했다몬", "바로 공유해줄게몬"]),
        _장(글들=["댓글로 남겨달라몬", "많은 관심을 끌었다몬"]),
    ]))
    assert 난것["캐릭터꼬리"] == "몬"


def test_꼬리가_없으면_안_싣는다():
    난것 = 말투틀.뽑기(_잰것([_장(글들=["오늘도 좋은 하루 보내세요"])]))
    assert not 난것.get("캐릭터꼬리")


def test_마침표를_쓰는지_잰다():
    """10벌이 갈린다 — 키키는 34줄에 0개, AI 시대는 22개다."""
