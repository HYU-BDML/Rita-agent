# ── 올린 사진을 «보고» 꽂는다 (사람 결정 2026-09-19·2026-09-20) ─────
#
# 여태는 올린 차례대로 앞에서부터 꽂았다 — 사람이 올린 차례가 카드 차례와 같을
# 까닭이 없어서 대개 엉뚱한 데 들어갔다. 이제 `사진읽기.꽂기` 가 사진을 보고
# 역할에 맞춰 꽂는다(표지는 뺀다).

def _사진자리있는틀(monkeypatch):
    """장마다 사진 자리가 하나 있는 틀로 갈아 끼운다.

    기본 시험 틀(`_틀`)은 장식영역이 비어 있다 — 꽂을 자리가 없으면 「안 잃는다」를
    보는 시험이 **아무것도 안 지키고 초록**이 된다.
    """
    틀 = _틀()
    for 장 in 틀["슬라이드"]:
        장["장식영역"] = [{"종류": "사진", "box": [0, 0, 100, 100]}]
        장["사진자리수"] = 1
    for 역할, 옷들 in 틀["서랍"].items():
        for 옷 in 옷들:
            옷["장식영역"] = [{"종류": "사진", "box": [0, 0, 100, 100]}]
            옷["사진자리수"] = 1
    monkeypatch.setattr(만들기, "틀받기",
                        lambda 이름: json.dumps(틀, ensure_ascii=False))


def _꽂기잡기(monkeypatch, 꽂을주소=None):
    """`사진읽기.꽂기` 를 갈아 끼운다. **망도 모델도 안 쓴다.**"""
    받은것 = {}

    def 가짜꽂기(카드들, 사진들, 주제, 보내기=None):
        받은것.update(카드수=len(카드들), 사진들=list(사진들), 주제=주제)
        받은것["불린수"] = 받은것.get("불린수", 0) + 1
        if 꽂을주소:
            for 카드 in 카드들:
                for r in 카드.get("장식영역") or []:
                    if r.get("종류") in ("사진", "인물"):
                        r["media_url"] = 꽂을주소
                        return {"꽂은수": 1, "안쓴사진": [], "본것": {}}
        return {"꽂은수": 0, "안쓴사진": list(사진들), "본것": {}}

    monkeypatch.setattr(만들기.사진읽기, "꽂기", 가짜꽂기)
    return 받은것


