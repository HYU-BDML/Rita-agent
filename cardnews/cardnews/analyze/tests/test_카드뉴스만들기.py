def test_말투를_이름으로_고르는_길은_없다():
    """**말투는 늘 틀의 짝이다**(사람 지시 2026-09-24: 「템플릿의 말투를 그대로
    쓴다, 사용자가 부탁해도 그냥 그 템플릿 말투 쓸거야」).

    여태 `말투받기(이름)` 과 `말투이름` 인자가 남아 있었다. 웹 채팅은 진작부터
    빈 값을 보내서 **그 갈래는 안 돌았는데**, 코드에 남아 있으니 읽는 사람이
    「고를 수 있구나」로 읽었다. 되살리려면 사람에게 먼저 묻는다.
    """
    import inspect
    assert not hasattr(만들기, "말투받기"), "이름으로 말투 받는 길이 되살아났다"
    for 무엇 in (만들기.대본까지, 만들기.짓기):
        칸 = inspect.signature(무엇).parameters
        assert "말투이름" not in 칸, f"{무엇.__name__} 에 말투이름이 되살아났다"


