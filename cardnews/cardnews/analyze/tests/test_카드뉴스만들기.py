def _위계있는틀():
    """`_틀()` 에 위계를 얹은 것(형광펜 색은 없음). 「본문」이 네 장 다 반복된다.

    **「슬라이드」와 「서랍」 둘 다 손본다.** `틀고르기.main()` 은 「서랍」에서
    디자인을 다시 꺼내 「슬라이드」를 새로 짓는다 — 「슬라이드」만 손보면
    `_강조글` 을 직접 부르는 시험은 통과해도, `짓기()` 사슬을 태우는 시험은
    (그 사슬이 실제로 쓰는 값은 「서랍」 쪽이라) 빈 채로 나온다.
    """
    틀 = _틀()
    글자슬롯_묶음 = [s["글자슬롯"] for s in 틀["슬라이드"]]
    for 디자인들 in 틀["서랍"].values():
        글자슬롯_묶음 += [d["글자슬롯"] for d in 디자인들]
    for 글자슬롯 in 글자슬롯_묶음:
        for 슬롯 in 글자슬롯:
            슬롯["위계"] = "본문"
    return 틀


def test_강조글이_같은_위계를_한_번만_담는다():
    """「본문」이 네 장(훅·사례·요약·CTA) 다 반복돼도 한 줄만 나와야 한다.

    **칸마다 할 말이 있을 때만 줄이 난다**(2026-09-18). 형광펜 금지를 없앴으니
    이제 남은 것은 소제목·출처뿐이다 — 그것을 얹어서 줄이 나게 한다.
    """
    틀 = _위계있는틀()
    for 디자인들 in 틀["서랍"].values():
        for d in 디자인들:
            for 슬롯 in d["글자슬롯"]:
                슬롯["소제목첫줄"] = True
    for s in 틀["슬라이드"]:
        for 슬롯 in s["글자슬롯"]:
            슬롯["소제목첫줄"] = True
    글 = 만들기._강조글(json.dumps(틀, ensure_ascii=False))
    assert 글.count("본문:") == 1, 글


