def test_다시_얹어도_꽂힌_사진을_안_잃는다(monkeypatch):
    """**여기가 제일 나기 쉬운 자리다.** 다시 얹으면 카드가 새로 만들어져
    `media_url` 이 통째로 날아간다 — 사람이 미리보기에서 본 사진이 사라진다."""
    _깔기(monkeypatch, [_구조1, "대본"], 검증들=[_통과4])
    _사진자리있는틀(monkeypatch)
    _꽂기잡기(monkeypatch, 꽂을주소="https://x/사람사진.png")
