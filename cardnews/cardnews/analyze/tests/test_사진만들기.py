def test_딱_떨어지는_자리는_정확히_맞는다():
    # 462:308 은 3:2 다. 16 을 곱해 1536x1024 — 오차가 정확히 0 이다.
    폭, 높 = 사진만들기.그림크기(462, 308)
    assert (폭, 높) == (1536, 1024)
    assert 폭 / 높 == 462 / 308


@pytest.mark.parametrize(("w", "h"), [(743, 708), (605, 346), (675, 320),
                                      (380, 246), (424, 244), (497, 335)])
def test_어긋남은_반픽셀_안이다(w, h):
    """**«같다» 를 픽셀로 잰다**(사람 물음 2026-09-20: 「어떻게 보편적으로」).

    0.1% 처럼 못 박으면 자리마다 뜻이 달라진다 — 708px 자리에서는 0.7px 이고
    246px 자리에서는 0.2px 이다. 자리에 넣었을 때의 어긋남으로 재야 한 가지 뜻이다.
    """
    폭, 높 = 사진만들기.그림크기(w, h)
    비 = w / h
    어긋남 = abs(폭 / 높 - 비) / 비 * min(w, h)
    assert 어긋남 <= 0.5, (폭, 높, 어긋남)


