def 카드(*영역, 글=("첫 줄", "둘째 줄"), 역할="사례"):
    return {"역할": 역할,
            "장식영역": [{"종류": 종, "box": [0, 0, 100, 100]} for 종 in 영역],
            "글자영역": [{"lines": list(글), "위계": "제목"}]}


@pytest.fixture(autouse=True)
def _한장씩(monkeypatch):
    """**이 파일은 «부른 차례» 를 본다** — 그래서 한 장씩 돌린다.

    실물은 일곱 장을 한꺼번에 건다(`동시일꾼 = 0`). 여럿이 같이 돌면 부르는
    차례가 매번 달라져서, 「첫째 자리에 첫째 주소」 같은 시험이 들쭉날쭉해진다.
    한꺼번에 거는 길 자체는 `test_한꺼번에걸기.py` 가 따로 본다.
    """
    monkeypatch.setattr(사진만들기, "동시일꾼", 1)


def _손(주소들, 품질모음=None):
    """부른 지시문을 모아 두고 주소를 차례로 돌려주는 가짜 fal.

    `품질모음` 을 주면 «어느 품질로 불렀나» 도 같이 쌓는다 — 장마다 고른 품질로
    부르는지 보는 시험이 쓴다.
    """
    부른것 = []

    def 부르기(지시문, 누끼=False, 품질=None, 크기=None, 마감=None, 그만인가=None):
        부른것.append(지시문)
        if 품질모음 is not None:
            품질모음.append(품질)
        부르기.크기들.append(크기)
        난것 = 주소들[len(부른것) - 1]
        if isinstance(난것, Exception):
            raise 난것
        return 난것

    부르기.크기들 = []      # 자리마다 «어떤 크기로» 불렀는지
    return 부르기, 부른것


