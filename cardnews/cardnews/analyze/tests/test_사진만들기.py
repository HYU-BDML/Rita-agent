def test_사진과_인물_자리만_채운다():
    # 로고와 도형은 그 디자인의 알맹이지 사진이 아니다 — 덮으면 안 된다.
    카드들 = [카드("사진", "로고", "도형", "인물")]
    부르기, 부른것 = _손(["https://x/1.png", "https://x/2.png"])
    몇 = 사진만들기.채우기(카드들, "연말정산", 부르기=부르기, 잔액보기=lambda: 10.0)
    assert 몇 == 2
    자리 = 카드들[0]["장식영역"]
    assert 자리[0]["media_url"] == "https://x/1.png"
    assert 자리[3]["media_url"] == "https://x/2.png"
    assert "media_url" not in 자리[1] and "media_url" not in 자리[2]
    assert len(부른것) == 2


