# ── 빈손이면 결과를 다시 집는다 (사람 지시 2026-09-22) ──────────────
#
# 상태가 COMPLETED 라고 결과가 그 순간 준비된 것은 아니다. 그 틈에 집으면
# 빈손이 온다. **다시 집는 것은 돈이 안 든다** — 이미 만든 것을 집어 올 뿐이다.


class _가짜망:
    """`requests` 자리에 끼우는 가짜. 결과 문을 몇 번째에 채워 줄지 정해 준다."""

    def __init__(self, 언제채우나):
        self.언제채우나 = 언제채우나      # 결과 문을 몇 번째 물음부터 채울까
        self.결과물음 = 0

    def post(self, *_, **__):
        return _답({"status_url": "https://q/s", "response_url": "https://q/r"})

    def get(self, 주소, **__):
        if 주소.endswith("/s"):
            return _답({"status": "COMPLETED"})
        self.결과물음 += 1
        if self.결과물음 >= self.언제채우나:
            return _답({"images": [{"url": "https://x/1.png"}]})
        return _답({})


class _답:
    def __init__(self, 것):
        self.것 = 것
        self.status_code = 200

    def json(self):
        return self.것


def _망갈기(monkeypatch, 망):
    monkeypatch.setitem(sys.modules, "requests", 망)
    monkeypatch.setenv("FAL_KEY", "시험용")
    monkeypatch.setattr(사진만들기, "다시집는틈", 0)
    monkeypatch.setattr(사진만들기.time, "sleep", lambda *_: None)


def test_결과가_아직_비었으면_다시_집어_온다(monkeypatch, capsys):
    망 = _가짜망(언제채우나=2)      # 첫 물음엔 빈손, 두 번째에 그림
    _망갈기(monkeypatch, 망)
    assert 사진만들기.부르기("아무 지시문") == "https://x/1.png"
    assert 망.결과물음 == 2, "한 번 비었다고 바로 포기하면 안 된다"
    assert "집어 왔다" in capsys.readouterr().out, "조용히 넘기면 아무도 모른다"


