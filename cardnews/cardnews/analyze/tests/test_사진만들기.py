def test_품질과_값이_모델_페이지_표와_같다():
    """**품질과 값은 한 짝이다.** 한쪽만 고치면 로그에 찍히는 값과 잔액에서
    빠지는 값이 갈린다 — 2026-09-20 에 실제로 두 번 어긋났고 여기서 잡았다.

    **2026-09-20 에 모델 페이지에서 직접 확인한 표**(1024×1536). 품질은 **다섯**
    이다 — 셋인 줄 알고 적었다가 다시 보고 채웠다.
    """
    표 = {"low": 0.00474, "medium": 0.01029, "high": 0.04116,
         "xhigh": 0.07377, "max": 0.16464}
    assert 사진만들기.품질표 == pytest.approx(표)
    assert (사진만들기.그림폭, 사진만들기.그림높이) == (1024, 1536)
    for 품질 in (사진만들기.표지품질, 사진만들기.본문품질):
        assert 품질 in 표, f"«{품질}» 이 모델 페이지 표에 없다"
        assert 사진만들기.한장값(품질) == pytest.approx(표[품질])


def test_모르는_품질은_제일_비싼_값으로_친다():
    """**모자라게 잡으면 잔액이 있는 줄 알고 시작했다가 중간에 멈춘다.**"""
