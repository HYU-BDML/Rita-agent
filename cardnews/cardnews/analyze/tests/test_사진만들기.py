# ── 누끼로 받는다 (사람 지시 2026-09-19) ────────────────────────────
#
# 「배경은 필요없고 사물이던 사람이든 그것만 필요해서 넣어야함. 근데 사진은
# 테두리가 사각형이잖아.. 딱 그 것만 넣고 배경은 그냥 카드뉴스 배경으로」
#
# **사각형이 문제가 아니다 — 네모 안이 투명하면 없는 것과 같다.** 굽는 쪽이
# `alpha_composite` 로 얹어서 투명한 자리는 카드 배경이 그대로 비친다
# (`cardnews_compose._decoration_속`). 장식 누끼가 이미 그렇게 돈다
# (`gpt누끼.py` 의 `"background": "transparent"`).

def test_사람_사물은_투명_배경으로_부른다():
    난것 = {}

    def _가짜(url, headers=None, data=None, timeout=None):  # noqa: ARG001
        난것.update(사진만들기.json.loads(data))
        raise RuntimeError("여기까지만 본다")

    import types
    가짜requests = types.SimpleNamespace(post=_가짜, get=None)
    옛 = 사진만들기.__dict__.get("requests")
    try:
        import sys
        sys.modules["requests"] = 가짜requests
        try:
            사진만들기.부르기("아무 말", 누끼=True)
        except RuntimeError:
            pass
    finally:
        if 옛 is not None:
            sys.modules["requests"] = 옛
    assert 난것.get("background") == "transparent", 난것


def test_배경_사진은_투명하게_안_부른다():
    """장 전체를 덮는 배경까지 투명하면 카드가 텅 빈다."""
    난것 = {}

    def _가짜(url, headers=None, data=None, timeout=None):  # noqa: ARG001
        난것.update(사진만들기.json.loads(data))
