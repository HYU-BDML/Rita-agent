# -*- coding: utf-8 -*-
"""문단 사이 빈 줄이 합칠 때 사라지던 것.

실측(2026-09-18, DG0AA6PJ8s4 2번 장): 줄 사이 틈이 보통 18~25px 인데 2→3 과
5→6 은 90px 였다 — 원본엔 거기 빈 줄이 있다. 줄 글자만 `\n` 으로 이어 붙여서
그 틈이 사라졌고, 되돌려 그리니 세 문단이 한 덩어리로 위에 몰렸다.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import layout_labeled as 배치잼  # noqa: E402


def _줄(글, y0, y1):
    return {"text": 글, "box": [0, y0, 100, y1]}


def test_틈이_보통의_두_배를_넘으면_빈_줄을_하나_끼운다():
    # 2번 장 실측값 그대로 — 2→3 사이 90px, 나머지는 18~22px
    줄들 = [_줄("얼마전", 374, 416), _줄("이름하여", 438, 481),
           _줄("공개", 571, 618), _줄("뮤비", 636, 681), _줄("인급동", 702, 745)]
    assert 배치잼._문단줄(줄들) == ["얼마전", "이름하여", "", "공개", "뮤비", "인급동"]


def test_틈이_고르면_아무것도_안_끼운다():
    줄들 = [_줄("가", 0, 40), _줄("나", 60, 100), _줄("다", 120, 160)]
    assert 배치잼._문단줄(줄들) == ["가", "나", "다"]


def test_줄이_둘이면_잴_보통_틈이_없어서_안_끼운다():
    줄들 = [_줄("가", 0, 40), _줄("나", 200, 240)]
    assert 배치잼._문단줄(줄들) == ["가", "나"]


def test_줄이_하나거나_없어도_죽지_않는다():
    assert 배치잼._문단줄([_줄("가", 0, 40)]) == ["가"]
    assert 배치잼._문단줄([]) == []
