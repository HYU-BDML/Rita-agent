# -*- coding: utf-8 -*-
"""딴 줄 버리기 — 글자 네모 안에서 읽혔지만 그 글 덩어리가 아닌 줄을 뺀다.

**사진에서 온 줄 하나가 크기·굵기·색·정렬 넷을 다 흔든다**(실물 2026-09-15,
DSW-6lrk5rs). 6번 장 제목 네모에 병 라벨의 잔글씨 「3」이 같이 읽혀 제목 pt 가
두 줄의 중간값(31)으로 내려앉고, 새 제목이 「1번째 줄」 의 가늘고 갈색인 값을
받았다. 7번 장 본문 네모에는 폰 캡처 속 「맛있는 밀키트」 가 끼어 정렬이 «가운데»
로 갈렸고 2번째 줄이 굵어졌다. 재는 방식이 «줄들을 합쳐 통계» 라 잘못된 줄 하나가
전체를 끌고 간다.

한 네모는 한 글 덩어리다 — 크기가 같고 한 축으로 정렬돼 있다. 그 둘에서 크게
벗어난 줄은 통계에 넣기 전에 뺀다.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))

import layout_labeled  # noqa: E402


def _줄(글: str, x0: int, y0: int, h: int, 자폭: int | None = None) -> dict:
    """글자마다 상자 하나. `h` 가 잉크 높이다(한글은 그대로, 숫자는 환산돼 들어간다)."""
    자폭 = 자폭 or h
    syms = [{"text": c, "box": [x0 + i * 자폭, y0, x0 + (i + 1) * 자폭, y0 + h]}
            for i, c in enumerate(글)]
    return {"text": 글, "box": [x0, y0, x0 + len(글) * 자폭, y0 + h], "symbols": syms}


def _본문(첫x=143, h=41, n=5):
    """실물처럼 줄 길이는 제각각, 왼쪽 끝은 같다."""
    글들 = ["가나다라마바사아자차카타", "가나다라마바사아자", "가나다라마바사아자차카", "가나다라마바", "가나다라마바사아자차"]
    return [_줄(글들[i % 5], 첫x, 100 + i * 55, h) for i in range(n)]


def test_잔글씨_한_줄은_버린다():
    """제목 네모: 병 라벨 「3」(작음) + 진짜 제목(큼)."""
    줄들 = [_줄("3", 140, 890, 14), _줄("성공적인어필리에이트마케팅", 140, 905, 45)]
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert [l["text"] for l in 남은] == ["성공적인어필리에이트마케팅"]
    assert 버린[0]["text"] == "3" and 버린[0]["why"]


def test_사진속_캡션은_정렬에서_튀어_버린다():
    """본문 네모: 왼쪽 맞춘 다섯 줄 + 화면 한가운데 박힌 캡션 한 줄."""
    줄들 = _본문()
    줄들.insert(1, _줄("맛있는밀키트", 480, 155, 41))
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert len(남은) == 5
    assert [l["text"] for l in 버린] == ["맛있는밀키트"]


def test_들여쓰기_정도는_안_버린다():
    """「→ …」 처럼 한 글자쯤 들여쓴 줄은 그 덩어리다."""
    줄들 = _본문() + [_줄("→뒤처지지않고", 143 + 30, 100 + 5 * 55, 41)]
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert not 버린


def test_가운데_정렬_블록은_안_버린다():
    """폭이 제각각이라도 가운데가 맞으면 한 덩어리다."""
    줄들 = []
    for i, 글 in enumerate(["가나다라마바사아", "가나다라", "가나다라마바사아자차"]):
        폭 = len(글) * 40
        줄들.append(_줄(글, 540 - 폭 // 2, 100 + i * 55, 40))
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert not 버린


def test_두_줄_제목은_안_버린다():
    줄들 = [_줄("살아남는사람의", 78, 965, 91), _줄("조건이있다", 78, 1085, 91)]
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert not 버린


def test_한_줄이면_그대로다():
    줄들 = [_줄("3", 140, 890, 14)]
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert 남은 == 줄들 and not 버린


def test_크기를_못_잰_줄은_크기로는_안_버린다():
    """라틴 글자만 있는 줄은 잉크 높이가 없다 — 모르는 것으로 버리지 않는다."""
    줄들 = _본문() + [_줄("COSRX", 143, 100 + 5 * 55, 41)]
    남은, 버린 = layout_labeled.딴줄버리기(줄들, 1.0)
    assert not 버린
