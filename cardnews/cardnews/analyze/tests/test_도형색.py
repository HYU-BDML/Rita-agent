"""**제 글자가 얹힌 도형도 색을 잰다.**

사람이 네모 하나를 긋고 「안에 글자 있다」를 켜면 도형과 글자가 «같은 자리» 가
된다. 그러면 글자 네모를 빼는 순간 잴 화소가 0 이 되고, 색을 못 잰 도형은 굽는
쪽이 통째로 건너뛴다.

실물 2026-08-30(DYzN0Uzgaq6): 민트색 제목 띠 다섯 개가 그렇게 사라졌고, 사람이
「제목 부분에 도형이 있었던 것 같은데」라고 짚을 때까지 아무도 몰랐다.
"""
import os
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(여기))
os.environ.setdefault("CARDNEWS_DATA", str(여기 / "data"))

import numpy as np  # noqa: E402

import merge_labeled as M  # noqa: E402

민트 = (76, 240, 197)


def _띠(글자몫=0.35):
    """민트 띠 위에 검은 글자가 얹힌 그림 한 장."""
    그림 = np.zeros((300, 900, 3), np.uint8)
    그림[:] = (20, 20, 20)                       # 어두운 바탕
    그림[100:200, 100:800] = 민트                # 띠
    끝 = 100 + int(700 * 글자몫)
    그림[120:180, 110:끝] = (10, 10, 10)         # 그 위의 글자
    return 그림


# **라벨은 «kind» 를 쓴다.** 실물과 같은 이름이어야 시험이 뜻이 있다.
_도형 = {"kind": "도형", "box": [100, 100, 800, 200]}


def test_같은_자리_글자를_빼도_색을_잰다():
    """**이 시험이 이번 고침의 전부다.**"""
    난것 = M._color_of(_띠(), _도형, [[100, 100, 800, 200]])
    assert 난것["hex"], 난것
    assert 난것["kind"] == "으뜸색"
    ㄱ, ㄴ, ㄷ = (int(난것["hex"][i:i + 2], 16) for i in (1, 3, 5))
    assert abs(ㄱ - 민트[0]) < 24 and abs(ㄴ - 민트[1]) < 24 and abs(ㄷ - 민트[2]) < 24, 난것


def test_왜_그렇게_쟀는지_적는다():
    """값만 남기면 나중에 「이 색은 어디서 왔나」를 알 수 없다."""
    난것 = M._color_of(_띠(), _도형, [[100, 100, 800, 200]])
    assert "가장 넓은 색" in (난것.get("why") or ""), 난것


def test_글자가_넓어도_바탕색이_이긴다():
    """글자 획이 굵어도 바탕보다 넓지는 않다."""
    난것 = M._color_of(_띠(글자몫=0.7), _도형, [[100, 100, 800, 200]])
    ㄱ, ㄴ, ㄷ = (int(난것["hex"][i:i + 2], 16) for i in (1, 3, 5))
    assert ㄴ > 150 and ㄷ > 120, 난것   # 민트 쪽이지 검정이 아니다


def test_남은_자리가_깨끗하면_격자로_잰다():
    """**물러서는 것은 «색을 못 얻었을 때» 뿐이다.**

    글자를 다 뺀 나머지가 민트뿐이면 격자가 제대로 판정한다 — 그때는 잘 잰 값을
    그대로 쓴다. 앞 판 시험은 글자 일부가 남는 그림으로 이걸 재려 해서, 규칙이
    「도형은 색을 못 얻으면 으뜸색」으로 넓어지자 뜻이 어긋났다(2026-08-30).
    """
    난것 = M._color_of(_띠(), _도형, [[100, 100, 400, 200]])
    assert 난것["kind"] != "으뜸색", 난것
    assert 난것.get("hex"), 난것


def test_자투리_몇_화소로는_안_잰다():
    """도형과 글자 네모가 2~4px 어긋나면 수백 화소가 남는다 — 그걸로 재면
    가장자리 색을 채움색이라 우기게 된다."""
    난것 = M._color_of(_띠(), _도형, [[102, 102, 798, 198]])
    assert 난것["kind"] == "으뜸색", 난것


def test_문턱을_적어_둔다():
    assert M.남을화소 == 4000


# ── 글자가 «네모 안에 박혀» 있을 때 ────────────────────────────────
#
# 라벨이 「안에 글자 있다」를 켠 도형 하나만 그으면, 글자 네모가 따로 없어 뺄
# 것이 없다. 그러면 도형이 통째로 들어가고 `judge` 가 민트+검정을 보고 「사진」
# 이라 답한다 — 사진에는 hex 가 없다(실물 2026-08-30, 이쪽이 진짜 경우였다).

def test_뺄_글자_네모가_없어도_도형_색을_잰다():
    """**이 시험이 실물의 경우다.** 앞 시험은 「같은 자리」였고 이건 「뺄 것이
    아예 없는」 경우다. 둘 다 채움색이 비면 도형이 안 그려진다."""
    난것 = M._color_of(_띠(), _도형, [])      # 글자 네모를 안 준다
    assert 난것["hex"], 난것
    assert 난것["kind"] == "으뜸색", 난것
    ㄴ, ㄷ = (int(난것["hex"][i:i + 2], 16) for i in (3, 5))
    assert ㄴ > 150 and ㄷ > 120, 난것


def test_평평한_도형은_격자로_잰_값을_그대로_쓴다():
    """물러설 자리는 «못 얻었을 때» 만이다 — 잘 잰 값을 덮으면 안 된다."""
    그림 = np.zeros((300, 900, 3), np.uint8)
    그림[:] = (20, 20, 20)
    그림[100:200, 100:800] = 민트              # 글자 없는 민트 띠
    난것 = M._color_of(그림, _도형, [])
    assert 난것["kind"] != "으뜸색", 난것
    assert 난것.get("hex"), 난것


def test_도형이_아니면_안_물러선다():
    """사진·인물은 색을 안 재는 것이 맞다 — 여기서 억지로 색을 지어내면 안 된다."""
    난것 = M._color_of(_띠(), {"kind": "사진", "box": [100, 100, 800, 200]}, [])
    assert 난것["kind"] != "으뜸색", 난것


def test_선만_있는_도형은_고리에서_색을_잰다():
    """**파이프라인이 이미 고리에서 잰다** — `_regions()` 가 `cutout` 의
    테두리·구멍으로 `region["mask"]` 를 미리 만들어 붙이고(`_mask_from_outline`),
    `_color_of` 는 `_도형마스크` → `_mask_of` 로 그 마스크를 그대로 쓴다. 이
    시험은 그 마스크를 실제로 붙인 네모를 넘겨 그 사실을 확인한다 — `cutout`
    원본만 든 네모를 넘기면(마스크 없이) `_color_of` 는 네모 전체로 물러서
    무엇을 재는지 증명하지 못한다.

    실물 2026-09-17, ④ #키워드 알약 — 네모 전체로 재면 속 배경색 #ECEBEB 가
    나와 검은 테두리가 사라진다(그 실패는 자동창이 고리를 떨어뜨려 모양
    자체가 안 실린 것이었고 `cutout._찬몫` 이 고쳤다 — 이 시험이 확인하는
    것은 «모양이 실리면 색은 고리에서 나온다» 는 쪽이다).
    이 손그림 알약의 실측값: 잰 색 `#595757`(선 색 그대로, 배경 `#ECEBEB` 가
    아니다). 고리가 가늘어 유효 격자가 `MIN_CELLS` 미만이라 `tint.judge` 가
    최빈색으로 떨어지지만(`kind`: `미측정`), `hex` 는 여전히 고리 색이다 —
    이 시험이 보는 것은 `hex` 값이지 `kind` 가 아니다."""
    import cv2
    import numpy as np
    img = np.full((300, 400, 3), (236, 235, 235), np.uint8)
    cv2.ellipse(img, (200, 150), (150, 60), 0, 0, 360, (89, 87, 87), 8)
    바깥 = [[float(x), float(y)] for x, y in
           cv2.ellipse2Poly((200, 150), (154, 64), 0, 0, 360, 5)]
    안 = [[float(x), float(y)] for x, y in
         cv2.ellipse2Poly((200, 150), (146, 56), 0, 0, 360, 5)]
    마스크 = M._mask_from_outline(바깥, [안], img.shape[:2])
    r = {"box": [45, 85, 355, 215], "kind": "도형", "mask": 마스크,
         "cutout": {"테두리": 바깥, "구멍": [안]}}
    난것 = M._color_of(img, r, [])
    잰것 = (난것.get("hex") or "").upper()
    ㄱ, ㄴ, ㄷ = (int(잰것[i:i + 2], 16) for i in (1, 3, 5))
    # 배경(236,235,235)이 섞여 들어오지 않았는지 — 선 색(89,87,87)에서
    # 너무 멀면(배경 쪽으로) 고리가 아니라 네모 전체를 잰 것이다.
    assert abs(ㄱ - 89) < 40 and abs(ㄴ - 87) < 40 and abs(ㄷ - 87) < 40, \
        f"고리 색이 아니라 배경 쪽이다: {잰것}"
