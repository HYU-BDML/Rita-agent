"""테두리 따기 — 배경이 어디서 끝나는지로 그래픽의 모양을 낸다.

**SAM 과 정반대다.** SAM 은 「물체가 어디 있나」를 보고, 이건 「배경이 어디까지인가」
를 본다. 카드뉴스 그래픽(원형 크롭·둥근 알약·하트)은 «자른 자국» 이라 물체가
아니고, 그래서 SAM 이 못 잡는다(실측 2026-08-26: 원의 9.9%).
"""
import sys
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))

import outline as O          # noqa: E402

바탕색 = (246, 243, 238)


def _판(w=400, h=400):
    return np.full((h, w, 3), 바탕색, np.uint8)


def _별(cx, cy, R, r, n=5):
    pts = []
    for i in range(2 * n):
        t = -np.pi / 2 + i * np.pi / n
        rad = R if i % 2 == 0 else r
        pts.append([cx + rad * np.cos(t), cy + rad * np.sin(t)])
    return np.array(pts, np.int32)


def _iou(a, b):
    return float((a & b).sum()) / float((a | b).sum())


def _진짜(img):
    return np.abs(img.astype(int) - np.array(바탕색)).max(axis=2) > 28


def _되채움(shape, 테두리, 구멍들):
    """`테두리`(+ `구멍`) 만으로 마스크를 다시 만든다 — A7·A8·A11 이 실제로
    받는 값이 `마스크` 가 아니라 `테두리`/`구멍` 이라, 그걸 되채워서 `마스크`
    와 맞는지 봐야 진짜 확인이 된다."""
    a = np.zeros(shape, np.uint8)
    cv2.drawContours(a, [np.array(테두리, np.int32)], -1, 1, -1)
    for 구멍 in 구멍들:
        cv2.drawContours(a, [np.array(구멍, np.int32)], -1, 0, -1)
    return a.astype(bool)


def test_원을_정확히_딴다():
    img = _판(); cv2.circle(img, (200, 200), 150, (30, 30, 30), -1)
    난것 = O.테두리따기(img, [20, 20, 380, 380])
    assert _iou(_진짜(img), 난것["마스크"]) > 0.99
    assert 난것["못땄음"] is None


def test_별도_사다리꼴도_삼각형도_딴다():
    셋 = {
        "별": lambda a: cv2.fillPoly(a, [_별(200, 200, 160, 68)], (200, 40, 60)),
        "사다리꼴": lambda a: cv2.fillPoly(
            a, [np.array([[80, 320], [320, 320], [260, 90], [140, 90]], np.int32)], (40, 90, 200)),
        "삼각형": lambda a: cv2.fillPoly(
            a, [np.array([[200, 60], [340, 330], [60, 330]], np.int32)], (250, 180, 20)),
    }
    for 이름, 그리기 in 셋.items():
        img = _판(); 그리기(img)
        난것 = O.테두리따기(img, [20, 20, 380, 380])
        assert _iou(_진짜(img), 난것["마스크"]) > 0.99, 이름


def test_둥근_알약의_둥글기가_살아_있다():
    """«알약» 은 타원이 아니라 스타디움(직선 옆면 + 반원 두 끝)이다.

    이전엔 `cv2.ellipse(...,0,360)` 으로 그렸는데, 그건 꽉 찬 타원이라
    area/minAreaRect 비율이 기하로 π/4 ≈ 0.785 로 정해져 있다(실물 검은
    알약은 0.974 — 둥근 «네모» 라서). 진짜 알약 모양이어야 아래 단언이
    말이 된다.
    """
    img = _판()
    cv2.rectangle(img, (90, 130), (310, 270), (15, 15, 15), -1)   # 곧은 몸통
    cv2.circle(img, (90, 200), 70, (15, 15, 15), -1)              # 왼쪽 둥근 끝
    cv2.circle(img, (310, 200), 70, (15, 15, 15), -1)             # 오른쪽 둥근 끝
    난것 = O.테두리따기(img, [10, 120, 390, 280])
    c = np.array(난것["테두리"], np.int32)
    면적 = cv2.contourArea(c)
    rect = cv2.minAreaRect(c)
    네모닮음 = 면적 / (rect[1][0] * rect[1][1])
    assert 0.9 < 네모닮음 < 0.99, f"정확한 네모도 아니고 원도 아닌 «알약» 이어야 한다: {네모닮음}"


def test_속이_뚫린_도형은_구멍을_낸다():
    img = _판()
    cv2.circle(img, (200, 200), 150, (20, 150, 90), -1)
    cv2.circle(img, (200, 200), 70, 바탕색, -1)
    난것 = O.테두리따기(img, [20, 20, 380, 380])
    assert 난것["구멍"], "가운데 뚫린 자리를 구멍으로 잡아야 한다"
    # 구멍은 딱 하나여야 한다 — 예전엔 마스크에 이미 뚫린 구멍을
    # `_윤곽` 의 `안쪽들` 로 한 번 잡고, 같은 자리를 `구멍마스크` 로 또 한
    # 번 윤곽 따서 붙여 폴리곤 둘(넓이 15498·15108)이 실렸었다.
    assert len(난것["구멍"]) == 1, f"같은 구멍이 두 번 실렸다: {len(난것['구멍'])}개"
    assert _iou(_진짜(img), 난것["마스크"]) > 0.99


def test_이웃을_덮어_딸려온_조각을_버린다():
    """카드뉴스는 도형과 글자가 곧잘 붙어 있다 — 안 덮으면 한 덩이가 된다."""
    img = _판()
    cv2.circle(img, (200, 200), 120, (30, 30, 30), -1)
    cv2.rectangle(img, (180, 300), (380, 340), (30, 30, 30), -1)   # 붙어 있는 글자띠
    붙은채 = O.테두리따기(img, [20, 20, 380, 380])
    덮고 = O.테두리따기(img, [20, 20, 380, 380], 이웃=[[180, 300, 380, 340]])
    assert 덮고["마스크"].sum() < 붙은채["마스크"].sum(), "이웃이 안 떨어졌다"
    원 = np.zeros(img.shape[:2], bool)
    cv2.circle(원.view(np.uint8), (200, 200), 120, 1, -1)
    assert _iou(_진짜(img) & 원, 덮고["마스크"]) > 0.9


