def test_완만한_그라데이션_배경에서도_물체를_딴다():
    """뜻이 바뀐 시험(2026-09-17). 옛 문지기(`띠평평`)는 «네모 둘레가 한 색인가»
    만 보고 그라데이션이면 무조건 막았다. 새 문지기(`찬몫문턱`)는 «결과가 네모를
    얼마나 채웠나» 만 본다 — 실측(카드뉴스 실물 배경 기준 완만한 그라데이션):
    물체가 있으면 IoU 0.877 로 여전히 잘 딴다. 그래서 이 시험은 이제 «막힌다»
    가 아니라 «막히지 않는다» 를 확인한다."""
    img = np.zeros((400, 400, 3), np.uint8)
    for y in range(400):
        v = 220 + y * 30 // 400
        img[y, :] = (v, v, v)
    cv2.circle(img, (200, 200), 120, (20, 20, 20), -1)
    난것 = O.테두리따기(img, [20, 20, 380, 380])
    assert 난것["못땄음"] is None
    참 = np.zeros(img.shape[:2], bool)
    cv2.circle(참.view(np.uint8), (200, 200), 120, 1, -1)
    assert _iou(참, 난것["마스크"]) > 0.85


def test_아주_가파른_그라데이션은_아직_걸러내지_못한다():
    """**남은 한계를 시험으로 못 박아 둔다.** 완만한 그라데이션(위 시험, 400줄에
    30단계)은 새 문지기(`찬몫문턱`)가 잘 거르지만, 400줄에 60단계로 더 가파르면
    흘려채우기가 `FLOODFILL_FIXED_RANGE`(허용 6) 탓에 씨앗 여덟 개 둘레만 채우고
    가운데를 못 채운다 — 물체가 하나도 없는데도 안 채워진 가운데 자리를 «찾았다»
    고 오인한다(실측 2026-09-17: 넓이비율 0.3075, 문턱 0.25 를 넘어 버린다).

    이건 이번 과제(문지기를 «둘레 색» 에서 «찬 정도» 로 바꾸는 일)에서 고칠
    범위가 아니다. 카드뉴스 실물 배경은 이 정도로 가파르지 않아(브리프 실물
    예시 ③ 은 3.7%로 정상 거절됐다) 지금 당장 문제는 아니지만, 실물에서 더
    가파른 배경이 나오면 걸릴 수 있다. 나중에 문지기를 고칠 때 이 시험이
    먼저 «땄다» → «막았다» 로 바뀌며 실패해 알려 주도록, 지금 실제로 일어나는
    일(«못 거른다»)을 있는 그대로 확인한다."""
    img = np.zeros((400, 400, 3), np.uint8)
    for y in range(400):
        v = 20 + y * 60 // 400
        img[y, :] = (v, v, v)
    난것 = O.테두리따기(img, [20, 20, 380, 380])
    assert 난것["못땄음"] is None, "이 문턱은 여기서 못 거른다 — 한계가 사라졌다면 이 시험을 다시 살펴라"
    assert 난것["마스크"] is not None
    비율 = 난것["마스크"].sum() / (360 * 360)
    assert 0.25 < 비율 < 0.4, f"실측(0.3075)과 크게 달라졌다: {비율:.4f}"


