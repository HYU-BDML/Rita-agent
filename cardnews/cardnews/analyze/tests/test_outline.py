def test_테두리를_되채우면_마스크와_같다():
    """실제로 밖으로 나가 A7·A8·A11 이 쓰는 값은 `마스크`(bool 배열)가 아니라
    `approxPolyDP` 로 줄인 `테두리`/`구멍` 좌표다. 여덟 시험이 전부 `마스크`
    로만 IoU 를 쟀으니, 점 줄이기가 `테두리` 를 마스크에서 벗어나게 만들어도
    아무도 못 잡는다 — 그래서 `테두리` 를 도로 채워 `마스크` 와 겹쳐 본다.
    """
    img = _판(); cv2.circle(img, (200, 200), 150, (30, 30, 30), -1)
    난것 = O.테두리따기(img, [20, 20, 380, 380])
    되 = _되채움(img.shape[:2], 난것["테두리"], 난것["구멍"])
    assert _iou(되, 난것["마스크"]) > 0.99

    # 구멍이 있는 경우 — 바깥을 채우고 `구멍` 들을 파낸 것이 마스크와 맞아야
    # 한다(구멍을 안 파내면 여기서 어긋난다).
    img2 = _판()
    cv2.circle(img2, (200, 200), 150, (20, 150, 90), -1)
    cv2.circle(img2, (200, 200), 70, 바탕색, -1)
    난것2 = O.테두리따기(img2, [20, 20, 380, 380])
    되2 = _되채움(img2.shape[:2], 난것2["테두리"], 난것2["구멍"])
    assert _iou(되2, 난것2["마스크"]) > 0.99


