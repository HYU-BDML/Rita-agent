# -*- coding: utf-8 -*-
"""틀 목록에 거는 「한 판」 그림.

**RITA 카드는 그림을 잘라 넣는다** — 818×288 자리에 `object-fit: cover`,
가운데 맞춤(실측 2026-08-28). 판이 그 비율이 아니면 잘린다. 처음 만든 4칸 2줄
(1.62)은 608px 중 262px 이 잘려 나갔고, 첫 줄 제목이 통째로 사라졌다.
"""
import os
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(여기))
os.environ.setdefault("CARDNEWS_DATA", str(여기 / "data"))

import lambda_분석 as 분석  # noqa: E402

쪽비 = 240 / 300      # 인스타 카드뉴스 한 장(1080×1350)


def _짜임(장수):
    칸 = 분석._칸수고르기(장수, 쪽비)
    return 칸, (장수 + 칸 - 1) // 칸


def test_아랫줄이_거의_비는_짜임을_안_고른다():
    """8장을 7+1 로 쪼개면 아랫줄이 텅 빈다 — 비율만 보면 그게 이긴다."""
    칸, 줄 = _짜임(8)
    assert (칸, 줄) == (4, 2), f"{칸}칸 {줄}줄"


def test_적은_장수는_한_줄로_편다():
    for 장수 in (6, 7):
        칸, 줄 = _짜임(장수)
        assert (칸, 줄) == (장수, 1), f"{장수}장이 {칸}칸 {줄}줄"


def test_많으면_줄을_늘려_장을_키운다():
    """16장을 한 줄로 펴면 장이 51px 로 쪼그라든다."""
    칸, 줄 = _짜임(16)
    assert 줄 == 2 and 칸 == 8


def test_고른_짜임이_늘_제일_크게_보인다():
    """잣대 자체를 못 박는다 — 어떤 장수에서도 더 큰 짜임이 없어야 한다."""
    def 보이는폭(칸, 줄):
        return min(분석.카드폭 / 칸, (분석.카드높이 * 쪽비) / 줄)

    for 장수 in range(1, 21):
        칸, 줄 = _짜임(장수)
        내것 = 보이는폭(칸, 줄)
        for 딴줄 in range(1, 장수 + 1):
            딴칸 = (장수 + 딴줄 - 1) // 딴줄
            assert 보이는폭(딴칸, 딴줄) <= 내것 + 1e-9, f"{장수}장: {딴칸}칸 {딴줄}줄이 더 크다"


def test_카드비는_실측값이다():
    """818×288 은 화면에서 잰 값이다. 바뀌면 판을 다시 만들어야 한다."""
    assert (분석.카드폭, 분석.카드높이) == (818, 288)
    assert abs(분석.카드비 - 2.84) < 0.01
