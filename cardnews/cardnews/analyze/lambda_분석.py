# 값이 바뀌면 여기만 고치면 된다.
카드폭, 카드높이 = 818, 288
카드비 = 카드폭 / 카드높이


def _칸수고르기(장수: int, 쪽비: float) -> int:
    """**장 하나가 제일 크게 보이는** 짜임의 «한 줄에 넣을 장 수».

    비율을 카드에 맞추고 나면 남는 물음은 몇 줄로 나누느냐 하나다. 그런데
    「비율에 가까운 짜임」으로 고르면 8장이 7+1 로 쪼개져 아랫줄이 텅 빈다
    (실측 2026-08-28). 사람이 보는 것은 비율이 아니라 **장이 얼마나 크게
    보이는가**다 — 그걸 바로 잰다.

    카드에 보이는 자리는 818×288 로 정해져 있으니, 줄 수를 정하면 장 하나의
    보이는 폭이 나온다 — 가로로 갈리는 몫과 세로로 갈리는 몫 중 **작은 쪽**이다.
    그 값이 가장 큰 줄 수를 고른다. 8장이면 4칸 2줄, 7장이면 한 줄, 16장이면
    8칸 2줄이 이긴다.
    """
    좋은것, 가장큼 = 1, -1.0
    for 줄 in range(1, 장수 + 1):
        칸 = (장수 + 줄 - 1) // 줄
        보이는폭 = min(카드폭 / 칸, (카드높이 * 쪽비) / 줄)
        if 보이는폭 > 가장큼:
            좋은것, 가장큼 = 칸, 보이는폭
    return 좋은것


