def _옛개인(pid: str):
    """창고에 이미 있는 틀이 **공용인가 개인인가**. 없으면 `None`.

    **다시 분석할 때 그 값을 잃지 않으려는 것이다** — `_옛이름` 과 같은 까닭이다.
    실물 2026-09-19: 수집기에서 만든 **공용** 틀 「아이돌 브랜딩」을 코드 고치고
    다시 분석했더니 **개인**으로 떨어졌다. 재분석은 `개인` 을 안 실어 보내고
    받는 쪽 기본값이 「개인」이라서다.

    그러면 오른쪽 화면에는 그대로 보이는데 모델에게 주는 목록에서는 빠진다 —
    **보이는데 고를 수 없는** 상태가 된다. 그 카드를 눌러도 「그 템플릿은 목록에
    없어요」만 나온다.

    **`개인` 칸이 없는 옛 틀은 공용으로 본다.** 창고의 열 벌에는 그 칸이 없는데,
    그것들은 사장님이 만든 공용이다.
    """
    try:
        raw = _창고().get_object(Bucket=os.environ["BUCKET"],
                                Key=f"templates/{pid}.json")["Body"].read()
        return bool(json.loads(raw.decode("utf-8")).get("개인", False))
    except Exception:  # noqa: BLE001 — 없거나 깨졌으면 부르는 쪽 값을 쓴다
        return None


def 한판(pid: str, 이름: str = "", 개인: bool = True, 목록건너뛰기: bool = False) -> dict:
    """게시물 하나를 재고, 틀을 뽑아 창고에 올린다.

    **`merge_labeled.build` 가 게시판 상태를 스스로 챙긴다** — 시작할 때
    「분석중」, 끝나면 「분석 끝」, 터지면 「분석 실패」다(`pull`·`finish`).
    여기서 또 만지면 두 번 쓰게 되고, 실패했을 때 어느 쪽이 이겼는지 헷갈린다.

    틀 만들기(`make_dsl_cardnews`)는 계량표가 있어야 돌아가므로 그 뒤에 부른다.
    무거운 임포트라 함수 안에서 한다 — 계량만 하다 죽는 판에서 yaml 이 없다고
    같이 죽을 이유가 없다.
    """
    잰것 = merge_labeled.build(pid, publish=True, pull=True)

    import make_dsl_cardnews as 틀만들기  # noqa: PLC0415

    # **배경판을 먼저 올린다.** 틀이 그 주소를 담고 나가므로 순서가 중요하다 —
    # 틀에 주소만 있고 그림이 창고에 없으면 굽는 쪽이 조용히 배경을 잃는다.
    올린판 = _배경판올리기(pid, 잰것)
    올린누끼 = _누끼올리기(잰것)

    자리 = Path(config.DATA) / "templates" / f"{pid}.json"
    # **한 번만 정한다.** 틀 이름과 말투 이름이 같은 값에서 나와야 한다 —
    # 갈리면 「파란 타임라인」 틀에 「DSW-6lrk5rs」 말투가 붙어, 사람이 방금
    # 붙인 이름으로 말투를 고르면 «그런 말투가 없다» 가 난다(실물 2026-08-31).
    이름 = 이름 or _옛이름(pid)
    # **이미 있던 틀이면 공용·개인을 그대로 둔다**(사람 결정 2026-09-19).
    # 다시 분석하는 일은 잦은데(코드를 고칠 때마다 돌린다), 그때마다 공용이던
    # 것이 개인으로 떨어지면 서른다섯 명이 그 템플릿을 못 고른다 — 화면에는
    # 보이므로 «왜 안 되는지» 알 길도 없다. `_옛개인` 참고.
    옛것 = _옛개인(pid)
    틀 = 틀만들기.틀_쓰기(pid, 자리, 이름,
                    _미리보기올리기(pid), _한판올리기(pid),
                    개인=개인 if 옛것 is None else 옛것)
    # **사진 자리에 번호를 찍은 판**(사람 지시 2026-09-22). 굽기 전 미리보기가
    # 맨 위에 걸어서 「사진1 이 장 어디인가」를 보여 준다. 틀을 다 쓴 «뒤» 라야
