def 명단다시짓기() -> dict:
    """창고의 틀 파일들을 훑어 명단(`templates/목록.json`)과 옷장을 처음부터 다시 짓는다.

    여럿을 동시에 분석할 때 쓴다 — 분석은 제 틀 파일만 저장하고(`목록건너뛰기`), 다
    끝난 뒤 이것을 한 번 부른다. 명단은 틀 파일들에서 다시 만들 수 있는 것이라 따로
    지킬 이유가 없다(사람 결정 2026-09-19).
    """
    통 = os.environ["BUCKET"]
    쌓인것 = _창고().list_objects_v2(Bucket=통, Prefix="templates/")
    # **작업대에서 손으로 고쳐 저장한 틀(`<32자리 열쇠>-<판>.json`)은 명단에서 뺀다**
    # (사람 결정 2026-09-19). 창고를 훑는 길에서만 보이던 것들이고, 시험 삼아 저장한
    # 것이 섞여 있다. 라벨링해서 뽑은 틀만 고르는 칸에 올린다.
    작업대꼴 = re.compile(r"^[0-9a-f]{32}-\d+$")
    코드들 = []
    for 몫 in 쌓인것.get("Contents") or []:
        뒤 = 몫["Key"][len("templates/"):]
        if "/" in 뒤 or not 뒤.endswith(".json") or 뒤 in ("목록.json", "기본.json"):
            continue
        코드 = 뒤[:-5]
        if 작업대꼴.match(코드):
            continue
        코드들.append(코드)
    import make_dsl_cardnews as 틀만들기  # noqa: PLC0415
    목록 = []
    for 코드 in sorted(코드들):
        틀 = _틀읽기(코드)
        if 틀:
            목록.append(틀만들기.틀목록줄(틀, 코드))
    목록주소 = _올리기("templates/목록.json",
                    json.dumps(목록, ensure_ascii=False, indent=1))
    print(f"++ 명단 다시 지음: 틀 {len(목록)}벌")
    곁 = _옷장과_yml(목록)
    return {"ok": True, "개수": len(목록), "목록": 목록주소, **곁}


def _옷장과_yml(목록: list) -> dict:
    """기본 옷장(`기본.json`)과 Dify 용 yml 을 **다시 짜서 올린다.**

    둘을 한 함수에 둔 까닭은 둘 다 «목록 전체» 를 보고 만들어지기 때문이다 —
    라벨을 하나 더 할 때마다 옷장이 두꺼워지고 고르는 칸에 줄이 하나 는다.

    **터져도 분석은 산다.** 방금 잰 틀은 이미 창고에 올라가 있다. 곁다리가
    무너졌다고 그걸 잃을 이유가 없다 — 다음 분석 때 다시 짜인다.

    **yml 은 지금 아무도 안 열지만 그냥 둔다**(사람 결정 2026-09-19).
    카드뉴스를 만드는 길은 채팅 화면으로 옮겨 갔고 Dify 는 안 쓴다. 그래도
    「그 안의 무언가를 나중에 쓸지 모른다」고 해서 남긴다. 값이 거의 안 든다 —
    분석 한 번에 파일 하나를 더 올릴 뿐이고, 터져도 위와 같이 분석은 산다.
    **지우지 마라.** 되살리는 값이 두는 값보다 훨씬 크다.
    """
    난것 = {}
    import make_dsl_cardnews as 틀만들기  # noqa: PLC0415

    try:
        틀들 = [t for t in (_틀읽기(줄.get("코드") or "") for 줄 in 목록) if t]
        난것["기본"] = _올리기("templates/기본.json",
                          json.dumps(틀만들기.합치기(틀들), ensure_ascii=False, indent=1))
        print(f"++ 기본 옷장: 틀 {len(틀들)}벌을 합쳤다")
    except Exception:  # noqa: BLE001
        traceback.print_exc()

    try:
        글 = 틀만들기.yml_글([줄.get("이름") for 줄 in 목록])
        통 = os.environ["BUCKET"]
        키 = "templates/카드뉴스_생성기.yml"
        _창고().put_object(Bucket=통, Key=키, Body=글.encode("utf-8"),
                         ContentType="text/yaml; charset=utf-8")
        지역 = os.environ.get("AWS_REGION", "ap-northeast-2")
        난것["yml"] = f"https://{통}.s3.{지역}.amazonaws.com/{키}"
        print(f"++ yml 다시 짬: 고를 것 {len(목록) + 1}줄")
    except Exception:  # noqa: BLE001
        traceback.print_exc()
    return 난것


