def _창고():
    return boto3.client("s3")


def _올리기(키: str, 글: str) -> str:
    """S3 창고에 글 파일 하나. 주소를 돌려준다."""
    통 = os.environ["BUCKET"]
    _창고().put_object(
        Bucket=통, Key=키, Body=글.encode("utf-8"),
        ContentType="application/json; charset=utf-8")
    지역 = os.environ.get("AWS_REGION", "ap-northeast-2")
    return f"https://{통}.s3.{지역}.amazonaws.com/{키}"


def _목록읽기(키: str = "templates/목록.json") -> list:
    """창고의 목록 파일. 없으면 빈 목록 — 첫 판이면 없는 게 맞다.

    **`ListBucket` 없이 한다.** 역할에 그 권한을 일부러 안 줬다(작업대 쪽과 같은
    결). 목록 파일 하나를 읽는 것으로 충분하다.
    """
    try:
        몸 = _창고().get_object(Bucket=os.environ["BUCKET"], Key=키)
        return json.loads(몸["Body"].read().decode("utf-8"))
    except Exception:  # noqa: BLE001 — 없거나 깨졌으면 이번 것만으로 새로 만든다
        return []


def _얹기(옛것: list, 이번것: list) -> list:
    """옛 목록에 이번 것을 얹는다. 같은 코드는 새것으로 갈아 끼운다."""
    새코드 = {x.get("코드") for x in 이번것}
    남은것 = [x for x in 옛것 if x.get("코드") not in 새코드]
    return sorted(남은것 + 이번것, key=lambda x: (x.get("만든날") or "", x.get("코드") or ""))


def _목록얹기(이번것: list) -> list:
    """틀 목록에 얹는다."""
    return _얹기(_목록읽기(), 이번것)


