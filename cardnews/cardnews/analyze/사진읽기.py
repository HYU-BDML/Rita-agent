# -*- coding: utf-8 -*-
"""사람이 올린 사진을 **보고**, 어느 자리에 넣을지 정한다.

사람 결정 2026-09-19: 「대본이 받은 사진을 보게 해야지 딥시크 비전 있잖아」.
설계: `docs/superpowers/specs/2026-09-19-사진과-미리보기-design.md` §6.2

**여태는 올린 순서대로 앞에서부터 꽂았다.** 사진이 무엇인지 안 보고 1번 사진을
1번 자리에, 2번을 2번 자리에 넣었다. 사람이 올린 차례가 카드 차례와 같을 까닭이
없으니 대개 엉뚱한 데 들어갔다.

**맞추는 기준은 «역할» 이다**(2026-09-20). 자리마다 역할이 있고(`훅`·`사례`·
`데이터`…) 그 역할이 「여기엔 이런 그림이 온다」를 이미 말해 준다. 자리에 사람이
적은 «설명» 이 있으면 그것도 같이 본다 — 그건 더 센 단서다.

**표지 자리는 후보에 아예 안 넣는다**(사람 결정 2026-09-20: 「1번으로 ㄱ」).
표지는 좋은 품질로 밈을 만드는 자리라(`사진만들기.표지틀`), 사람 사진이 자동으로
거기 꽂히면 그걸 통째로 버린다. 표지에 쓰고 싶으면 미리보기에서 끌어다 놓는다.

**억지로 안 꽂는다.** 안 꽂아도 역할 틀이 제대로 된 그림을 만든다. 어중간하게
맞는 사진을 넣느니 비워 두는 편이 낫다.

값: 모델 페이지에서 확인(2026-09-20, api-docs.deepseek.com/quick_start/pricing).
`deepseek-flash` 만 **Vision 을 지원한다** — 대본 모델(`deepseek-v4-pro`)은 «Not
supported» 다. 한가할 때 100만 토큰에 입력 $0.15 · 출력 $0.60, 바쁠 때 두 배
(UTC 01~04시·06~10시 평일). 사진 열 장이면 한 판에 **$0.003 쯤**이다.

열쇠는 `대본짓기` 가 쓰는 `DEEPSEEK_API_KEY` 하나를 그대로 쓴다. 머리말에만
싣는다 — 주소나 몸통에 넣으면 실패할 때 자국에 그대로 찍힌다.
"""
import json
import os

import 대본짓기

# **비전은 flash 만 된다.** 대본 모델을 그대로 쓰면 「Not supported」로 튕긴다.
비전모델 = os.environ.get("DEEPSEEK_VISION_MODEL") or "deepseek-flash"

# 한 번에 볼 사진 수. 상한이 없으면 서른 장을 한 봉투에 밀어 넣게 된다.
사진최대 = 20

_시스템 = """너는 카드뉴스에 넣을 사진을 고르는 일을 한다.

사람이 올린 사진들을 보고, 각각을 카드뉴스의 «빈 자리» 중 하나에 짝지어라.

지켜야 할 것:
- 자리마다 «역할» 이 적혀 있다. 그 역할에 어울리는 사진을 넣어라.
- 자리에 «설명» 이 적혀 있으면 그게 역할보다 세다. 그 설명에 맞는 사진을 넣어라.
- **어울리는 자리가 없으면 넣지 마라.** 자리를 비워 두면 AI 가 알아서 그린다.
  억지로 넣은 엉뚱한 사진보다 그 편이 낫다.
- 한 자리에 사진 하나, 한 사진은 자리 하나. 같은 사진을 두 자리에 넣지 마라.

답은 JSON 하나로만 낸다. 다른 말은 쓰지 마라.

{"사진": [{"번호": 1, "본것": "사진에 무엇이 있는지 한 줄", "자리": 2},
         {"번호": 2, "본것": "…", "자리": null}]}

"번호" 는 받은 사진 차례(1부터), "자리" 는 넣을 자리 번호(1부터) 또는 null 이다."""


def 자리적기(자리들: list) -> str:
    """모델에게 보여 줄 빈 자리 목록. **사람 글만 담는다** — box·pt 는 쓸 데가 없다."""
    줄 = []
    for i, (자리, 카드) in enumerate(자리들, start=1):
        역할 = str((카드 or {}).get("역할") or "").strip() or "본문"
        설명 = str((자리 or {}).get("설명") or "").strip()
        줄.append(f"{i}번 자리 — 역할 「{역할}」" + (f", 설명 「{설명}」" if 설명 else ""))
    return "\n".join(줄)


def _몸짓기(사진들: list, 자리들: list, 주제: str) -> dict:
    쪽 = [{"type": "text",
          "text": f'카드뉴스 주제: "{주제}"\n\n빈 자리 {len(자리들)}개:\n'
                  + 자리적기(자리들)
                  + f"\n\n사진 {len(사진들)}장을 차례로 보여 준다."}]
    for 주소 in 사진들:
        쪽.append({"type": "image_url", "image_url": {"url": 주소}})
    return {"model": 비전모델,
            "messages": [{"role": "system", "content": _시스템},
                         {"role": "user", "content": 쪽}],
            "max_tokens": 2000,
            "temperature": 0.2}


def 읽고맞추기(사진들: list, 자리들: list, 주제: str, 보내기=None) -> list:
    """`[{번호, 본것, 자리}, …]`. **못 하면 빈 목록** — 사진 때문에 카드가 안 나오면 안 된다.

    한 번만 부른다. 사진마다 따로 부르면 「이 사진이 저 사진보다 이 자리에 낫다」를
    가릴 수가 없다 — 짝짓기는 한꺼번에 봐야 하는 일이다.
    """
    사진들 = [str(u).strip() for u in (사진들 or []) if str(u).strip()][:사진최대]
    if not 사진들 or not 자리들:
        return []
    if not (os.environ.get("DEEPSEEK_API_KEY") or ""):
        print("!! DEEPSEEK_API_KEY 가 없다 — 사진을 안 보고 넘어간다")
        return []

    보내기 = 보내기 or 대본짓기._보내기
    try:
        글 = 대본짓기._꺼내기(보내기(_몸짓기(사진들, 자리들, 주제),
                              대본짓기.읽기상한))
        난것 = json.loads(_JSON만(글)).get("사진") or []
    except Exception as e:  # noqa: BLE001
        # **사진 때문에 카드뉴스를 죽이지 않는다.** 못 읽으면 안 꽂을 뿐이다 —
        # 빈 자리는 역할 틀이 그린다.
        print(f"!! 사진을 못 읽었다: {type(e).__name__} — 안 꽂고 넘어간다")
        return []
    return [x for x in 난것 if isinstance(x, dict)]


def _JSON만(글: str) -> str:
    """앞뒤에 붙은 말이나 ```json 울타리를 걷어낸다."""
    글 = str(글 or "").strip()
    처음, 끝 = 글.find("{"), 글.rfind("}")
    return 글[처음:끝 + 1] if 0 <= 처음 < 끝 else "{}"


def 꽂기(카드들: list, 사진들: list, 주제: str, 보내기=None) -> dict:
    """사람이 올린 사진을 자리에 꽂는다. **카드들은 그 자리에서 고쳐진다.**

    돌려주는 것: `{"꽂은수": n, "안쓴사진": [주소, …], "본것": {주소: 한 줄}}`

    「안 쓴 사진」은 미리보기 아래에 띄운다(설계 §6.2) — 사람이 끌어다 놓을 수
    있어야 하므로 버리지 않고 돌려준다.
    """
    import 사진만들기  # noqa: PLC0415 — 표지 가리는 규칙 한 곳을 같이 쓴다

    사진들 = [str(u).strip() for u in (사진들 or []) if str(u).strip()]
    빈자리 = [(r, 카드) for 카드 in (카드들 or [])
            for r in (카드.get("장식영역") or [])
            if r.get("종류") in 사진만들기.사진종류
            and not str(r.get("media_url") or "").strip()
            # **표지는 후보에서 뺀다**(사람 결정 2026-09-20).
            and not 사진만들기.표지인가(카드)]
    if not 사진들 or not 빈자리:
        return {"꽂은수": 0, "안쓴사진": 사진들, "본것": {}}

    짝 = 읽고맞추기(사진들, 빈자리, 주제, 보내기)
    본것, 쓴것 = {}, set()
    찬자리 = set()
    for x in 짝:
        번호 = x.get("번호")
        자리번호 = x.get("자리")
        if not isinstance(번호, int) or not 1 <= 번호 <= len(사진들):
            continue
        주소 = 사진들[번호 - 1]
        본것[주소] = str(x.get("본것") or "").strip()
        if not isinstance(자리번호, int) or not 1 <= 자리번호 <= len(빈자리):
            continue
        # 같은 자리·같은 사진을 두 번 쓰지 않는다 — 모델이 어길 수 있다.
        if 자리번호 in 찬자리 or 주소 in 쓴것:
            continue
        빈자리[자리번호 - 1][0]["media_url"] = 주소
        찬자리.add(자리번호)
        쓴것.add(주소)

    안쓴것 = [u for u in 사진들 if u not in 쓴것]
    print(f"++ 올린 사진 {len(사진들)}장 중 {len(쓴것)}장을 꽂았다 "
          f"(빈 자리 {len(빈자리)}개, 안 쓴 사진 {len(안쓴것)}장)")
    return {"꽂은수": len(쓴것), "안쓴사진": 안쓴것, "본것": 본것}


def 본것만(카드들: list, 사진들: list, 주제: str, 보내기=None) -> dict:
    """참조로 쓸 사진을 **보기만** 한다 — 자리에 안 꽂는다. `{주소: 한 줄}`.

    사람 결정 2026-09-28: 올린 사진을 «그대로 넣기» 가 아니라 «참조해서 만들기» 로
    고르면, 그 사진 속 사람·물건으로 새 장면을 만든다. 그러려면 사진이 무엇인지
    글로 알아야 계획(`사진계획`)에 줄 수 있다.

    `읽고맞추기` 를 그대로 쓴다 — 짝짓기 답은 버리고 «본것» 만 남긴다. 표지 자리도
    목록에 넣는다(참조는 표지에도 쓸 수 있다, 설계 §5.2).
    """
    import 사진만들기  # noqa: PLC0415

    사진들 = [str(u).strip() for u in (사진들 or []) if str(u).strip()]
    자리들 = [(r, 카드) for 카드 in (카드들 or [])
           for r in (카드.get("장식영역") or [])
           if r.get("종류") in 사진만들기.사진종류
           and not str(r.get("media_url") or "").strip()]
    if not 사진들 or not 자리들:
        return {}
    난것 = {}
    for x in 읽고맞추기(사진들, 자리들, 주제, 보내기):
        번호 = x.get("번호")
        if isinstance(번호, int) and not isinstance(번호, bool) and 1 <= 번호 <= len(사진들):
            난것[사진들[번호 - 1]] = str(x.get("본것") or "").strip()
    return 난것
