# -*- coding: utf-8 -*-
"""로고 자리를 채우거나 **아예 없앤다**.

사람 지시 2026-09-19: 「채팅에 로고를 넣었으면 좋겠어. 로고 안 넣기를 선택하면
만들어질 때 로고 영역은 없어지는 거지」.

**왜 없애야 하나.** 로고 자리를 빈 채로 두면 완성 카드에 **점선 네모와 물음표가
그대로 박혀 나간다**(`render/cardnews_compose._decoration_칠` 의 자리표시).
자리표시는 「여기 뭔가 들어올 자리다」는 뜻이라 작업대에서는 맞지만, 다 만들어진
카드에 있으면 못 쓴다.

**사진과 다르다.** 사진 자리는 비워 두는 것이 답일 때가 있어서(자기 사진을
작업대에서 채우는 사람) 물음표를 그대로 둔다. 로고는 그런 뒷일이 없다 —
「없이」는 나중에 채울 것이 아니라 **그냥 없는 것**이다.

**원본 로고는 절대 안 베낀다.** 라벨이 로고 자리를 «빈 자리» 로만 남기는 까닭이
그것이다 — 「남의 계정 로고가 우리 카드뉴스에 박혀 나간다」(`merge_labeled`).
그래서 이 자리는 **사람이 올리지 않으면 반드시 빈다.**

그리는 쪽은 안 건드린다. `cardnews_compose` 는 진작부터 `media_url` 을 받아
로고를 **안 잘리게 안에 맞춰**(`_contain_fit`) 넣게 돼 있었다.
"""

로고종류 = "로고"
"""«로고 자리» 로 세는 것. `web/server/chat.로고자리수` 와 같은 하나다."""


def 자리수(카드: list) -> int:
    """로고 자리가 몇 개인가. 채팅이 「몇 개 있어요」라고 말하는 그 수와 같다."""
    return sum(1 for _ in _로고자리들(카드))


def _로고자리들(카드: list):
    for 장 in 카드 or []:
        칸들 = (장 or {}).get("장식영역")
        for r in 칸들 if isinstance(칸들, list) else []:
            if isinstance(r, dict) and r.get("종류") == 로고종류:
                yield 장, r


def 채우기(카드: list, 주소: str = "") -> int:
    """로고 자리를 처리한다. **카드를 그 자리에서 고친다.**

    `주소` 가 있으면 자리마다 그 주소를 박고, 비면 자리를 **통째로 뺀다**.
    돌려주는 것은 «손댄 자리 수» 다.

    **주소를 안 재검사한다.** 우리 창고 것인지는 채팅 서버가 이미 걸렀다
    (`web/server/chat.쓸로고`). 두 곳에서 거르면 규칙이 두 벌이 된다.
    """
    주소 = (주소 or "").strip()
    센것 = 0
    for 장, 칸 in list(_로고자리들(카드)):
        if 주소:
            칸["media_url"] = 주소
        else:
            # **뺀다 — 비우지 않는다.** `media_url` 만 지우면 그리는 쪽이
            # 「아직 안 채운 자리」로 보고 점선과 물음표를 찍는다.
            장["장식영역"] = [r for r in 장["장식영역"] if r is not 칸]
        센것 += 1
    return 센것
