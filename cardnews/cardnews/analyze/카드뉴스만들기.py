class 못만듦(Exception):
    """만들다 멈췄다. `코드` 는 사람에게 보일 말을 고르는 데 쓴다."""

    def __init__(self, 코드: str, 말: str = ""):
        super().__init__(말 or 코드)
        self.코드 = 코드
        self.말 = 말


def 말나누기(말: str) -> tuple:
    """RITA 가 준 한 덩이를 «주제» 와 «원고» 로. 둘 중 하나는 빈 글자다."""
    말 = (말 or "").strip()
    if len(말) >= 원고길이:
        # 원고를 쓸 때도 주제 칸이 비면 안 된다 — 프롬프트가 첫 줄에 그것을
        # 적는다. 원고의 첫 줄을 주제로 삼는 것이 사람이 쓰는 방식에 가깝다.
        return 말.splitlines()[0][:100], 말
    return 말, ""


def _부르기(길: str, 몸: dict, 초: int = 180):
    """작업대 람다를 **직접** 부른다. 바깥 문(게이트웨이)을 안 거친다.

    **게이트웨이가 하던 봉투를 우리가 짓는다** — 받는 쪽(`render/app.handler`)은
    `rawPath` 와 `body` 만 본다. 그 둘을 맞춰 주면 코드는 한 줄도 안 바뀐다.

    `초` 는 이제 안 쓴다 — 받는 쪽 람다의 제 시간(600초)이 한도다. 부르는 자리가
    여럿이라 인자는 그대로 둔다.
    """
    import boto3  # noqa: PLC0415 — 무거운 임포트라 여기서

    봉투 = {"rawPath": 길,
          "requestContext": {"http": {"method": "POST"}},
          "body": json.dumps(몸, ensure_ascii=False)}
    답 = boto3.client("lambda").invoke(
        FunctionName=작업대함수,
        Payload=json.dumps(봉투, ensure_ascii=False).encode("utf-8"))
    # **터진 것을 조용히 넘기지 않는다.** 직접 부르면 람다가 터져도 HTTP 오류가
    # 아니라 답 안에 `FunctionError` 로 온다 — 안 보면 「없는 답」을 쓰게 된다.
    if 답.get("FunctionError"):
        속 = 답["Payload"].read().decode("utf-8", "replace")[:300]
        print(f"!! {길} 를 부르다 작업대가 터졌다 — {속}")
        raise 못만듦("upstream_failed", f"{길} 를 부르지 못했다")
    난것 = json.loads(답["Payload"].read().decode("utf-8"))
    코드 = int(난것.get("statusCode") or 0)
    몸통 = 난것.get("body") or "{}"
    if 200 <= 코드 < 300:
        return json.loads(몸통)
    return _부르다탈(길, 코드, 몸통[:300])


def _부르다탈(길: str, 코드: int, 몸통: str):
    """게이트웨이 때와 같은 탈을 낸다 — 부르는 쪽 코드가 안 바뀌게."""
    print(f"!! {길} 가 {코드} — {몸통}")
    # **못 찾은 것(404)은 사람에게 그대로 전한다.** 우리 서버가 담아 보낸
    # 말이고, 「그런 말투가 없다 — 있는 것은 …」처럼 사람이 바로 고칠 수
    # 있는 내용이다. 남의 서버 문구가 아니라 우리가 쓴 문구다.
    if 코드 == 404:
        try:
            말 = json.loads(몸통).get("error") or ""
        except Exception:  # noqa: BLE001 — JSON 이 아니면 일반 문구로
            말 = ""
        if 말:
            raise 못만듦("not_found", 말)
    # 나머지는 몸통을 자국에만 남긴다 — 남의 서버 문구를 화면에 싣지 않는다.
    raise 못만듦("upstream_failed", f"{길} 를 부르지 못했다")


