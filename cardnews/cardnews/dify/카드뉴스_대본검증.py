def _다시감기(줄들, n, lo, hi, 끝줄하한=True, 표시줄들=None):
    """줄바꿈은 LLM 이 아니라 코드가 맡는다 — 실물 실행(2026-08-23, §27 후속)에서
    "정확히 N줄, 각 줄 M~M자" 를 LLM 에게 직접 맞히라고 시켰더니 재작성을 여러
    판 거쳐도 계속 틀렸다(줄 수만 8줄을 낸 적도 있다). 그런데 **낱말 순서만
    지키면** 되는 줄바꿈은 코드가 항상 정확히 풀 수 있는 문제다 — 그러니 LLM
    에게는 "총 이 정도 분량으로 써라" 만 맡기고, 몇 글자에서 끊을지는 여기서
    낱말 경계를 그대로 두고 다시 감는다(의미·낱말 순서는 안 바뀐다, 띄어쓰기
    위치만 줄바꿈으로 바뀐다). 원문 그대로도 이미 조건을 만족하면 이 함수는
    안 불린다 — 만족 못 할 때만 마지막 구제책으로 쓴다.

    `표시줄들`(선택) — **표시(`**`·`##`)가 살아 있는 같은 글의 줄들.** 줄 나눌
    자리는 항상 `줄들`(표시를 뗀 글, 자수 기준)의 낱말 길이로 고른다. 낱말
    수가 서로 같으면(거의 늘 같다 — 표시는 낱말 안에 붙지 띄어쓰기를 새로
    만들지 않는다) 그 자리에 표시가 붙은 낱말을 끼워 돌려준다. 다르면(드문
    엇갈림) 표시 없는 낱말로 물러선다 — 표시를 잃을 뿐 줄바꿈 자체는 그대로다.
    """
    낱말들 = " ".join(줄들).split()
    if not 낱말들:
        return None
    표시낱말들 = " ".join(표시줄들).split() if 표시줄들 is not None else None
    쓸것 = 표시낱말들 if (표시낱말들 is not None and len(표시낱말들) == len(낱말들)) else 낱말들
    N = len(낱말들)
    길이들 = [len(w) for w in 낱말들]

    @lru_cache(maxsize=None)
    def 풀기(i, 남은줄):
        if 남은줄 == 0:
            return () if i == N else None
        총 = -1
        for j in range(i, N):
            총 = 길이들[j] if 총 < 0 else 총 + 1 + 길이들[j]
            if 총 > hi:
                break
            if 남은줄 == 1:
                if j != N - 1:
                    continue
                if 끝줄하한 and 총 < lo:
                    return None   # 마지막 줄도 최소 자수를 지켜야 한다 — 실물 2026-08-24,
                                   # 여기가 빠져서 "모두 확인이 됩니다."(11자, 최소 19자)
                                   # 같은 너무 짧은 마지막 줄을 성공으로 잘못 승인했다.
                return (" ".join(쓸것[i:j + 1]),)
            if 총 >= lo:
                나머지 = 풀기(j + 1, 남은줄 - 1)
                if 나머지 is not None:
                    return (" ".join(쓸것[i:j + 1]),) + 나머지
        return None

    풀린것 = 풀기(0, n)
    풀기.cache_clear()
    return list(풀린것) if 풀린것 else None


def _벗기기(글):
    """LLM 이 ```json 으로 감싸 보내는 일이 흔하다."""
    글 = (글 or "").strip()
    글 = re.sub(r"^```(?:json)?\s*|\s*```$", "", 글, flags=re.M).strip()
    처음, 끝 = 글.find("{"), 글.rfind("}")
    return 글[처음:끝 + 1] if 처음 >= 0 and 끝 > 처음 else 글


# 굵게·형광펜 표시. **재는 쪽과 그리는 쪽이 어긋나서 넣는다.**
#
# 레시피는 장마다 「마크다운 기호 제외」라고 적어 두고 자수를 정한다. 그런데
# 그 말만 있고 **기호를 빼는 코드가 어디에도 없었다** — 세는 쪽은 `**`·`##` 를
# 글자로 같이 세고, 그리는 쪽은 그것을 글자로 그렸다. 실물(2026-08-27 RITA 첫
# 성공): 2번 장 제목이 «**감성 인테리어 포토존 특화 카페**» 로 별표까지 찍혀
# 나왔다. `##` 도 같이 떼야 한다 — 안 그러면 형광펜 표시가 글자로 세어져 예산이
# 어긋나고, 그리는 쪽은 그 표시를 안 그리므로 상자가 헐거워진다.
#
# 뗄 표시는 `카드뉴스_강조.떼기` 가 이미 안다 — **세는 쪽과 감는 쪽이 같이
# 쓰는 한 곳**이라 여기서도 그걸 쓴다. 두 벌로 갈리면 검증과 배치가 서로 다른
# 자리를 표시로 본다. 짝이 안 맞고 남은 별표(`_뜬별표`)도 `강조.떼기` 안에서
# 같이 떼므로 여기서 따로 뗄 것이 없다.


def _기호빼기(글: str) -> str:
    """`**굵게**`·`##형광펜##` → 알맹이만. 짝이 안 맞는 별표도 떼어 낸다.

    **자수는 표시를 뺀 길이로 센다.** 표시를 글자로 세면 예산이 어긋나고,
    그리는 쪽은 그 표시를 안 그리므로 상자가 헐거워진다.
    """
    return 강조.떼기(글)[0]


# **남의 브랜드 이름 검사를 뺐다**(사람 결정 2026-09-24).
#
