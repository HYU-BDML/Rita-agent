#
# **이 노드가 하는 일: 대본이 규칙표(docs/규칙표_카드뉴스.md) §1(자수)·골격을
# 지키는지 기계가 다시 센다.** 기준값은 전부 「레시피 꺼내기」 노드가 내놓는
# `틀_json` 에서 온다 — 여기 손으로 적은 숫자는 하나도 없다. `틀_json` 은
# `analyze/recipe.py` 의 `char_limit_rows()`·`role_quotes()` 실측을 그대로 담고
# 있다(dify/make_dsl_cardnews.py 가 빌드할 때 박는다).
#
# 입력 변수:
#     text     String   ← 대본 / text                (처음 쓴 것)
#     틀_json   String   ← 레시피 꺼내기 / 틀_json      (골격·장마다 글자슬롯·자수 한계)
#     고친것    String   ← 대본 다시 쓰기 / text        (안 돌았으면 빈 글자)
#
# **왜 «고친것» 을 받나.** 이 노드로 오는 길이 둘이다 — 막힌 게 없으면 갈래에서
# 바로 오고, 막혔으면 «다시 쓰기» 를 거쳐 온다. 한 쪽만 읽게 하면 **안 돈 노드의
# 결과를 읽으려다 죽는다**(dify-workflow 스킬, 06_본문검증.py 와 같은 이유).
#
# 출력 변수:
#     slides   Array[Object]  파싱한 장들 [{"role":.., "blocks":[..]}] — 표시(`**`·`##`)
#                              를 뗀 글. 사람이 점수표에서 읽기 좋게 남긴다.
#     표시슬라이드 Array[Object]  같은 모양이지만 **표시가 살아 있는 글**.
#                              배치가 받는 것은 이것이다 — 배치가 `**`·`##` 를
#                              직접 찾아 굵기·형광펜을 만들기 때문이다
#                              (표시를 뗀 `slides` 를 배치로 보내면 그 둘이 늘
#                              빈 목록이 된다, 검토 지적 ①).
#     count    Number
#     blocked  String   **되돌려야 하는 잘못.** 비어 있으면 통과
#                        칸 이름은 아스키다 — LLM 프롬프트가 {{#..#}} 로 이 값을
#                        직접 읽는데, Dify 의 변수 참조 정규식이 아스키만 받는다
#                        (한글 칸은 조용히 치환이 안 된 채로 간다. 오류모음 §22).
#     점수표    String   사람이 보는 몫. 되돌리지 않는다 — {{#..#}} 로 안 읽혀서 그대로 둔다
#     ok       String   "1" 이면 통과, "0" 이면 다시 쓰기로
#                        **글자다.** Dify 의 갈래(`is`)가 글자끼리만 비교한다
#     draft    String   **실제로 검증한 글**(고친것 이 있었으면 그것, 없었으면 text
#                        그대로). 되돌리기를 여러 판 잇댈 때 다음 판의 `text` 입력이
#                        이걸 받는다 — "이번 판이 실제로 무엇을 검증했는지"를 다음
#                        판이 원본이 아니라 여기서 이어받아야, 이미 통과한 고친
#                        글을 다음 판이 원본으로 되돌려 다시 검증하는 일이 없다.
#
# 자수 상·하한을 **둘 다** 막는 이유: 진행표 "Task 9 규칙표에 사람이 오늘 정한 것
# 셋" (2) — "아래 공백(하한)도 넘침(상한)만큼 중요하다"(2026-08-20, 사람이 그림을
# 보고 정함). 배치 단계에서도 같은 것을 다시 재지만(방어가 하나뿐이면 배치가
# 상자·자수를 잘못 짝지어도 못 잡는다), 여기서 먼저 잡으면 LLM 이 고칠 기회가
# 있다 — 배치 뒤에서는 코드로 자르는 것(넘침)만 가능하고 늘리는 건 못 한다.

