# 고쳐야 한다. 되살릴 일이 생기면 이 주석이 출발점이다.
def _슬라이드뽑기(글):
    """LLM 출력에서 «slides» 목록을 꺼낸다. **조용한 0개를 만들지 않는다.**

    `(json.loads(글) or {}).get("slides") or []` 한 줄로 줄이면 파싱 실패·안 돈
    노드의 `null`·칸 이름이 다른 경우가 전부 «0개» 로 뭉개진다 — 06_본문검증.py 의
    `_꼭지뽑기` 가 이미 겪고 고친 것과 같은 함정이다.

    돌려주는 것: (장 목록, 무슨 일이 있었나 — 아무 탈 없으면 빈 글자)
    """
    벗긴것 = _벗기기(글)
    if not (벗긴것 or "").strip():
        return [], "대본이 비어 있다 — 앞 노드가 아무것도 안 내놨다"
    try:
        d = json.loads(벗긴것)
    except Exception as e:
        return [], f"대본이 JSON 이 아니다 ({e}) — 앞 300자: «{벗긴것[:300]}»"
    if not isinstance(d, dict):
        return [], f"대본이 묶음이 아니라 {type(d).__name__} 다"
    if not isinstance(d.get("slides"), list):
        return [], f"«slides» 칸이 없다 — 들어 있는 칸: {sorted(d)[:8]}"
    return d["slides"], ""


def main(text: str, 틀_json: str, 고친것: str = "") -> dict:
    글 = 고친것 if (고친것 or "").strip() else text
    틀 = json.loads(틀_json)
    골격 = 틀["골격"]
    슬라이드틀 = {s["index"]: s for s in 틀["슬라이드"]}
    # **몇 곳을 쓸지는 안 막는다 — 쏠림만 막는다**(사람 결정 2026-09-17).
    # 예전엔 위계별 최빈값(`강조.모으기()`)과 슬롯마다의 개수를 견줬는데,
    # 실측(기본·DG0AA6PJ8s4·DHqCBQnRAjW)에서 「대부분 0」이 이겨 모든 틀의
    # 형광펜이 0곳으로 뭉개졌다. 이제는 같은 위계 칸이 둘 이상일 때 «어느
    # 칸엔 있고 어느 칸엔 없는지» 만 본다 — 아래 루프에서 칸마다
    # `강조모음` 에 담고, 루프가 끝난 뒤 위계별로 한 번에 검사한다.
    강조모음: dict = {}

    슬라이드, 파싱탈 = _슬라이드뽑기(글)
    blocked = []
    if 파싱탈:
        blocked.append(파싱탈)

    n = len(슬라이드)
    if n != len(골격):
        blocked.append(f"장이 {n}개인데 골격은 {len(골격)}장이다 "
                        f"({' → '.join(골격)}) — 지어내지도 빼지도 마라")

    넘침, 미달 = 0, 0
    무른것 = []   # 막을 것까지는 아닌 것 — 아래 「굳은 것과 무른 것」 참고
    권고 = []     # **막지 않고 알려만 주는 것.** 자수 미달이 여기로 온다
    정리된_슬라이드 = []
    # **표시(`**`·`##`)가 살아 있는 같은 슬라이드.** `정리된_슬라이드` 는 이미
    # `_기호빼기` 를 거친 글이라 배치가 찾을 표시가 하나도 안 남는다(검토
    # 지적 ① — 배치의 `굵기`·`형광펜` 이 늘 빈 목록이 되는 원인). 배치는
    # 이 목록을 받는다.
    표시_슬라이드 = []
    for i, 카드 in enumerate(슬라이드, start=1):
        if i > len(골격):
            break
        기대역할 = 골격[i - 1]
        # **여기서부터 반환하는 「slides」는 항상 {role, blocks} 뿐인 깔끔한
        # 묶음이다.** LLM 이 붙인 딴 칸(예: "characters":[[13,14]])을 그대로
        # 돌려주면 장마다 모양이 달라져 Dify 의 출력 형식 검사가 code 노드
        # 자체를 죽인다("'list' object has no attribute 'items'", 실물
        # 2026-08-23) — try/except 밖이라 이 파일 안에서 못 잡는다. 카드가
        # 묶음이 아니거나 블록 안에 글자 아닌 게 섞여도 여기서 먼저 걸러
        # **막힘으로 보고하고, 깨진 모양 그대로는 절대 내보내지 않는다.**
        if not isinstance(카드, dict):
            blocked.append(f"{i}번 장이 묶음이 아니라 {type(카드).__name__} 다")
            정리된_슬라이드.append({"role": 기대역할, "blocks": []})
            표시_슬라이드.append({"role": 기대역할, "blocks": []})
            continue
        # **역할은 골격에서 온다 — 모델에게 안 묻는다.**
        #
        # 몇 번째 장이 무슨 역할인지는 골격이 이미 안다. 그런데 모델에게 그
        # 낱말을 다시 써 내라 하고, 다르면 막았다. 그러면 «글은 잘 썼는데 이름을
        # 잘못 붙였다» 는 이유로 다 된 대본을 버리게 된다 — 실물(2026-08-28):
        # 사례 자리에 「정의」·「문제」라고 적었다고 두 판을 태우고 막혔다.
        #
        # 코드가 알 수 있는 것은 코드가 정한다. 줄 나누기를 코드가 맡은 것과
        # 같은 결이다. 모델이 맞춰야 하는 것은 «차례대로 그 칸에 맞는 글» 이지
        # 이름표가 아니다.
        역할 = 기대역할
        블록원본 = 카드.get("blocks") or []
        if not isinstance(블록원본, list):
            blocked.append(f"{i}번 장 blocks 가 목록이 아니라 {type(블록원본).__name__} 다")
            정리된_슬라이드.append({"role": 역할, "blocks": []})
            표시_슬라이드.append({"role": 역할, "blocks": []})
            continue
        # 강조 수는 표시를 떼기 **전** 글에서 센다 — 뗀 뒤로는 `**`·`##` 가
        # 이미 사라져 있어서 셀 것이 안 남는다.
        원문블록 = [b if isinstance(b, str) else json.dumps(b, ensure_ascii=False)
                for b in 블록원본]
        블록 = [_기호빼기(t) for t in 원문블록]
        정리된_슬라이드.append({"role": 역할, "blocks": 블록})
        # 표시가 살아 있는 채로 시작해, 아래에서 다시 감긴 블록만 그 자리에서
        # 표시가 붙은 낱말로 갈아 낀다(그대로 통과한 블록은 원문 그대로 둔다).
        표시블록 = list(원문블록)
        표시_슬라이드.append({"role": 역할, "blocks": 표시블록})
        슬롯들 = 슬라이드틀.get(i, {}).get("글자슬롯", [])
        if len(블록) != len(슬롯들):
            blocked.append(f"{i}번 장({역할}) 블록이 {len(블록)}개인데 슬롯은 "
                        f"{len(슬롯들)}개다")
            continue
        for j, (슬롯, 블록글, 원문글) in enumerate(zip(슬롯들, 블록, 원문블록), start=1):
            # **번호 칸은 안 본다**(사람 결정 2026-08-30). 그 자리는 대본이
            # 아니라 장 차례로 채운다(`카드뉴스_배치._번호글`) — 모델이 무엇을
            # 썼든 버려지므로, 여기서 자수를 따지면 안 쓸 글 때문에 다 된 대본이
            # 막힌다.
            if 슬롯.get("위계") == "번호":
                continue
            # **강조는 아무것도 안 막는다**(사람 결정 2026-09-18).
            #
            # 형광펜 색이 없어도 안 막는다 — 배치가 게시물 강조색으로 그린다
            # (`카드뉴스_배치`: `슬롯.get("형광펜색") or 강조색`). 막을 기술적
            # 이유가 없었다.
            #
            # 세기만 해서 점수표에 남긴다. 나중에 실물이 쌓이면 그 기록으로
            # 「몇 대 몇부터 쏠림인가」를 잴 수 있다 — 지금은 근거가 없다.
            센것 = 강조.세기(원문글)
            위계 = 슬롯.get("위계")
            if 위계:
                강조모음.setdefault(위계, []).append(
                    {"자리": f"{i}번 장", "굵게": 센것["굵게"] > 0,
                     "형광펜": 센것["형광펜"] > 0})
            # **모든 칸을 통틀어 몇 자로 본다**(사람 결정 2026-09-16 본문,
            # 2026-09-18 전부: 「세로줄은 안 본다니까」). 줄은 배치가 글꼴 폭을
            # 재서 나누므로 여기서 줄 수·줄마다 자수를 따지면 «폭을 다 못 쓰는 짧은
            # 줄» 을 통과시키고 «폭을 채운 긴 줄» 을 막는다 — 거꾸로다.
            덩어리 = 자수.한덩어리(블록글)
            블록[j - 1] = 덩어리
            # 통자수 자리는 배치가 스스로 표시를 떼고 폭을 재서 감는다
            # (`카드뉴스_배치.main` 의 `자수.한덩어리` → `강조.떼기` →
            # `자수.폭감기` 순서) — 여기서는 줄만 한 덩어리로 고르고,
            # 표시는 그대로 둔다.
            표시블록[j - 1] = 자수.한덩어리(원문글)
            통최소, 통최대 = 자수.통자수(슬롯)
            # **글자 수가 아니라 «몇 자 분량» 으로 잰다**(사람 결정 2026-09-18) —
            # 실제 글꼴 폭 ÷ 「가」 한 자 폭. 영문·숫자·띄어쓰기가 섞인 글이 글자
            # 수로는 넘치고 폭으로는 들어가는 일이 예시 5개 중 3개에서 났다.
            총 = 자수.자분량(슬롯, 덩어리)
            분량 = f"{round(총, 1):g}자 분량(글자 수 {len(덩어리)})"
            if 총 > 통최대:
                # **하한도 같이 적는다**(사람 지적 2026-09-19: 「글자수가 웰케
                # 이랬다 저랬다임?」).
                #
                # 여기 적히는 말이 그대로 고쳐 쓰기 프롬프트로 간다
                # (`카드뉴스만들기._대본사슬` → `프롬프트.다시쓰기_사용자`). 그런데
                # 넘어가는 것은 **막힘 목록뿐**이고 자수 미달은 「권고」라서 안
                # 실린다 — 즉 고쳐 쓰는 모델은 「길다」는 말만 듣고 「짧다」는 말은
                # 한 번도 못 듣는다.
                #
                # 그래서 「최대 118자인데 132자다, 줄여라」만 보고 32자까지 잘랐다
                # (실물 2026-09-19: 4장 32자·5장 25자, 하한은 73자·76자였다).
                # 첫 판이 넘쳤느냐 아니냐로 결과가 갈려 판마다 들쭉날쭉했다.
                #
                # 위아래를 같이 주고 «범위 안으로» 라고 적으면 내려갈 바닥이 생긴다.
                blocked.append(f"{i}번 장 블록{j} 은 통틀어 {통최소}~{통최대}자여야 하는데 "
                               f"{분량}이다 — 그 **범위 안으로** 줄여라. "
                               f"{통최소}자 아래로 내려가면 안 된다: «{덩어리}»")
            elif 총 < 통최소:
                권고.append(f"{i}번 장 블록{j} 은 통틀어 최소 {통최소}자인데 {분량}이다 "
                          f"(모자라면 아래가 빈다)")

    # **쏠림을 안 막는다 — 점수표에만 적는다**(사람 결정 2026-09-18: 「그냥
    # 알아서 강조할 부분에 강조하고, 형광펜 쓰고 싶은 부분에 형광펜 쓰고」).
    #
    # 여기까지 세 판이었다. ① 위계별 개수를 못 박았다 — 「대부분 0」이 이겨
    # 실측 틀 전부에서 형광펜이 0곳으로 뭉개졌다. ② 개수를 빼고 «쓰거나 안
    # 쓰거나가 같은지» 를 봤다 — 설계서엔 「쏠림을 막는다」고 써 놓고 코드는
    # `any and not all`, 곧 «전부 아니면 전무» 였다. ③ 그 규칙으로 실물 다섯
    # 벌을 만들어 보니 **한 벌도 안 나왔다**(2026-09-18 실측: 막은 것 19건 중
    # 강조가 10건 — 22칸 중 6칸에 형광펜을 쓴 것까지 막혔다).
    #
    # 「몇 대 몇부터 쏠림인가」를 정할 실측 근거가 없다. 표본 넷(1/2·1/8·6/22)으로
    # 문턱을 박으면 또 근거 없는 숫자를 넣는 것이다. 그래서 세기만 하고 남긴다.
    강조적기 = []
    for 위계, 자리들 in 강조모음.items():
        for 갈래 in ("굵게", "형광펜"):
            쓴수 = sum(1 for x in 자리들 if x[갈래])
            if 쓴수:
                강조적기.append(f"{위계} {갈래} {쓴수}/{len(자리들)}칸")

    점수 = [f"장 {n}개 (골격 {len(골격)}개)",
            f"자수 넘침 {넘침}건 · 자수 미달 {미달}건(권고, 안 막음)"]
    if 강조적기:
        점수.append("강조 " + " · ".join(강조적기) + " (안 막음)")
    점수 += 권고[:12]

    # **굳은 것과 무른 것을 갈라서 낸다.**
    #
    # 자수 미달은 «네모가 좀 헐렁해 보인다» 는 뜻이다 — 보기에 아쉬울 뿐 카드가
    # 망가지지는 않는다. 넘침은 다르다: 글자가 네모 밖으로 나가거나 잘린다.
    #
    # 그런데 여태 둘을 똑같이 막았다. 그래서 **두 자밖에 안 모자란 제목 한 줄
    # 때문에 다 된 일곱 장을 통째로 버리는** 일이 생겼다(실물 2026-08-27:
    # «강남 카페 4대 트렌드 총정리» 16자, 하한 18자). 사람이 이미 「너무 빡빡하게
    # 하면 글자수 때문에 제대로 못 한다」고 정해 준 자리다.
    #
    # 그래서 **고쳐 쓰라고는 하되, 마지막에 그것만 남았으면 통과시킨다.**
    # `blocked`(다시 쓰기에게 줄 말)는 그대로 다 담고, `굳은막힘`(정말 막아야
    # 하는 것)만 따로 낸다. 부르는 쪽이 어느 걸 볼지 고른다.
    굳은것 = [x for x in blocked if x not in 무른것]

    return {"slides": 정리된_슬라이드, "표시슬라이드": 표시_슬라이드, "count": n,
            "blocked": "\n".join(blocked), "점수표": "\n".join(점수),
            "굳은막힘": "\n".join(굳은것), "굳은ok": "0" if 굳은것 else "1",
            "ok": "0" if blocked else "1", "draft": 글}
