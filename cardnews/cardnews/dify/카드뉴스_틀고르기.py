def 대신할역할(역할: str, 서랍: dict):
    """`역할` 이 서랍에 없을 때 대신 쓸 역할. 있으면(대신할 필요가 없으면) None."""
    if 서랍.get(역할):
        return None
    for 딴것 in 대신표.get(역할, ()):
        if 서랍.get(딴것):
            return 딴것
    return None


# 「본문류」 — 칸 구성이 「소제목 한 줄 + 본문 여러 줄」로 같아서 서로 바꿔 써도
# 어긋나지 않는 무리다. **이 무리는 «그 역할이 있어도» 한 통으로 모은다.**
#
# 없을 때만 대신하면 서랍이 기울어 있을 때 놀고 있는 옷이 생긴다 — 실측
# (DG0AA6PJ8s4): 사례 1벌 · 해결 4벌인데 사례 자리 넷을 그 «하나»로 돌려 쓰고
# 해결 넷은 한 번도 안 불렸다(2026-08-26). 훅·요약·CTA 는 모으지 않는다.
# 요약 자리에 CTA 디자인이 섞이면 그건 다른 옷이다.
본문류 = ("사례", "해결", "정의", "문제", "비교", "데이터")


def 후보모으기(역할: str, 서랍: dict) -> list:
    """그 역할에 쓸 디자인 후보. 본문류면 무리를 통째로 모은다.

    모을 때 차례는 `본문류` 에 적힌 차례다 — 서랍의 열쇠 차례(파이썬 사전 순서)에
    기대면 계량표를 다시 뽑을 때마다 고르는 옷이 조용히 바뀐다.
    """
    if 역할 in 본문류:
        모은것 = []
        for 이름 in (역할,) + tuple(x for x in 본문류 if x != 역할):
            모은것 += 서랍.get(이름) or []
        return 모은것
    return 서랍.get(역할) or []


def 고르기(서랍: dict, 골격: list) -> list:
    """골격의 장마다 디자인 하나씩. **아직 안 쓴 것을 먼저** 쓴다.

    같은 디자인이 연달아 나오면 눈에 띈다. 그래서 역할마다 순번을 따로 돌리고,
    다 쓰면 처음부터 다시 돈다. 서랍이 얕으면(디자인이 하나뿐이면) 결과가 예전
    돌려쓰기와 같아진다 — 그건 서랍을 채우면 저절로 나아지는 문제지 코드 문제가
    아니다.

    본문류(사례·해결·정의·문제·비교·데이터)는 `후보모으기` 가 무리를 통째로
    모아서 준다 — 그 역할이 서랍에 있어도 그렇다. 훅·요약·CTA 는 그대로
    「없을 때만」 대신표를 탄다.
    """
    쓴수 = {}
    난것 = []
    for 역할 in 골격:
        후보 = 후보모으기(역할, 서랍)
        쓸역할 = 역할
        if not 후보:
            쓸역할 = 대신할역할(역할, 서랍)
            후보 = 서랍.get(쓸역할) or [] if 쓸역할 else []
        if not 후보:
            raise ValueError(f"서랍에 «{역할}» 도, 대신 쓸 것도 하나도 없다 — "
                             f"있는 것: {', '.join(sorted(서랍)) or '없음'}")
        # **셈 열쇠는 «어느 통에서 꺼냈나» 로 잡는다.** 본문류는 `후보모으기`
        # 가 요청 역할마다 다른 차례로 통을 새로 만든다 — 그래서 역할이 곧
        # 통이고, 역할로 세면 된다. 반면 훅·요약·CTA 의 대신하기는 **남의
        # 통을 그대로 빌리는 것**이다 — 「요약 자리」와 「요약으로 대신한
        # CTA 자리」가 같은 서랍 칸(같은 통)을 나눠 쓴다. 그런데도 역할로
        # 세면 두 자리가 각자 0번부터 세서 같은 디자인이 잇달아 나온다
        # (재현: 서랍에 요약 두 벌·CTA 없이 훅·사례·요약·CTA 를 고르면 요약
        # 자리와 CTA 자리가 둘 다 첫 번째 요약을 집는다 — 2026-08-26 재검토).
        # 그래서 이 갈래는 쓸역할(실제로 연 통)로 세야 한다.
        통열쇠 = 역할 if 역할 in 본문류 else 쓸역할
        i = 쓴수.get(통열쇠, 0)
        쓴수[통열쇠] = i + 1
        고른것 = dict(후보[i % len(후보)])
        # **다른 역할 디자인을 골랐으면 적어 둔다.** 조용히 바꿔치기하면 결과가
        # 이상할 때 원인을 못 찾는다. 이 값은 `main` 이 쪽지로 옮기고 틀에는
        # 안 실린다. 본문류는 대신표를 안 타고도 무리에서 다른 역할을 집을 수
        # 있어서, 「대신표를 탔는가」가 아니라 「고른 디자인의 역할이 요청한
        # 역할과 다른가」로 판단한다.
        if 고른것.get("역할") != 역할:
            고른것["_대신"] = 역할
        난것.append(고른것)
    return 난것


def _본보기고르기(slot: dict, 언어: str) -> str:
    """**한 틀에 두 목소리** — 고른 언어에 맞는 말투 본보기를 꺼낸다.

    사람 결정 2026-09-18. 본보기는 장식이 아니라 대본 지시문 «안» 으로
    들어간다. 영어로 쓰라는 지시는 맨 앞 세 줄인데 한국어 예문은 열네 덩이라
    (실측: 틀 DNUFIa4NIkK 의 본보기 18개 중 14개가 한글) 분량 싸움에서 진다.

    **영어 칸이 없으면 한국어로 물러선다.** 틀마다 영어를 채우는 데는 시간이
    걸리고, 아직 안 채운 틀로도 영어 카드가 나와야 한다. 그때는 대본 지시문의
    「본보기는 한국어지만 말투만 배워라」 한 줄이 받쳐 준다(`프롬프트._영어로`).

    **고른 언어와 다른 말로 된 본보기는 안 쓴다**(사람 지시 2026-09-22:
    「한국어면 한글로 하는걸로 하고 영어면 영어로 하는걸로해」).

    여태는 본보기가 늘 한국어라고 봐도 됐다 — 영문 자리는 글자 크기를 못 재서
    슬롯째로 버려졌기 때문이다(`layout.ink_height`). 2026-09-22 에 영문도 재게
    고치자 「Switzerland」·「Weekly AI」 같은 본보기가 틀에 들어왔고, 한국어
    카드를 만드는데 그 자리 제목이 영어로 나왔다(실물).

    **본보기는 결을 주는 것이지 언어를 정하는 것이 아니다.** 말이 다르면 결을
    못 주고 언어만 잘못 가르치므로, 그때는 비운다 — 자리·자수·굵기는 그대로라
    빈 자리에 고른 언어가 제 길이로 들어간다.
    """
    if 언어 == "영어":
        영 = str(slot.get("본보기영어") or "").strip()
        if 영:
            return _자른표시떼기(영)
        # 영어 판에서는 한글 본보기를 그대로 쓴다 — 대본 지시문의 「본보기는
        # 한국어지만 말투만 배워라」 한 줄이 받쳐 준다(`프롬프트._영어로`).
        # 다만 **한글이 아예 없는 본보기는 그 자체가 영어**라 그대로 쓰면 된다.
        return _자른표시떼기(str(slot.get("본보기") or ""))
    본 = _자른표시떼기(str(slot.get("본보기") or ""))
    return 본 if _한글있나(본) else ""


def _한글있나(글: str) -> bool:
    return any("가" <= ch <= "힣" for ch in str(글 or ""))


def _자른표시떼기(본: str) -> str:
    """끝에 붙은 «…» 를 뗀다 — 그건 말이 아니라 우리가 자른 표시다.

    **코드만 고치면 지금 있는 틀은 안 고쳐진다.** 창고의 틀에는 이미 「…」가
    박혀 있고(`make_dsl_cardnews._본보기` 의 옛 판이 붙였다), 그 틀을 다시
    만들어야 반영된다. 여기서 떼면 지금 있는 틀에 바로 듣는다.

    **끝에 붙은 것만 뗀다.** 「음… 그게 말이죠」 처럼 사람이 일부러 쓴 것은
    그대로 둔다 — 그건 진짜 말투다.
    """
    본 = str(본 or "").rstrip()
    while 본.endswith("…"):
        본 = 본[:-1].rstrip()
    return 본


def 칸설명(슬라이드: list, 본보기끄기: bool = False, 언어: str = "한국어") -> str:
    """「대본」 LLM 에게 줄 칸 설명 — 장마다 어떤 칸이 몇 줄·몇 자인지.

    `main` 에서 뽑아 둔 것은 **말이 맞는지 따로 시험하기 위해서**다 — 틀을
    통째로 고르지 않고도 칸 설명만 견줄 수 있다.

    `언어` 는 말투 본보기에만 닿는다. 자리·자수는 틀이 정하는 것이라 안 바뀐다.
    """
    # **장 수를 맨 앞에 숫자로 못 박는다.**
    #
    # 「1번 장 … 7번 장」 이 죽 적혀 있으니 개수는 «세면» 알 수 있다. 그런데
    # 모델이 그걸 안 센다 — 실물(2026-08-28): 7장짜리 틀에 **9장을 써서** 두 판을
    # 고쳐 쓰고도 막혔다. 세게 하지 말고 그냥 알려 준다.
    골격줄 = " → ".join(s["역할"] for s in 슬라이드)
    줄 = [f"이 카드뉴스는 「정확히 {len(슬라이드)}장」이다. "
         f"slides 를 {len(슬라이드)}개 낸다 — 더도 덜도 안 된다.",
         f"차례: {골격줄}",
         "",
         "장마다 쓸 수 있는 칸:"]
    for s in 슬라이드:
        줄.append(f"{s['index']}번 장 ({s['역할']}):")
        for j, slot in enumerate(s["글자슬롯"], start=1):
            # **위계를 맨 앞에 적는다.** 「이 칸은 제목이다」를 알면 LLM 이 글을
            # 그에 맞게 쓴다 — 굵기·자수만으로는 그 뜻이 전해지지 않는다.
            # 틀에 위계가 없으면(옛 틀) 그 말만 빠지고 나머지는 그대로다.
            #
            # **별표로 감싸지 않는다.** 여기 `**제목**` 이 있으니 모델이 그걸
            # 따라 써서 카드에 별표가 그대로 찍혀 나왔다(실물 2026-08-27:
            # «**감성 인테리어 포토존 특화 카페**»). 낫표로 바꾸면 그 유혹이 없다.
            머리 = f"「{slot['위계']}」, " if slot.get("위계") else ""
            # **줄 수를 안 시킨다 — 「통틀어 몇 자」 하나만 시킨다**(사람 결정
            # 2026-09-16 본문, 2026-09-18 모든 칸: 「세로줄은 안 본다니까」).
            #
            # 「정확히 4줄, 줄마다 15~23자」를 시키면 모델이 그걸 «네 문장» 으로
            # 읽고 문장마다 30자씩 쓴다(실물 2026-08-28). 짧게 끊어 상자 오른쪽이
            # 빈 채로 나오기도 한다(실물: 파란 타임라인 5번 장, 오른쪽 35% 가 빔).
            # 줄 나누기는 코드가 글꼴 폭을 재서 한다.
            통최소, 통최대 = 자수.통자수(slot)
            줄.append(f"  블록{j}: {머리}{slot.get('weight')}, 줄 나누지 말고 "
                     f"한 덩어리로, 통틀어 {통최소}~{통최대}자(서식 기호 제외, "
                     f"영문·숫자·띄어쓰기는 반 자로 센다)")
            # **원래 있던 말을 같이 보여 준다.** 자리만 맞고 말투가 딴 사람이면
            # 그건 그 디자인이 아니다. 결만 따르라고 프롬프트가 못 박는다.
            #
            # **제 말투를 골랐으면 끄지 않는다**(사람 결정 2026-08-29). 여태는
            # 말투를 «고르기만 하면» 껐다 — 「키키 템플릿에 키키 말투」처럼 같은
            # 게시물에서 나온 짝까지 원문이 사라졌다. 말투를 고르는 것은 「그
            # 템플릿의 훅과 규칙을 다 배워 따라 써라」는 뜻인데, 정작 배울 글을
            # 지워 버리니 모델이 스스로 지어내고 그래서 「AI 스럽다」가 됐다.
            #
            # 남의 말투(다른 게시물)일 때만 끈다 — 그때는 목소리가 둘이 된다.
            if slot.get("본보기") and not 본보기끄기:
                # **줄마다 나눠 보여 준다**(사람 지적 2026-08-30).
                #
                # 한 덩이로 붙여 보내면 모델이 그걸 «산문» 으로 읽고 한 문장을
                # 죽 쓴다. 그러면 코드가 폭에 맞춰 다시 감는데, 그 자리는 낱말
                # 경계일 뿐 뜻의 경계가 아니다 — 원본은 「① 압도적인 광고
                # 효율성 / 평균 1100%에 달하는… / 기업의…」처럼 첫 줄이
                # 소제목인데, 우리 것은 「① 창의적 사고 없던 것을 / 만드는 인간
                # 고유의 발상력 / …」로 문장 중간에서 잘렸다.
                #
                # 원본이 어디서 끊었는지와 **줄마다 몇 자였는지**를 그대로
                # 보여 준다. 모델이 그 결로 쓰면 다시 감기가 아예 안 돈다.
                본 = _본보기고르기(slot, 언어)
                조각 = [x.strip() for x in 본.split("/") if x.strip()]
                if len(조각) > 1:
                    # **자수도 고른 본보기 것으로 따라간다.** 한글 자수를
                    # 영어에 들이대면 줄이 절반 길이가 된다.
                    줄.append("      원본은 줄마다 이렇게 끊었다 "
                              f"({'·'.join(str(len(x)) for x in 조각)}자):")
                    줄 += [f"        {k}줄: «{x}»" for k, x in enumerate(조각, 1)]
                else:
                    줄.append(f"      말투 본보기: «{본}»")
    return "\n".join(줄)


# 끝맺는 역할. **서랍에 있는 것만 골격에 넣는다**(사람 결정 2026-09-18: 「너 CTA
# 2개 쓴 거 맞네, 애초에 대본을 템플릿에 맞춰서 작성했어야지」).
#
# 여태는 `["요약", "CTA"]` 를 못 박아 서랍이 무엇을 갖고 있든 넣었다. 그래서
# 없는 역할이 대신표(`대신표`)를 타고 **있는 역할의 디자인을 빌려 썼고**, 같은
# 옷이 두 장 나왔다 — 실물 DYzN0Uzgaq6(AI소식 미니)의 서랍에는 요약이 없어서
# 요약 자리가 CTA 를 빌렸다.
#
# 본문류(사례 등)는 그대로 둔다 — 그쪽은 서로 바꿔 입어도 어긋나지 않는 한 무리라
# 빌려 쓰는 것이 뜻이 있다(`본문류` 참고).
끝맺는역할 = ("요약", "CTA")


def _마무리(서랍: dict) -> list:
    """서랍에 있는 끝맺는 역할만. 둘 다 없으면 빈 목록 — 본문으로 끝난다."""
    return [역할 for 역할 in 끝맺는역할 if 서랍.get(역할)]


def main(틀_json: str, 사례_개수: str, 본보기끄기: bool = False,
         언어: str = "한국어") -> dict:
    틀 = json.loads(틀_json)
    서랍 = 틀.get("서랍")
    if not 서랍:
        raise ValueError("이 틀에는 «서랍» 이 없다 — 옛 모양이다. "
                         "make_dsl_cardnews.py 를 다시 돌려 기본.json 을 만들거나, "
                         "작업대에서 「틀로 저장」한 파일을 써라")
    try:
        n = max(1, min(6, int(str(사례_개수).strip())))
    except (ValueError, TypeError):
        n = 4
    골격 = ["훅"] + ["사례"] * n + _마무리(서랍)
    고른것 = 고르기(서랍, 골격)

    슬라이드 = []
    for i, 디자인 in enumerate(고른것, start=1):
        슬라이드.append({"index": i, "역할": 디자인["역할"],
                      "배경": 디자인["배경"],
                      "장식영역": 디자인["장식영역"],
                      "글자슬롯": 디자인["글자슬롯"]})
    새틀 = dict(틀)
    새틀["골격"] = 골격
    새틀["슬라이드"] = 슬라이드
    새틀.pop("서랍", None)   # 뒤 노드는 서랍을 안 본다 — 깊이를 얕게 유지한다

    설명 = 칸설명(슬라이드, 본보기끄기, 언어)
    쪽지 = []
    for s, 디자인 in zip(슬라이드, 고른것):
        사진자리 = sum(1 for r in s["장식영역"] if r.get("종류") in ("사진", "인물"))
        대신 = 디자인.get("_대신")
        꼬리 = f" ← «{대신}» 자리에 대신 씀" if 대신 else ""
        쪽지.append(f"{s['index']}번 장({s['역할']}) — 글자 {len(s['글자슬롯'])}덩이 · "
                  f"사진자리 {사진자리}개{꼬리}")
    return {"틀_json": json.dumps(새틀, ensure_ascii=False),
            "few_shot": 설명,
            "고른것": "\n".join(쪽지)}
