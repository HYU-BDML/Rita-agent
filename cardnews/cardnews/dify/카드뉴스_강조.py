# -*- coding: utf-8 -*-
"""**강조는 낱말에 붙는다 — 줄 번호가 아니다.**

여태 틀은 원본 글의 «몇 번째 줄이 굵었나» 를 적어 뒀다. 새 글은 줄 나뉨이
달라서 그 값이 엉뚱한 자리에 걸렸다(실물 2026-09-17: 본문 첫 줄만 뜬금없이
굵어지고, 4번 장 셋째 상자는 둘째 줄만 굵어졌다).

이제 LLM 이 글 안에 직접 표시한다. 여기는 **세는 쪽(대본 검증)과 감는 쪽
(배치)이 같이 쓰는 한 곳**이다 — 두 벌로 갈리면 「검증은 통과했는데 배치에서
자리가 어긋나는」 일이 난다.
"""
import re

굵게표 = "**"
형광펜표 = "##"

# **글자색은 여는 표시와 닫는 표시가 다르다**(사람 결정 2026-09-19).
#
# `**`·`##` 처럼 같은 글자를 양쪽에 쓰면 «짝이 안 맞는 하나» 를 곱셈인지 표시인지
# 가릴 수가 없어 `_뜬별표` 같은 뒤처리가 붙는다. 대괄호는 여는 것과 닫는 것이
# 달라 그 일이 없다 — 짝이 안 맞으면 애초에 안 걸린다(`배열[0]` 은 그대로).
글자색열기 = "[["
글자색닫기 = "]]"

# 표시 안은 **비어 있으면 안 되고**, 양 끝이 공백이면 서식이 아니다.
# 짝이 안 맞는 `*` 는 곱셈일 수 있으니 안 건드린다(`2*3`).
_찾기 = re.compile(r"(\*\*|##)(?=\S)(.+?)(?<=\S)\1"
                 r"|(\[\[)(?=\S)(.+?)(?<=\S)\]\]", re.S)

_이름 = {굵게표: "굵게", 형광펜표: "형광펜", 글자색열기: "글자색"}

# 짝이 안 맞고 남은 별표(`*기울임*`처럼 홑별표를 쓰거나, `**` 한쪽만 붙인 것).
# **한쪽만 글자에 붙은 것만 뗀다** — 양쪽이 다 글자면 그건 서식이 아니라
# 내용이다(`2*3`). 다 지우면 곱셈 기호가 조용히 사라진다.
#
# `떼기()` 안에서 정식 표시(`**…**`·`##…##`)를 먼저 걷어낸 «뒤» 남은 조각에만
# 걸어야 한다 — 먼저 걸면 정식 표시의 여는 별표까지 «떠 있다» 고 잘못 본다.
_뜬별표 = re.compile(r"(?<!\S)\*+|\*+(?!\S)")


def 떼기(글: str) -> tuple:
    """`(표시 없는 글, [{종류, 시작, 끝}, …])`.

    자리는 **뗀 글** 기준이다 — 굽는 쪽이 그 글을 그리기 때문이다.

    **짝 안 맞는 별표(`_뜬별표`)도 여기서 같이 뗀다.** 세는 쪽(대본 검증)과
    감는 쪽(배치)이 이 함수 하나로 표시를 떼므로, 여기서 떼지 않으면 검증은
    글자 수에서 뺐어도 배치가 그 별표를 그대로 카드에 찍는 일이 생긴다(검토
    지적, 2026-09-17) — 정식 표시를 먼저 걷어낸 조각마다 떼서, 자리(`자리들`)도
    최종 글 기준으로 맞게 나온다.
    """
    난것 = []
    자리들 = []
    끝까지 = 0
    for m in _찾기.finditer(글):
        # 정규식이 두 벌이라 걸린 쪽을 가린다 — `**`·`##` 는 1·2번,
        # `[[…]]` 는 3·4번 묶음이다.
        표, 속글 = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
        전 = _뜬별표.sub("", 글[끝까지:m.start()])
        난것.append(전)
        시작 = sum(len(x) for x in 난것)
        # **겹친 표시도 끝까지 뗀다**(2026-09-28 실물: 표지에 「[[공제]]가 온다」가
        # 괄호째 찍혔다 — 모델이 `**[[공제]]**` 로 겹쳐 썼다). 안쪽을 같은 셈으로 한 번
        # 더 떼고, 안쪽 자리는 바깥이 시작한 만큼 밀어 싣는다. 효과는 다 남는다.
        속, 속자리 = 떼기(속글)
        난것.append(속)
        자리들.append({"종류": _이름[표], "시작": 시작, "끝": 시작 + len(속)})
        자리들.extend({**x, "시작": x["시작"] + 시작, "끝": x["끝"] + 시작} for x in 속자리)
        끝까지 = m.end()
    난것.append(_뜬별표.sub("", 글[끝까지:]))
    return "".join(난것), 자리들


def 세기(글: str) -> dict:
    """갈래마다 몇 곳인가."""
    센것 = {"굵게": 0, "형광펜": 0, "글자색": 0}
    for 자리 in 떼기(글)[1]:
        센것[자리["종류"]] += 1
    return 센것


