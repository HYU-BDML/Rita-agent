# Dify 코드 노드 「배치 검증」   ← 「배치」 뒤에 붙는다
#
# **막는 것은 겹침과 화면 밖뿐이다.** 자수는 대본 검증에서 이미 쟀고, 세로로
# 밀려 나간 것은 세기만 한다(사람 결정 2026-09-18: 「세로줄은 안 본다니까」).
# 상자가 화면 밖으로 나가거나 글자끼리 겹치는 건 대본 검증 단계에서는 볼 수
# 없다 — 그건 글이 아니라 자리의 탈이라 여기서만 잡힌다.
#
# **겹침은 «글자 대 글자» 와 «글자 대 로고» 만 본다.** 실물(DHqCBQnRAjW)에서
# 사진·인물 네모는 서로 겹치는 게 정상이다(콜라주) — 1번 장 인물 네모
# [39,256,587,1127] 이 사진 네모 셋과 다 겹친다. 사진 위에 글자를 얹는 것도
# 정상이다 — 그게 이 템플릿의 실제 디자인이다(1번 장 헤드라인이 인물 사진
# 위에 얹혀 있다). **깨지는 건 글자끼리 겹치는 것과, 글자가 로고를 가리는
# 것뿐이다** — 둘 다 실측 데이터에는 없다(사진·인물끼리, 사진·글자는 겹치되
# 글자·글자, 글자·로고는 안 겹친다는 걸 실물로 확인함). 여기서 사진·인물끼리
# 겹침을 «막힘» 으로 잡으면 원본 그대로 배치해도 배치 검증이 못 통과한다.
#
# 입력 변수:
#     카드_json  String  ← 배치 / cards_json               (처음 배치한 것)
#     틀_json    String  ← 레시피 꺼내기 / 틀_json          (캔버스 크기)
#
# 출력 변수:
#     cards_json  String   최종 카드(다음 노드 — 굽기 — 가 이걸 읽는다). 굽기의
#                          HTTP 본문이 {{#..#}} 로 이 값을 직접 읽으므로 칸
#                          이름이 아스키여야 한다(Dify 변수 참조 정규식, 오류모음 §22)
#     막힘        String
#     점수표      String
#     ok         String   "1"/"0"

import json

줄간격기본 = 1.32
"""줄 간격 — `make_dsl_cardnews.줄간격기본`·`cardnews_compose.LINE_SPACING` 과 같은 값."""


def _겹침넓이(a: list, b: list) -> float:
    ax0, ay0, ax1, ay1 = a
    bx0, by0, bx1, by1 = b
    ox = max(0, min(ax1, bx1) - max(ax0, bx0))
    oy = max(0, min(ay1, by1) - max(ay0, by0))
    return ox * oy


def main(카드_json: str, 틀_json: str) -> dict:
    글 = 카드_json
    카드들 = json.loads(글)
    틀 = json.loads(틀_json)
    W, H = 틀["캔버스"]["w"], 틀["캔버스"]["h"]

    막힘, 권고 = [], []
    밀림 = 겹침 = 화면밖 = 로고가림 = 0
    for 카드 in 카드들:
        i = 카드["index"]
        장식영역 = 카드.get("장식영역") or []
        글자영역 = 카드.get("글자영역") or []
        전체영역 = [r["box"] for r in 장식영역] + [r["box"] for r in 글자영역]

        # **세로로 밀려 나간 것은 세기만 한다 — 안 막는다**(사람 결정 2026-09-18:
        # 「세로줄은 안 본다니까」). 자수 한계가 네모 «넓이» 를 글자 한 개 넓이로
        # 나눈 값이라(`make_dsl_cardnews._자수매기기`) 한계껏 쓴 글은 낱말 경계
        # 때문에 줄 끝이 조금씩 비어 한 줄을 더 잡아먹는다 — 여기서 막으면 규칙
        # 그대로 쓴 대본이 막힌다(실물 2026-09-18: 시험대본이 1·6번 장에서 막혔다).
        # **마지막 줄은 줄간격을 안 먹는다**(사람 지적 2026-09-19: 「보편적 규칙을
        # 고치는거지?」). 두 줄이면 «글자 높이 + 줄간격 한 번» 이지 «줄간격 두 번» 이
        # 아니다. 여태 `int(높이 / 줄높이)` 로 세어 **늘 한 줄씩 손해**를 봤다.
        #
        # 실물(주간 AI 소식 제목): 높이 194 · pt 82 · 줄간격 1.19 → 줄높이 97.6.
        # 194/97.6 = 1.99 → 1줄로 셌는데, 실제로는 82 + 97.6 = 179.6 이라 **2줄이
        # 들어간다.** 그 칸은 한 줄에 11자쯤인데 원본은 28자를 썼으니 원래 2줄짜리다.
        #
        # 그래서 원본만큼 쓸 때마다 「2줄인데 자리는 1줄이다 — 더 짧게 줄여라」가
        # 떠서 제목이 11자 근처로 눌렸다. 틀 열 벌을 돌려 보니 **글자칸 193개 중
        # 35개(18%)**가 이렇게 세어지고 있었다(제목 14 · 본문 11 · 꼬리표 10).
        for j, r in enumerate(글자영역, start=1):
            pt = float(r.get("pt") or 0)
            줄높이 = pt * float(r.get("줄간격") or 줄간격기본)
            높이 = (r["box"][3] - r["box"][1]) if r.get("box") else 0
            들어갈줄 = int((높이 - pt) / 줄높이) + 1 if (줄높이 > 0 and 높이 >= pt) else 0
            if 들어갈줄 and len(r.get("lines") or []) > 들어갈줄:
                밀림 += 1
                # **어느 칸인지 대 준다.** 여태 「{i}번 장 글이」 라고만 해서, 그 말을
                # 받은 모델이 무엇을 줄일지 몰라 **본문까지 같이 줄였다**(실물
                # 2026-09-19: 제목이 길어 걸렸는데 114자짜리 본문이 30자가 됐다).
                # `글자영역` 차례는 대본 블록 차례 그대로다(`카드뉴스_배치` 의
                # `zip(슬롯들, 블록)`).
                어디 = f"블록{j}" + (f"({r['위계']})" if r.get("위계") else "")
                # **몇 자로 줄여야 하는지 같이 댄다**(사람 지적 2026-09-24:
                # 「더 짧게가 아니라 그 범위 안으로 다시 적어라 이렇게 보내야지」).
                #
                # 여태 「몇 줄인데 자리는 몇 줄이다」만 보냈다. 모델은 얼마나
                # 줄여야 하는지 모르니 **넉넉히 깎는다** — 그러면 이번엔 자수
                # 검사가 「최소 18자인데 9자다」로 되튕긴다. 두 검사가 서로 반대
                # 방향으로 미는 꼴이라 판만 태운다.
                #
                # 하한을 같이 대는 것은 자수 검사와 같은 까닭이다 — 위아래를
                # 함께 주면 «범위 안으로» 가 뜻을 갖는다.
                범위 = ""
                if r.get("최소") and r.get("최대"):
                    범위 = (f" — 그 칸은 통틀어 {int(r['최소'])}~{int(r['최대'])}자다. "
                          f"그 범위 안으로 줄여라")
                권고.append(f"{i}번 장 {어디} 이 폭에 맞춰 감으니 "
                          f"{len(r['lines'])}줄인데 자리는 {들어갈줄}줄이다{범위}")

        # **글자가 «도형» 안에 있는 것은 세지도 않는다.** 그게 글자그릇이다 —
        # 검은 알약 안의 소제목, 초록 하트 옆의 글자. 겹치라고 있는 자리를
        # 「겹침」으로 세면 알약 디자인이 통째로 막힌다(2026-08-26).
        # 로고 겹침은 «경고» 로만 센다(2026-08-25). 글자끼리는 그대로 막는다 —
        # 그건 읽을 수가 없다.
        글자박스 = [r["box"] for r in 글자영역]
        로고박스 = [r["box"] for r in 장식영역 if r.get("종류") == "로고"]
        for a in range(len(글자박스)):
            for b in range(a + 1, len(글자박스)):
                if _겹침넓이(글자박스[a], 글자박스[b]) > 0:
                    겹침 += 1
                    막힘.append(f"{i}번 장 글자가 글자와 겹친다 — {글자박스[a]} 와 {글자박스[b]}")
        # **글자가 로고를 가리는 것은 «경고» 다 — 막지 않는다.**
        # 처음엔 막았다. 실측 게시물이 하나(DHqCBQnRAjW)뿐이었고 거기서는 한 번도
        # 안 겹쳤기 때문이다. 둘째 게시물(DG0AA6PJ8s4)을 재 보니 일곱 장 중
        # **다섯 장**에서 본문 글자 네모가 구석 로고를 문다 — 디자이너가 늘 그렇게
        # 긋는다는 뜻이지 잘못 그은 게 아니다. 표본 하나로 정한 규칙이었다.
        # 사람이 「로고 덮어도 괜찮다」고 정했다(2026-08-25).
        # 글자끼리 겹치는 것은 그대로 막는다 — 그건 읽을 수가 없다.
        for gb in 글자박스:
            for lb in 로고박스:
                if _겹침넓이(gb, lb) > 0:
                    로고가림 += 1

        for box in 전체영역:
            x0, y0, x1, y1 = box
            if x0 < 0 or y0 < 0 or x1 > W or y1 > H:
                화면밖 += 1
                막힘.append(f"{i}번 장 영역이 화면({W}x{H}) 밖이다 — {box}")

    점수 = [f"장 {len(카드들)}개",
            f"겹침 {겹침}건 · 화면밖 {화면밖}건",
            f"경고 — 아래로 밀림 {밀림}건 · 글자가 로고를 가림 {로고가림}건 (둘 다 안 막는다)",
            *권고[:12]]

    return {"cards_json": 글, "막힘": "\n".join(막힘), "점수표": "\n".join(점수),
            "ok": "0" if 막힘 else "1"}
