# -*- coding: utf-8 -*-
"""**이 틀에서 무엇이 안 그려지는가.**

오늘 하루에 같은 모양의 탈이 다섯 번 났다(2026-08-29~30).

| 잃은 것 | 어떻게 잃었나 |
|---|---|
| 배경판 | 주소가 한글이라 요청이 실패했고, 그 실패를 삼켰다 |
| 글씨체 | 굽는 쪽이 슬롯의 `font` 를 아예 안 읽었다 |
| 형광펜 | 분석이 잡지 않는다 — 여덟 틀 모두 0개 |
| 도형 | 채움색을 못 재서 굽는 쪽이 통째로 건너뛴다 |
| 역할 | 판정을 자리 아닌 번호로 붙여 「미정」이 됐다 |

**다섯 다 조용했다.** 사람이 결과를 눈으로 보고 「이거 이상한데」 할 때까지
아무도 몰랐다. 하나씩 고치는 것은 땜빵이다 — 다음에 또 다른 것이 조용히 사라진다.

그래서 잣대를 뒤집는다. **「잘 됐나」를 묻지 말고 「무엇이 안 그려지나」를 세게
한다.** 분석이 끝날 때마다 스스로 세어 틀에 적고, 목록과 만들기 답에 드러낸다.
조용히 사라지는 것이 없으면 사람이 눈으로 찾아낼 일도 없다.

여기는 **판단만** 한다 — 창고도 모델도 안 부른다. 그래야 시험이 쉽고, 굽는 쪽과
분석 쪽 어디서든 부를 수 있다.
"""

# 굽는 쪽이 그릴 줄 아는 글씨체. `cardnews_compose.한글글꼴` 과 같아야 한다.
# **두 벌인 까닭은 배포 단위가 달라서다** — 분석은 굽는 쪽 모듈을 다 안 싣는다.
그릴수있는글꼴 = ("프리텐다드", "원티드산스", "지마켓산스", "에스코어드림",
             "여기어때잘난체", "검은고딕", "배민도현", "나눔스퀘어라운드", "나눔명조")

# 배경이 이것이면 판이 없어도 그릴 수 있다.
색으로그리는배경 = ("단색", "그라데이션")


def 점검(틀: dict) -> list:
    """안 그려질 것들. `[{장, 무엇, 까닭, 고치는법}, …]` — 없으면 빈 목록.

    **못 그리는 것만 센다.** 「덜 예쁘다」는 여기서 안 본다 — 그건 사람이 볼 일이고,
    여기 섞으면 진짜 잃은 것이 묻힌다.
    """
    난것 = []
    for 장 in (틀 or {}).get("슬라이드") or []:
        i = 장.get("index")

        # ① 역할 — 대본이 이 자리에 무엇을 쓸지 못 고른다
        if (장.get("역할") or "미정") == "미정":
            난것.append({"장": i, "무엇": "역할",
                       "까닭": "이 장이 흐름에서 맡은 자리를 못 정했다",
                       "고치는법": "다시 분석하면 판정을 새로 받는다"})

        # ② 배경 — 무엇으로도 못 그리면 통째로 빈다
        #
        # **사진 배경은 판을 일부러 안 싣는다**(2026-08-31). 사람은 배경 사진에
        # 네모를 안 그으므로 그 장의 판은 «뺀 나머지» 가 아니라 원본 사진 그
        # 자체다 — 실으면 우리 카드뉴스에 남의 사진이 표지로 나온다. 대신
        # 「비었을 때 깔 색」으로 그린다. 그러니 사진 배경에서 봐야 할 것은
        # 「판이 있나」가 아니라 **「그 색을 쟀나」** 다.
        # **빌린 바닥판은 다르다**(2026-09-15). 사진 아닌 장에서 뜬 «그냥 배경»
        # 이라 남의 사진이 아니다 — 틀이 `빌린판` 표를 남긴다.
        배경 = 장.get("배경") or {}
        if 배경.get("종류") == "사진":
            if 배경.get("판") and not 배경.get("빌린판"):
                난것.append({"장": i, "무엇": "배경",
                           "까닭": "사진 배경에 판이 실렸다 — 원본 게시물 사진이 "
                                 "그대로 표지로 나온다",
                           "고치는법": "다시 분석하면 판을 안 싣는다"})
            if not 배경.get("hex"):
                난것.append({"장": i, "무엇": "배경",
                           "까닭": "사진 배경인데 대신 깔 색을 안 쟀다 — 흰 바탕이 "
                                 "되어 흰 글자가 안 읽힌다",
                           "고치는법": "다시 분석하면 원본 사진의 평균색을 잰다"})
        elif 배경.get("종류") not in 색으로그리는배경 and not 배경.get("판"):
            난것.append({"장": i, "무엇": "배경",
                       "까닭": f"배경이 «{배경.get('종류') or '모름'}» 인데 배경판이 없다",
                       "고치는법": "그 장의 배경이 사진이면 사람이 사진을 넣어야 한다"})

        # ③ 배경판 주소 — 아스키가 아니면 서버가 못 연다
        판 = 배경.get("판") or ""
        if 판 and not 판.isascii():
            난것.append({"장": i, "무엇": "배경판 주소",
                       "까닭": "주소에 아스키 아닌 글자가 있다",
                       "고치는법": "다시 분석하면 새 자리(plates/)에 올라간다"})

        # ④ 도형 — 채움색이 없으면 굽는 쪽이 건너뛴다
        for d in 장.get("장식영역") or []:
            if d.get("종류") == "도형" and not d.get("채움색"):
                난것.append({"장": i, "무엇": "도형",
                           "까닭": "채움색을 못 재서 안 그려진다",
                           "고치는법": "도형 위에 글자가 얹혀 있으면 색을 못 잰다 — "
                                   "라벨에서 도형과 글자를 따로 그어 본다"})

        # ④-2 장식 — 그림도 media_url 도 없으면 굽는 쪽이 아예 안 그린다
        #
        # 장식은 자동 누끼 갈래라 대개 PNG 가 나오지만, 찬몫이 창 밖이거나
        # 테두리따기가 실패하면 `그림`(자동)도 `media_url`(사람이 올린 것)도
        # 안 붙는다. 예전엔 회색 자리표시가 이어 그린 배경을 덮었는데
        # (2026-09-17 최종 검토 지적 ②) 이제 아예 안 그려서 더 조용해졌다.
        for d in 장.get("장식영역") or []:
            if d.get("종류") == "장식" and not d.get("그림") and not d.get("media_url"):
                난것.append({"장": i, "무엇": "장식",
                           "까닭": "그림도 media_url 도 없어 안 그려진다",
                           "고치는법": "다시 분석하면 누끼를 다시 뜬다 — 안 되면 "
                                   "사람이 사진을 넣는다"})

        # ⑤ 장 번호 — 배경판에 박혀 있으면 원본 번호가 그대로 나온다
        #
        # 사람이 그 자리를 「번호」로 라벨하면 배경판에서 구멍으로 빠지고 우리가
        # 장 차례로 다시 찍는다. 안 라벨하면 원본 03·07 이 그대로 딸려 온다 —
        # 실물 2026-08-30: 일곱 장짜리에 07 이 여섯 번째로 나왔다.
        #
        # **판이 있는 장에서만 본다.** 판이 없으면 번호가 박힐 자리도 없다.
        #
        # **배지를 장식으로 오려 놓았으면 안 따진다**(사람 결정 2026-09-17:
        # 「숫자 필요없다고! 장식이라고 했잖아, 그대로 나오게 만드는 거 성공했잖아」).
        # 장 번호 동그라미를 「장식」으로 그으면 원본 그대로 오려져 그림으로
        # 실리므로, 번호는 배경판이 아니라 그 그림에서 나온다 — 실물
        # DSW-6lrk5rs 에서 배지 여덟 개를 다 오려 놓고도 이 헛알람이 여덟 번 찍혔다.
        #
        # **「번호판」이 있으면 아예 안 따진다**(2026-09-19). 사람이 배지 하나에
        # 「장번호」 라벨을 그으면 분석이 숫자를 지운 도장을 만들어 틀 맨 위
        # `번호판` 으로 싣고, 배치가 표지 뺀 모든 장에 찍는다 — 장마다 「번호」
        # 위계 슬롯이 있을 이유가 없다. 안내문에서 「위계를 번호로 고른다」도 뺐다:
        # 그 값은 라벨 화면에 없다(2026-09-19 제거).
        오린장식 = any(d.get("종류") == "장식" and d.get("그림")
                    for d in 장.get("장식영역") or [])
        if 틀.get("번호판"):
            pass
        elif 배경.get("판") and not 오린장식 and not any(
                (x.get("위계") or "") == "번호" for x in 장.get("글자슬롯") or []):
            난것.append({"장": i, "무엇": "장 번호",
                       "까닭": "번호를 라벨 안 했다 — 배경에 박힌 원본 번호가 그대로 나온다",
                       "고치는법": "번호가 있는 배지 하나에 「장번호」 라벨을 긋고 "
                               "다시 분석한다. 번호가 없는 틀이면 무시해도 된다"})

        # ⑥ 글씨체 — 표에 없으면 프리텐다드로 바뀐다
        for x in 장.get("글자슬롯") or []:
            글꼴 = (x.get("font") or "").strip()
            if 글꼴 and 글꼴 not in 그릴수있는글꼴:
                난것.append({"장": i, "무엇": "글씨체",
                           "까닭": f"«{글꼴}» 은 굽는 쪽에 없다 — 프리텐다드로 그려진다",
                           "고치는법": "그 글꼴 파일을 render/fonts 에 넣는다"})
            # ⑦ 글자색을 우리가 뒤집었다 — 조용히 바꾸면 안 된다
            바꿈 = x.get("색바꿈") or {}
            if 바꿈:
                난것.append({"장": i, "무엇": "글자색",
                           "까닭": f"«{바꿈.get('본래')}» 이 배경 «{바꿈.get('바닥')}» "
                                 f"위에서 명암비 {바꿈.get('명암비')} 라 안 읽혀 "
                                 f"«{x.get('글자색')}» 로 뒤집었다",
                           "고치는법": "원본이 사진 배경이면 사진을 넣으면 원래 색이 "
                                   "맞다 — 작업대에서 되돌릴 수 있다"})

            # ⑧ 한글이 아닌 잣대로 글씨 크기를 쟀다(사람 지시 2026-09-22).
            #
            # **조용히 넘어가면 안 된다.** 여태는 아예 못 재고 그 칸을 통째로
            # 버렸는데, 그것도 한 줄 안 적혀서 틀 두 벌에서 제목 자리 14개가
            # 사라진 줄도 몰랐다(실물 2026-09-22). 이제 재기는 하되 얼마나
            # 믿을 만한지를 같이 말한다.
            갈래 = x.get("잰갈래")
            if 갈래:
                흔들림 = "13%" if 갈래 == "대문자" else "29%"
                난것.append({"장": i, "무엇": "글씨 크기",
                           "까닭": f"한글이 없어 «{갈래}» 높이로 쟀다 — 글꼴에 따라 "
                                 f"{흔들림}까지 어긋날 수 있다",
                           "고치는법": "작업대에서 글씨 크기를 눈으로 보고 고친다"})

            # ⑨ 기계가 스스로 찾은 칸 — 사람이 보고 지울 수 있어야 한다
            if x.get("스스로찾음"):
                난것.append({"장": i, "무엇": "스스로 찾은 칸",
                           "까닭": f"사람이 안 그은 «{x.get('위계') or '글자'}» 자리를 "
                                 f"기계가 찾아 넣었다",
                           "고치는법": "엉뚱한 자리면 라벨링에서 그 자리에 네모를 "
                                   "긋거나, 작업대에서 그 칸을 지운다"})

            # ⑩ 자수 — 말이 안 되면 대본 검증이 늘 막힌다
            최소, 최대 = x.get("최소"), x.get("최대")
            if isinstance(최대, int) and 최대 < 1:
                난것.append({"장": i, "무엇": "자수",
                           "까닭": f"이 칸에 들어갈 글자가 {최대}자다",
                           "고치는법": "네모가 너무 좁거나 글자가 너무 크다"})
            elif isinstance(최소, int) and isinstance(최대, int) and 최소 > 최대:
                난것.append({"장": i, "무엇": "자수",
                           "까닭": f"하한 {최소} 이 상한 {최대} 보다 크다",
                           "고치는법": "다시 분석하면 다시 잰다"})
    return 난것


def 한줄(점검난것: list) -> str:
    """사람이 읽을 한 줄. 없으면 빈 글자."""
    if not 점검난것:
        return ""
    셈 = {}
    for x in 점검난것:
        셈[x["무엇"]] = 셈.get(x["무엇"], 0) + 1
    속 = " · ".join(f"{k} {n}" for k, n in sorted(셈.items(), key=lambda t: -t[1]))
    return f"안 그려지는 것 {len(점검난것)}개 — {속}"
