# -*- coding: utf-8 -*-
"""말투 본보기를 **줄 단위로** 자른다 — 글자 수로 자르지 않는다.

**실물 2026-09-19.** 영어 카드를 처음 만들어 보니 카드 글이 「…coming back…」
「…Card-wor…」 로 끝났다. 낱말 한가운데서 잘린 모양이다.

원인: 틀에 싣는 본보기를 `한줄[:60] + "…"` 로 잘랐다. 모델은 그 「…」가 **우리가
자른 표시**인 줄 모른다 — 「이 사람은 문장을 …로 끝내는구나」로 읽고 따라 쓴다.
실측: 틀 DNUFIa4NIkK 의 본보기 18개 중 9개가 「…」로 끝나 있었다.

**줄 단위로 자르면 셋이 한꺼번에 풀린다.**
1. 낱말이 안 잘리니 「…」를 붙일 이유가 없다 → 모델이 따라 쓸 것도 없다
2. 남은 줄이 전부 온전하니 「이 줄은 12자였다」가 **진짜 값**이 된다
   (지금은 잘린 마지막 줄의 길이를 알려 주고 있어 그것도 틀렸다)
3. 한국어 카드에서도 같은 일이 났을 것이다 — 자르는 코드는 언어를 안 가린다
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "dify"))
sys.path.insert(0, str(ROOT / "render"))

import make_dsl_cardnews as 틀만들기  # noqa: E402
import 카드뉴스_틀고르기 as 틀고르기  # noqa: E402


def _잰것(*줄들):
    return {"line_detail": [{"text": x} for x in 줄들]}


# ── 만들 때 — 줄 단위로 자른다 ──────────────────────────────────────

def test_짧으면_그대로_다_싣는다():
    assert 틀만들기._본보기(_잰것("가나다", "라마바")) == "가나다 / 라마바"


def test_넘치면_줄을_통째로_뺀다():
    """**줄 가운데서 안 자른다.** 마지막 줄을 통째로 뺀다."""
    긴 = "가" * 40
    난것 = 틀만들기._본보기(_잰것(긴, 긴, 긴))
    assert 난것 == f"{긴} / {긴}"[:len(긴)] or 난것.count("/") <= 1
    for 조각 in 난것.split(" / "):
        assert 조각 == 긴, f"줄이 잘렸다: «{조각}»"


def test_말줄임표를_안_붙인다():
    """이게 이 고침의 핵심이다 — 모델이 따라 쓸 것을 애초에 안 만든다."""
    난것 = 틀만들기._본보기(_잰것("가" * 40, "나" * 40, "다" * 40))
    assert "…" not in 난것, f"자른 표시가 본보기 안에 남아 있다: «{난것}»"


def test_첫_줄이_이미_길면_예산까지만_두되_말줄임표는_안_붙인다():
    """**예산은 사람이 정한 것이라 안 뒤집는다** — 「길면 프롬프트만 부풀고
    모델이 내용까지 베낄 유혹이 커진다」(`test_본보기는_짧게_자른다`).

    첫 줄 하나가 이미 예산을 넘으면 어쩔 수 없이 글자에서 끊는다. 그래도
    괜찮다 — **자르는 것 자체가 아니라 「…」 표시가 문제였다.** 표시가 없으면
    모델에게는 그냥 짧은 문장이라 따라 쓸 것이 없다.
    """
    긴 = "가" * 200
    난것 = 틀만들기._본보기(_잰것(긴))
    assert len(난것) == 틀만들기.본보기길이
    assert "…" not in 난것


def test_빈_줄은_빼고_잰다():
    assert 틀만들기._본보기(_잰것("", "  ", "가나다")) == "가나다"
    assert 틀만들기._본보기(_잰것()) == ""


# ── 읽을 때 — 이미 창고에 있는 틀을 받아 준다 ────────────────────────

def _슬라이드(본보기):
    슬롯 = {"슬롯키": "훅 Bold 40", "box": [0, 0, 1000, 200], "pt": 40,
          "weight": "Bold", "align": "왼쪽", "font": "프리텐다드",
          "위계": "제목", "줄종류": "한줄", "최소": 5, "최대": 20,
          "줄수": 1, "본보기": 본보기}
    return [{"index": 1, "역할": "훅", "글자슬롯": [슬롯], "덩이수": 1}]


def test_이미_박힌_말줄임표는_떼고_보여_준다():
    """**코드만 고치면 지금 있는 틀은 안 고쳐진다.** 창고의 틀에는 이미
    「…」가 박혀 있고, 다시 만들어야 반영된다. 읽을 때 떼면 바로 듣는다.
    """
    글 = 틀고르기.칸설명(_슬라이드("요즘 트렌드 / 느좋 매거…"))
    assert "…" not in 글, 글
    assert "느좋 매거" in 글


def test_자수도_말줄임표를_빼고_센다():
    """「…」를 한 자로 세면 모델에게 알려 주는 줄 길이가 한 자씩 길어진다."""
    글 = 틀고르기.칸설명(_슬라이드("가나다 / 라마…"))
    assert "(3·2자)" in 글, 글        # 라마 = 2자, 「…」는 안 센다


def test_가운데_점_세_개는_안_건드린다():
    """사람이 일부러 쓴 말줄임표까지 지우면 안 된다 — 끝에 붙은 것만 뗀다."""
    글 = 틀고르기.칸설명(_슬라이드("음… 그게 말이죠"))
    assert "음… 그게 말이죠" in 글
