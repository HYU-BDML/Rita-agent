import make_dsl_cardnews as 틀만들기  # noqa: E402
import 카드뉴스_배치 as 배치  # noqa: E402


def _틀한칸(box, pt=40):
    슬롯 = {"box": list(box), "pt": pt, "weight": "Regular", "font": "Pretendard",
          "align": "왼쪽", "글자색": "#000000", "위계": "본문"}
    틀만들기._자수매기기(슬롯)
    return 슬롯, json.dumps(
        {"골격": ["훅"], "캔버스": {"w": 1080, "h": 1350},
         "슬라이드": [{"index": 1, "역할": "훅",
                   "배경": {"종류": "단색", "hex": "#FFFFFF"},
                   "장식영역": [], "글자슬롯": [슬롯]}]}, ensure_ascii=False)


def _감긴줄수(글, 틀):
    슬라이드 = [{"role": "훅", "blocks": [str(글)]}]
    카드 = json.loads(배치.main(슬라이드, 틀)["cards_json"])[0]
    return 카드["글자영역"][0]["lines"]


def test_상한만큼_써도_세로로_안_넘친다():
    """넓이로 잡은 상한을 꽉 채워도 네모 높이 안에서 감겨야 한다."""
    for box, pt in (([50, 50, 950, 450], 40), ([50, 50, 700, 200], 36),
                    ([50, 50, 400, 600], 30)):
        슬롯, 틀 = _틀한칸(box, pt)
        글 = " ".join(["가나다"] * max(1, 슬롯["최대"] // 4))
        줄들 = _감긴줄수(글, 틀)
        줄높이 = pt * float(슬롯.get("줄간격") or 틀만들기.줄간격기본)
        높이 = box[3] - box[1]
        assert len(줄들) * 줄높이 <= 높이 + 줄높이, (
            f"{box} pt{pt}: 상한 {슬롯['최대']}자를 쓰니 {len(줄들)}줄 "
            f"({len(줄들) * 줄높이:.0f}px) 인데 네모는 {높이}px 다")


def test_세로로_키우면_상한이_는다():
    """**세로줄은 안 본다** — 네모가 세로로 커지면 그만큼 더 쓸 수 있다."""
    작은것, _ = _틀한칸([50, 50, 700, 200])
    큰것, _ = _틀한칸([50, 50, 700, 600])
    assert 큰것["최대"] > 작은것["최대"] * 2.5, (작은것["최대"], 큰것["최대"])


def test_줄수_줄종류를_안_싣는다():
    """줄이 몇 줄이 될지는 배치가 폭을 재서 정한다 — 틀이 미리 못 박지 않는다."""
    슬롯, _ = _틀한칸([50, 50, 950, 450])
    assert "줄수" not in 슬롯 and "줄종류" not in 슬롯, 슬롯


