def test_서로_얼마나_같은_네모인지를_잰다():
    """한쪽으로만 재면 «큰 도형 안의 작은 글자» 도 1.0 이 나와 잘못 걸린다.

    글자가 도형에 든 것과 «도형을 따라 그은 것» 은 다르다. 앞엣것은 그냥 겹친
    것이고 뒤엣것은 같은 네모다 — 그 둘을 가르는 자가 IoU 다.
    """
    작은것 = 틀만들기._겹친몫([10, 10, 20, 20], [0, 0, 100, 100])
    assert 작은것 < 0.05, "한 귀퉁이 글자는 «같은 네모» 가 아니다"
    똑같은것 = 틀만들기._겹친몫([0, 0, 100, 100], [0, 0, 100, 100])
    assert 똑같은것 == 1.0
    assert 틀만들기._겹친몫(None, [0, 0, 10, 10]) == 0.0
    assert 틀만들기._겹친몫([0, 0, 0, 0], [0, 0, 10, 10]) == 0.0


