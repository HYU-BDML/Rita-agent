# 있든 무시했다. 실물 DYzN0Uzgaq6(AI소식 미니)의 서랍에는 훅·사례·문제·데이터·
# 비교·정의·CTA 일곱이 있고 **「요약」이 없다.** 그래서 요약 자리가 대신표를 타고
# CTA 를 빌려 써, 같은 CTA 디자인이 두 장 나왔다.

def _서랍만(역할들):
    """그 역할들만 든 서랍. 디자인 속은 이 시험이 안 본다."""
    return {역할: [{"역할": 역할, "배경": {"종류": "단색", "hex": "#FFF"},
                  "장식영역": [], "글자슬롯": []}] for 역할 in 역할들}


def test_서랍에_요약이_없으면_골격에도_안_넣는다():
    """요약을 넣으면 CTA 를 빌려 써 같은 디자인이 두 장 나온다."""
    틀 = json.dumps({"서랍": _서랍만(["훅", "사례", "CTA"])}, ensure_ascii=False)
    난것 = 틀고르기.main(틀, "3")
    골격 = json.loads(난것["틀_json"])["골격"]
    assert "요약" not in 골격, 골격
    assert 골격.count("CTA") == 1, 골격


def test_서랍에_요약이_있으면_넣는다():
    틀 = json.dumps({"서랍": _서랍만(["훅", "사례", "요약", "CTA"])}, ensure_ascii=False)
    골격 = json.loads(틀고르기.main(틀, "3")["틀_json"])["골격"]
    assert 골격 == ["훅", "사례", "사례", "사례", "요약", "CTA"], 골격


def test_서랍에_CTA가_없으면_요약이_끝을_맡는다():
    틀 = json.dumps({"서랍": _서랍만(["훅", "사례", "요약"])}, ensure_ascii=False)
    골격 = json.loads(틀고르기.main(틀, "2")["틀_json"])["골격"]
    assert "CTA" not in 골격 and 골격[-1] == "요약", 골격


# ── 자수는 넓이 하나로 본다(사람 결정 2026-09-18) ────────────────────
#
# 「내가 글자 라벨링을 해, 그럼 사각형이 나올 거 아니야? 그리고 글자 하나 크기를
# 재, 사각형을 재, 그리고 넓이를 각각 나누면 되잖아 — 그럼 총 최대 몇 자까지
# 들어갈 수 있는지 나오잖아」·「세로줄은 안 본다니까」.
#
# 여태는 «한 줄에 몇 자»(가로폭 ÷ 글자폭)를 상한으로 쓰고, 줄 수를 원본에 묶어
# 따로 막았다. 그래서 네모를 크게 그어도 원본이 3줄이면 3줄에 묶였다
# (`줄수 = min(잰 줄수, 들어갈 줄수)` — 줄이기만 하고 늘리지 않았다).

def _칸(box, pt=40, font="Pretendard", weight="Regular"):
    return {"box": list(box), "pt": pt, "font": font, "weight": weight,
            "위계": "본문", "align": "왼쪽"}


def test_자수_한계는_네모_넓이로_잰다():
    """가로만이 아니라 세로까지 — 넓이 ÷ 글자 한 개 넓이."""
    넓은칸 = _칸((0, 0, 900, 400))
    좁은칸 = _칸((0, 0, 900, 100))
    틀만들기._자수매기기(넓은칸)
    틀만들기._자수매기기(좁은칸)
    assert 넓은칸["최대"] > 좁은칸["최대"] * 3, (넓은칸["최대"], 좁은칸["최대"])


def test_세로로_키우면_자수가_는다():
    """**세로줄은 안 본다** — 네모가 세로로 커지면 그만큼 더 쓸 수 있다."""
    작은칸 = _칸((0, 0, 600, 200))
    큰칸 = _칸((0, 0, 600, 600))
    틀만들기._자수매기기(작은칸)
    틀만들기._자수매기기(큰칸)
    assert 큰칸["최대"] >= 작은칸["최대"] * 2.5, (작은칸["최대"], 큰칸["최대"])


def test_하한은_총량의_65퍼센트다():
    칸 = _칸((0, 0, 900, 400))
    틀만들기._자수매기기(칸)
    assert 칸["최소"] == round(칸["최대"] * 0.65), (칸["최소"], 칸["최대"])


def test_줄수와_줄종류를_안_싣는다():
    """줄이 몇 줄이 될지는 배치가 폭을 재서 정한다 — 틀이 미리 못 박지 않는다."""
    칸 = _칸((0, 0, 900, 400))
    칸["줄수"] = 3
    칸["줄종류"] = "한줄"
    틀만들기._자수매기기(칸)
    assert "줄수" not in 칸 and "줄종류" not in 칸, 칸
