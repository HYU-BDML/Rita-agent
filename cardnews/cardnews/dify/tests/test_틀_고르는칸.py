def _글자칸(줄굵기=None, 줄색=None, 줄수=3, 줄pt=None):
    """`줄pt`(선택) — 줄마다의 크기. **출처 판정은 이제 `ruler.text._출처줄인가`
    와 같은 잣대(크기·오른쪽 끝)를 본다**(검토 지적 ④) — `line_detail` 에
    `pt`·`box`(오른쪽 끝 500 으로 다 맞춰 둔다)가 있어야 그 잣대가 잡힌다.
    """
    줄pt = 줄pt or [40] * 줄수
    line_detail = [{"box": [0, i * 50, 500, i * 50 + 40], "pt": 줄pt[i]}
                   for i in range(줄수)]
    if 줄색:
        for l, c in zip(line_detail, 줄색):
            l["color"] = c
    t = {"pt": 40, "weight": "Regular", "align": "왼쪽", "lines": ["가"] * 줄수,
         "line_detail": line_detail}
    if 줄굵기:
        t["줄굵기"] = 줄굵기
    if 줄색:
        t["줄색"] = 줄색
    return t


