def test_네모를_좁히면_자수도_줄어든다():
    """자수 상한은 「이 네모에 몇 자 들어가나」다. 네모를 좁혀 놓고 상한을 그대로
    두면 그 말이 거짓이 된다 — 실측(DG0AA6PJ8s4): 626px 네모에 17자가 들어가는데
    상한이 28자였다. LLM 이 그걸 채우면 배치에서 넘친다.
    """
    def _칸():
        return {"box": [67, 76, 1042, 229], "pt": 40, "weight": "Bold",
                "font": "프리텐다드", "align": "왼쪽", "_잉크": (236, 133, 510, 170)}

    # 좁히기 «전» 의 상한을 같은 셈으로 먼저 낸다 — 옛 시험은 28 이라는 숫자를
    # 박아 뒀는데, 그건 가로폭만 보던 시절 값이다(2026-09-18 넓이로 바뀜).
    안좁힌것 = _칸()
    틀만들기._자수매기기(안좁힌것)
    슬롯들 = [_칸()]
    틀만들기._도형안글자_가운데(슬롯들, [_도형([70, 88, 1022, 209])])
    슬 = 슬롯들[0]
    assert 슬["최대"] < 안좁힌것["최대"], (슬["최대"], 안좁힌것["최대"])
    assert 슬["최소"] == max(1, round(슬["최대"] * 틀만들기.바닥비)), "하한은 그 65%"


