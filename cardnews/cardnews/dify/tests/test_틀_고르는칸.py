def _시작칸(dsl):
    시작 = next(n for n in dsl["workflow"]["graph"]["nodes"]
              if n["data"].get("type") == "start")
    return {v["variable"]: v for v in 시작["data"]["variables"]}


def test_고르는_칸에_목록이_박힌다():
    칸 = _시작칸(틀만들기.만들기(["키키 밈체", "아기 파스텔"]))["template_name"]
    assert 칸["type"] == "select"
    assert 칸["options"] == [틀만들기.기본이름, "키키 밈체", "아기 파스텔"]
    assert 칸["default"] == 틀만들기.기본이름


