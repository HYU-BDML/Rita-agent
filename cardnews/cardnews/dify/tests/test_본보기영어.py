# -*- coding: utf-8 -*-
"""한 틀에 두 목소리 — 고른 언어에 맞는 말투 본보기를 꺼낸다.

사람 결정 2026-09-18: 틀 DNUFIa4NIkK(「파스텔 둥근네모」)로 영어 카드를 보고
「틀도 영어로 바꿔야겠다」. 고른 방식은 **한 틀에 두 목소리** — 같은 틀 안에
한국어 본보기와 영어 본보기를 나란히 두고 언어에 맞는 쪽을 꺼낸다.

**왜 이게 필요한가.** 본보기는 장식이 아니라 대본 지시문 «안» 으로 들어간다.
영어로 쓰라는 지시는 맨 앞 세 줄인데 한국어 예문은 열네 덩이다(실측:
DNUFIa4NIkK 의 본보기 18개 중 14개가 한글). 분량 싸움에서 진다.

**글자 수까지 같이 간다.** 「원본은 줄마다 12·15·9자로 끊었다」를 알려 주는데
그 숫자가 한글 기준이라, 영어로 그 자수를 맞추면 줄이 절반 길이가 된다.
영어 본보기를 쓰면 그 숫자도 영어 것으로 따라간다.

**한국어 카드는 하나도 안 바뀐다** — 그게 이 방식을 고른 까닭이다.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "dify"))
sys.path.insert(0, str(ROOT / "render"))

import 카드뉴스_틀고르기 as 틀고르기  # noqa: E402


def _슬라이드(본보기, 본보기영어=None):
    슬롯 = {"슬롯키": "훅 Bold 40", "box": [0, 0, 1000, 200], "pt": 40,
          "weight": "Bold", "align": "왼쪽", "font": "프리텐다드",
          "위계": "제목", "줄종류": "한줄", "최소": 5, "최대": 20,
          "줄수": 1, "본보기": 본보기}
    if 본보기영어 is not None:
        슬롯["본보기영어"] = 본보기영어
    return [{"index": 1, "역할": "훅", "글자슬롯": [슬롯], "덩이수": 1}]


def test_영어를_고르면_영어_본보기를_보여_준다():
    글 = 틀고르기.칸설명(_슬라이드("요즘 트렌드", "What's trending now"),
                   언어="영어")
    assert "What's trending now" in 글
    assert "요즘 트렌드" not in 글, "한국어 본보기가 아직 섞여 있다"


def test_한국어는_지금까지와_똑같다():
    """**이게 이 방식을 고른 까닭이다.** 영어 칸이 붙어도 한국어는 안 바뀐다."""
    있음 = 틀고르기.칸설명(_슬라이드("요즘 트렌드", "What's trending now"))
    없음 = 틀고르기.칸설명(_슬라이드("요즘 트렌드"))
    assert 있음 == 없음
    assert "요즘 트렌드" in 있음 and "What's trending now" not in 있음


def test_영어_본보기가_없으면_한국어로_물러선다():
    """**틀마다 영어를 채우는 데는 시간이 걸린다.** 아직 안 채운 틀로도 영어
    카드가 나와야 한다 — 그때는 한국어 본보기를 보여 주되, 대본 지시문의
    「본보기는 한국어지만 말투만 배워라」 한 줄이 받쳐 준다(`프롬프트._영어로`).
    """
    글 = 틀고르기.칸설명(_슬라이드("요즘 트렌드"), 언어="영어")
    assert "요즘 트렌드" in 글


def test_빈_영어_본보기는_없는_것으로_본다():
    """빈 글자가 들어가 있으면 «영어 본보기가 있다»고 속으면 안 된다."""
    글 = 틀고르기.칸설명(_슬라이드("요즘 트렌드", "   "), 언어="영어")
    assert "요즘 트렌드" in 글


def test_줄마다_자수도_영어_것으로_따라간다():
    """한글 자수를 영어에 들이대면 줄이 절반 길이가 된다."""
    글 = 틀고르기.칸설명(
        _슬라이드("가나다 / 라마바사", "Hello there / Friends"), 언어="영어")
    assert "(11·7자)" in 글, 글      # Hello there=11, Friends=7
    assert "(3·4자)" not in 글       # 한글 것이 새면 안 된다


def _틀(본보기, 본보기영어=None):
    """서랍에 네 역할이 한 벌씩 든 최소 틀."""
    def 옷(역할):
        슬롯 = _슬라이드(본보기, 본보기영어)[0]["글자슬롯"][0]
        return {"역할": 역할, "배경": {"종류": "단색", "hex": "#FFFFFF"},
                "장식영역": [], "글자슬롯": [dict(슬롯)], "덩이수": 1}
    역할들 = ("훅", "사례", "요약", "CTA")
    return json.dumps({"골격": list(역할들), "캔버스": {"w": 1080, "h": 1350},
                       "서랍": {r: [옷(r)] for r in 역할들}}, ensure_ascii=False)


def test_언어가_틀고르기_전체를_지나_칸설명까지_닿는다():
    """**마디가 하나라도 끊기면 조용히 한국어가 나온다.** 카드는 나오고
    한국어일 뿐이라 눈으로 못 잡는다 — 그래서 사슬 끝에서 본다."""
    난것 = 틀고르기.main(_틀("요즘 트렌드", "What's trending now"), "1", 언어="영어")
    assert "What's trending now" in 난것["few_shot"]
    assert "요즘 트렌드" not in 난것["few_shot"]


def test_틀고르기도_아무_말_없으면_한국어다():
    난것 = 틀고르기.main(_틀("요즘 트렌드", "What's trending now"), "1")
    assert "요즘 트렌드" in 난것["few_shot"]
    assert "What's trending now" not in 난것["few_shot"]


def test_본보기끄기는_언어와_상관없이_먼저다():
    """남의 말투일 때는 아예 안 보여 준다 — 그때는 목소리가 둘이 된다."""
    글 = 틀고르기.칸설명(_슬라이드("요즘 트렌드", "What's trending now"),
                   본보기끄기=True, 언어="영어")
    assert "What's trending now" not in 글 and "요즘 트렌드" not in 글
