# -*- coding: utf-8 -*-
"""**고른 언어와 다른 말로 된 본보기는 안 쓴다.**

사람 지시 2026-09-22: 「한국어면 한글로 하는걸로 하고 영어면 영어로 하는걸로해」.

여태는 본보기가 늘 한국어라고 봐도 됐다 — 영문 자리는 글자 크기를 못 재서
슬롯째로 버려졌기 때문이다(`analyze/layout.ink_height`). 2026-09-22 에 영문도
재게 고치자 「Switzerland」·「Weekly AI」 같은 본보기가 틀에 들어왔고, **한국어
카드를 만드는데 그 자리 제목이 영어로 나왔다**(실물).

본보기는 «결» 을 주는 것이지 언어를 정하는 것이 아니다.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import 카드뉴스_틀고르기 as T  # noqa: E402


def test_한국어판은_영문_본보기를_안_쓴다():
    """실물에서 카드 제목이 「Switzerland」로 나온 그 자리다."""
    assert T._본보기고르기({"본보기": "Switzerland"}, "한국어") == ""
    assert T._본보기고르기({"본보기": "AI NEWS | Claude"}, "한국어") == ""


def test_한국어판은_한글_본보기를_그대로_쓴다():
    본 = "알프스 하이킹, 빙하 트레킹"
    assert T._본보기고르기({"본보기": 본}, "한국어") == 본


def test_한글이_한_글자라도_있으면_쓴다():
    """「AI 소식」처럼 섞인 말은 우리 말이다 — 통째로 버리면 결을 잃는다."""
    assert T._본보기고르기({"본보기": "7월 5주차 AI 소식"}, "한국어") == "7월 5주차 AI 소식"


def test_영어판은_영문_본보기를_쓴다():
    """영어로 만들 때는 그 자체가 맞는 본보기다."""
    assert T._본보기고르기({"본보기": "Switzerland"}, "영어") == "Switzerland"


def test_영어판은_본보기영어를_먼저_쓴다():
    난것 = T._본보기고르기({"본보기": "알프스", "본보기영어": "Alps hiking"}, "영어")
    assert 난것 == "Alps hiking"


def test_영어판은_영어칸이_없으면_한글로_물러선다():
    """아직 영어를 안 채운 틀로도 영어 카드가 나와야 한다 — 지시문이 받쳐 준다."""
    assert T._본보기고르기({"본보기": "알프스 하이킹"}, "영어") == "알프스 하이킹"


def test_빈_본보기는_빈_글자다():
    for 언어 in ("한국어", "영어"):
        assert T._본보기고르기({}, 언어) == ""
        assert T._본보기고르기({"본보기": ""}, 언어) == ""


def test_자른_표시는_여전히_뗀다():
    """「…」 는 말이 아니라 우리가 자른 표시다 — 언어를 가리는 것과 별개다."""
    assert T._본보기고르기({"본보기": "알프스 하이킹…"}, "한국어") == "알프스 하이킹"
