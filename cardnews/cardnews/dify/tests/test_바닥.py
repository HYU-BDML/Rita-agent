# -*- coding: utf-8 -*-
"""**바닥은 게시물에 하나고, «그냥 배경» 뿐이다**(사람 결정 2026-09-15).

여태는 장마다 따로 배경을 정했다. 사진 배경 장은 남의 사진을 못 쓰니 그 사진의
평균색을 칠했고, 그래서 흰 종이 위에 만든 카드뉴스의 사진 장이 **갈색 판**으로
나왔다(실물 DSW-6lrk5rs 6번 장). 2번 장에서 흰 종이를 보고도 6번 장에서 까먹은
것이다.

이제 사진 아닌 장에서 찾은 배경을 «바닥» 으로 삼아 **모든 장에 깐다.** 바닥은
종이 질감(바닥판, `merge_labeled.바닥판`)이나 그라데이션 뿐이다 — 어느 장의
배경판을 통째로 빌리면 그 장의 선·동그라미가 딸려 온다. 사진 장은 그 바닥 위에
«장 전체 사진 자리» 가 얹힌다. 전부 사진이면 볼 데가 없으니 흰색.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import make_dsl_cardnews as m  # noqa: E402


def _장(kind, hex=None, 판=None, 네모수=0, **더):
    배경 = {"kind": kind, "hex": hex, **더}
    if 판:
        배경["판"] = 판
    if kind == "사진":
        배경["빈자리색"] = hex
    return {"background": 배경, "regions": [{} for _ in range(네모수)]}


def test_사진_아닌_장의_색이_바닥색이다():
    장들 = [_장("사진", "#534A43", 판="X/01.png"),
          _장("단색", "#FEFEFE", 판="X/02.png", 네모수=3)]
    assert m._바닥(장들)["hex"] == "#FEFEFE"


def test_전부_사진이면_흰색이고_판은_없다():
    장들 = [_장("사진", "#534A43", 판="X/01.png"),
          _장("사진", "#413D39", 판="X/02.png")]
    assert m._바닥(장들) == {"hex": "#FFFFFF", "판": None}


def test_장의_배경판은_절대_안_빌린다():
    """배경판에는 그 장의 선·동그라미가 들어 있다 — 바닥이 아니다."""
    장들 = [_장("단색", "#FEFEFE", 판="X/02.png", 네모수=2)]
    assert m._바닥(장들)["판"] is None


def test_바닥판이_있으면_그것이_판이다():
    장들 = [_장("단색", "#FEFEFE", 판="X/02.png", 네모수=2)]
    바닥판 = {"hex": "#FEFEFE", "판": "X/바닥.png"}
    assert m._바닥(장들, 바닥판) == {"hex": "#FEFEFE", "판": "X/바닥.png"}


def test_바닥판은_색이_달라도_쓴다():
    """바닥판은 GPT 가 만든 «게시물의 종이» 다(2026-09-19). 색 이름이 어긋나도
    판이 진짜다 — 색은 판이 안 깔릴 때의 대비 재기용이다."""
    장들 = [_장("단색", "#FEFEFE"), _장("단색", "#FEFEFE"), _장("단색", "#000000")]
    바닥판 = {"hex": "#000000", "판": "X/바닥.png"}
    assert m._바닥(장들, 바닥판) == {"hex": "#FEFEFE", "판": "X/바닥.png"}


def test_그라데이션_게시물도_바닥판이_있으면_판을_쓴다():
    띠 = [{"hex": "#000000", "at": 0.0}, {"hex": "#FFFFFF", "at": 1.0}]
    장들 = [_장("그라데이션", dir="세로", stops=띠), _장("그라데이션", dir="세로", stops=띠)]
    난것 = m._바닥(장들, {"hex": None, "판": "X/바닥.png"})
    assert 난것["판"] == "X/바닥.png" and 난것["그라데이션"]


def test_가장_많은_색이_바닥색이다():
    장들 = [_장("단색", "#000000"), _장("단색", "#FEFEFE"), _장("단색", "#FEFEFE")]
    assert m._바닥(장들)["hex"] == "#FEFEFE"


def test_그라데이션이_다수면_그라데이션이_바닥이다():
    띠 = [{"hex": "#000000", "at": 0.0}, {"hex": "#FFFFFF", "at": 1.0}]
    장들 = [_장("그라데이션", dir="세로", stops=띠),
          _장("그라데이션", dir="세로", stops=띠),
          _장("사진", "#534A43")]
    assert m._바닥(장들) == {"hex": None, "판": None,
                          "그라데이션": {"방향": "세로", "띠": "#000000@0% → #FFFFFF@100%"}}


def test_사진_장은_바닥의_색과_판을_받는다():
    배경 = {"kind": "사진", "hex": "#534A43", "판": "X/06.png", "빈자리색": "#534A43"}
    난것 = m._배경출력(배경, {"hex": "#FEFEFE", "판": "X/바닥.png"})
    assert 난것["종류"] == "사진"
    assert 난것["hex"] == "#FEFEFE"
    assert 난것["판"].endswith("/X/바닥.png")
    assert 난것["빌린판"] is True


def test_사진_장은_제_판을_안_싣는다():
    """그 장의 판은 남의 사진 그 자체다."""
    배경 = {"kind": "사진", "hex": "#534A43", "판": "X/06.png", "빈자리색": "#534A43"}
    난것 = m._배경출력(배경, {"hex": "#FFFFFF", "판": None})
    assert "판" not in 난것
    assert 난것["hex"] == "#FFFFFF"


def test_사진_장은_그라데이션_바닥을_받는다():
    배경 = {"kind": "사진", "hex": "#534A43", "빈자리색": "#534A43"}
    바닥 = {"hex": None, "판": None, "그라데이션": {"방향": "세로", "띠": "#000000@0% → #FFFFFF@100%"}}
    assert m._배경출력(배경, 바닥) == {"종류": "그라데이션", "방향": "세로",
                                 "띠": "#000000@0% → #FFFFFF@100%"}


def test_단색_장에도_바닥판을_깐다():
    """장마다 뜨던 배경판은 없다(사람 결정 2026-09-19 「라벨한 것만 나온다」).
    사진 아닌 모든 장에 게시물 바닥판 하나를 깐다 — 사진 장과 같은 «빌린판» 이다."""
    배경 = {"kind": "단색", "hex": "#FEFEFE"}
    난것 = m._배경출력(배경, {"hex": "#FEFEFE", "판": "X/바닥.png"})
    assert 난것 == {"종류": "단색", "hex": "#FEFEFE",
                  "판": f"{m.창고}/{m.판칸}/X/바닥.png", "빌린판": True}


def test_옛_계량표의_제_판은_무시한다():
    배경 = {"kind": "단색", "hex": "#FEFEFE", "판": "X/02.png"}
    난것 = m._배경출력(배경, {"hex": "#FEFEFE", "판": None})
    assert "판" not in 난것


def test_그라데이션_장에도_바닥판을_깐다():
    배경 = {"kind": "그라데이션", "dir": "세로",
          "stops": [{"hex": "#000000", "at": 0.0}, {"hex": "#FFFFFF", "at": 1.0}]}
    난것 = m._배경출력(배경, {"hex": None, "판": "X/바닥.png", "그라데이션": {"방향": "세로", "띠": "x"}})
    assert 난것["종류"] == "그라데이션" and 난것["판"].endswith("/X/바닥.png") and 난것["빌린판"] is True


def test_사진_장은_그라데이션보다_바닥판을_먼저_받는다():
    배경 = {"kind": "사진", "hex": "#534A43", "빈자리색": "#534A43"}
    바닥 = {"hex": None, "판": "X/바닥.png", "그라데이션": {"방향": "세로", "띠": "x"}}
    난것 = m._배경출력(배경, 바닥)
    assert 난것["종류"] == "사진" and 난것["판"].endswith("/X/바닥.png") and 난것["빌린판"] is True


def test_빌린_판_위에서는_대비를_잰다():
    """제 판이면 글자 밑에 뭐가 있는지 몰라 안 재지만, 빌린 판은 «종이» 라 안다.
    안 재면 흰 종이 위에 흰 글자가 그대로 남는다."""
    슬롯 = {"box": [0, 0, 10, 10], "글자색": "#FFFFFF"}
    배경출력 = {"종류": "사진", "hex": "#FEFEFE", "판": "u", "빌린판": True}
    assert m._밑바닥색(슬롯, [], 배경출력) == "#FEFEFE"
