# -*- coding: utf-8 -*-
"""**안 읽히는 글자색은 읽히는 쪽으로 뒤집는다.**

실물 2026-09-01, DSW-6lrk5rs 7번 장: 제목 `#42361B` 가 배경 `#534A43` 위에서
명암비 **1.37** 이라 아무것도 안 보였다. 원본에서는 그 자리가 사진의 «밝은 부분»
이라 어두운 글자가 맞았는데, 사진을 평균색 하나로 바꾸니 밝은 부분이 사라졌다.

**잰 값을 함부로 버리는 것이 아니다.** 명암비 2.5 아래는 「그렇게 디자인했다」가
아니라 「우리가 그 자리를 못 되살렸다」는 뜻이다 — 같은 틀의 멀쩡한 칸들은
7.4~20.6 이고, 흐린 회색 부제조차 3 을 넘는다.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import make_dsl_cardnews as m  # noqa: E402


def _칸(글자색, box=(100, 100, 900, 200), **더):
    return {"box": list(box), "글자색": 글자색, **더}


def _사진배경(hex글="#534A43"):
    return {"종류": "사진", "hex": hex글}


# ── 명암비 셈 ──────────────────────────────────────────────────────

def test_흑백이_21이고_같은_색이_1이다():
    assert round(m._명암비("#000000", "#FFFFFF"), 1) == 21.0
    assert round(m._명암비("#534A43", "#534A43"), 2) == 1.0


def test_실물_값을_그대로_잰다():
    """이 시험이 지키는 것은 «문턱이 실물을 가른다» 는 사실이다."""
    assert round(m._명암비("#42361B", "#534A43"), 2) == 1.37   # 깨진 것
    assert round(m._명암비("#FEFEFE", "#615245"), 2) == 7.43   # 성한 것
    assert round(m._명암비("#010203", "#D0EBFF"), 2) == 16.82  # 도형 위 글자


# ── 뒤집기 ────────────────────────────────────────────────────────

def test_안_보이는_글자를_흰색으로_뒤집는다():
    칸 = _칸("#42361B")
    바뀐것 = m._대비고치기([칸], [], _사진배경())
    assert 칸["글자색"] == "#FFFFFF"
    assert len(바뀐것) == 1


def test_밝은_바탕이면_검정으로_뒤집는다():
    칸 = _칸("#F4F2EE")
    m._대비고치기([칸], [], {"종류": "단색", "hex": "#FFFFFF"})
    assert 칸["글자색"] == "#000000"


def test_성한_색은_안_건드린다():
    """멀쩡한 것을 건드리면 원본과 달라진다 — 그게 더 나쁘다."""
    for 글, 바 in (("#FEFEFE", "#615245"), ("#020202", "#FEFEFE")):
        칸 = _칸(글)
        assert m._대비고치기([칸], [], {"종류": "단색", "hex": 바}) == []
        assert 칸["글자색"] == 글


def test_바꾼_것을_남긴다():
    """조용히 바꾸면 「왜 원본이랑 색이 다르지」를 아무도 못 푼다."""
    칸 = _칸("#42361B")
    m._대비고치기([칸], [], _사진배경())
    assert 칸["색바꿈"] == {"본래": "#42361B", "바닥": "#534A43", "명암비": 1.37}


def test_줄색도_같이_뒤집는다():
    """슬롯 색만 바꾸면 줄들이 옛 색으로 그려져 도로 안 보인다."""
    칸 = _칸("#42361B", 줄색=["#42361B", "#FFFFFF"])
    m._대비고치기([칸], [], _사진배경())
    assert 칸["줄색"] == ["#FFFFFF", "#FFFFFF"]


def test_출처줄_색도_대비를_본다():
    """검토 지적 ③ — `출처줄.색` 은 `_뜻으로` 가 원본 줄에서 직접 재 온 값이라
    슬롯 `글자색` 과 다른 값일 수 있다. 대비 고치기를 안 거치면 바닥과 안 맞을
    때 그대로 묻힌다."""
    칸 = _칸("#000000", 출처줄={"색": "#42361B", "align": "오른쪽"})
    m._대비고치기([칸], [], _사진배경())
    assert 칸["출처줄"]["색"] == "#FFFFFF"


def test_출처줄_색이_성하면_안_건드린다():
    칸 = _칸("#000000", 출처줄={"색": "#FEFEFE", "align": "오른쪽"})
    m._대비고치기([칸], [], {"종류": "단색", "hex": "#615245"})
    assert 칸["출처줄"]["색"] == "#FEFEFE"


def test_출처줄이_없으면_안_건드린다():
    칸 = _칸("#42361B")
    assert m._대비고치기([칸], [], _사진배경()) == [칸]
    assert "출처줄" not in 칸


# ── 밑바닥이 무엇인가 ─────────────────────────────────────────────

def test_도형_안_글자는_도형_채움색으로_잰다():
    """글자 밑에 실제로 깔린 것은 배경이 아니라 그 도형이다."""
    도형 = {"종류": "도형", "box": [50, 50, 1000, 300], "채움색": "#101010"}
    칸 = _칸("#151515", (100, 100, 900, 200))
    m._대비고치기([칸], [도형], {"종류": "단색", "hex": "#FFFFFF"})
    assert 칸["글자색"] == "#FFFFFF", "배경(흰색)으로 쟀다 — 도형을 봐야 한다"


def test_그라데이션은_안_본다():
    """자리마다 색이 달라 한 값으로 못 말한다 — 모르는 것은 안 건드린다."""
    칸 = _칸("#42361B")
    assert m._대비고치기([칸], [], {"종류": "그라데이션", "띠": "#000@0% → #FFF@100%"}) == []
    assert 칸["글자색"] == "#42361B"


def test_색을_못_쟀으면_안_본다():
    칸 = _칸("#42361B")
    assert m._대비고치기([칸], [], {"종류": "사진", "hex": None}) == []


def test_도형이_칸을_다_안_품으면_배경으로_잰다():
    """반만 걸친 도형은 밑바닥이 아니다."""
    도형 = {"종류": "도형", "box": [50, 50, 500, 300], "채움색": "#101010"}
    칸 = _칸("#42361B", (100, 100, 900, 200))
    m._대비고치기([칸], [도형], _사진배경())
    assert 칸["색바꿈"]["바닥"] == "#534A43"


def test_배경판이_있으면_배경색을_안_본다():
    """판은 색 이름으로 못 담는 것을 담은 그림이다 — 글자 밑에 무엇이 있는지
    여기서는 알 수 없다. 실물 DSW-6lrk5rs 2번 장: 장 번호가 판에 든 «파란
    동그라미» 위 흰 글자였는데, 바탕색(흰색)으로 재서 검정으로 뒤집혔다."""
    칸 = _칸("#FEFEFE")
    배경 = {"종류": "단색", "hex": "#FEFEFE", "판": "https://x/a.png"}
    assert m._대비고치기([칸], [], 배경) == []
    assert 칸["글자색"] == "#FEFEFE"


def test_판이_있어도_도형_위_글자는_본다():
    """도형은 판 «위» 에 우리가 그린다 — 밑바닥을 확실히 안다."""
    도형 = {"종류": "도형", "box": [50, 50, 1000, 300], "채움색": "#101010"}
    칸 = _칸("#151515", (100, 100, 900, 200))
    배경 = {"종류": "단색", "hex": "#FEFEFE", "판": "https://x/a.png"}
    m._대비고치기([칸], [도형], 배경)
    assert 칸["글자색"] == "#FFFFFF"
