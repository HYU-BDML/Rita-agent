# ── 강조 — 아무것도 안 막는다(사람 결정 2026-09-18) ────────────────
#
# 「그냥 알아서 강조할 부분에 강조하고, 형광펜 쓰고 싶은 부분에 형광펜 쓰고」.
#
# 여기까지 세 판이었다. ① 위계별 개수를 못 박았다 — 위계마다 값을 하나로
# 모으느라 「대부분 0」이 이겨 실측 틀 전부에서 형광펜이 0곳으로 뭉개졌다.
# ② 개수를 빼고 «같은 위계 칸끼리 쓰거나 안 쓰거나가 같은지» 를 봤다 — 설계서에는
# 「쏠림을 막는다」고 써 놓고 코드는 `any and not all`, 곧 «전부 아니면 전무» 였다.
# ③ 그 규칙으로 실물 다섯 벌을 만들어 보니 **한 벌도 안 나왔다**(2026-09-18 실측:
# 막은 것 19건 중 강조가 10건 — 22칸 중 6칸에 형광펜을 쓴 것까지 막혔다).
#
# 「몇 대 몇부터 쏠림인가」를 정할 실측 근거가 없다. 표본 넷(1/2·1/8·6/22)으로
# 문턱을 박으면 또 근거 없는 숫자를 넣는 것이다. 그래서 **안 막는다.**

def _다중틀(n, 형광펜색=None):
    """`n` 장, 슬라이드마다 위계 「부제목」인 한줄 슬롯 하나."""
    import json
    골격 = [f"장{i}" for i in range(1, n + 1)]
    슬롯 = {"위계": "부제목", "최소": 1, "최대": 200, "줄수": 1, "줄종류": "한줄"}
    if 형광펜색:
        슬롯["형광펜색"] = 형광펜색
    슬라이드 = [{"index": i, "역할": r, "글자슬롯": [dict(슬롯)]}
              for i, r in enumerate(골격, start=1)]
    return json.dumps({"골격": 골격, "슬라이드": 슬라이드}, ensure_ascii=False)


def _다중대본(블록들):
    import json
    골격 = [f"장{i}" for i in range(1, len(블록들) + 1)]
    return json.dumps({"slides": [{"role": r, "blocks": [b]}
                                 for r, b in zip(골격, 블록들)]}, ensure_ascii=False)


