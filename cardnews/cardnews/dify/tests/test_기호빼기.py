# ── 형광펜은 우리가 안 찍는다(사람 결정 2026-09-18) ─────────────────
#
# 「형광펜은 너가 하지 마, 그냥 굵기 정도나 하고, 형광펜은 마지막에 사용자가
# 할 수 있게」.
#
# **잰 형광펜 색을 못 믿는다.** 색은 원본에서 «줄 뒤에 깔린 띠» 를 재서 고르는데,
# 어두운 배경 디자인에서는 글자 사이로 비친 배경이 띠로 잡힌다. 실물
# DYzN0Uzgaq6(AI소식 미니): 형광펜색이 #0E0C0D · #0F0C0A · #1E1F1E — 셋 다
# 거의 검정이라 검은 글자 위에 검은 띠가 깔려 글자가 안 보였다.
#
# 작업대에는 형광펜 단추가 이미 있다 — 긁어서 칠하고, 한 번 더 누르면 뺀다.

def test_프롬프트가_형광펜을_안_시킨다():
    import sys as _s
    from pathlib import Path as _P
    _s.path.insert(0, str(_P(__file__).resolve().parents[1]))
    import 프롬프트
    글 = 프롬프트.대본_시스템("<레시피>")
    assert "##" not in 글, "형광펜 표시법을 아직 시킨다"
    assert "**굵게**" in 글, "굵게까지 없애면 안 된다"


def test_형광펜을_써도_배치가_형광펜을_안_낸다():
    """막지도 않고 싣지도 않는다 — 글자만 남는다.

    `표시슬라이드` 는 표시를 «일부러» 남기는 칸이라 거기에 `##` 가 있는 것은
    맞다. 재야 할 것은 배치가 낸 결과다.
    """
    import sys as _s
    from pathlib import Path as _P
    _s.path.insert(0, str(_P(__file__).resolve().parents[1]))
    import json as _j
    import 카드뉴스_배치 as 배치
    틀 = _다중틀(1, 형광펜색="#FFEE00")
    틀d = _j.loads(틀)
    틀d["슬라이드"][0]["글자슬롯"][0].update(
        {"box": [50, 50, 950, 200], "pt": 40, "weight": "Regular", "align": "왼쪽",
         "font": "Pretendard", "글자색": "#000000"})
    틀d["캔버스"] = {"w": 1080, "h": 1350}
    for s in 틀d["슬라이드"]:
        s.setdefault("배경", {"종류": "단색", "hex": "#FFFFFF"})
        s.setdefault("장식영역", [])
    틀 = _j.dumps(틀d, ensure_ascii=False)
    난것 = 검증.main(_다중대본(["##형광펜## 이 있는 **굵은** 글입니다요"]), 틀)
    assert 난것.get("ok") == "1", 난것.get("blocked")
    카드들 = _j.loads(배치.main(난것["표시슬라이드"], 틀)["cards_json"])
    글자칸 = [r for c in 카드들 for r in (c.get("글자영역") or [])]
    assert 글자칸, "글자칸이 없다"
    for r in 글자칸:
        assert not any(d.get("형광펜") for 줄 in r["글줄"] for d in 줄["덩어리"]), f"형광펜이 실렸다: {r['글줄']}"
        assert "##" not in "".join(r.get("lines") or []), "표시가 글에 남았다"
    assert any(d.get("굵게") for r in 글자칸 for 줄 in r["글줄"] for d in 줄["덩어리"]), "굵게까지 사라졌다"
