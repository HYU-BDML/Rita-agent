# ── 글자색 (사람 결정 2026-09-19) ──────────────────────────────────
#
# 「"AI 광고 미친놈이네요" 이렇게 있을 때 "AI 광고"는 노란색으로 해야겠군 하면
# 그렇게 적용하면 되는 거 아님?」 — 그대로다. **원본의 어느 «자리»가 노랑이었는지는
# 새 글로 못 옮긴다**(글이 통째로 다르다). 분석이 주는 것은 «이 틀이 쓰는 색»이고,
# 새 글에서 어디를 칠할지는 LLM 이 고른다. 굵게·형광펜과 똑같은 길이다.

def test_글자색_표시를_떼고_자리를_낸다():
    글, 자리 = 강조.떼기("[[AI 광고]] 미친놈이네요")
    assert 글 == "AI 광고 미친놈이네요"
    assert 자리 == [{"종류": "글자색", "시작": 0, "끝": 5}]
    assert 글[0:5] == "AI 광고"


def test_셋이_섞여도_자리가_맞는다():
    글, 자리 = 강조.떼기("**굵게** 가운데 ##형광## 끝 [[색]]")
    assert 글 == "굵게 가운데 형광 끝 색"
    assert [x["종류"] for x in 자리] == ["굵게", "형광펜", "글자색"]
    for x in 자리:
        assert 글[x["시작"]:x["끝"]] in ("굵게", "형광", "색")


def test_글자색도_글자_하나에_걸린다():
    # 사람 결정 2026-09-18: 「문자 하나하나도 할 수 있어야 함」.
    글, 자리 = 강조.떼기("[[안]]녕하세요")
    assert 글 == "안녕하세요"
    assert 자리 == [{"종류": "글자색", "시작": 0, "끝": 1}]


def test_세기가_글자색도_센다():
    센것 = 강조.세기("**굵게** ##형광## [[색]] [[또색]]")
    assert 센것 == {"굵게": 1, "형광펜": 1, "글자색": 2}


def test_짝이_안_맞는_대괄호는_안_건드린다():
    # 글에 대괄호가 그냥 쓰일 수 있다 — 짝이 맞고 안이 비지 않은 것만 표시다.
    글, 자리 = 강조.떼기("배열[0] 과 [단독")
    assert 글 == "배열[0] 과 [단독"
    assert 자리 == []


# ── 겹친 표시 (2026-09-28 실물) ──────────────────────────────────
#
# 표지 제목에 「월세 가고 병원 가고 [[공제]]가 온다」가 괄호째 찍혔다. 모델이
# `**[[공제]]**` 처럼 굵게 안에 글자색을 «겹쳐» 썼는데, 바깥 표시 하나만 떼고
# 안쪽은 글자로 남겼다. 겹친 표시는 **끝까지 떼고 효과는 다 남긴다.**

def _갈래자리(자리):
    return sorted((x["종류"], x["시작"], x["끝"]) for x in 자리)


def test_굵게_안의_글자색도_떼고_둘_다_남긴다():
    글, 자리 = 강조.떼기("월세 가고 병원 가고 **[[공제]]**가 온다")
    assert 글 == "월세 가고 병원 가고 공제가 온다"
    assert _갈래자리(자리) == [("굵게", 12, 14), ("글자색", 12, 14)]


def test_글자색_안의_굵게도_떼고_둘_다_남긴다():
    글, 자리 = 강조.떼기("[[**공제**]]가")
    assert 글 == "공제가"
    assert _갈래자리(자리) == [("굵게", 0, 2), ("글자색", 0, 2)]


def test_형광펜_안의_글자색도_뗀다():
    글, 자리 = 강조.떼기("##[[공제]]## 끝")
    assert 글 == "공제 끝"
    assert _갈래자리(자리) == [("글자색", 0, 2), ("형광펜", 0, 2)]


def test_겹친_표시_안에_글이_더_있어도_자리가_맞는다():
    글, 자리 = 강조.떼기("**앞 [[가운데]] 뒤**")
    assert 글 == "앞 가운데 뒤"
    assert _갈래자리(자리) == [("굵게", 0, 7), ("글자색", 2, 5)]


def test_세기가_겹친_표시를_둘_다_센다():
    assert 강조.세기("**[[공제]]**") == {"굵게": 1, "형광펜": 0, "글자색": 1}
