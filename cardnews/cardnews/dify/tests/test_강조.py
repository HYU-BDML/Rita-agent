"""LLM 이 글 안에 표시한 강조를 떼어 내고 자리를 낸다."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import 카드뉴스_강조 as 강조  # noqa: E402


def test_굵게_표시를_떼고_자리를_낸다():
    글, 자리 = 강조.떼기("결국 **전환율** 이 오른다")
    assert 글 == "결국 전환율 이 오른다"
    assert 자리 == [{"종류": "굵게", "시작": 3, "끝": 6}]
    assert 글[3:6] == "전환율"


def test_형광펜_표시도_같이_낸다():
    글, 자리 = 강조.떼기("##구매 전환율## 3배")
    assert 글 == "구매 전환율 3배"
    assert 자리 == [{"종류": "형광펜", "시작": 0, "끝": 6}]


def test_둘이_섞여도_자리가_맞는다():
    글, 자리 = 강조.떼기("**앞** 가운데 ##뒤##")
    assert 글 == "앞 가운데 뒤"
    assert 자리 == [{"종류": "굵게", "시작": 0, "끝": 1},
                  {"종류": "형광펜", "시작": 6, "끝": 7}]


def test_표시가_없으면_빈_목록():
    assert 강조.떼기("그냥 글") == ("그냥 글", [])


def test_짝이_안_맞는_표시는_글자로_친다():
    """`2*3` 같은 곱셈을 서식으로 오해하면 글이 조용히 바뀐다."""
    글, 자리 = 강조.떼기("2*3 은 6")
    assert 글 == "2*3 은 6"
    assert 자리 == []


def test_세기는_갈래마다_센다():
    assert 강조.세기("**가** ##나## **다**") == {"굵게": 2, "형광펜": 1, "글자색": 0}


def test_줄바꿈을_건너뛰는_표시도_받는다():
    """LLM 이 줄을 나눠 써도 표시는 이어진다."""
    글, 자리 = 강조.떼기("**앞\n뒤**")
    assert 글 == "앞\n뒤"
    assert 자리 == [{"종류": "굵게", "시작": 0, "끝": 3}]


