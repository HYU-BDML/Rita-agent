"""본문은 «통틀어 몇 자» 로 재고, 줄은 코드가 폭을 재서 감는다.

실물 2026-09-16 파란 타임라인 5번 장: 상자는 원본 폭의 83% 인데 대본 LLM 이 한 줄을
16~21자에서 끊어(자리 규칙 12~25자) 오른쪽 35% 가 비었다. 라벨 잘못이 아니다 —
아무도 폭에 맞춰 다시 감지 않았다(사람 결정 2026-09-16, 최소는 60%).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import 카드뉴스_대본검증 as 검증  # noqa: E402
import 카드뉴스_자수 as 자수  # noqa: E402


def _본문(**더):
    return {"위계": "본문", "최소": 90, "최대": 150, **더}


def test_통자수는_틀의_최소최대_그대로다():
    """**곱하지 않는다** — `최소`·`최대` 가 이미 총량이다(2026-09-18)."""
    assert 자수.통자수(_본문()) == (90, 150)
    assert 자수.통자수(_본문(최소=55, 최대=92)) == (55, 92)


def _글자당10(글):
    return 10.0 * len(글)


def test_폭감기_낱말_경계에서_끊는다():
    줄들 = 자수.폭감기("두 전략은 비슷해 보이지만 다른 전략입니다", _글자당10, 120)
    assert 줄들 == ["두 전략은 비슷해", "보이지만 다른", "전략입니다"]
    for 줄 in 줄들:
        assert _글자당10(줄) <= 120


def test_폭감기_원문_줄바꿈은_지운다():
    assert 자수.폭감기("가나\n다라\n마", _글자당10, 200) == ["가나 다라 마"]


def test_폭감기_긴_낱말은_글자로_쪼갠다():
    assert 자수.폭감기("가나다라마바사아", _글자당10, 30) == ["가나다", "라마바", "사아"]


def test_폭감기_빈_글은_빈_목록():
    assert 자수.폭감기("", _글자당10, 100) == []
    assert 자수.폭감기("   \n ", _글자당10, 100) == []


def test_폭감기_넘쳐도_자르지_않는다():
    줄들 = 자수.폭감기("가 나 다 라 마 바 사 아 자 차", _글자당10, 30)
    assert "".join(줄들).replace(" ", "") == "가나다라마바사아자차"


def test_한덩어리():
    assert 자수.한덩어리("가나\n다라  마\r\n바") == "가나 다라 마 바"


def test_실제_글꼴로_감으면_폭을_채우고_예산_안_글은_줄수_안이다():
    """파란 타임라인 5번 장 원문(띄어쓰기 포함 180자, 원본은 양쪽 맞춤으로 6줄)·
    상자 폭 892px·프리텐다드 Regular 41pt. 글꼴 파일은 굽기와 같은 것이다
    (`_SUBSTITUTED` 가 비어 있어야 한다 — 대체 글꼴로 재면 폭이 딴 값이 된다)."""
    sys.path.insert(0, str(ROOT.parent / "analyze"))
    import verify_labeled  # noqa: E402,PLC0415 — analyze/ 를 방금 sys.path 에 넣었다

    # **줄수·줄종류를 안 싣는다**(2026-09-18). 최소·최대는 넓이로 잰 총량이다 —
    # 이 네모(893×342px)에 41pt 로 통틀어 몇 자가 들어가나.
    슬롯 = {"font": "프리텐다드", "weight": "Regular", "pt": 41,
           "box": [134, 737, 1027, 1079], "위계": "본문",
           "최소": 90, "최대": 150}
    원문 = ("두 전략은 비슷해 보이지만 다른 전략입니다! 인플루언서 마케팅은 브랜드와 함께 기획한 "
           "콘텐츠이기에 광고 느낌이 나지만, 메시지 관리가 쉽다는 장점이 있죠. 반대로 어필리에이트 "
           "마케팅은 크리에이터가 자율적으로 제품을 소개하는 경우가 많아 상대적으로 진정성은 높게 "
           "느껴지지만, 그 내용과 표현을 세세하게 통제하기가 어렵습니다.")
    # **이 시험이 «잰 것» 만 본다.** `_SUBSTITUTED` 는 판을 도는 내내 쌓이는
    # 목록이라, 앞서 돈 다른 시험이 다른 글꼴로 물러선 것까지 여기 걸린다.
    앞서있던것 = set(verify_labeled._SUBSTITUTED)
    재기 = 자수.글꼴재기(슬롯)
    폭 = 슬롯["box"][2] - 슬롯["box"][0]

    줄들 = 자수.폭감기(원문, 재기, 폭)
    assert all(재기(줄) <= 893 for 줄 in 줄들), 줄들
    assert max(len(줄) for 줄 in 줄들) >= 22   # 폭을 실제로 채운다 — 16~21자에서 안 끊는다
    # 180자는 슬롯 예산(150자)을 넘는 글이라 6줄을 못 채우는 게 맞다 — 7줄이면 배치 검증이
    # 막고 다시 쓰기로 간다.
    assert 1 <= len(줄들) <= 7, 줄들

    # 예산 안으로 줄인 글은 «반드시» 네모 «높이» 안에 든다 — 뒷단이 기대는 보장이다.
    예산 = 자수.통자수(슬롯)[1]
    줄인글 = 자수.한덩어리(원문)[:예산].rsplit(" ", 1)[0]
    줄인줄들 = 자수.폭감기(줄인글, 재기, 폭)
    들어갈줄 = int((슬롯["box"][3] - 슬롯["box"][1]) / (슬롯["pt"] * 1.32))
    assert 1 <= len(줄인줄들) <= 들어갈줄, (줄인줄들, 들어갈줄)
    assert all(재기(줄) <= 893 for 줄 in 줄인줄들), 줄인줄들

    # 대체 글꼴로 떨어졌으면 잰 폭을 믿을 수 없다.
    assert verify_labeled._SUBSTITUTED - 앞서있던것 == set()


def test_모르는_글꼴_이름이면_프리텐다드로_잰다():
    """상자 안에서는 기준 글꼴(윈도 malgun.ttf)을 못 연다 — 굽기처럼 프리텐다드로
    물러서야 배치가 안 죽는다(최종 검토 2026-09-17)."""
    sys.path.insert(0, str(ROOT.parent / "analyze"))

    모름 = 자수.글꼴재기({"font": "못 가림", "weight": "Regular", "pt": 41})
    프리 = 자수.글꼴재기({"font": "프리텐다드", "weight": "Regular", "pt": 41})
    assert 모름("가나다") > 0
    assert 모름("가나다") == 프리("가나다")   # 둘 다 프리텐다드 Medium 으로 잰 값이다


# ── 자수는 통틀어 하나로 본다(사람 결정 2026-09-18) ──────────────────
#
# 「세로줄은 안 본다니까」. 틀에서 `줄수`·`줄종류` 를 걷어냈으니 검증도 줄로
# 나눠 보지 않는다 — 몇 줄로 나뉠지는 배치가 글꼴 폭을 재서 정한다.

def _넓이틀(최소, 최대):
    import json
    슬롯 = {"위계": "본문", "최소": 최소, "최대": 최대,
          "box": [50, 50, 950, 450], "pt": 40, "weight": "Regular",
          "font": "Pretendard", "align": "왼쪽", "글자색": "#000000"}
    return json.dumps({"골격": ["훅"], "캔버스": {"w": 1080, "h": 1350},
                       "슬라이드": [{"index": 1, "역할": "훅",
                                 "배경": {"종류": "단색", "hex": "#FFFFFF"},
                                 "장식영역": [], "글자슬롯": [슬롯]}]},
                      ensure_ascii=False)


def _한장(글):
    import json
    return json.dumps({"slides": [{"role": "훅", "blocks": [글]}]}, ensure_ascii=False)


def test_줄이_몇_줄이든_총량만_맞으면_통과한다():
    """여덟 줄로 써도 총량이 한계 안이면 안 막는다."""
    글 = "\n".join(["짧은 줄입니다"] * 8)          # 8줄 · 띄어쓰기 빼고 56자
    난것 = 검증.main(_한장(글), _넓이틀(40, 80))
    assert 난것.get("ok") == "1", 난것.get("blocked")


def test_총량이_넘치면_막는다():
    글 = "아주 긴 글입니다 " * 20
    난것 = 검증.main(_한장(글), _넓이틀(40, 80))
    assert 난것.get("ok") != "1", "넘쳤는데 통과했다"


def test_줄수나_줄종류를_안_봐도_안_죽는다():
    """옛 틀에만 있던 칸이다 — 없다고 터지면 안 된다."""
    난것 = 검증.main(_한장("한 줄로 쓴 글입니다요"), _넓이틀(5, 80))
    assert "줄" not in (난것.get("blocked") or ""), 난것.get("blocked")
