# -*- coding: utf-8 -*-
"""**장 번호 칸은 한글 자로 잰 값이 안 맞는다.**

번호는 이제 번호판(`analyze/번호판`)이 찍는다. 그런데 그 칸에 붙는
값들은 전부 «한글을 재는 자» 로 잰 것이라, 숫자에는 세 군데가 어긋났다
(실물 2026-09-01, DSW-6lrk5rs — 구운 그림을 잘라서 눈으로 확인했다).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import make_dsl_cardnews as m  # noqa: E402


def _번호칸(본보기="01", **더):
    return {"위계": "번호", "본보기": 본보기, "최소": 1, "최대": 1,
            "align": "왼쪽", "효과": ["밑줄"], **더}


def test_두_자리_번호가_안_잘리게_상한을_올린다():
    """36px 칸의 상한이 「1자」로 잡혀 「02」가 「0」으로 잘렸다."""
    칸 = _번호칸("01")
    m._번호칸손질(칸)
    assert 칸["최대"] >= 2


def test_본보기가_길면_그만큼_받는다():
    """「3/10」 꼴이면 네 자다."""
    칸 = _번호칸("3/10")
    m._번호칸손질(칸)
    assert 칸["최대"] == 4


def test_거짓_밑줄을_뗀다():
    """원본에는 없다 — 배지 가장자리가 밑줄로 읽힌 것이다."""
    칸 = _번호칸()
    m._번호칸손질(칸)
    assert "효과" not in 칸


def test_가운데_정렬로_바꾼다():
    """배지 안 번호는 가운데다. 새 번호가 길거나 짧아도 한가운데에 앉는다."""
    칸 = _번호칸()
    m._번호칸손질(칸)
    assert 칸["align"] == "가운데"


def test_번호를_자르던_노드는_사라졌다():
    """마지막 방어선이던 「자수 줄여 다시」를 **없앴다**(2026-09-18).

    그 노드는 36px 짜리 번호 칸의 상한이 「1자」로 잡혀 「02」를 「0」으로
    자른 적이 있다. 자수 한계가 네모 넓이로 정해진 뒤로는 모든 글자칸이
    «통틀어 몇 자» 라 줄 단위로 잘라 낼 것이 아예 없어서 노드째 뺐다.
    """
    import importlib.util
    assert importlib.util.find_spec("카드뉴스_자수줄이기") is None, "찌꺼기가 남아 있다"


def test_배지_구멍을_네모로_메우지_않는다():
    """면 잇기(`analyze/배경판.면잇기`)가 배경판에서 배지 동그라미까지
    이어 그린다. 땜질이 남아 있으면 빌린 판을 쓰는 사진 배경 장에서 없던
    파란 네모가 생긴다(실물 2026-09-17, 새 예시 3번 장 「03」)."""
    import io as _io
    글 = _io.open(ROOT / "make_dsl_cardnews.py", encoding="utf-8").read()
    # 옛 땜질은 «배지네모» 를 판에 네모로 칠했다. 번호판(2026-09-19)은 배지 «색» 을
    # 대비 셈에 쓰므로 그 낱말은 남고, 네모로 메우던 길만 없어야 한다.
    assert "배지네모" not in 글, "배지 땜질이 남아 있다"


def test_번호_손질이_도형_가운데맞춤_뒤에_있다():
    """`_도형안글자_가운데` 가 배지 도형에 맞춰 네모를 다시 잡고 자수를 다시
    잰다 — 그 앞에서 고치면 한글 자로 잰 값이 도로 덮어쓴다(실물 2026-09-01:
    판이 있는 장만 상한이 「1자」로 되돌아가 「04」가 막혔다)."""
    import io as _io
    글 = _io.open(ROOT / "make_dsl_cardnews.py", encoding="utf-8").read()
    가운데 = 글.index("_도형안글자_가운데(글자슬롯, 장식영역)")
    손질 = 글.index("_번호칸손질(슬롯)", 가운데)
    assert 손질 > 가운데
