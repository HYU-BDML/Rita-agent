# -*- coding: utf-8 -*-
"""분석이 잰 둘레 선(`선색`·`선굵기`)이 틀까지 실려 가는가.

`테두리` 는 도형 «모양» 을 이루는 점 목록이고 `선색`·`선굵기` 는 그 둘레에
두르는 «눈에 보이는 선» 이다 — 이름이 비슷해 헷갈리기 쉬워 키를 아예 다르게
뒀다(사람 요청 2026-09-19).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]      # cardnews/
sys.path.insert(0, str(ROOT / "dify"))

import make_dsl_cardnews as m          # noqa: E402


def _칸(추가=None):
    return {"id": "b1", "kind": "사진", "box": [100, 100, 500, 400],
            "cutout": {"box": [100, 100, 500, 400]}, **(추가 or {})}


def test_잰_선이_틀에_실린다():
    난것 = m._장식칸(_칸({"선색": "#1971C2", "선굵기": 8}))
    assert 난것["선색"] == "#1971C2"
    assert 난것["선굵기"] == 8


def test_안_잰_선은_안_싣는다():
    """옛 틀에는 이 값이 없다 — 기본으로 두르면 여태 만든 카드가 다 달라진다."""
    난것 = m._장식칸(_칸())
    assert "선색" not in 난것
    assert "선굵기" not in 난것


def test_도형_모양과_섞이지_않는다():
    """`테두리`(점 목록)와 `선색`·`선굵기` 는 따로 실린다."""
    난것 = m._장식칸({"id": "b2", "kind": "도형", "box": [0, 0, 300, 300],
                   "cutout": {"box": [0, 0, 300, 300],
                              "테두리": [[150, 0], [300, 150], [150, 300], [0, 150]]},
                   "선색": "#E03131", "선굵기": 6})
    assert 난것["테두리"] == [[150, 0], [300, 150], [150, 300], [0, 150]]
    assert 난것["선색"] == "#E03131"
    assert 난것["선굵기"] == 6
