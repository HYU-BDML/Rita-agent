_같아보임 = 60


def _비슷한색(가: str | None, 나: str | None) -> bool:
    """눈으로 구별이 안 될 만큼 가까운가. 둘 중 하나라도 모르면 `False`."""
    가, 나 = (가 or "").lstrip("#"), (나 or "").lstrip("#")
    if len(가) != 6 or len(나) != 6:
        return False
    return sum(abs(int(가[i:i + 2], 16) - int(나[i:i + 2], 16))
               for i in (0, 2, 4)) < _같아보임


_덩어리효과 = ("색", "형광펜", "굵게", "밑줄")


def _덩어리정리(덩어리들: list) -> list:
    """빈 덩어리를 빼고 이웃한 같은 효과를 합친다 — `render/edit_store.덩어리정리` 와
    같은 셈이다(이 파일은 Dify 코드 노드로도 들어가 혼자 서야 해서 임포트하지 않는다)."""
    난것 = []
    for d in 덩어리들:
        글 = d.get("글") or ""
        if not 글:
            continue
        효과 = {k: d[k] for k in _덩어리효과 if d.get(k) not in (None, False, "")}
        if 난것 and {k: 난것[-1][k] for k in _덩어리효과 if k in 난것[-1]} == 효과:
            난것[-1]["글"] += 글
        else:
            난것.append({"글": 글, **효과})
    return 난것


def _글줄만들기(순수글: str, 줄들: list, 자리들: list, 슬롯: dict, 칠할색) -> list:
    """감기 «전» 글의 강조 표시를 감은 «뒤» 줄의 덩어리로 옮긴다 — **글자에 붙인다.**

    숫자 위치를 만들지 않는다(사람 지시 여섯 번 — 설계 2026-09-28). 글자 하나하나에
    효과를 적고, 감은 줄을 따라 글자를 나눠 담은 뒤 같은 효과끼리 묶는다.

    **만들 때만 도는 규칙 둘도 여기서 글자에 붙이고 끝낸다:**
    - 틀이 「첫 줄은 소제목」 → 첫 줄 글자들에 굵게.
    - 틀이 「마지막 줄은 출처」(줄이 둘 이상일 때) → 마지막 줄 글자에 출처 색(따로
      칠한 색이 없는 글자만), 출처 정렬이 있으면 그 줄을 새 문장으로 떼고 정렬을 단다.

    **형광펜 표시는 안 찍는다**(사람 결정 2026-09-18) — 사람이 작업대에서 칠한다.
    감은 줄 사이에는 띄어쓰기 하나가 있었거나(낱말 경계) 없다(긴 낱말을 글자로
    쪼갠 자리) — 둘 다 받는다. 원문과 안 맞는 글자는 효과 없이 둔다.
    """
    글자효과 = [dict() for _ in 순수글]
    for 자리 in 자리들:
        for k in range(max(0, 자리["시작"]), min(len(순수글), 자리["끝"])):
            if 자리["종류"] == "굵게":
                글자효과[k]["굵게"] = True
            elif 자리["종류"] == "글자색" and 칠할색:
                글자효과[k]["색"] = 칠할색
    글줄 = []
    p = 0
    for i, 줄 in enumerate(줄들):
        효과들 = []
        for ch in 줄:
            while p < len(순수글) and 순수글[p] != ch and 순수글[p].isspace():
                p += 1
            if p < len(순수글) and 순수글[p] == ch:
                효과들.append(글자효과[p])
                p += 1
            else:
                효과들.append({})
        while p < len(순수글) and 순수글[p].isspace():
            p += 1
        글줄.append({"새문장": i == 0,
                   "덩어리": _덩어리정리([{"글": ch, **e} for ch, e in zip(줄, 효과들)])})
    if 슬롯.get("소제목첫줄") and 글줄:
        글줄[0]["덩어리"] = _덩어리정리([{**d, "굵게": True} for d in 글줄[0]["덩어리"]])
    출처 = 슬롯.get("출처줄")
    if 출처 and len(글줄) >= 2:
        끝줄 = 글줄[-1]
        if 출처.get("색"):
            끝줄["덩어리"] = _덩어리정리([d if d.get("색") else {**d, "색": 출처["색"]}
                                     for d in 끝줄["덩어리"]])
        if 출처.get("align"):
            끝줄["새문장"] = True
            끝줄["정렬"] = 출처["align"]
    return 글줄


def _사진_채운(장식영역: list, 사진순번, 로고: str) -> list:
    """장식영역 목록을 그대로 두되, "사진"·"인물"은 사진 주소 큐에서 하나씩,
    "로고"는 고정 주소 하나를 `media_url` 로 얹는다. 주소가 없으면(큐가 비었거나
    아예 안 왔으면) 아무것도 안 얹는다 — 굽는 쪽(`cardnews_compose.py`)이 이미
    `media_url` 없으면 회색 자리표시로 그리게 돼 있다."""
    결과 = []
    for r in 장식영역:
        r = dict(r)
        if r.get("종류") in ("사진", "인물"):
            url = next(사진순번, None)
            if url:
                r["media_url"] = url
        elif r.get("종류") == "로고" and 로고:
            r["media_url"] = 로고
        결과.append(r)
    return 결과


번호위계 = "번호"


def _번호글(차례: int, 전체: int, 본보기: str = "") -> str:
    """이 장에 찍을 번호. **원본이 쓰던 꼴을 그대로 따른다.**

    원본이 「03」이면 「05」로, 「3」이면 「5」로, 「3/10」이면 「5/7」로 찍는다.
    본보기가 없거나 못 읽으면 두 자리로 채운다 — 카드뉴스에서 가장 흔한 꼴이다.
    """
    본 = (본보기 or "").strip()
    빗금 = re.match(r"^\s*(\d+)\s*/\s*(\d+)\s*$", 본)
    # **「몇 분의 몇」으로 말이 될 때만 빗금 꼴로 본다.** 앞이 뒤보다 크면 그건
    # 차례/전체가 아니라 잘못 읽은 것이다 — 실물 2026-09-01: 원본의 「08」을
    # OCR 이 「8 / 0」 으로 읽어, 일곱 장짜리 여섯째 장에 「6/7」이 찍혔다
    # (다른 장은 전부 「02」·「03」 꼴이었다).
    if 빗금 and int(빗금.group(1)) <= int(빗금.group(2)):
        폭 = len(빗금.group(1))
        return f"{차례:0{폭}d}/{전체:0{폭}d}"
    낱 = re.match(r"^\s*(\d+)\s*$", 본)
    폭 = len(낱.group(1)) if 낱 else 2
    return f"{차례:0{폭}d}"


숫자넓이비 = 0.6
"""숫자 한 자의 폭 ≈ pt × 이 값(프리텐다드 굵게 「0」 실측 0.58). 번호를 찍을 네모의
폭을 잡는 데만 쓴다 — 실제 폭은 굽는 쪽이 글꼴로 잰다."""


def 찍을네모(번호판: dict, 글자수: int) -> list:
    """번호판 위에 숫자를 찍을 글자 네모(1080 공간). 잰 중심에 가운데 맞춘다 —
    폭은 숫자 수 × pt × 0.6 에 한 자 여유, 높이는 줄높이(pt × 1.32)."""
    x0, y0, x1, y1 = 번호판["box"]
    숫 = 번호판.get("숫자") or {}
    pt = float(숫.get("pt") or max(12, (y1 - y0) * 0.5))
    중심 = 숫.get("중심") or [0.5, 0.5]
    cx = x0 + (x1 - x0) * float(중심[0])
    cy = y0 + (y1 - y0) * float(중심[1])
    w = pt * 숫자넓이비 * max(1, 글자수) + pt * 0.8
    h = pt * 1.32
    return [int(round(cx - w / 2)), int(round(cy - h / 2)), int(round(cx + w / 2)), int(round(cy + h / 2))]


def _번호판얹기(카드들: list, 번호판: dict) -> None:
    """**표지와 마지막 장(CTA)을 뺀 모든 장**에 번호판 그림을 얹고 장 차례
    (1·2·3…)를 찍는다(사람 결정 2026-09-19 · 2026-09-24).

    **마지막 장은 늘 뺀다.** 여태는 원본을 읽어 「마지막 장에 번호가 있었나」를
    가렸다(`마지막장`). 그 한 표를 얻으려고 장마다 그림 전체를 구글에 보냈고
    (게시물당 $0.014), 한 장을 잘못 읽으면 되돌릴 길이 없었다.

    번호판 그림은 «장식» 으로, 숫자는 «번호» 위계의 글자칸으로 싣는다 — 굽는 쪽과
    작업대가 이미 아는 두 가지라 새로 배울 것이 없다.
    """
    if not 번호판 or not 번호판.get("그림") or len(카드들) < 3:
        return                              # 표지와 CTA 뿐이면 찍을 자리가 없다
    대상 = 카드들[1:-1]
    숫 = 번호판.get("숫자") or {}
    본 = 숫.get("본보기") or "01"
    for 차례, 카드 in enumerate(대상, start=1):
        글 = _번호글(차례, len(대상), 본)
        카드["장식영역"] = list(카드.get("장식영역") or []) + [
            {"종류": "장식", "box": list(번호판["box"]), "그림": 번호판["그림"], "번호판": True}]
        네모 = 찍을네모(번호판, len(글))
        pt = 숫.get("pt") or max(12, int((번호판["box"][3] - 번호판["box"][1]) * 0.5))
        카드["글자영역"] = list(카드.get("글자영역") or []) + [{
            "종류": "글자", "box": 네모, "pt": pt, "weight": 숫.get("weight") or "Bold",
            "align": "가운데", "font": 숫.get("font") or "프리텐다드",
            "글자색": 숫.get("글자색") or "#FFFFFF", "최소": 1, "최대": max(2, len(글)),
            "lines": [글], "글줄": [{"새문장": True, "덩어리": [{"글": 글}]}], "위계": 번호위계, "세로가운데": True,
            "번호판": True}]


def main(slides: list, 틀_json: str, photo_urls: str = "", logo_url: str = "",
         재기만들기=None) -> dict:
    틀 = json.loads(틀_json)
    슬라이드틀 = {s["index"]: s for s in 틀["슬라이드"]}
    골격 = 틀["골격"]
    강조색 = 틀.get("강조색") or "#C9FC95"

    if len(slides) != len(골격):
        raise ValueError(f"장이 {len(slides)}개인데 골격은 {len(골격)}장이다 — "
                          f"대본 검증을 통과했어야 하는 값이 안 맞는다")

    # 사진은 결과를 보고 «작업대»에서 넣는다(설계 §1). 여기서는 손으로 붙여넣은
    # 주소만 받는다 — 자동화로 미리 주소를 아는 경우에 쓴다.
    사진목록 = [u.strip() for u in (photo_urls or "").splitlines() if u.strip()]
    사진순번 = iter(사진목록)
    로고 = (logo_url or "").strip()

    카드들 = []
    for i, (기대역할, 카드) in enumerate(zip(골격, slides), start=1):
        틀장 = 슬라이드틀[i]
        블록 = (카드 or {}).get("blocks") or []
        슬롯들 = 틀장["글자슬롯"]
        if len(블록) != len(슬롯들):
            raise ValueError(f"{i}번 장 블록 {len(블록)}개, 슬롯 {len(슬롯들)}개 — "
                              f"대본 검증을 통과했어야 하는 값이 안 맞는다")

        글자영역 = []
        for 슬롯, 블록글 in zip(슬롯들, 블록):
            # **감는 것은 표시를 뗀 글이다.** 표시(`**굵게**`·`##형광펜##`)를 단
            # 채로 폭을 재면 그 표시 글자까지 폭에 들어가 상자가 헐거워진다.
            # **띄어쓰기를 고르고 나서 표시를 뗀다.** `자수.폭감기` 는 안에서
            # `한덩어리()` 를 불러 겹친 띄어쓰기·앞뒤 공백을 지운다 — 표시를
            # 뗀 «뒤» 자리로 고르면 그 자리가 뒤로 밀려 감은 줄과 안 맞는다
            # (검토 지적, 실측: "앞  단어 **강조** 뒤" 에서 자리가 「강조」
            # 대신 「조 」를 가리켰다). `한덩어리` 를 먼저 걸어 두면 `폭감기`
            # 안의 호출은 이미 고른 글에 다시 걸리는 것이라 안 바뀐다.
            순수글, 자리들 = 강조.떼기(자수.한덩어리(블록글 or ""))
            # **본문은 폭을 재서 감는다**(사람 결정 2026-09-16). LLM 이 어디서 끊었든
            # 지우고, 이 슬롯의 글꼴로 낱말을 이어 붙이다 상자 폭을 넘으면 줄을 바꾼다.
            # 그래야 원본처럼 오른쪽까지 찬다. 넘쳐도 안 자른다 — 배치 검증이 잡는다.
            재기 = (재기만들기 or 자수.글꼴재기)(슬롯)
            줄들 = 자수.폭감기(순수글, 재기, 슬롯["box"][2] - 슬롯["box"][0])
            # **번호는 대본이 아니라 셈이다**(사람 결정 2026-08-30).
            #
            # 원본의 01·02·03 은 여태 배경판에 그림으로 박혀 딸려 왔다. 그래서
            # 일곱 장짜리에 07 이 여섯 번째로 나왔다. 사람이 그 자리를 「번호」로
            # 라벨하면 배경판에서 구멍으로 빠지고, 여기서 **장 차례**로 다시
            # 찍는다. 모델이 무엇을 썼든 버린다 — 번호는 지어낼 것이 아니다.
            if 슬롯.get("위계") == 번호위계:
                줄들 = [_번호글(i, len(골격), 슬롯.get("본보기"))]
                자리들 = []   # 줄을 갈아치웠으니 옛 자리는 이 줄과 안 맞는다

            # **형광펜은 우리가 안 찍는다**(사람 결정 2026-09-18). 잰 색을 못
            # 믿는다 — 어두운 배경 디자인에서는 글자 사이로 비친 배경이 띠로
            # 잡혀 형광펜색이 거의 검정으로 나온다(실물 DYzN0Uzgaq6: #0E0C0D ·
            # #0F0C0A · #1E1F1E). 검은 글자 위에 검은 띠가 깔렸다.
            # 사람이 작업대에서 긁어 칠한다 — 그 단추는 이미 있다.
            #
            # **글자색은 낱말에 붙는다**(사람 결정 2026-09-19). 원본의 어느
            # «자리»가 노랑이었는지는 새 글로 못 옮긴다 — 글이 통째로 다르다.
            # 그래서 굵게와 같은 길로 간다: LLM 이 `[[…]]` 로 감싸고, 무슨 색으로
            # 칠할지는 이 틀이 쓰는 강조색을 쓴다. 안 감싼 글자는 색이 없다 —
            # 굽는 쪽이 칸 색(`글자색`)으로 그린다.
            #
            # **칸 색이 이미 강조색이면 안 건다**(사람 지적 2026-09-19:
            # 「미친놈이네요는 색깔 검은색이 아닌데?」). 강조색은 그 게시물에서
            # 제일 튀는 색 하나인데 어떤 칸은 글자 전체가 이미 그 색이다 —
            # 실물 키키 제목 `#ABEC67` 대 강조색 `#A9ED66`, 차이 4다. 칠해 봐야
            # 아무 일도 안 일어난다(창고 273칸 중 24칸, 8%).
            #
            # 안 보이는 강조가 걸려 있으면 사람은 「왜 안 되지」를 알 길이 없다.
            # 차라리 안 걸고 작업대에서 직접 칠하게 둔다.
            칠할색 = 슬롯.get("강조글자색") or 강조색
            if _비슷한색(슬롯.get("글자색"), 칠할색):
                칠할색 = None
            # **글자에 붙인다**(2026-09-28) — 숫자 위치를 만들지 않는다.
            # 「첫 줄은 소제목」·「마지막 줄은 출처」도 여기서 한 번 붙이고 끝이다.
            글줄 = _글줄만들기(순수글, 줄들, 자리들, 슬롯, 칠할색)

            글자영역.append({
                "종류": "글자", "box": 슬롯["box"], "pt": 슬롯["pt"],
                "weight": 슬롯["weight"], "align": 슬롯["align"],
                "font": 슬롯["font"], "글자색": 슬롯["글자색"],
                "최소": 슬롯["최소"], "최대": 슬롯["최대"],
                "lines": 줄들,
                "글줄": 글줄,
            })
            # **틀에 있을 때만 옮긴다.** 안 잰 값을 기본값으로 채우면 굽는 쪽이
            # 그걸 「잰 값」으로 착각한다 — 줄간격이 특히 그렇다(붙박이 1.32 와
            # 재어 온 1.32 는 뜻이 다르다). `줄색`·`줄굵기` 는 이제 배치가 안 낸다
            # (굵게·색은 `글줄` 의 글자에 붙는다) — 옛 틀에 남아 있어도
            # 옮기면 굽는 쪽이 줄 단위 굵기로 되돌아간다.
            for 이름 in ("위계", "줄간격", "효과", "각도", "세로가운데"):
                if 이름 in 슬롯:
                    값 = 슬롯[이름]
                    # `슬롯` 은 한 틀의 글자슬롯 하나다 — 같은 역할(사례 등)의
                    # 카드가 여러 장이면 이 슬롯 하나를 장마다 돌려 쓴다. 목록
                    # (`효과`)을 그대로 물려주면 한 장에서 고친 목록이 다른
                    # 장에도 그대로 걸친다 — `list(...)` 로 떠서 끊는다.
                    글자영역[-1][이름] = list(값) if isinstance(값, list) else 값

        카드들.append({
            "index": i, "역할": 기대역할, "배경": 틀장["배경"],
            "장식영역": _사진_채운(틀장["장식영역"], 사진순번, 로고), "글자영역": 글자영역,
        })

    _번호판얹기(카드들, 틀.get("번호판"))
    return {"cards_json": json.dumps(카드들, ensure_ascii=False), "count": len(카드들)}
