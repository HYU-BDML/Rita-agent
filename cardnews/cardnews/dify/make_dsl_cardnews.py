# [65,83,1032,216] — 글자 쪽이 되레 넓어 몫이 0.86 이다). 1.0 을 바라면 하나도
# 안 걸리고, 0.5 로 낮추면 도형에 살짝 얹힌 글자까지 끌려 들어간다.
# 글자 네모와 도형 네모가 «같은 네모» 라고 볼 겹침 정도(IoU).
#
# 0.6 은 실측에서 잡았다 —
#
# | 무엇 | IoU |
# |---|---|
# | 도형을 따라 그은 글자칸 (DG0AA6PJ8s4 2번 장) | **0.772** |
# | 같은 것, 조금 더 헐렁하게 (기본 옷장 2번 장) | **0.896** |
# | 도형에 살짝 얹힌 글자 (막아야 하는 것) | 0.4 |
#
# 처음엔 「글자 네모가 도형에 얼마나 들었나」로 0.8 을 봤는데, 사람이 네모를
# 도형보다 조금 크게 긋는 흔한 경우가 0.772 로 **아슬하게 빠졌다**(사람이
# 2026-08-27 「아직도 이상하다」고 알려 줬다). 한쪽으로만 재면 그렇게 된다 —
# 서로가 서로에 얼마나 드는지를 함께 보는 IoU 가 이 판단에 맞는 자다.
같은네모문턱 = 0.6


def _네모(값):
    try:
        x0, y0, x1, y1 = (float(v) for v in 값)
    except (TypeError, ValueError):
        return None
    return (x0, y0, x1, y1) if x1 > x0 and y1 > y0 else None


def _겹친몫(안, 밖) -> float:
    """두 네모가 얼마나 같은 자리인가 (IoU, 0~1). 못 재면 0."""
    a, b = _네모(안), _네모(밖)
    if not a or not b:
        return 0.0
    가로 = max(0.0, min(a[2], b[2]) - max(a[0], b[0]))
    세로 = max(0.0, min(a[3], b[3]) - max(a[1], b[1]))
    겹 = 가로 * 세로
    합 = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - 겹
    return 겹 / 합 if 합 > 0 else 0.0


# 말투 본보기로 실을 최대 길이. 길면 프롬프트만 부풀고, 모델이 «내용» 까지
# 베낄 유혹이 커진다. 한두 줄이면 결은 충분히 전해진다.
본보기길이 = 60


def _본보기(t: dict) -> str:
    """그 자리에 **원래 있던 말**. 대본 LLM 이 말투를 맞추는 데 쓴다.

    여태 틀은 「몇 자·몇 줄·무슨 굵기」만 실었다. 그래서 카드가 자리에는 맞는데
    **말투가 딴 사람** 이었다 — 원본이 「~한대요」로 끝나는 가벼운 말이어도 대본은
    「~합니다」로 나왔다. 사람이 2026-08-27 「말투나 이런 건 따라 해야지」라고
    짚어 준 자리다.

    **내용이 아니라 결을 주는 것이다.** 짧게 잘라 싣고, 프롬프트가 「베끼지
    말고 결만 따르라」고 못 박는다.
    """
    줄들 = [x for x in (str(l.get("text") or "").strip()
                      for l in (t.get("line_detail") or [])) if x]
    if not 줄들:
        return ""

    # **줄 단위로 자른다 — 글자 수로 자르지 않는다**(실물 2026-09-19).
    #
    # 여태는 `한줄[:60] + "…"` 였다. 낱말 한가운데서 잘렸고, 모델은 그 「…」가
    # «우리가 자른 표시» 인 줄 모른다 — 「이 사람은 문장을 …로 끝내는구나」로
    # 읽고 따라 썼다. 영어 카드 실물에 「…coming back…」·「…Card-wor…」 가
    # 그대로 찍혀 나왔다(틀 DNUFIa4NIkK 의 본보기 18개 중 9개가 「…」로 끝나
    # 있었다). 한국어에서도 같은 일이 났을 것이다 — 이 코드는 언어를 안 가린다.
    #
    # 줄 단위로 자르면 셋이 한꺼번에 풀린다. 낱말이 안 잘리고, 「…」를 붙일
    # 이유가 없어지고, 남은 줄이 전부 온전해 「이 줄은 12자였다」가 진짜 값이
    # 된다(`카드뉴스_틀고르기.칸설명` 이 그 길이를 모델에게 알려 준다).
    #
    # **예산은 그대로 지킨다**(사람 결정: 「길면 프롬프트만 부풀고 모델이
    # 내용까지 베낄 유혹이 커진다」, `test_본보기는_짧게_자른다`). 첫 줄 하나가
    # 이미 예산을 넘으면 그때는 어쩔 수 없이 글자에서 끊는다 — 다만 **「…」는
    # 안 붙인다.** 자르는 것 자체가 아니라 그 표시가 문제였다.
    난것, 쓴것 = [], 0
    for x in 줄들:
        if 난것 and 쓴것 + len(x) > 본보기길이:
            break
        난것.append(x)
        쓴것 += len(x)
    한줄 = " / ".join(난것)
    return 한줄 if len(난것) > 1 else 한줄[:본보기길이]


def _잉크네모(t: dict):
    """잰 글자가 실제로 차지한 자리. 줄마다의 네모를 다 감싼 하나."""
    네모들 = [_네모(l.get("box")) for l in (t.get("line_detail") or [])]
    네모들 = [x for x in 네모들 if x]
    if not 네모들:
        return None
    return (min(x[0] for x in 네모들), min(x[1] for x in 네모들),
            max(x[2] for x in 네모들), max(x[3] for x in 네모들))


# 여백이 도형을 다 잡아먹지 않게 하는 상한. 한쪽이 도형 폭의 이만큼을 넘으면
# 잰 값이 아니라 «글이 짧아서» 그렇게 보이는 것이다.
여백상한 = 0.25


def _여백먹인네모(도형box, 잉크, 정렬: str):
    """도형 안에 글자가 앉을 자리. **여백은 잰 값에서 온다.**

    사람이 도형을 따라 네모를 그으면 그 네모는 «도형» 이지 «글자» 가 아니다.
    그대로 쓰면 글자가 도형 변에 딱 붙는다 — 실측(DG0AA6PJ8s4 2번 장): 알약이
    x70 에서 시작하는데 글자칸은 x67 이라 글자가 알약 왼쪽 끝을 넘어갔다.
    정작 원본 잉크는 x236 에서 시작한다(왼쪽 여백 166px).

    **그 166 을 쓴다.** 짐작한 값이 아니라 그 디자인이 실제로 가진 여백이다.
    """
    도형 = _네모(도형box)
    if not 도형 or not 잉크:
        return None
    폭 = 도형[2] - 도형[0]
    왼 = max(0.0, 잉크[0] - 도형[0])
    오 = max(0.0, 도형[2] - 잉크[2])
    # 오른쪽 여백은 «글이 짧아서» 커 보이기 쉽다. 왼쪽 정렬이면 왼쪽 값을
    # 양쪽에 쓰고, 가운데·오른쪽이면 둘 중 작은 쪽을 쓴다.
    여백 = 왼 if 정렬 == "왼쪽" else min(왼, 오)
    여백 = min(여백, 폭 * 여백상한)
    if 여백 < 1:
        return None
    return [round(도형[0] + 여백), round(도형[1]),
            round(도형[2] - 여백), round(도형[3])]


def _원본자수(t: dict) -> tuple:
    """`(글자 수, 줄 수)` — 그 칸에 **원본이 실제로 쓴** 양. 못 읽으면 `(0, 0)`.

    자수창이 이걸 기준으로 삼는다. 네모 넓이로 뽑은 상한은 「빈틈없이 채웠을
    때」라 원본과 어긋나기 때문이다(`template_out.자수창` 참고).
    """
