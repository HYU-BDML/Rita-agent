def 틀목록줄(틀: dict, 이름: str) -> dict:
    """틀 하나에서 명단 한 줄을 만든다.

    **`목록만들기`(폴더를 훑는 길)와 `lambda_분석.명단다시짓기`(창고를 훑는 길)가
    같은 줄을 만들어야 한다.** 두 벌로 두면 한쪽에만 칸이 늘어 채팅이 그 칸을
    못 찾는다(2026-09-19).
    """
    슬라이드 = 틀.get("슬라이드") or []
    역할 = {}
    for s in 슬라이드:
        역할[s.get("역할")] = 역할.get(s.get("역할"), 0) + 1
    줄 = {
        "코드": 틀.get("코드") or 이름,
        "이름": 틀.get("이름") or 이름,
        "만든날": _오늘(),
        "장수": len(슬라이드),
        "역할": 역할,
        "미리보기": 틀.get("미리보기"),
        "한판": 틀.get("한판"),
        # 사진 자리에 번호를 찍은 판(`analyze/자리판.py`). 굽기 전 미리보기가
        # 맨 위에 걸어서 「사진1 이 장 어디인가」를 보여 준다. **채팅은 틀
        # 파일이 아니라 이 목록을 본다** — 여기 안 실으면 화면이 못 찾는다.
        "자리판": 틀.get("자리판"),
        # **안 그려지는 것이 몇 개인가.** 목록에서 바로 보이게 싣는다 —
        # 틀 파일을 열어 봐야 아는 값이면 아무도 안 본다.
        "못그림": len(틀.get("못그림") or []),
        "강조색": 틀.get("강조색"),
        "한계출처": 틀.get("한계출처"),
        "나온곳": _나온곳(틀),
        "주소": f"{창고}/templates/{이름}.json",
    }
    # **채팅은 틀 파일이 아니라 이 목록을 본다**(`deps.틀읽기`). 여기 안
    # 실으면 영어를 골라도 한국어 이름이 나온다(실물 2026-09-19 — 틀에만
    # 넣었더니 화면이 안 바뀌었다).
    #
    # **없으면 칸을 아예 안 만든다.** 빈 글자를 넣으면 `보일이름` 이
    # 「영어 이름이 있다」로 오해한다. 없어야 한국어로 물러선다.
    영 = str(틀.get("이름영어") or "").strip()
    if 영:
        줄["이름영어"] = 영
    # **옛 틀에는 이 칸이 없다.** 그것들은 사장님이 만든 공용이니 «없으면
    # 공용» 으로 읽는다 — 갑자기 안 보이면 고를 것이 없어진다.
    줄["개인"] = bool(틀.get("개인", False))
    return 줄


def 목록만들기(터) -> list:
    """그 폴더의 틀들을 훑어 `목록.json` 을 쓴다. **목록은 간판이고 좌표는 각 파일 안에 있다.**

    **빼는 것 둘** — `목록.json` 자신과 `기본.json`. 기본은 여러 게시물을 합친
    것이라 «한 게시물의 틀» 이 아니다.

    작업대가 뽑은 틀(`<edit_id>-<판>.json`)도 같은 폴더에 오면 여기 실린다.
    그때는 `나온곳` 이 `"작업대"` 다 — 라벨링해서 뽑은 틀과 손으로 고친 틀이
    한 목록에 나란히 쌓이는 것이 이 저장소의 목적이다.
    """
    터 = Path(터)
    줄들 = []
    for p in sorted(터.glob("*.json")):
        if p.name in ("목록.json", "기본.json"):
            continue
        try:
            틀 = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        줄들.append(틀목록줄(틀, p.stem))

    (터 / "목록.json").write_text(json.dumps(줄들, ensure_ascii=False, indent=1),
                                encoding="utf-8")
    return 줄들


