# · 검정 ↔ 연두 `#AAEC66`(235). 그래서 24 면 잡음만 걸러진다.
같은색문턱 = 24


def _색차(a: str, b: str) -> int:
    """두 hex 색의 채널별 차이 중 최댓값. 못 읽으면 «아주 멀다» 로 친다."""
    def 뜯기(h):
        h = (h or "").lstrip("#")
        return [int(h[i:i + 2], 16) for i in (0, 2, 4)] if len(h) == 6 else None
    x, y = 뜯기(a), 뜯기(b)
    if not x or not y:
        return 999
    return max(abs(p - q) for p, q in zip(x, y))


def _줄별색(t: dict) -> list:
    """줄마다 «눈에 다른» 색이 있으면 목록으로, 다 같아 보이면 빈 목록.

    **덩이 색은 줄들을 접은 것이다**(최빈색). 접히는 순간 사라지는 것이 있다 —
    실측: 키키 표지는 첫 줄이 노랑 `#FFDD58`, 둘째 줄이 빨강 `#DD363E` 인데
    덩이 값은 노랑 하나뿐이다.

    **그냥 줄 색을 그대로 실으면 안 된다.** 재는 오차가 통째로 실린다 —
    `#010101` 과 `#010201` 은 눈으로 같은 검정인데 목록에는 다른 값이 된다.
    그러면 굽는 쪽이 줄마다 «다른» 검정을 칠하려 들고 틀만 지저분해진다.
    덩이 색에서 `같은색문턱` 안이면 덩이 색으로 되돌린다.

    **줄 수가 달라져도 안 무너지게 쓴다.** 대본 LLM 이 다른 글을 넣으면 줄 수가
    바뀐다 — 읽는 쪽이 모자라면 마지막 것을 이어 쓴다.
    """
    덩이 = t.get("color")
    줄들 = [l.get("color") for l in (t.get("line_detail") or [])]
    if not 덩이 or len(줄들) < 2 or not all(줄들):
        return []
    고른것 = [덩이 if _색차(c, 덩이) <= 같은색문턱 else c for c in 줄들]
    return [] if len(set(고른것)) < 2 else 고른것


def _줄별굵기(t: dict) -> list:
    """줄마다 다른 굵기가 있으면 목록으로. **여기엔 잡음이 없다** —
    Bold·Regular 둘뿐이라 값이 띄엄띄엄하다."""
    줄들 = [l.get("weight") for l in (t.get("line_detail") or [])]
    if len(줄들) < 2 or not all(줄들) or len(set(줄들)) < 2:
        return []
    return 줄들


