# 두 색이 «눈에 같은가» 를 가르는 문턱. RGB 채널별 차이의 최댓값 기준이다.
#
# 실측(게시물 둘, 여러 줄 덩이 16개): 검정 본문의 줄색이 `#010101`·`#010201`·
