# ── 한 장이 터져도 넘기기는 산다 (사용자 지적 2026-09-24) ─────────────
#
# 「채팅 화면 안의 작업대에서 「다음」이 안 넘어감 — 2/6에서 멈춤. 새 탭으로
# 열면 넘어감.」
#
# 넘기는 셈 자체는 멀쩡했다. 그런데 **한 장을 손보다 터지면 그 뒤가 통째로 안
# 돌아** 단추가 죽는다 — 셈을 다시 적는 줄도, 단추를 되살리는 줄도 못 지나간다.
# 사람에게는 「눌러도 안 넘어간다」로만 보인다.
#
# **원인을 고친 것이 아니다.** 다시 나도 멈추지 않게, 그리고 다음엔 무엇이
# 터졌는지 알 수 있게 한 것이다.

def test_장마다_따로_감싼다():
    """한 장이 터져도 나머지 장은 그대로 간다."""
    쪽 = _쪽()
    앞 = 쪽.index("function 가자(")
    몸 = 쪽[앞:앞 + 1600]
    # 장을 도는 고리 «안» 에 try 가 있어야 한다 — 고리 밖이면 첫 탈에 고리가 끝난다.
    고리 = 몸[몸.index("무대.children"):]
    assert "try {" in 고리[:200], "장을 도는 고리 안에 감싼 것이 없다"


def test_터지면_자국을_남긴다():
    """조용히 멈추면 다시 나도 알 길이 없다."""
    쪽 = _쪽()
    assert "console.error" in 쪽, "터진 것을 아무 데도 안 적는다"
    assert "[결과쪽]" in 쪽, "어디서 난 것인지 알아볼 표가 없다"


def test_셈과_단추는_반드시_지나간다():
    """위에서 터져도 셈을 다시 적고 단추를 되살려야 한다."""
    쪽 = _쪽()
    앞 = 쪽.index("function 가자(")
    몸 = 쪽[앞:앞 + 1600]
    셈자리 = 몸.index("getElementById('셈')")
    # 셈·단추를 만지는 곳이 **장 고리보다 뒤** 여야 한다.
    assert 셈자리 > 몸.index("무대.children"), "셈이 장 고리보다 앞에 있다"
    # 없는 칸을 만지다 터지지 않게 지킨다.
    for 이름 in ("셈", "앞단추", "뒤단추"):
        assert f"if ({이름})" in 몸, f"{이름} 가 없을 때를 안 지킨다"
