def test_자수_한계는_네모_넓이에서_나온다(글꼴책):
    """최대 = 네모 넓이 ÷ (한 자 폭 × 줄높이). 관측할 원문이 없어도 이것만으로 잰다."""
    box = [50, 100, 1050, 300]                      # 1000 × 200
    최소, 최대 = to.자수한계(글꼴책, "Regular", 40, box)
    한자 = to._한자폭(글꼴책, "Regular", 40)
    assert 최대 == int(1000 * 200 // (한자 * 40 * to.줄간격기본))
    assert 최소 == round(최대 * to.바닥비)


def test_상한은_언제나_넓이_나누기_글자넓이다(글꼴책):
    """**진짜 합격 기준** — 상한 × 글자 한 개 넓이가 네모 넓이를 절대 안 넘는다
    (물리 제약). 폭·높이·pt·굵기를 이리저리 바꿔도 늘 성립해야 한다."""
    for 폭 in (40, 137, 500, 794, 1026):
        for 높이 in (60, 143, 400):
            for pt in (20, 37, 60, 106):
                for weight in ("Regular", "Bold"):
                    한자 = to._한자폭(글꼴책, weight, pt)
                    _, 최대 = to.자수한계(글꼴책, weight, pt, [0, 0, 폭, 높이])
                    assert 최대 == max(1, int(폭 * 높이 // (한자 * pt * to.줄간격기본)))
                    assert 최대 * 한자 * pt * to.줄간격기본 <= 폭 * 높이 or 최대 == 1


