위치칸 = {"줄번호", "시작", "끝", "몇번째", "글자수"}


def _위치칸이_없다(값):
    if isinstance(값, dict):
        assert not (위치칸 & set(값)), f"숫자 위치 칸이 남았다: {값}"
        for v in 값.values():
            _위치칸이_없다(v)
    elif isinstance(값, list):
        for v in 값:
            _위치칸이_없다(v)


def _칸(**더):
    return {"종류": "글자", "box": [0, 0, 500, 300], "pt": 40, "weight": "Regular",
            "align": "왼쪽", "font": "프리텐다드", "글자색": "#111111", **더}


def _글들(글줄):
    return [(줄["새문장"], "".join(d["글"] for d in 줄["덩어리"])) for 줄 in 글줄]


