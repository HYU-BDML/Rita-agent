자수구간 = ((50, 2.0), (150, 1.5), (200, 1.3))
"""`(원본 자수 상한, 배수)`. 이 위는 마지막 배수(1.2)를 쓴다.

**경계는 실측에서 나왔다**(칸 54개, 사람 결정 2026-09-19). 원본 자수를 구간별로
세어 보니 50자에서 제목과 본문이 갈렸다 — 50자 이하 29칸 중 22칸이 제목이고,
51~100자 여덟 칸은 **전부 본문**이다. 그리고 긴 글일수록 배수를 좁힌다. 165자짜리
본문에 ×2 를 주면 330자까지 열려 밀도가 딴판이 된다."""

자수바닥 = 15
"""**상한이 이보다 좁아지지 않게 한다.** 원본이 다섯 자면 ×2 라도 열 자뿐인데,
한국어는 낱말 하나가 서너 자라 두세 낱말이다. 다만 네모에 그만큼 안 들어가면
물리한계가 이긴다 — 바닥은 «보장» 이지 «강제» 가 아니다."""


def 자수배수(원본: int) -> float:
    """원본 길이에 따른 배수. 짧을수록 헐렁하게, 길수록 조이게."""
    for 상한, 배수 in 자수구간:
        if 원본 <= 상한:
            return 배수
    return 1.2


def 자수창(상한: int, 원본: int = 0) -> tuple:
    """`(최소, 최대)`. `원본` 은 그 칸에 **원본이 실제로 쓴 글자 수**다.

        최소 = 원본 ÷ 배수
        최대 = min( max(물리한계, 원본) , max(원본 × 배수, 15) )

    **왜 원본을 기준으로 삼나** — `넓이상한` 이 내는 상한은 「글자로 네모를
    빈틈없이 채웠을 때」라서 원본과 안 맞는다. 실측(DG0AA6PJ8s4): 6번 장 제목은
    원본이 「이지리스닝」 **다섯 자**인데 넓이 셈은 27~42자를 요구했다. 여덟 배다.
    그 칸을 맞추면 오히려 원본 디자인이 무너진다 — 짧은 명사구가 큼직하게 박히는
    자리에 문장이 통째로 들어간다.

    **원본이 물리한계를 넘으면 원본이 천장이다.** 칸 64개 중 23개(36%)가 그랬다.
    `_한자폭` 이 한글 「가」 하나로 재는데 실제 글에는 공백·숫자·영문이 섞여 더
    좁기 때문이다. 원본이 그 네모에 실제로 들어갔다는 것이 우리 계산보다 센
    증거다. 공식 자체는 안 고친다 — 배치·검증·작업대가 다 같이 보는 값이라
    파장이 크다.

    **원본이 없으면 옛 공식(상한의 65%) 그대로다.** 라벨한 네모와 잰 글자가
    안 맞아 원본을 못 꺼낸 칸이 16% 있다.
    """
    상한 = max(1, int(상한))
    원본 = int(원본 or 0)
    if 원본 <= 0:
        return max(1, min(상한, round(상한 * 바닥비))), 상한
    배수 = 자수배수(원본)
    천장 = max(상한, 원본)
    최대 = max(1, min(천장, int(max(원본 * 배수, 자수바닥))))
    최소 = max(1, min(최대, round(원본 / 배수)))
    return 최소, 최대


def 넓이상한(한자폭: float, pt: float, 줄간격, box: list) -> int:
    """네모 넓이를 글자 한 개 넓이(한 자 폭 × 줄높이)로 나눈 값. 0 이면 못 잰 것."""
    줄높이 = float(pt) * float(줄간격 or 줄간격기본)
    if not box or 한자폭 <= 0 or 줄높이 <= 0:
        return 0
    x0, y0, x1, y1 = box
    return int((x1 - x0) * (y1 - y0) // (한자폭 * 줄높이))


def _한자폭(fonts: tr.FontBook, weight: str, pt: float, font: str = None) -> float:
    """그 크기·굵기·**글씨체**로 한글 한 자를 그렸을 때의 폭. 자간은 0 이다
    (`cardnews_compose._draw_text_region` 이 tracking 없이 잰다).

    **굽는 쪽이 쓰는 그 함수(`글꼴이름`)로 고른다.** 여기서 따로 표를 만들면
    잰 폭과 실제 그리는 폭이 어긋난다.

    **여태는 `WEIGHT_TO_FONT` 한 줄로 무조건 프리텐다드를 쟀다.** 굽는 쪽은
    2026-08-29 에 `한글글꼴` 표가 생겨 글씨체대로 그리는데(사람 지적:
    「글씨체 다양하게 받은 거 맞아?」) 여기만 안 따라왔다 — **그때 고친 바로
    그 어긋남이 이 자리에 남아 있었다.**

    실측(40pt, 「가」 한 자 폭이 프리텐다드 대비): 여기어때잘난체 114% ·
    지마켓산스/에스코어드림/나눔명조 109% · 배민도현 89%. 프리텐다드로 재면
    잘난체 칸은 한 자를 14% 좁게 보므로 **자수 상한이 그만큼 헐거워진다.**

    `font` 가 없으면 `글꼴이름` 이 프리텐다드로 물러선다 — 옛 부르는 쪽과 같다.
    """
    f = fonts.get(글꼴이름({"font": font, "weight": weight}), int(round(pt)))
    d = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
    return tr._measure_tracked(d, "가", f)


def 자수한계(fonts: tr.FontBook, weight: str, pt: float, box: list, 줄간격=None,
          font: str = None):
    """`(최소, 최대)` — 이 네모에 통틀어 몇 자. 위 `넓이상한`·`자수창` 그대로다.

    `font` 는 그 칸의 글씨체다. **안 주면 프리텐다드로 잰다** — 옛 부르는 쪽이
    그대로 돌게 두려는 것이지, 그게 맞는 값이라서가 아니다.
    """
    return 자수창(넓이상한(_한자폭(fonts, weight, pt, font), pt, 줄간격, box))


사진종류 = ("사진", "인물")
"""«사진 자리» 로 세는 것. 로고와 장식은 안 센다 — 고를 때 보는 것은 「이 디자인에
사진이 몇 장 들어가나」 이고, 로고는 어느 디자인에나 붙는 장식이라 판단에 안 쓴다."""


def 서랍만들기(슬라이드들: list) -> dict:
    """역할별 디자인 묶음. **«몇 번째 장» 이 아니라 «어떤 옷» 이다.**

    지금 틀의 `슬라이드` 는 자리 번호(1번 장·2번 장…)로 되어 있어서, 사례를 더 쓰려면
    관측된 것을 순서대로 돌려쓸 수밖에 없다 — 눈이 없다. 서랍이 있으면 대본이 정한
    장마다 **어울리는** 디자인을 고를 수 있다.

    `덩이수`·`사진자리수` 를 미리 세어 둔다 — 고르는 쪽이 다시 안 세게 하고,
    무엇을 보고 고르는지가 파일에 드러나게 한다.
    """
    서랍 = {}
    for s in 슬라이드들:
        역할 = s.get("역할")
        글자 = s.get("글자슬롯") or s.get("글자영역") or []
        장식 = s.get("장식영역") or []
        서랍.setdefault(역할, []).append({
            "역할": 역할,
            "배경": s.get("배경"),
            "장식영역": 장식,
            "글자슬롯": 글자,
            "덩이수": len(글자),
            "사진자리수": sum(1 for r in 장식 if r.get("종류") in 사진종류),
        })
    return 서랍


def _있으면(칸: dict, 이름: str, 값, 버릴값=None) -> None:
    """값이 있을 때만 칸에 넣는다. **없는 것은 없는 채로 둔다.**

    `dify/make_dsl_cardnews._있으면` 과 **같은 규칙이다 — 두 벌이 갈리면
    안 된다.** 임포트로 합치지 않은 것은 방향이 반대라서다: `make_dsl_cardnews`
    가 이미 이 모듈(`template_out`)을 `서랍만들기` 때문에 불러 쓰고 있어서,
    거꾸로 여기서 그쪽을 부르면 돌고 돈다(순환 임포트).
    """
    if 값 is None or 값 == 버릴값:
        return
    칸[이름] = 값


def _층얹기(나갈것: dict, r: dict) -> dict:
    """`층` 이 있으면 옮겨 싣는다. 없으면 칸 자체를 안 만든다.

    **없는 것은 없는 채로 둬야 한다.** 그리는 쪽(`cardnews_compose._장식순서`,
    `web/lib/workbench.js` 의 `장식순서`)은 한 칸이라도 층이 비면 층을 통째로
    무시하고 옛 순서를 쓴다. 여기서 0 같은 값을 채워 넣으면 그 규칙이 깨진다.

    **왜 이 함수가 따로 있나.** 작업대에서 재어 놓고 아래로 내려가면서 조용히
    버리는 구멍이 이 프로젝트에서 네 번 났다 — 오른쪽 정렬 · 회전 · 강조색 · 층.
    이번이 다섯 번째다(위계·줄간격·효과·잉크범위·테두리·구멍·가려짐·못땄음·
    채움색) — 아래 `_장식더얹기`·`틀뽑기` 참고.
    """
    if isinstance(r.get("층"), int) and not isinstance(r.get("층"), bool):
        나갈것["층"] = r["층"]
    return 나갈것


def _장식더얹기(나갈것: dict, r: dict) -> dict:
    """장식이 지고 있는 나머지 계량값 — 있을 때만 옮겨 싣는다.

    **칸 이름·「없으면 안 넣는다」 규칙은 `make_dsl_cardnews._장식칸` 과
    똑같이 맞춘다** — 분석이 처음 뽑은 틀과 작업대를 거쳐 다시 뽑은 틀이
    같은 모양이어야 Dify 가 둘을 구별할 필요가 없다. 거기서는 계량표의
    `cutout.테두리` 처럼 한 겹 안에 있던 값인데, 여기 `r` 은 이미 그 값이
    `_장식칸` 을 한 번 거쳐 최상위로 올라와 있으니 그대로 읽으면 된다.
    """
    _있으면(나갈것, "테두리", r.get("테두리"))
    _있으면(나갈것, "구멍", r.get("구멍"), [])
    _있으면(나갈것, "가려짐", r.get("가려짐"), 0)
    _있으면(나갈것, "못땄음", r.get("못땄음"))
    _있으면(나갈것, "채움색", r.get("채움색"))
    return 나갈것


def 틀뽑기(cards: list, fonts: tr.FontBook, 강조색: str) -> dict:
    슬라이드 = []
    for c in cards:
        장식 = [_장식더얹기(_층얹기({"종류": r.get("종류"), "box": list(r["box"]),
                                "각도": float(r.get("각도") or 0)}, r), r)
              for r in (c.get("장식영역") or [])]
        슬롯 = []
        for r in (c.get("글자영역") or []):
            # **글씨체를 같이 넘긴다.** 두 줄 아래에서 틀에 싣는 그 값이다 —
            # 안 넘기면 잘난체 칸을 프리텐다드로 재서 상한이 14% 헐거워진다.
            최소, 최대 = 자수한계(fonts, r.get("weight", "Regular"), r["pt"], r["box"],
                             r.get("줄간격"), r.get("font"))
            한칸 = {
                "슬롯키": f"{c.get('역할')} {r.get('weight')} {r['pt']:.0f}",
                "box": list(r["box"]), "pt": r["pt"], "weight": r.get("weight"),
                "align": r.get("align", "왼쪽"), "font": r.get("font"),
                "글자색": r.get("글자색"),
                "최소": 최소, "최대": 최대,
                "자리가변": False,
                "각도": float(r.get("각도") or 0),
            }
            # 아래 셋도 `make_dsl_cardnews.build_recipe_payload` 와 같은 칸
            # 이름·규칙이다 — 작업대가 검은 알약·원형 크롭을 고쳐 「틀로
            # 내보내기」 해도 다음 판이 회색 네모·붙박이 줄간격으로 돌아가면
            # 안 된다.
            _있으면(한칸, "위계", r.get("위계"))
            _있으면(한칸, "줄간격", r.get("줄간격"), 0)
            _있으면(한칸, "효과", list(r.get("효과") or []), [])
            # **`잉크범위` 는 안 싣는다(2026-08-26 코디네이터 판정).** 이 칸은
            # `make_dsl_cardnews._장식칸`/`_뒷도형칸` 쪽에서 «글자 뒤 도형의
            # 상자» 였다는 게 드러났다 — 이름과 달리 글자 잉크 범위가 아니었고,
            # 읽는 곳도 없었다(파이썬·JS 어디도 안 읽음). 뒷도형은 이제
            # `장식영역` 에 `도형` 으로 실린다(위 `장식` 목록 — 작업대는 이미
            # 검은 알약을 종류 `도형`인 장식 칸으로 다루고 있다, `web/lib/
            # workbench.js` 의 `r.종류 === '도형' && r.채움색` 참고). 그러니
            # 여기서 다시 `잉크범위` 로 되실을 이유가 없다.
            #
            # **`각도` 는 그대로 둔다.** 여기(작업대)의 `각도` 는 분석 쪽과
            # 출처가 다르다 — `make_dsl_cardnews` 의 글자슬롯 각도는 언제나
            # `cutout.angle`(뒷도형 각도)의 오기였지만, 여기 `r.get("각도")`
            # 는 사람이 작업대에서 그 글자 칸을 직접 골라 회전 손잡이로 돌린
            # 값일 수 있다(`workbench.py` 의 `꾸미기(el, '글자', ...)` +
            # `회전손잡이` — 글자 칸도 장식 칸과 똑같이 돌릴 수 있다, `edit_
            # store._각도탈`·`cardnews_compose._draw_text_region` 이 실제로
            # 검증·렌더한다). 즉 같은 칸 이름이라도 이 파일에서는 «글자 자체의
            # 회전»이라는 뜻이 이미 유효하다 — 지우면 사람이 작업대에서 돌려
            # 놓은 글자가 다음 판 「틀로 내보내기」에서 조용히 다시 수평으로
            # 돌아간다.
