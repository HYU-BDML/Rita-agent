# 열쇠가 담긴 환경변수 이름. **값은 코드·문서·자국 어디에도 없다.**
열쇠칸 = "RITA_AGENT_SECRET"

# 받아 줄 크기. 넘으면 `413` 이다(규격 §9 의 `protocol_payload_too_large`).
말_최대 = 20_000
기록_최대 = 100
