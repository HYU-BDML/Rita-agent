"""RITA 와 주고받는 **봉투**. 규격서(`cardnews/rita-agent-api-spec.md`)가 정본이다.

여기는 카드뉴스를 만들지 않는다. **모양만 맞춘다** — 자물쇠를 열고, 번호표를
찍고, 답을 규격이 받아 주는 꼴로 담는다. 진짜 일은 분석 Lambda 가 한다.

**규격이 빨간 글씨로 적은 함정 넷을 이 파일이 막는다.**

1. 폴링 봉투에 `status`·`progress` 말고 아무것도 넣지 않는다. 접수증과 모양이
   다르다 — `job_id` 를 넣으면 거부된다(§7.2).
2. id 셋을 엄격히 검사하지 않는다. UUID 판 니블이 `4` 만 오지 않는다. 실제로
   이 자리에서 사고가 났다고 규격서가 적어 뒀다(§1.1).
3. 구조화 결과는 «정확히 일치» 다. 칸 하나만 더 붙어도 통째로 버려지고 화면에
   빈 자리만 남는다(§4).
4. 그림은 마크다운으로 못 보낸다. `image` 칸에 담는다(§5).
"""
