# 물어보러 오는 사이. 생략하면 3,000 이고, 무엇을 주든 RITA 가 2,000~10,000 으로
# 다듬는다(§7.1). 카드뉴스는 몇 분이라 느슨한 쪽이 낫다.
물어볼사이 = 5_000


def 열쇠확인(헤더: dict, 칸: str = "") -> bool:
    """`Authorization: Bearer <열쇠>` 하나뿐이다.

    **열쇠가 없으면 통과시키지 않는다.** 규격이 「인증 없는 fallback 을 두지
    마라」고 못 박았다(§2) — 편의로 열어 두면 그게 바로 문이 열린 상태다.

    **`칸` 으로 어느 열쇠를 볼지 고른다**(2026-09-22). 비우면 RITA 열쇠다.
    우리 웹 전용 문은 `WEB_SECRET` 을 본다 — RITA 열쇠를 돌려쓰면 **저쪽도 우리
    돈 쓰는 문을 열 수 있게 된다.** 저쪽은 `/chat` 과 `/jobs` 만 쓰면 된다.
    """
    볼칸 = 칸 or 열쇠칸
    참열쇠 = os.environ.get(볼칸, "")
    if not 참열쇠:
        print("!! " + 볼칸 + " 이 없다 — 아무도 못 들어온다")
        return False
    온것 = ""
    for 키, 값 in (헤더 or {}).items():
        if 키.lower() == "authorization":
            온것 = 값 or ""
            break
    앞 = "Bearer "
    if not 온것.startswith(앞):
        return False
    # **바이트로 견준다.** `compare_digest` 는 글자로 받으면 아스키만 다룬다 —
    # 열쇠에 아스키 아닌 글자가 하나만 섞여도 여기서 터지고, 그러면 아무도 못
    # 들어온다. 바이트로 바꾸면 무엇이 오든 «시간이 같은» 비교가 된다.
    return hmac.compare_digest(온것[len(앞):].encode("utf-8"),
                               참열쇠.encode("utf-8"))


def _글인가(x) -> bool:
    return isinstance(x, str)






def 번호만들기() -> str:
    """번호표. **아무도 못 찍게** 256비트다(§7.2 가 128비트 이상을 요구한다)."""
    return "job_" + secrets.token_urlsafe(32)


# 번호표의 생김새. **창고 열쇠를 이걸로 만들기 때문에 꼴을 반드시 본다** —
# 안 보면 주소에 `../` 를 적어 창고의 딴 파일을 읽어 갈 수 있다.
_번호꼴 = re.compile(r"^job_[A-Za-z0-9_-]{20,120}$")


def 번호맞나(번호: str) -> bool:
    return bool(_글인가(번호) and _번호꼴.match(번호))


def 접수봉투(번호: str, 밑주소: str) -> dict:
    """`202` 로 돌려줄 것. 칸은 **정확히 넷**이고 다른 것은 거부된다(§7.1)."""
    return {"type": "job", "job_id": 번호,
            "status_url": f"{밑주소.rstrip('/')}/jobs/{번호}",
            "poll_after_ms": 물어볼사이}


def 폴링봉투(일: dict) -> dict:
    """`GET /jobs/{번호}` 가 돌려줄 것.

    🔴 **`status` 와 `progress` 말고 아무것도 담지 않는다.** `type`·`job_id` 를
    넣으면 `invalid_envelope` 로 거부된다 — 접수증과 모양이 다르다(§7.2).
    규격서가 「이 자리 때문에 등록 화면의 비동기 검증만 계속 실패했다」고 적었다.
    """
    상태 = (일 or {}).get("status") or "queued"
    봉투 = {"status": 상태}
    진행 = (일 or {}).get("progress")
    if isinstance(진행, int) and 0 <= 진행 <= 100:
        봉투["progress"] = 진행
    if 상태 == "succeeded":
        봉투["result"] = (일 or {}).get("result") or {"content": "완료했습니다."}
    elif 상태 == "failed":
        탈 = (일 or {}).get("error") or {}
        봉투["error"] = {"code": (탈.get("code") or "job_failed")[:64],
                         "message": (탈.get("message") or "작업을 완료하지 못했습니다.")[:4000]}
    return 봉투


# ── 주소와 글 거르기 ────────────────────────────────────────────────

# **규칙은 `주소.py` 한 벌뿐이다**(2026-09-23 옮김). 여기 두고 저기도 두면
# 언젠가 갈린다 — `주소다듬기` 가 이미 같은 까닭으로 그쪽을 부른다.
막을호스트 = _주소.막을호스트
막을아이피 = _주소.막을아이피


def 주소다듬기(주소: str) -> str:
    """**주소는 아스키만 담는다.** 까닭과 실제 셈은 `주소.다듬기` 에 있다 —
    같은 함수를 두 벌 두면 언젠가 갈린다(2026-08-29 에 실제로 그랬다)."""
    return _주소.다듬기(주소)

def 안전한주소(주소: str) -> bool:
    """공개 `https://` 만. 사용자 정보·사설 주소·긴 것은 막는다(§4.1).

    **셈은 `주소.안전한가` 한 벌에 있다** — 같은 함수를 두 벌 두면 언젠가
    갈린다(`주소.py` 가 생긴 까닭).
    """
    return _주소.안전한가(주소)


_그림마크 = re.compile(r"!\[[^\]]*\]\([^)]*\)")
_태그 = re.compile(r"<[^>]*>")
_주석 = re.compile(r"<!--.*?-->", re.S)
_위험꼴 = re.compile(r"(javascript|data|vbscript)\s*:", re.I)
_평문주소 = re.compile(r"http://\S+", re.I)


def 글거르기(글: str) -> str:
    """답 글에서 위험한 것을 걷어낸다(§5).

    **마크다운을 통째로 파싱하지 않는다.** 그럴 필요가 없어서다 — 이 글은
    우리가 짓는다. LLM 이 쓴 자유로운 글을 그대로 싣는 자리가 아니다. 사람이
    보낸 말을 되비출 때만 위험한데, 그건 `되비출글` 이 먼저 막는다.

    **토막마다 따로 거르지 않는다.** 위험한 꼴이 토막 경계에서 잘려 검사를
    빠져나간다 — 다 짓고, 한 번 거르고, 그다음에 내보낸다.
    """
    글 = _주석.sub("", 글 or "")
    글 = _그림마크.sub("", 글)
    글 = _태그.sub("", 글)
    글 = _위험꼴.sub("", 글)
    글 = _평문주소.sub("", 글)
    return 글.strip()


_되비출때뺄것 = re.compile(r"[<>\[\]`*_!\\]")


def 되비출글(말: str, 최대: int = 60) -> str:
    """사람이 보낸 말을 답에 되비출 때. **서식 글자를 빼고 짧게 자른다.**

    되비추는 것은 친절이지만, 사람이 보낸 글은 우리가 안 지은 글이다. 마크다운
    글자를 그대로 두면 답의 서식이 사람 손에 넘어간다.
    """
    깎은것 = _되비출때뺄것.sub("", (말 or "").strip())
    깎은것 = " ".join(깎은것.split())
    return 깎은것[:최대] + ("…" if len(깎은것) > 최대 else "")


# ── 구조화 결과 ────────────────────────────────────────────────────
#
# 🔴 **칸 하나만 더 붙어도 통째로 버려진다.** 그래서 만드는 함수를 따로 두고,
# 그 함수가 내는 칸 말고는 어디서도 안 붙인다.

def 그림칸(주소: str, 알림글: str, 이름: str = "") -> dict | None:
    """`image` — 필수 `url`·`alt`, 선택 `title`. 주소가 안전하지 않으면 `None`."""
    주소 = 주소다듬기(주소)
    if not 안전한주소(주소):
        return None
    칸 = {"type": "image", "url": 주소, "alt": (알림글 or "카드뉴스")[:4000]}
    if 이름:
        칸["title"] = 이름[:120]
    return 칸


def 링크칸(주소: str, 이름: str) -> dict | None:
    """`link` — 필수 `url`·`label`. **`title` 이 아니라 `label` 이다.**"""
    주소 = 주소다듬기(주소)
    if not 안전한주소(주소) or not 이름:
        return None
    return {"type": "link", "url": 주소, "label": 이름[:120]}






