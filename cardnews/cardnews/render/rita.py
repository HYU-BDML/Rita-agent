def 답만들기(난것: dict) -> dict:
    """만든 것을 §3.2 의 답 하나로. `{"content": …, "components": […]}`."""
    장수 = 난것.get("장수") or 0
    주제 = 되비출글(난것.get("주제") or "")
    글 = 글거르기(f"「{주제}」 카드뉴스 {장수}장을 만들었습니다.\n\n"
               "아래 작업대에서 글자를 고치고 사진을 넣을 수 있습니다.")
    # **덜 만들어진 것을 조용히 넘기지 않는다**(2026-09-24). 사진 자리가 빈 채로
    # 나가면 사람은 «왜 비었나» 도, «다시 누르면 되나» 도 모른다. 다시 눌러도
    # **빈 자리에만** 값이 나간다는 것까지 적어야 사람이 고를 수 있다.
    못만든 = int(난것.get("못만든사진") or 0)
    if 못만든:
        # **사람이 눌러서 멈춘 것을 「시간이 없었다」고 하지 않는다**(2026-09-24).
        까닭 = ("그만두셔서 사진 {n}장은 안 만들었습니다"
              if 난것.get("그만뒀나") else
              "사진 {n}장은 시간 안에 못 만들었습니다")
        글 += 글거르기(f"\n\n{까닭.format(n=못만든)}. "
                   "「이대로 만들기」를 다시 누르면 빈 자리만 만듭니다 "
                   "— 이미 만든 사진에는 값이 또 안 나갑니다.")
    칸들 = [그림칸(난것.get("표지") or "", f"{주제} 카드뉴스 표지"),
          링크칸(난것.get("작업대") or "", "작업대에서 고치기")]
    칸들 = [c for c in 칸들 if c]
    return {"content": 글, "components": 칸들} if 칸들 else {"content": 글}
