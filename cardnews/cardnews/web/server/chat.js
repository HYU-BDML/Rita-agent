export function checkChatBody(body) {
  // **언어부터 고른다.** 거르다 걸린 까닭(`why`)도 말풍선에 그대로 뜨므로,
  // 나중에 정하면 그 세 마디만 한국어로 튀어나온다(실물 2026-09-19).
  //
  // **모르는 값은 한국어로 떨어뜨린다 — 거절하지 않는다.** 「en」·오타가 와도
  // 카드는 나와야 한다. 안 나오는 것보다 한국어로 나오는 편이 낫다.
  const 언어 = 언어들.includes(body?.언어) ? body.언어 : 언어들[0]
  const 말 = String(body?.말 ?? '').trim()
  if (!말) return { why: 봇(언어)('말비었음'), 언어 }
  if (말.length > 말최대) return { why: 봇(언어)('말너무김', 말.length), 언어 }
  const 대화 = body?.대화 == null ? '' : String(body.대화)
  if (대화 && !isConversationId(대화)) return { why: 봇(언어)('대화번호이상'), 언어 }
  // **「다시」는 화면이 알려 준다.** 서버가 말을 읽어 알아내려 하면 언어마다
  // 문구가 달라 깨진다. 이 값이 참일 때만 갈래를 새로 뽑는다.
  //
  // **틀코드도 화면이 알려 준다**(사람 결정 2026-09-28) — 「이 템플릿으로
  // 만들기」 단추가 싣는다. 코드 꼴이 아니면 안 실은 것으로 친다.
  const 틀코드 = typeof body?.틀코드 === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(body.틀코드)
    ? body.틀코드 : ''
  // **화풍도 화면이 알려 준다**(사람 결정 2026-09-29) — 화풍 카드가 번호를 싣는다.
  // 목록에 있는 번호와 「알아서」만 받는다. 아니면 안 실은 것으로 친다.
  const 화풍 = (body?.화풍 === 화풍알아서 || 화풍번호인가(body?.화풍)) ? body.화풍 : ''
  return { 말, 대화, 언어, 다시: body?.다시 === true,
    ...(틀코드 ? { 틀코드 } : {}), ...(화풍 ? { 화풍 } : {}) }
}

const 글 = (v) => (typeof v === 'string' ? v : '')

/** 고를 것 한 줄을 «글자» 로. 덩어리로 와도 받는다.
 *
 * **모델이 `{제목, 설명}` 으로 내는 일이 있다**(사람 지적 2026-09-19:
 * 「왜 자꾸 이해를 못했다 다시 말해달라 이말이 나오는지」). 지시문이
 * 「각 줄은 『제목 — 설명』 꼴로 쓴다」고 시키니 그 둘을 칸으로 나눠 내는
 * 것이 자연스럽다. 여태는 글자가 아니라고 셋 다 버렸고, 빈 목록이 되어
 * 답 전체가 버려졌다 — 사람 눈에는 「못 알아들었어요」만 떴다.
 *
 * **여기서 붙여 주면 한 바퀴를 안 버린다.** 화면은 그대로 단추로 그리므로
 * 글자로만 내보낸다.
 */
const 고를줄 = (x) => {
  if (typeof x === 'string') return x.trim()
  if (!x || typeof x !== 'object' || Array.isArray(x)) return ''
  const 제목 = 글(x.제목 || x.title).trim()
  const 설명 = 글(x.설명 || x.description).trim()
  if (제목 && 설명) return `${제목} — ${설명}`
  return 제목 || 설명
}

/** 사람 말이 **방금 내가 낸 갈래** 중 하나인가. 맞으면 그 글, 아니면 빈 글자.
 *
 * **주제 갈래에만 쓴다.** 사진·로고·담기 선택창도 단추를 깔지만 그건 주제가
 * 아니다 — 「비워 둘게요」가 주제로 둔갑하면 안 된다.
 *
 * **느슨하게 맞춘다.** 사람이 단추를 안 누르고 앞부분만 쳐도 걸려야 한다.
 * 「제목 — 설명」 꼴이니 제목만 같아도 같은 것으로 본다. 다만 제목이 너무 짧으면
 * 엉뚱한 말이 걸리므로 네 글자는 넘어야 한다.
 */
export function 고른것찾기(물은것, 말) {
  if (!물은것 || 물은것.무엇 !== '주제') return ''
  const 목록 = Array.isArray(물은것.고를것) ? 물은것.고를것 : []
  const 친말 = String(말 ?? '').trim()
  if (!친말) return ''
  for (const x of 목록) {
    const 것 = String(x ?? '').trim()
    if (!것) continue
    if (것 === 친말) return 것
    const 제목 = 것.split('—')[0].trim()
    if (제목.length > 4 && (제목 === 친말 || 친말.startsWith(제목))) return 것
  }
  return ''
}

/** 화풍 물음에 대한 답인가. 맞으면 화풍 번호(또는 「알아서」), 아니면 빈 글자.
 *
 * 카드를 누르면 화면이 번호를 같이 싣는다(`화풍`). 사람이 이름을 쳐도 받는다 —
 * 한국어 이름·영어 이름·번호, 그리고 「알아서」. 그 밖의 말은 평소 길(딥시크)로 간다.
 */
const 펴기 = (s) => String(s ?? '').replace(/\s+/g, '').toLowerCase()
// «알아서» 로 받는 말의 길이 상한(띄어쓰기 뺀 글자 수). 「그냥 알아서 해 줘」는 받고,
// 「주제는 알아서 하지 말고 원고대로 써 줘」 같은 긴 말은 딥시크로 보낸다(2026-09-29 검토).
const 알아서최대 = 12

export function 화풍찾기(물은것, 말, 화풍) {
  if (!물은것 || 물은것.무엇 !== '화풍') return ''
  if (화풍 === 화풍알아서 || 화풍번호인가(화풍)) return 화풍
  // 띄어쓰기·대소문자는 안 가린다 — 「픽셀그림」도 「픽셀 그림」이다.
  const 친말 = 펴기(말)
  if (!친말) return ''
  if ((친말.includes('알아서') && 친말.length <= 알아서최대) || 친말 === 'letaipick') return 화풍알아서
  const 맞은것 = 화풍목록.find((x) => [x.id, x.이름, x.이름영어].some((n) => 펴기(n) === 친말))
  return 맞은것 ? 맞은것.id : ''
}

/** 사람 말이 **방금 낸 사진·로고 단추** 중 하나인가. 맞으면 고른 값, 아니면 null.
 *
 * **글자까지 똑같을 때만 잡는다**(2026-09-28 실물: 「비워 둘게요」에 딥시크가 빈 답을
 * 두 번 내 「대답을 못 하겠어요」). 단추는 눌렀을 때 그 글이 그대로 돌아오므로 코드가
 * 무엇을 골랐는지 안다. 사람이 딴말로 쳤으면 여태처럼 모델이 읽는다.
 *
 * 단추 차례는 우리가 정했다: 사진 `[비워 둘게요, AI가 만들어 주세요]`,
 * 로고 `[로고 올리기, 로고 없이]` — 「로고 올리기」는 말을 안 보내고 파일 고르기를 연다.
 */
export function 단추답찾기(물은것, 말) {
  if (!물은것 || !Array.isArray(물은것.고를것)) return null
  const 친말 = String(말 ?? '').trim()
  const [첫, 둘] = 물은것.고를것
  if (물은것.무엇 === '사진') {
    if (친말 === 첫) return { 사진: '비움' }
    if (친말 === 둘) return { 사진: '만듦' }
  }
  if (물은것.무엇 === '로고' && 친말 === 둘) return { 로고: 로고안씀 }
  return null
}

// 딥시크 답을 읽는다. 코드펜스는 벗긴다. 여섯 밖이면 null.
//
// **버릴 때는 «왜» 를 알린다**(사람 결정 2026-09-19). 버리는 자리가 다섯인데
// 여태 아무 데도 안 적어서, 「못 알아들었어요」가 떠도 다섯 중 무엇에 걸린
// 것인지 알 길이 없었다. `적기` 는 그 한 줄을 받는 손이다 — 안 주면 아무 일도
// 안 한다(시험이 그대로 부른다).
//
// **사람이 쓴 글은 안 적는다.** 까닭과 «생김새» 만 적는다 — 원고를 통째로
// 붙여 넣으면 그것이 이 답 안에 들어 있다(`대본짓기.py` 와 같은 결).
export function parseReply(text, 적기 = () => {}) {
  let obj
  const 벗긴것 = String(text ?? '').replace(/^\s*```(?:json)?\s*|\s*```\s*$/g, '').trim()
  try {
    obj = JSON.parse(벗긴것)
  } catch {
    // JSON 이 아닐 때만 앞머리를 조금 붙인다. 이 자리는 «구조»(`{"할일": …`)
    // 이거나 모델이 제 말로 쓴 사과문이라 사람 글이 들어올 자리가 아니다.
    적기(`JSON 이 아니다 (${벗긴것.length}자)`, 벗긴것.slice(0, 60))
    return null
  }
  if (!obj || typeof obj !== 'object' || Array.isArray(obj)) {
    적기(`객체가 아니다 (${Array.isArray(obj) ? '배열' : typeof obj})`, '')
    return null
  }
  if (!할일들.includes(obj.할일)) {
    적기(`할일이 여섯 밖이다: ${JSON.stringify(글(obj.할일)).slice(0, 40)}`, '')
    return null
  }
  const 난것 = { 할일: obj.할일, 말: 글(obj.말), 틀: 글(obj.틀), url: 글(obj.url),
               // **말투 칸은 안 읽는다**(사람 지적 2026-09-21: 「이건 llm이 아니라
               // 코드야」). 모델이 적어 보내도 버린다 — 없는 이름(「키키 말투」,
               // 진짜는 「키키로 배우는 브랜딩 전략 말투」)을 지어내 초안이 404 로
               // 멈췄다(실물 2026-09-21 18:55·19:00).
               주제: 글(obj.주제), 원고: 글(obj.원고),
               담을까: 글(obj.담을까),
               // **두 값 밖은 버린다.** 이 값은 돈을 쓸지 말지를 가른다 —
               // 모델이 「네」·「좋아요」 를 보내면 안 고른 것으로 치고 다시 묻는다.
               사진: 사진갈래.includes(글(obj.사진)) ? 글(obj.사진) : '',
               // **「없음」 하나만 받는다.** 로고를 «올리는» 길은 화면이 따로
               // 처리하고 딥시크를 안 거친다 — 모델이 주소를 지어내면 안 된다.
               로고: 글(obj.로고) === 로고안씀 ? 로고안씀 : '' }
  if (obj.할일 === '고르기') {
    // **단추 없는 선택창은 막다른 길이다.** 고를 것이 없으면 사람이 아무것도
    // 못 누르고, 봇은 「고르세요」만 하고 멈춘다 — 답을 통째로 버린다.
    const 갈래 = 글(obj.무엇)
    if (!고를갈래.includes(갈래)) {
      적기(`고르기인데 무엇이 갈래 밖이다: ${JSON.stringify(갈래).slice(0, 40)}`, '')
      return null
    }
    // **글자로 내보낸다.** 화면이 그대로 단추로 그리므로 객체가 섞이면
    // 「[object Object]」가 찍힌다. 덩어리로 와도 `고를줄` 이 붙여 준다.
    const 온것 = Array.isArray(obj.고를것) ? obj.고를것 : []
    const 것들 = 온것.map(고를줄).filter(Boolean).slice(0, 고를것수)
    if (!것들.length) {
      // **말 길이도 적는다** — 갈래를 `말` 안에 줄글로 썼는지가 길이로 갈린다.
      // 「네, 골라 주세요」면 서른 자 안쪽이고, 셋을 풀어 썼으면 이백 자쯤이다.
      // **글은 안 적는다** — 사람이 붙여 넣은 원고가 이 답 안에 있을 수 있다.
      적기(`고르기인데 고를것이 비었다 (${온것.length}개 왔고 생김새 `
        + `${온것.map((x) => (Array.isArray(x) ? '배열' : typeof x)).join('·') || '없음'}`
        + `, 말 ${난것.말.length}자)`, '')
      // **답을 통째로 버리지 않는다**(사람 결정 2026-09-19). 단추는 못 지었어도
      // `말` 은 멀쩡히 썼다 — 그것만 보여 줘도 「못 알아들었어요」보다 훨씬 낫다.
      //
      // **다만 여기서 「되묻기」로 낮추지 않는다**(사람 지시 2026-09-22). 낮추면
      // 모델이 쓴 「셋 중 하나를 골라 주세요」가 **단추 없이** 그대로 나갔다 —
      // 고를 것도 없이 고르라는 막다른 길이다. 「고르기」인 채로 넘기면
      // `runTurn` 이 **앞서 낸 목록을 다시 깔거나**, 그것도 없으면 말을
      // 「무슨 주제로 만들까요?」로 갈아 끼운다.
      //
      // **말까지 비었으면 그때는 버린다** — 빈 말풍선을 띄울 수는 없다.
      if (!난것.말.trim()) return null
    }
    난것.무엇 = 갈래
    난것.고를것 = 것들
  }
  return 난것
}

