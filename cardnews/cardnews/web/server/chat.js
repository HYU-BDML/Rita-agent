const 다시묻는판 = [{}, { 강제없이: true }, { 강제없이: true, 흔들림: 0.7 }]

export async function askDeepseek(env, messages, 생각 = true, fetchImpl = fetch) {
  let 마지막 = { ok: false, why: '빈 답을 받았습니다' }
  for (const 판 of 다시묻는판) {
    마지막 = await _askOnce(env, messages, fetchImpl, 생각, 판)
    if (마지막.ok || 마지막.why !== '빈 답을 받았습니다') return 마지막
  }
  return 마지막
}

async function _askOnce(env, messages, fetchImpl, 생각 = true, 판 = {}) {
  let r
  try {
    r = await fetchImpl('https://api.deepseek.com/chat/completions', {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        authorization: `Bearer ${env.DEEPSEEK_API_KEY ?? ''}`,
      },
      body: JSON.stringify({
        model: env.DEEPSEEK_MODEL || DEFAULT_MODEL,
        messages,
        ...(판.강제없이 ? {} : { response_format: { type: 'json_object' } }),
        temperature: 판.흔들림 ?? 0,
        // **끌 때만 싣는다.** 기본이 켜진 것이라, 안 싣는 것이 곧 「켠다」다
        // (딥시크 문서: 「Supports both non-thinking and thinking (default) modes」).
        ...(생각 ? {} : { thinking: { type: 'disabled' } }),
      }),
    })
  } catch (e) {
    return { ok: false, why: e.message }
  }
  const payload = await r.json().catch(() => null)
  if (!r.ok) return { ok: false, why: payload?.error?.message || `딥시크 HTTP ${r.status}` }
  const raw = payload?.choices?.[0]?.message?.content
  const text = typeof raw === 'string' ? raw.trim() : ''
  if (!text) return { ok: false, why: '빈 답을 받았습니다' }
  return { ok: true, text }
}

