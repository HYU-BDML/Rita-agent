// 「7자리」라고 해 놓고 5장만 만든다.
const 건너뛸역할 = ['CTA']

/**
 * 틀 하나에 사진 자리가 몇 개인가. **못 읽으면 0** — 만들기를 막지 않는다.
 *
 * 목록(`templates/목록.json`)에는 이 수가 안 실려 있어서 틀 파일을 따로 읽는다.
 * 사진을 벌써 고른 뒤에는 안 부르므로 카드뉴스 한 판에 많아야 한 번이다.
 *
 * 창고가 잠깐 안 되는 것과 「사진 자리가 없다」는 다른 일이지만, 둘 다 만들기를
 * 막지는 않는다 — 사진은 지금까지처럼 빈 자리로 남는다.
 */
async function _자리수(deps, 코드, 종류들, 뺄역할) {
  if (typeof deps?.틀하나읽기 !== 'function' || !코드) return 0
  let 틀
  try {
    틀 = await deps.틀하나읽기(코드)
  } catch {
    return 0
  }
  const 장들 = Array.isArray(틀?.슬라이드) ? 틀.슬라이드 : []
  return 장들
    .filter((장) => !(뺄역할 || []).includes(장?.역할))
    .reduce((합, 장) => 합 + (Array.isArray(장?.장식영역) ? 장.장식영역 : [])
      .filter((r) => 종류들.includes(r?.종류)).length, 0)
}

