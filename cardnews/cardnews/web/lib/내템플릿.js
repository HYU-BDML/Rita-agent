// 내가 만든 템플릿을 **이 브라우저에만** 적어 둔다.
//
// 사람 지시 2026-09-19. 서른다섯 명이 리타 링크로 들어와 각자 인스타 주소를
// 담고 라벨을 쳐서 자기 템플릿을 만든다. **직접 라벨링해서 제 템플릿이 나오는
// 것이 이 제품의 알맹이라** 그 길은 막지 않는다.
//
// 그런데 템플릿 목록은 창고에 **파일 하나**(`templates/목록.json`)라, 그대로
// 두면 서른다섯 명이 서로의 템플릿을 다 보게 된다. 그래서 가른다:
//
//     수집기에서 분석  →  공용   (사장님 자리. 이름도 물어본다)
//     채팅·라벨판에서  →  개인   (여기 적어 둔 사람에게만 보인다)
//
// **창고를 나누지 않는다.** 틀 파일은 그대로 한 곳에 있고, 보여 줄 때만 고른다.
// 나누려면 로그인이 있어야 하는데 이 화면은 열린 주소다(사람 결정 2026-09-16).
//
// **이 브라우저에만 남는다.** 방문 기록을 지우거나 다른 기기로 가면 자기
// 템플릿도 안 보인다. 일회용 체험이라 그걸로 됐다 — 「내 것 다시 보기」가
// 필요해지면 그때는 로그인을 붙여야 한다.

const 열쇠 = 'cardnews.내템플릿'

const _저장소 = () => {
  try {
    return localStorage
  } catch {
    return null   // 사생활 보호 창
  }
}

/** 이 브라우저가 만든 템플릿 코드들. 못 읽으면 빈 목록 — 화면은 떠야 한다. */
export function 내것들(저장소) {
  const 통 = 저장소 ?? _저장소()
  try {
    const 것 = JSON.parse(통.getItem(열쇠) || '[]')
    return Array.isArray(것) ? 것.filter((x) => typeof x === 'string') : []
  } catch {
    return []
  }
}

/** 방금 만든 것을 적어 둔다. 같은 것을 두 번 적어도 하나다. */
export function 내것더하기(코드, 저장소) {
  const 통 = 저장소 ?? _저장소()
  const 것 = String(코드 || '').trim()
  if (!것) return 내것들(저장소)
  const 다음 = 내것들(저장소)
  if (!다음.includes(것)) 다음.push(것)
  try {
    통.setItem(열쇠, JSON.stringify(다음))
  } catch { /* 사생활 보호 창 — 이번 판에만 안 남는다 */ }
  return 다음
}

/**
 * 화면에 걸 것만 고른다 — **공용 전부 + 내가 만든 개인 것.**
 *
 * `개인` 칸이 없는 줄은 **공용으로 본다.** 창고에 이미 있는 열 벌에는 그 칸이
 * 없는데, 갑자기 안 보이면 서른다섯 명이 고를 것이 하나도 없어진다.
 */
export function 보일것(목록, 저장소) {
  const 내것 = new Set(내것들(저장소))
  return (목록 || []).filter((x) => !x?.개인 || 내것.has(x?.코드))
}
