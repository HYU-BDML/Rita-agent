/**
 * 밑그림 한 덩이 → 화면이 그릴 만큼만 간추린 장 목록.
 *
 * **여기가 «무엇을 보여 줄지» 를 정하는 자리다.** 굽는 데 드는 칸(box·글꼴·
 * 색·형광펜…)은 다 버린다 — 사람이 볼 것은 글과 사진 계획뿐이다.
 *
 * **글은 «대본»(`밑그림.슬라이드`)에서 가져온다.** 카드 안의 글은 이미 줄로
 * 나뉘고 표시가 떼인 것이라, 그걸 고치게 하면 되돌릴 방법이 없다. 대본이 안
 * 실려 온 옛 밑그림이면 카드에서 읽어 **보기만** 하게 둔다.
 */
export function 장별로(밑그림, 사진갈래 = '') {
  const 카드들 = (밑그림 && Array.isArray(밑그림.카드)) ? 밑그림.카드 : []
  const 슬라이드 = (밑그림 && Array.isArray(밑그림.슬라이드)) ? 밑그림.슬라이드 : null
  return 카드들.map((c, i) => {
    const 영역들 = (c?.글자영역) || []
    const 블록 = 슬라이드 && Array.isArray(슬라이드[i]?.blocks) ? 슬라이드[i].blocks : null
    // 대본이 있으면 **대본 칸마다** 하나씩. 없으면 카드에서 읽어 보기만 한다.
    //
    // **칸 번호는 «대본에서 몇 번째» 다.** 번호 칸을 걸러 낸 뒤에도 그 값을
    // 지킨다 — 고친 글을 되돌려 넣을 자리가 그 번호이기 때문이다.
    const 글칸 = 블록
      ? 블록.map((글, j) => ({ 글: String(글 ?? ''), j, 영역: 영역들[j] }))
        .filter(({ 영역 }) => !번호칸인가(영역))
        .map(({ 글, j, 영역 }) => 칸짓기(글, 영역, j, true))
      : 영역들.map((r, j) => (번호칸인가(r) ? null : 칸짓기(줄합치기(r), r, j, false)))
        .filter((x) => x && x.글)
    return {
      // **`차례` 와 `번호` 는 다른 것이다.** `번호` 는 사람에게 보여 줄 장
      // 번호(카드가 들고 온 `index`)이고, `차례` 는 대본 목록에서 몇 번째인가다.
      // 고친 글을 되돌려 넣을 때 쓰는 것은 `차례` 다 — `index` 를 쓰면 그 값이
      // 1 부터가 아닌 판에서 남의 장을 덮는다.
      차례: i,
      번호: Number(c?.index) || i + 1,
      역할: String(c?.역할 || ''),
      글칸,
      // 사람이 넣은 사진은 «주소» 가 차 있고, 빈 자리는 «설명» 만 있다.
      //
      // **`만듦` 은 그 자리에 «정말로» 사진이 생기는가다.** 사람이 「비워 두기」를
      // 골랐으면 설명이 적혀 있어도 안 생긴다 — 그때 「AI가 만들 사진」이라고
      // 적으면 미리보기가 거짓말을 한다.
      // **`자리` 는 «장식영역에서 몇 번째» 다.** 사진 자리만 걸러 낸 뒤에도 그
      // 값을 지킨다 — 끌어다 놓을 때 되돌려 넣을 곳이 그 번호이기 때문이다.
      사진: ((c?.장식영역) || [])
        .map((r, j) => ({ r, j }))
        .filter(({ r }) => 사진종류.includes(r?.종류))
        .map(({ r, j }) => {
          const 설명 = String(r?.설명 || '').trim()
          const 주소 = String(r?.media_url || '').trim()
          // 참조 사진(2026-09-28) — 계획이 «이 사진으로 만들라» 고 배정한 주소.
          const 참조 = String(r?.참조 || '').trim()
          return { 주소, 설명, 참조, 자리: j,
            만듦: !주소 && 사진갈래 === '만듦'
              && (!건너뛸역할.includes(String(c?.역할 || '')) || !!설명) }
        }),
    }
  })
}

const 줄합치기 = (영역) =>
  한덩어리(((영역?.lines) || []).map((l) => (typeof l === 'string' ? l : l?.글) ?? '').join(' '))

const 칸짓기 = (글, 영역, 칸번호, 고칠수있나) => ({
  글,
  칸번호,
  자수: 셈(글),
  최대: Number(영역?.최대) || 0,
  // **제목인지 본문인지를 같이 낸다**(사람 지시 2026-09-22: 「제목 본문은
  // 어디들어감?」). 글만 늘어놓으면 그것이 큰 제목 자리인지 아래 본문 자리인지
  // 알 길이 없다 — 자리 판의 청록 딱지와 같은 말이다.
  위계: String(영역?.위계 || ''),
  // 번호 칸은 고쳐 봐야 얹을 때 다시 찍힌다 — 고치게 두면 조용히 사라진다.
  고칠수있나: !!고칠수있나 && 영역?.위계 !== 번호위계,
})

// ── 사진을 만지는 손 (사람 지시 2026-09-20) ────────────────────────
//
// 「이 부분은 좀 안 맞네 하면 뺄수도 있는 칸 혹은 다른 칸이랑 바꿀수도 있는」
//
// **곳(`곳`)은 두 가지다** — 카드의 자리(`{장, 자리}`)이거나 「안 쓴 사진」의
// 한 칸(`{안쓴: true}`). 빼기·옮기기·바꾸기가 다 이 둘 사이의 오감이라, 셋을
// 따로 만들지 않고 **옮기기 하나**로 푼다.
//
//     빼기        자리 → 안 쓴 사진
//     되돌리기     안 쓴 사진 → 자리
//     바꾸기       자리 → 자리 (둘 다 차 있으면 서로 맞바꾼다)

const _자리찾기 = (밑그림, 곳) => {
  const 카드 = ((밑그림 && 밑그림.카드) || [])[곳 && 곳.장]
  return ((카드 && 카드.장식영역) || [])[곳 && 곳.자리] || null
}

/** 그 곳에서 사진을 **빼낸다.** 없으면 빈 글자. */
function _집기(밑그림, 곳) {
  if (!곳) return ''
  if (곳.안쓴 != null) {
    const 목록 = (밑그림 && 밑그림.안쓴사진) || []
    const i = Number(곳.안쓴)
    if (!Number.isInteger(i) || i < 0 || i >= 목록.length) return ''
    return 목록.splice(i, 1)[0] || ''
  }
  const 자리 = _자리찾기(밑그림, 곳)
  if (!자리) return ''
  const 주소 = String(자리.media_url || '').trim()
  delete 자리.media_url
  return 주소
}

/** 그 곳에 사진을 **놓는다.** 원래 있던 것이 있으면 그것을 돌려준다(밀린 것). */
function _놓기(밑그림, 곳, 주소) {
  if (!곳 || !주소) return ''
  if (곳.안쓴 != null) {
    if (!밑그림.안쓴사진) 밑그림.안쓴사진 = []
    밑그림.안쓴사진.push(주소)
    return ''
  }
  const 자리 = _자리찾기(밑그림, 곳)
  if (!자리) return ''
  const 밀린것 = String(자리.media_url || '').trim()
  자리.media_url = 주소
  return 밀린것
}

/**
 * 사진 하나를 **`어디서` 에서 `어디로`** 옮긴다. 밑그림이 그 자리에서 고쳐진다.
 *
 * 놓을 곳에 이미 사진이 있으면 **서로 맞바꾼다** — 밀어내고 버리면 사람이
 * 방금 놓은 것 때문에 멀쩡한 사진을 잃는다.
 */
export function 사진옮기기(밑그림, 어디서, 어디로) {
  if (!밑그림 || !어디서 || !어디로) return false
  if (어디서.안쓴 == null && 어디로.안쓴 == null
      && 어디서.장 === 어디로.장 && 어디서.자리 === 어디로.자리) return false
  const 온것 = _집기(밑그림, 어디서)
  if (!온것) return false
  const 밀린것 = _놓기(밑그림, 어디로, 온것)
  if (밀린것) _놓기(밑그림, 어디서, 밀린것)
  return true
}

/** 자리에서 사진을 뺀다. **버리지 않고** 「안 쓴 사진」으로 보낸다. */
export function 사진빼기(밑그림, 곳) {
  return 사진옮기기(밑그림, 곳, { 안쓴: true })
}

/** 화풍 칸에 딸린 것 — 고른 번호, 예시 그림 주소, 안내 한 줄(사람 결정 2026-09-29).
 *
 * **화풍을 바꿀 때 화면은 이 둘(그림·안내)만 갈아 끼운다**(검토 I-2). 미리보기를 통째로
 * 다시 그리면 「이대로 만들기」 단추가 켜진 채로 새로 그려져, 굽는 동안 다시 눌러 사진값이
 * 두 번 나갈 수 있었다. 옛 밑그림(화풍 칸 없음)은 «기본» 이다. */
export function 화풍안내(밑그림, 언어) {
  const 후보 = Array.isArray(밑그림?.화풍후보) ? 밑그림.화풍후보 : []
  const 지금 = 화풍목록.find((x) => x.id === 밑그림?.화풍) || 화풍목록.find((x) => x.id === '기본')
  const 안내 = (지금.id === '필름스냅' && !후보.includes('필름스냅')) ? 말하다(언어)('필름안내') : ''
  return { 번호: 지금.id, 그림: 지금.예시, 안내 }
}

/** 오른쪽 칸에 그대로 넣을 HTML. **누르는 단추는 하나뿐이다** — 「이대로 만들기」.
 *
 * `굽는중` 이면 그 단추를 **꺼서** 그린다(2026-09-29). 굽는 동안 사진 빼기·옮기기·새로고침이
 * 미리보기를 다시 그리면 단추가 켜진 채로 새로 그려져, 다시 눌러 사진값이 두 번 나갈 수
 * 있었다. */
export function 미리보기html(밑그림, 언어, 사진갈래 = '', 자리판 = '', 굽는중 = false) {
  const 하다 = 말하다(언어)
  const 장들 = 장별로(밑그림, 사진갈래)
  if (!장들.length) return `<p class="muted">${esc(하다('빈초안'))}</p>`
  const 고칠수있나 = 장들.some((s) => s.글칸.some((t) => t.고칠수있나))

  const 사진칸 = (p, s, n) => {
    const 곳 = `data-장="${s.차례}" data-자리="${p.자리}"`
    if (p.주소) {
      // **끌 수 있고 뺄 수 있다**(사람 지시 2026-09-20). 빼도 버리지 않는다 —
      // 「안 쓴 사진」으로 가므로 다시 끌어다 놓을 수 있다.
      return `<div class="미리-사진 미리-끌것" draggable="true" ${곳}>`
        + `<img src="${esc(p.주소)}" alt="${esc(하다('사진자리'))}">`
        + `<button type="button" class="미리-빼기" ${곳} `
        + `title="${esc(하다('사진뺌'))}">✕</button></div>`
    }
    // **사진을 만드는 판에서는 설명을 «적을 수 있게» 한다**(사람 지시
    // 2026-09-22). 비우면 기본 지시문이 간다 — 그 말을 칸 안에 적어 둔다.
    //
    // 「비워 두기」를 고른 판(`사진갈래 !== '만듦'`)에는 안 낸다. 그때는 아무
    // 사진도 안 생기므로, 적을 칸을 내면 적어도 소용없는 것을 적게 된다.
    //
    // **`만듦` 이 아닌 자리에도 낸다.** CTA 처럼 건너뛰는 역할이라도 설명이
    // 적히면 그 자리는 만든다(`analyze/사진만들기.채우기`) — 적을 길을 막으면
    // 그 규칙에 닿을 방법이 없다.
    if (사진갈래 === '만듦') {
      return `<div class="미리-사진 미리-사진빔" ${곳}>`
        + `<span class="미리-사진번호">${esc(하다('사진번호', n))}</span>`
        + (p.참조 ? `<img class="미리-참조" src="${esc(p.참조)}" alt="${esc(하다('참조사진'))}" `
          + `title="${esc(하다('참조사진'))}">` : '')
        + `<textarea class="미리-설명칸" rows="2" ${곳} `
        + `placeholder="${esc(하다('설명넣는곳'))}">${esc(p.설명)}</textarea>`
        + `<span class="미리-꼬리">${esc(하다(p.만듦 ? '만들사진' : '빈사진'))}</span>`
        + `</div>`
    }
    // 빈 자리도 «놓을 곳» 이다 — 여기로 끌어다 놓으면 그 자리에 들어간다.
    return `<div class="미리-사진 미리-사진빔" ${곳}>`
      + `<span class="미리-꼬리">${esc(하다('빈사진'))}</span></div>`
  }

  // 자수 표. 넘치면 표를 하나 더 단다 — 색만으로는 못 알아보는 사람이 있고,
  // 넘친 채로 「이대로 만들기」를 누르면 굽기 전에 막힌다(배치 검증).
  const 자수칸 = (t) => {
    if (!t.최대) return ''
    const 넘침 = t.자수 > t.최대
    return `<span class="미리-자수${넘침 ? ' 넘침' : ''}">`
      + `${esc(하다('자수', t.자수, t.최대))}${넘침 ? ` ${esc(하다('넘침'))}` : ''}</span>`
  }

  // 「제목」·「본문」 딱지. **자리 판의 청록 딱지와 같은 낱말이라야 한다** —
  // 판에 「제목」이라 찍어 놓고 여기서 다른 말을 쓰면 짝을 못 맞춘다.
  const 위계칸 = (t) => (t.위계
    ? `<span class="미리-위계">${esc(낱말('위계', t.위계, 언어))}</span>` : '')

  const 글칸html = (s, t) => {
    if (!t.고칠수있나) return `<p>${위계칸(t)}${esc(t.글)}${자수칸(t)}</p>`
    const 줄수 = Math.min(6, Math.max(2, Math.ceil(t.자수 / 24)))
    return `<div class="미리-줄">${위계칸(t)}`
      + `<textarea class="미리-글칸" rows="${줄수}" data-장="${s.차례}" `
      + `data-칸="${t.칸번호}" data-최대="${t.최대}">${esc(t.글)}</textarea>`
      + 자수칸(t) + `</div>`
  }

  const 장칸 = (s) => `<li class="미리-장">`
    + `<div class="미리-머리"><b>${esc(하다('장', s.번호))}</b>`
    + `<span class="muted">${esc(낱말('역할', s.역할, 언어))}</span></div>`
    + `<div class="미리-글">${s.글칸.map((t) => 글칸html(s, t)).join('')}</div>`
    // **번호는 그 장 «안에서» 센다.** 「3장 사진2」로 부르려는 것이라, 판 전체를
    // 통틀어 세면 장 번호와 짝이 안 맞는다.
    + `<div class="미리-사진들">${s.사진.map((p, i) => 사진칸(p, s, i + 1)).join('')}</div>`
    + `</li>`

  // **안 쓴 사진 칸.** 빈 칸이면 아예 안 보인다 — 한 장이라도 남으면 눈에 띈다.
  const 안쓴것 = ((밑그림 && 밑그림.안쓴사진) || [])
    .filter((u) => typeof u === 'string' && u.trim())
  const 안쓴칸 = 안쓴것.length
    ? `<div class="미리-안쓴" data-안쓴통="1">`
      + `<div class="미리-머리"><b>${esc(하다('안쓴사진', 안쓴것.length))}</b>`
      + `<span class="muted">${esc(하다('안쓴까닭'))}</span></div>`
      + `<div class="미리-사진들">${안쓴것.map((u, i) =>
        `<div class="미리-사진 미리-끌것" draggable="true" data-안쓴="${i}">`
        + `<img src="${esc(u)}" alt=""></div>`).join('')}</div>`
      + `</div>`
    : ''

  // **사진 자리 판을 맨 위에 건다**(사람 지시 2026-09-22). 밑의 칸이 「사진1」
  // 이라고만 하면 그게 장 어디인지 알 수 없다 — 이 그림이 그것을 보여 준다.
  //
  // **사진을 만드는 판에서만 낸다.** 「비워 두기」면 적을 칸도 없으므로 번호를
  // 보여 줄 까닭이 없다. 판이 아직 없는 옛 틀이면 그냥 안 그린다.
  const 자리판칸 = (자리판 && 사진갈래 === '만듦')
    ? `<div class="미리-자리판"><img src="${esc(자리판)}" alt="${esc(하다('자리판'))}" `
      + `loading="lazy"><span class="muted">${esc(하다('자리판'))}</span></div>`
    : ''

  // **판 전체의 사진 결**(2026-09-28). 사진을 만드는 판에서만 — 비워 두기 판은 적을
  // 까닭이 없다. 비어 있어도 칸은 낸다 — 사람이 적을 수 있어야 한다.
  const 결칸 = (사진갈래 === '만듦')
    ? `<label class="미리-결"><span class="muted">${esc(하다('결이름'))}</span>`
      + `<textarea class="미리-결칸" rows="1" placeholder="${esc(하다('결넣는곳'))}">`
      + `${esc(String(밑그림?.사진결 || ''))}</textarea></label>`
    : ''
  // **판 전체의 화풍**(사람 결정 2026-09-29). 처음 값은 코드가 뽑은 것, AI 후보에는 표를
  // 단다. 옛 밑그림(화풍 칸 없음)은 «기본» — 굽는 쪽도 화풍 없이 예전처럼 간다.
  // 예시 그림과 안내는 `화풍안내` 가 정한다 — 화풍을 바꿀 때 화면이 이 둘만 갈아 끼운다.
  const 후보 = Array.isArray(밑그림?.화풍후보) ? 밑그림.화풍후보 : []
  const 칸값 = 화풍안내(밑그림, 언어)
  const 영어 = 쓸언어(언어) === '영어'
  const 화풍칸 = (사진갈래 === '만듦')
    ? `<label class="미리-화풍"><span class="muted">${esc(하다('화풍이름'))}</span>`
      + `<img class="미리-화풍그림" src="${esc(칸값.그림)}" alt="">`
      + `<select class="미리-화풍칸">${화풍목록.map((x) => `<option value="${esc(x.id)}"`
        + `${x.id === 칸값.번호 ? ' selected' : ''}>${esc(영어 ? x.이름영어 : x.이름)}`
        + `${후보.includes(x.id) ? ` · ${esc(하다('AI추천'))}` : ''}</option>`).join('')}</select>`
      + `<span class="muted 미리-화풍안내">${esc(칸값.안내)}</span></label>`
    : ''

  return `<p class="muted 미리-아직">${esc(하다('아직'))}</p>`
    + (고칠수있나 ? `<p class="muted 미리-안내">${esc(하다('강조안내'))}</p>` : '')
    + (사진갈래 === '만듦' ? `<p class="muted 미리-안내">${esc(하다('설명안내'))}</p>` : '')
    + 화풍칸 + 결칸
    + 자리판칸
    + `<p class="muted 미리-안내">${esc(하다('끄는법'))}</p>`
    + `<ol class="미리보기">${장들.map(장칸).join('')}</ol>`
    + 안쓴칸
    + `<div class="미리-바닥">`
    + `<button type="button" id="bakeGo" class="pick"${굽는중 ? ' disabled' : ''}>`
    + `${esc(하다(굽는중 ? '굽는중' : '이대로'))}</button>`
    + `</div>`
}
