// 강조 표시를 뗀 글. `dify/카드뉴스_강조.떼기` 와 같은 표시 셋이다.
//
// **세는 데만 쓴다.** 진짜로 떼는 것은 파이썬 몫이고(굽을 때 그 함수가 돈다),
// 여기는 「몇 자인가」를 사람에게 보여 주려는 것뿐이다 — 표시 글자까지 세면
// 「40자 중 46자」처럼 겁주는 숫자가 나온다.
const _표시 = /(\*\*|##)(?=\S)([\s\S]+?)(?<=\S)\1|(\[\[)(?=\S)([\s\S]+?)(?<=\S)\]\]/g
//
// **겹친 표시도 끝까지 뗀다**(2026-09-28 실물: `**[[공제]]**`). 한 번 바꾸면 바깥
// 표시만 떨어지고 안쪽이 글자로 남는다 — 더 떨어질 것이 없을 때까지 되풀이한다.
export const 표시뗀 = (글) => {
  let 지금 = String(글 ?? '')
  for (let 번 = 0; 번 < 10; 번++) {
    const 뗀것 = 지금.replace(_표시, (_m, a, 굵은속, _c, 색속) => (a ? 굵은속 : 색속))
    if (뗀것 === 지금) break
    지금 = 뗀것
  }
  return 지금
}

