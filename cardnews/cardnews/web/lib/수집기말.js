/** 창고 낱말 하나를 고른 언어로. 모르는 값은 그대로. */
export function 낱말(갈래, 값, 언어) {
  const 것 = String(값 ?? '')
  if (쓸언어(언어) !== '영어') return 것
  return (_낱말표[갈래] || {})[것] || 것
}

/** 「라벨 N/M장」처럼 값이 박힌 상태 글. 낱말표로는 못 잡아 따로 본다. */
export function 라벨몇장(값, 언어) {
  const m = /^라벨 (\d+)\/(\d+)장$/.exec(String(값 ?? ''))
  if (!m || 쓸언어(언어) !== '영어') return String(값 ?? '')
  return `Labelled ${m[1]}/${m[2]}`
}
