// 사람이 고르는 언어. **한 벌만 둔다.**
//
// 2026-09-18 검토에서 같은 값을 여덟 자리가 세 가지 규칙으로 거르고 있었다.
// 규칙이 갈리면 한쪽만 고쳤을 때 「봇은 한국어인데 카드는 영어」처럼 조용히
// 갈라진다. 채팅 화면·채팅 서버·수집기 화면이 전부 여기만 본다.
//
// **화면에 보이는 글자와 서버로 가는 값이 다르다.** 값은 `dify/프롬프트.py` 의
// 한국어·영어 와 **글자까지 같아야 한다** — 한 글자라도 어긋나면 람다가 조용히
// 한국어로 떨어뜨린다. 카드는 나오고 한국어일 뿐이라 눈으로 못 잡는다.
export const 언어표 = [{ 값: '한국어', 보임: '한국어' },
                    { 값: '영어', 보임: 'English' }]

export const 언어들 = 언어표.map((x) => x.값)

// 채팅이 여기 남기고 수집기가 읽는다. 이름이 갈리면 수집기만 한국어로 만든다.
export const 언어열쇠 = 'cardnews.언어'

/** 저장된 것이 없거나 이상하면 한국어. **거절하지 않는다** — 안 나오는 것보다 낫다. */
export function 쓸언어(저장된) {
  return 언어들.includes(저장된) ? 저장된 : 언어들[0]
}

/** 단추를 누르면 둘 사이를 오간다. 모르는 값에서 눌러도 영어로 간다. */
export function 다음언어(지금) {
  return 쓸언어(지금) === 언어들[0] ? 언어들[1] : 언어들[0]
}

/** 브라우저에 남겨 둔 것. 저장이 막힌 창(사생활 보호 창)에서도 안 죽는다. */
export function 저장된언어() {
  try {
    return 쓸언어(localStorage.getItem(언어열쇠))
  } catch {
    return 언어들[0]
  }
}

/** 고른 것을 남긴다. 저장이 막혀 있으면 조용히 넘어간다. */
export function 언어남기기(값) {
  try {
    localStorage.setItem(언어열쇠, 쓸언어(값))
  } catch { /* 사생활 보호 창 */ }
}
