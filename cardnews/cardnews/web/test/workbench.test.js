// ── 넘침 ──────────────────────────────────────────────────────

test('줄높이는 글자 크기의 1.32 배다', () => {
  assert.equal(줄간격, 1.32)
  // 부동소수점: 40 * 1.32 는 배정도에서 52.8 리터럴과 비트가 다르다
  // (52.800000000000004). 로직이 아니라 표현의 문제라 오차 허용으로 견준다.
  assert.ok(Math.abs(줄높이(40) - 52.8) < 1e-9, `줄높이(40) = ${줄높이(40)}`)
})

test('네모보다 긴 줄을 가로 넘침으로 잡는다', () => {
  const r = 넘침([300, 520, 499], 3, BOX, 40)   // 폭 500
  assert.deepEqual(r.가로, [1])                  // 0부터 센 둘째 줄만
})

test('줄이 많아 높이를 넘으면 세로 넘침이다', () => {
  assert.equal(넘침([10], 3, BOX, 40).세로, false)   // 3 × 52.8 = 158.4 ≤ 200
  assert.equal(넘침([10], 4, BOX, 40).세로, true)    // 4 × 52.8 = 211.2 > 200
})

test('오른쪽 정렬이어도 넘침은 폭만 본다', () => {
  const r = 넘침([600], 1, BOX, 40)
  assert.deepEqual(r.가로, [0])
})

