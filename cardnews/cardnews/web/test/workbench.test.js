const BOX = [100, 200, 600, 400]   // 폭 500, 높이 200

test('정렬이 앵커를 정한다', () => {
  assert.equal(앵커('왼쪽'), 'left')
  assert.equal(앵커('가운데'), 'center')
  assert.equal(앵커('오른쪽'), 'right')
  assert.equal(앵커('단일'), 'left')      // 모르는 값은 왼쪽
  assert.equal(앵커(undefined), 'left')
})

// ── 옆면: 왼쪽 정렬 ───────────────────────────────────────────

test('왼쪽 정렬에서 오른쪽 변을 끌면 왼쪽 변이 그대로다', () => {
  const b = 옆면조절(BOX, 'e', [700, 300], '왼쪽')
  assert.deepEqual(b, [100, 200, 700, 400])
})

test('왼쪽 정렬에서 왼쪽 변을 끌면 왼쪽 변이 움직인다', () => {
  const b = 옆면조절(BOX, 'w', [50, 300], '왼쪽')
  assert.deepEqual(b, [50, 200, 600, 400])
})

// ── 옆면: 가운데 정렬 ─────────────────────────────────────────

test('가운데 정렬은 오른쪽을 끌어도 중심이 안 움직인다', () => {
  const b = 옆면조절(BOX, 'e', [700, 300], '가운데')
  const 중심전 = (BOX[0] + BOX[2]) / 2
  const 중심후 = (b[0] + b[2]) / 2
  assert.equal(중심후, 중심전)
  assert.equal(b[2] - b[0], 700 - 100 + 100)   // 오른쪽으로 100 늘렸으니 양쪽 200
})

test('가운데 정렬은 왼쪽을 끌어도 중심이 안 움직인다', () => {
  const b = 옆면조절(BOX, 'w', [50, 300], '가운데')
  assert.equal((b[0] + b[2]) / 2, (BOX[0] + BOX[2]) / 2)
  assert.deepEqual(b, [50, 200, 650, 400])
})

test('가운데 정렬에서 홀수가 남으면 왼쪽에 더 준다', () => {
  const b = 옆면조절([100, 200, 601, 400], 'e', [602, 300], '가운데')
  assert.equal((b[2] - b[0]) % 1, 0, '정수로 떨어져야 한다')
  assert.equal(b[0] + b[2], 100 + 601, '중심이 안 변해야 한다')
})

