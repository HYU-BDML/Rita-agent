// ── 모서리: 비율 잠금 + 글자 크기 ─────────────────────────────

test('모서리를 끌면 가로세로 비율이 그대로다', () => {
  const 전 = (BOX[2] - BOX[0]) / (BOX[3] - BOX[1])
  const { box } = 비율조절(BOX, 'se', [800, 420], 40)
  const 후 = (box[2] - box[0]) / (box[3] - box[1])
  assert.ok(Math.abs(전 - 후) < 1e-9, `${전} → ${후}`)
})

test('모서리를 끌면 글자 크기가 같은 배수로 커진다', () => {
  const { box, pt } = 비율조절(BOX, 'se', [850, 500], 40)
  const 배수 = (box[2] - box[0]) / (BOX[2] - BOX[0])
  assert.ok(Math.abs(pt / 40 - 배수) < 1e-9, `배수 ${배수}, pt ${pt}`)
})

test('se 를 끌면 왼쪽 위가 고정된다 (왼쪽 정렬)', () => {
  const { box } = 비율조절(BOX, 'se', [800, 420], 40, '왼쪽')
  assert.equal(box[0], BOX[0])
  assert.equal(box[1], BOX[1])
})

test('가운데 정렬은 모서리를 끌어도 중심이 그대로다', () => {
  const { box } = 비율조절(BOX, 'se', [800, 420], 40, '가운데')
  assert.equal((box[0] + box[2]) / 2, (BOX[0] + BOX[2]) / 2)
  assert.equal(box[1], BOX[1], '위 변은 언제나 고정')
})

test('오른쪽 정렬은 모서리를 끌어도 오른쪽 변이 그대로다', () => {
  const { box } = 비율조절(BOX, 'se', [800, 420], 40, '오른쪽')
  assert.equal(box[2], BOX[2])
  assert.equal(box[1], BOX[1])
})

test('모서리로 아주 작게 끌어도 글자 크기가 0 이하로 안 간다', () => {
  const { pt } = 비율조절(BOX, 'se', [100, 200], 40)
  assert.ok(pt >= 1, `pt ${pt}`)
})

