test('글자는 언제나 사진 앞이라 겹치면 글자가 잡힌다', () => {
  assert.equal(고를것([[0, 0, 100, 100]], [[0, 0, 100, 100]], [50, 50]).갈래, '글자')
})

test('사진끼리는 층 순서를 따른다', () => {
  const 장식 = [[0, 0, 100, 100], [0, 0, 100, 100]]
  assert.equal(고를것(장식, [], [50, 50]).번호, 1)             // 순서 없으면 나중 것
  assert.equal(고를것(장식, [], [50, 50], 14, [1, 0]).번호, 0)  // 0 을 위로 올리면 0
})

test('손잡이가 겹치면 고른 칸 것이 먼저 잡힌다', () => {
  // 자리가 똑같은 사진 둘. 모서리 손잡이도 같은 자리에 포개진다.
  const 장식 = [[0, 0, 100, 100], [0, 0, 100, 100]]
  // 고른 것 없이 누르면 위엣것(1)이 잡힌다
  assert.equal(고를것(장식, [], [100, 100]).번호, 1)
  // 0 을 고른 상태면 0 의 손잡이가 잡힌다 — 안 그러면 뒤로 보낸 순간 손이 안 닿는다
  const 난것 = 고를것(장식, [], [100, 100], 14, null, { 갈래: '장식', 번호: 0 })
  assert.equal(난것.번호, 0)
  assert.equal(난것.손잡이, 'se')
})

test('손잡이는 위아래를 안 가린다 — 밑엣것 모서리가 위엣것 몸통을 이긴다', () => {
  // 이건 예전부터 그랬다. 큰 사진에 덮여도 작은 사진의 모서리는 잡힌다.
  const 장식 = [[0, 0, 100, 100], [0, 0, 200, 200]]
  assert.equal(고를것(장식, [], [100, 100]).번호, 0)
})

test('밑으로 면 고른 것 바로 밑엣것을 준다 — 덮인 것을 집어내는 길', () => {
  const 장식 = [[0, 0, 100, 100], [0, 0, 100, 100], [0, 0, 100, 100]]
  const 점 = [50, 50]
  assert.equal(고를것(장식, [], 점, 14, null, null, true).번호, 2)
  assert.equal(고를것(장식, [], 점, 14, null, { 갈래: '장식', 번호: 2 }, true).번호, 1)
  assert.equal(고를것(장식, [], 점, 14, null, { 갈래: '장식', 번호: 1 }, true).번호, 0)
  // 맨 밑에서 한 번 더 — 도로 맨 위로 돈다
  assert.equal(고를것(장식, [], 점, 14, null, { 갈래: '장식', 번호: 0 }, true).번호, 2)
})

test('밑으로 여도 겹친 게 하나뿐이면 그대로', () => {
  const 장식 = [[0, 0, 100, 100]]
  assert.equal(고를것(장식, [], [50, 50], 14, null, { 갈래: '장식', 번호: 0 }, true).번호, 0)
})

